/** كلُّ مصدرٍ في الصفحة: أرقامُ الفصول من سجلّها، ثمّ ما في النثر */
export function aboutSources(): AboutSource[] {
  const fromMetrics = CHAPTER_ORDER.flatMap((id) =>
    CHAPTERS[id].metrics.map((m) => ({
      claim: `${m.display_value} ${m.label_ar}`,
      source: m.source_context,
      url: m.source_url,
    })),
  )
  return [...fromMetrics, ...PROSE_SOURCES]
}

/* ─────────── النسخةُ النصّيّة — لسجلّ الصفحات وللزاحف ─────────── */

const metricLine = (m: TrustMetric) => `${m.display_value} ${m.label_ar}`

function chapterSection(id: ChapterId): StaticSection {
  const c = CHAPTERS[id]
  return {
    heading: c.title,
    paragraphs: c.paragraphs,
    ...(c.metrics.length ? { bullets: c.metrics.map(metricLine) } : {}),
  }
}

/** «من نحن» بصيغة الصفحات الثابتة — العنوانُ والوصفُ والفصولُ نصّا */
export function aboutStaticPage(): StaticPage {
  return {
    slug: 'about',
    title: ABOUT_TITLE,
    intro: ABOUT_DESCRIPTION,
    sections: [
      { paragraphs: [ABOUT_HERO.lead] },
      chapterSection('app'),
      chapterSection('maharat'),
      chapterSection('academy'),
      ...ACADEMY_STEPS.map((s) => ({ heading: s.title, paragraphs: [s.body] })),
      { heading: OUTCOMES_TITLE, bullets: OUTCOMES.map((o) => `${o.title}: ${o.body}${o.link ? ` ${o.link.label}.` : ''}`) },
      { heading: AUDIENCES_TITLE, bullets: AUDIENCES.map((a) => `${a.who}: ${a.gets}`), paragraphs: [HONESTY_LINE] },
      chapterSection('next'),
      { heading: CLOSING.title, paragraphs: [CLOSING.body] },
    ],
  }
}
