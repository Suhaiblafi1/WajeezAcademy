/** «من نحن» بصيغة الصفحات الثابتة — العنوانُ والوصفُ والأقسامُ نصّا */
export function aboutStaticPage(): StaticPage {
  return {
    slug: 'about',
    title: ABOUT_TITLE,
    intro: ABOUT_DESCRIPTION,
    sections: [
      {
        heading: FAMILY_INTRO.title,
        paragraphs: [FAMILY_INTRO.body],
        bullets: FAMILY_INTRO.products.map((p) => `${p.name} — ${p.note}: ${p.url}`),
      },
      { heading: FEATURE_HERO.lines.join(' '), paragraphs: [FEATURE_HERO.lead] },
      ...FEATURES.map((f) => ({
        heading: f.title,
        paragraphs: f.paragraphs,
        ...(f.id === 'sources' ? { bullets: [...SOURCE_KINDS] } : {}),
        ...(f.id === 'graduation'
          ? { bullets: OUTCOMES.map((o) => `${o.title}: ${o.body}${o.link ? ` ${o.link.label}.` : ''}`) }
          : {}),
      })),
      { heading: PRICE.title, paragraphs: [...PRICE.paragraphs, HONESTY_LINE] },
      { heading: CLOSING.title, paragraphs: [CLOSING.body] },
    ],
  }
}
