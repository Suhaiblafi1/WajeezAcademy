/* محتوى «التدريبُ معنا» — ما يُجاب به المدعوُّ قبل أن يتقدّم (٥ أكتوبر ٢٠٢٦).

   والأسئلةُ أسئلةُ مدرّبةٍ دعاها صاحبُ المنصّة، بترتيبها: الفئةُ ومستواها، والمواضيع،
   وعددُ الجلسات ومدّتُها، وحضوريٌّ أم عن بُعد، واللغة، والمواعيد، وهل يُعَدّ المحتوى
   كلُّه، والأتعابُ وآليّةُ التعاقد. والقرارُ وعلّةُ الإخفاء في
   `application/trainer/trainer-brief.ts`.

   ═══ وما يُكتب بحذر ═══

   · **كلُّ رقمٍ من ثابته** لا من الذاكرة: مهلةُ الإعداد وتمديدُها
     (`conditional-offer.ts`)، وحدُّ اللقاء (`session-length.ts`)، ومواعيدُ الصرف
     والاعتراض (`notice-periods.ts`)، والمواسم (`application-options.ts`). فإن
     تغيّر حدٌّ تغيّر نصُّه معه.
   · **وصيغُ الأتعاب ثلاثٌ كما في `TrainerCompensationRule`**: لكلّ متعلّم
     (`per_seat`) — ومعه أرضيّةٌ للشعبة (`minSeats × rate`، `seat-fee.ts`) لا تُدفع
     إلّا لشعبةٍ بدأت وقُدّمت، وأجرٌ أعلى لمقعد رابط الدعوة (`referralRate`، لهذه
     الصيغة وحدَها) — ومبلغٌ ثابتٌ للشعبة، ونسبةٌ من الإيراد المدفوع. وخصوماتُ
     المسارات لا تمسّ الأوليين لأنّهما على المقعد لا على ما دُفع (`earnings.service.ts`).
   · **والنطاقُ مثالٌ بأمر صاحب المنصّة**: «لا تعطِ أسعارا… قل مثلا من 20 إلى 40
     دولارا، للعامّ وللرابط». فيُقال مثالا، ويُقال إنّ الرقمَ في الاتفاقيّة.
   · **ولا «عرضك»** — `offer-word.test.ts` يحرسها في كلّ نصّ.
   · **ولا «نؤهّلك»** — قرارُ صاحب المنصّة (٥ أكتوبر ٢٠٢٦): «لا تقل نؤهّلك لأنّها قد
     تُقرأ ندرّبك». فمدرّبٌ خبيرٌ يُدعى لا يُقال له إنّه سيُؤهَّل: «نختار لك دوراتٍ
     تطابق خبرتك». ويحرسها `trainer-brief.test.ts` في نصوص الصفحة كلِّها.

   ═══ و«من نحن» في الصفحة الأولى (٥ أكتوبر ٢٠٢٦) ═══

   «أعطه مجالا يقرأ من نحن في الصفحة الأولى». فالتعريفُ من `data/about.ts` نفسِه —
   نصُّ «من نحن» وأخواها بموقعيهما — لا نسخةٌ تفترق عنه. وما يجده المتعلّمُ عندنا
   محطّاتُ «من نحن» بترتيبها (`FEATURES`) بلسان المدرّب: سجلٌّ بمفاتيحها، فمحطّةٌ
   تُضاف هناك ولا تُكتب هنا لا تُبنى. */

