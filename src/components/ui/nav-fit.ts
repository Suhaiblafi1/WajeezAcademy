/* كم تبويبا يسعه الشريط — والباقي خلف «المزيد».
 *
 * قرارُ صاحب المنصّة (٢٧ سبتمبر ٢٠٢٦): «اجعل قائمةَ العناوين مكتملةً ليست
 * داخلَ المزيد، إلّا إذا استُخدم الهاتفُ والشاشةُ صغيرة — هناك نستخدم
 * المزيدَ لمن لا يظهر». فليس في الشريط عددٌ ثابتٌ يُرى: يُرى ما وسعه،
 * و«المزيد» لما لم يسعه وحدَه، ولا يظهر أصلا حين يسع الكلّ.
 *
 * ── لماذا دالّةٌ نقيّةٌ منفصلة ──
 *
 * الإطارُ يقيس في المتصفّح ويمرّر الأرقام، وهذه تقرّر. فالقرارُ يُختبَر
 * بأرقامٍ في Node (`src/tests/trainer/nav-fit.test.ts`) بلا متصفّحٍ ولا
 * جلسةِ مدرّب — وما يُحرَس فيه ثلاث: أنّ الكلَّ يُرى متى وسعه الشريط، وأنّ
 * مكانَ «المزيد» يُحجَز **قبل** أن يُقال إنّ تبويبا وسع، وأنّ الترتيبَ
 * أولويّة يُملأ بها ما بقي من الفسحة (`fitIndices`).
 */

/* سماحٌ لكسور البكسل: عرضٌ يُقاس ١٠٠٠٫٣ في شريطٍ ١٠٠٠ لا يُرى قَصُّه بعين،
   وطردُ تبويبٍ من أجله يُظهر «المزيد» لبندٍ يسعه الشريط. */
const SLACK = 0.5

/**
 * @param widths    عرضُ كلِّ تبويبٍ بترتيبه في الشريط
 * @param gap       الفراغُ بين حبّتين — وهو نفسُه بين آخرِ تبويبٍ وزرّ «المزيد»
 * @param moreWidth عرضُ زرّ «المزيد»
 * @param available عرضُ الشريط المتاح كلِّه
 * @returns عددُ ما يُعرض من أوّل القائمة؛ وما بعده لـ«المزيد»
 */
/* ═══ والفسحةُ تُملأ — لا يقف الشريطُ عند أوّل عريض (٣ أكتوبر ٢٠٢٦) ═══

   قرارُ صاحب المنصّة على صورة الهاتف: الرئيسيةُ وشعبي وطلبتي ثمّ فراغٌ ثمّ
   «المزيد» — «make them appear more and what left goes to المزيد». وكان العدُّ
   يقف عند أوّل تبويبٍ لا يسع («طابورُ التقييم» بشارته)، فيُرمى كلُّ ما بعده
   في «المزيد» ولو وسع الفراغُ اثنين منه.

   فصار الملءُ بالترتيب **مع التخطّي**: يُعرض كلُّ تبويبٍ يسعه ما بقي، ويخرج
   ما لا يسع وحدَه. والترتيبُ ما زال أولويّة — الأوّلُ يُعطى مكانَه قبل من
   بعده — لكنّ عريضا لا يسع لا يحجب ضيّقا بعده. وتُعاد مواضعُ المعروض لا
   عددُه، لأنّ المعروضَ لم يعد «أوّلَ N». */
export function fitIndices(widths: readonly number[], gap: number, moreWidth: number, available: number): number[] {
  const room = available + SLACK
  const all = widths.reduce((sum, w) => sum + w, 0) + gap * Math.max(0, widths.length - 1)
  if (all <= room) return widths.map((_, i) => i)

  /* لا يسع الكلّ: فـ«المزيد» ظاهرٌ حتما، ومكانُه يُحجَز أوّلا ثمّ يُملأ ما
     بقي بالترتيب. ولو عُدّت التبويباتُ قبله لقيل «يسع عشرة» ثمّ جاء الزرُّ
     فقصَّ العاشر. */
  let used = moreWidth
  const shown: number[] = []
  widths.forEach((w, i) => {
    if (used + w + gap <= room) {
      used += w + gap
      shown.push(i)
    }
  })
  return shown
}

/* ── ومكانُ الشارة يُحجَز قبل أن يصل عددُها ──

   الإطارُ يُعاد تركيبُه مع كلّ شاشةٍ في البوّابة، وعدّادُ التصحيح يصل بعد
   التركيب بنداء. فلو قيس التبويبُ بلا شارته لوسعه الهاتفُ أوّلا، ثمّ وصل
   العددُ فعرُض التبويبُ فقفز إلى «المزيد» — في كلّ انتقال، وقِيس ذلك: ٤ ← ٣
   على ٣٩٠، و٥ ← ٤ على ٤٣٠. ومثلُه حين يفرغ الطابورُ فتنطفئ الشارة فيعود.

   فشبحُ كلِّ تبويبٍ له عدّادٌ يحمل شارةً برقمٍ واحدٍ على الأقلّ، صفرا كان
   عددُه أو لم يصل. والثمنُ تبويبٌ واحدٌ يخرج قبل أوانه على بعض العروض حين
   لا شيءَ ينتظر — وهو خيرٌ من شريطٍ يقفز تحت إصبع من يهمّ بالنقر.

   و`undefined` يبقى `undefined`: تبويبٌ بلا عدّادٍ أصلا لا يُحجَز له شيء. */
export function reservedCount(count: number | undefined): number | undefined {
  return count === undefined ? undefined : Math.max(count, 9)
}
