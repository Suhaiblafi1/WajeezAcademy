/* ملحقُ الدورات المعتمدة — وعدٌ في المتن يُوفى.

   ═══ ولمَ هو التزامٌ لا زينةُ عرض ═══

   البندُ 2-11 من المتن الذي وقّعه المدرّبُ يقول بحرفه: «وتوقع الأكاديمية هذا
   العرض من جهتها يوم يتحقق الشرط، فيصير عقدا نهائيا غير مشروط موقعا من
   الطرفين، **ويعاد إلى المدرب مع ملحق يبين الدورات المعتمدة له**».

   فوعدُ الملحق في الوثيقة الموقَّعة، ولم يكن يُبنى. ووثيقةٌ تَعِد بملحقٍ لا
   يصل تُقرأ على كاتبها لا له.

   ═══ ومكوّنٌ ثانٍ بجانب سجلّ التوقيع ═══

   سجلُّ التوقيع يقول **من وقّع وبم يُثبَت**، وهذا يقول **ما اعتمدناه فتحقّق
   الشرط**. ولو جُمعا في لوحٍ واحدٍ اختلط سؤالان يُسألان منفردَين بعد سنة.

   ═══ وكلاهما لا يدخل `bodyAr` ═══

   المتنُ مهشَّشٌ ويُقابَل هاشُه لحظةَ التوقيع. والملحقُ يُبنى **بعد** التوقيع
   بطبيعته (لا تُعرَف الدوراتُ المعتمدةُ قبل تقييم موادّها)، فإدخالُه في المتن
   ممتنعٌ منطقا لا ممنوعٌ اصطلاحا: لا يُزاد على نصٍّ وُقّع ما لم يكن موجودا
   يومَ وُقّع. */

import { readApprovedCourses } from '@/application/trainer/contract-execution'
import { APPROVAL_ANNEX_CLAUSE } from '@/application/trainer/contract-body'
import { fmtDateLong } from '@/application/text/format-ar'

export default function ContractApproval({
  snapshot, approvedAt,
}: { snapshot: unknown; approvedAt?: string | Date | null }) {
  const courses = readApprovedCourses(snapshot)
  /* ولا ملحقَ يُعرَض فارغا: «الدوراتُ المعتمدة: (لا شيء)» تحت وعدٍ بملحقٍ
     يبيّنها تُقرأ إلغاءً للاعتماد. وعقودُ ما قبل العمود، والعقدُ غيرُ
     المشروط، لا لقطةَ لهما — فلا يُدَّعى لهما ملحق. */
  if (courses.length === 0) return null

  return (
    <section className="contract-annex contract-prose" dir="rtl" aria-labelledby="ca-h">
      <header className="ca-head">
        {/* ورقمُ البند من مصدره لا مكتوبا حرفا: إحالةٌ خاطئةٌ في ملحقٍ
            قانونيٍّ أسوأُ من غياب الإحالة. */}
        <p className="ca-kicker">ملحقٌ للعقد — البند {APPROVAL_ANNEX_CLAUSE}</p>
        <h2 className="ca-title" id="ca-h">الدوراتُ المعتمدةُ لك</h2>
        <p className="ca-lede">
          قيّمت الأكاديميّةُ موادَّك واعتمدت هذه الدورات، فتحقّق شرطُ عرضك وصار العقدُ نافذا.
          {approvedAt ? ` وذلك بتاريخ ${fmtDateLong(approvedAt)}.` : ''}
        </p>
      </header>

      <ol className="ca-list">
        {courses.map((c) => <li key={c.courseId}>{c.titleAr}</li>)}
      </ol>

      {/* والبندُ 2-7 يقول إنّ القبولَ لكلّ دورةٍ على حدة — فما ليس هنا لا
          يُدرَّس، وهو أهمُّ ما يُقرأ في هذا الملحق. */}
      <p className="ca-note">
        والقبولُ لكلِّ دورةٍ على حدة (البند 2-7): لا تُقدَّم إلّا ما اعتُمد لك بعينه.
        وما أُعيد إليك بملاحظاتٍ تعدّله وتعيد رفعَه، فيُنظَر فيه من جديد.
      </p>
    </section>
  )
}
