/* إشارةُ «قُضي في خطّةٍ تنتظر الاعتماد» — وشارةُ القائمة تتبعها.

   العلّةُ علّةُ `grading-signal.ts` بعينها: الإطارُ (`AdminLayout`) يجلب عددَ
   «خططٌ تنتظر اعتمادك» مرّةً عند التركيب، والقرارُ يقع في متن الصفحة. فرُئي في
   لقطة الطابور (٣ أكتوبر ٢٠٢٦) رأسُ الصفحة يقول «٢» والشارةُ إلى جانب اسمها «٣»
   حتّى تُفتح شاشةٌ أخرى. فمن قضى في خطّةٍ أطلق الإشارة، والإطارُ يعيد الجلب.

   والاسمُ ثابتٌ واحدٌ يستورده الطرفان: حدثٌ يُطلق باسمٍ ويُسمع بآخرَ يصمت. */

export const PLANS_CHANGED = "wajeez:plans-changed";

/** يُطلقها من اعتمد خطّةً أو ردّها — فيعيد الإطارُ جلبَ عدد ما ينتظر */
export function signalPlansChanged() {
  window.dispatchEvent(new Event(PLANS_CHANGED));
}
