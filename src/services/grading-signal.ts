/* إشارةُ «تغيّر شيءٌ في الطابور».

   ── العطبُ الذي فُتحت له ──

   شارةُ «ينتظر تصحيحَك» في قائمة التبويبات، والطابورُ في متن الصفحة:
   الأولى يجلبها الإطارُ (`TrainerLayout`) مرّةً عند التركيب، والثاني يعيد
   تحميلَ نفسِه بعد كلّ فعل. فرصدت جولةُ ٢٠٢٦-٠٩ أنّ المدرّبَ يقبل آخرَ
   تسليمٍ فيصير المتنُ «الطابورُ نظيف» والشارةُ فوقه ما تزال «١» — ولا
   تنطفئ إلّا بإعادة تحميلٍ كاملة. فالعددُ صحيحٌ ولا يُعاد جلبُه.

   والإطارُ لا يملك أن يراقب ابنَه، فيُبلَّغ: من غيّر حالةَ تسليمٍ أطلق
   الإشارةَ، ومن يعرض العددَ أعاد جلبَه.

   ── ولمَ الاسمُ يُصدَّر من هنا ──

   حدثٌ يُطلق باسمٍ ويُسمع بآخرَ لا يسقط في شيءٍ ولا يشكو: يصمت. فالاسمُ
   ثابتٌ واحدٌ يستورده الطرفان، لا حرفٌ مكتوبٌ في ملفَّين. */

export const GRADING_CHANGED = "wajeez:grading-changed";

/** يُطلقها من غيّر حالةَ تسليم — فيعيد الإطارُ جلبَ عدد ما ينتظر التصحيح */
export function signalGradingChanged() {
  window.dispatchEvent(new Event(GRADING_CHANGED));
}
