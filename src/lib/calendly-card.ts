/* ما الذي تقوله بطاقةُ Calendly عن حالها — قرارٌ يُفحص، لا شرطٌ في JSX.

   ═══ العطبُ الذي كُتب له ═══

   كان تحذيرُ البطاقة مشروطا بـ`!ready`، و`ready` تعني «مفتاحُ توقيعٍ محفوظ»
   لا غير. فمن لصق رمزَه الشخصيَّ في حقل مفتاحِ التوقيع — والحقلان متجاوران
   وكلاهما مقنَّع — صارت عنده `ready` صادقةً ولا رمزَ عنده، فسكتت البطاقةُ
   سكوتَ السليم. وبقيت الحجوزاتُ لا تصل، والشاشةُ لا تقول شيئا (١٣ سبتمبر
   ٢٠٢٦: مضى على هذا يومٌ كاملٌ وحجزٌ حقيقيٌّ ضائع).

   ومفتاحُ التوقيع لا يسدّ مسدَّ الرمز أصلا: هو للمستقبِل الفوريّ، والاشتراكُ
   فيه خلفَ خطّةٍ مدفوعةٍ لا يملكها الحساب. والسؤالُ الدوريُّ وحدَه يعمل على
   المجّانيّة — ولا يعمل إلّا برمز.

   فصار القرارُ دالّةً خالصةً تُنادى بالحالات الأربع، لأنّ شرطا في JSX لا
   يُفحص إلّا بمطابقة نصِّ ملفٍّ — وهي المطابقةُ التي مرّ منها حرّاسٌ خضرٌ
   لأسبابٍ خاطئة في هذه المنصّة. */

export type CalendlyNoticeTone = 'danger' | 'positive'

/** الحالُ كما تعرضها `maskedIntegrationsView` — ولا شيءَ سواها يقرّر */
export interface CalendlyCardState {
  enabled: boolean
  hasToken: boolean
  hasSigningKey: boolean
}

export interface CalendlyNotice {
  tone: CalendlyNoticeTone
  textAr: string
}

/** والفراغُ يعني: لا شيءَ مضبوطٌ ولا شيءَ مفعَّل — فلا خبرَ ولا تحذير */
export function calendlyCardNotice(state: CalendlyCardState): CalendlyNotice | null {
  if (state.enabled && !state.hasToken) {
    return {
      tone: 'danger',
      /* والحالان يفترقان في العمل المطلوب: من لا مفتاحَ له ولا رمز يُقال له
         «الصق رمزا»، ومن لصق رمزَه في الحقل الخطأ يُقال له أين ذهب. */
      textAr: state.hasSigningKey
        ? 'مفتاحُ التوقيع محفوظٌ ولا رمزَ شخصيّ. والمفتاحُ للمستقبِل الفوريّ وحدَه وهو يقتضي خطّةً مدفوعة — فالصق الرمزَ في حقله فوقَه ليعمل السؤالُ الدوريُّ على المجّانيّة.'
        : 'مفعَّلٌ بلا رمزٍ شخصيّ — لا يصل حجزٌ إلى طابور المراجعة البتّة.',
    }
  }
  if (!state.enabled && state.hasToken) {
    return {
      tone: 'danger',
      textAr: 'الرمزُ محفوظٌ والتكاملُ مطفأ — فلا تُسأل Calendly البتّة. علّم «مفعَّل» ثمّ احفظ.',
    }
  }
  if (state.enabled && state.hasToken) {
    return {
      tone: 'positive',
      textAr: 'المزامنةُ بالسؤال الدوريّ — يسأل الخادمُ Calendly كلَّ خمس دقائق. تعمل على الخطّة المجّانيّة.',
    }
  }
  return null
}
