/* ═══ العربيّةُ بلا تشكيلٍ إعرابيّ — «اللغةُ البيضاء» (١١ أكتوبر ٢٠٢٦) ═══

   قرارُ صاحب المنصّة: «استخدم كلماتٍ عربيّةً بسيطة، ليست فصيحةً لدرجة الغرابة وتشكيلُها معقّد..
   استخدم اللغةَ البيضاء وتميل للفصحى». فنصوصُ الشاشات بلا حركاتٍ ولا تنوين ولا سكون — والشدّةُ
   وحدَها تبقى، تُعين على النطق ولا تثقل.

   وما كُتب قبل القرار وحُفظ في القاعدة (ملاحظاتُ المعتمِد، أسطرُ البطاقة) فيه تشكيل؛ فما يقرؤه
   من ذلك النصّ ويطابقه يمرّ به على هذه أوّلا، فيُطابق القديمُ والجديدُ معا. */

/** الحركاتُ والتنوينُ والسكون — والشدّةُ (U+0651) ليست منها */
export const CASE_MARKS = /[ً-ِْ]/g

/** النصُّ بلا تشكيلٍ إعرابيّ، والشدّةُ باقية */
export function plainAr(s: string): string {
  return s.replace(CASE_MARKS, '')
}
