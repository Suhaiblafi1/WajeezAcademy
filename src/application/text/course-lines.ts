/* الدوراتُ في رسالة واتساب — مرقّمةٌ بعناوينها القصيرة (٢٦ أكتوبر ٢٠٢٦).

   قال صاحبُ المنصّة عن رسالة المسار: «الدوراتُ نصوصٌ صعبٌ قراءتُها.. اجعلها أجملَ للقراءة». فاسمُ الدورة في
   الكتالوج جملتان: «دورة اكتشاف العملاء وعرض القيمة: إثبات المشكلة بأدلّة سلوك لا بآراء» — وفي سطرٍ ضيّقٍ من
   واتساب يلتفّ على سطرين ويضيع أوّلُه في آخره. فيُكتب العنوانُ وحدَه بلا «دورة» قبله ولا الشرح بعد النقطتين،
   ويُرقَّم فيُعدّ بنظرة. والاسمُ الكاملُ يبقى في الصفحة وفي الورقة لمن أراده. */

/** «دورة اكتشاف العملاء وعرض القيمة: إثبات…» ← «اكتشاف العملاء وعرض القيمة». وما لا يبقى منه شيءٌ يُكتب كما هو */
export function shortCourseTitleAr(name: string): string {
  const short = name.split(':')[0].replace(/^\s*دورة\s+/, '').trim()
  return short || name.trim()
}

/** سطرٌ لكلّ دورة: «1. العنوان» */
export function courseLinesAr(names: readonly string[]): string {
  return names.map((n, i) => `${i + 1}. ${shortCourseTitleAr(n)}`).join('\n')
}
