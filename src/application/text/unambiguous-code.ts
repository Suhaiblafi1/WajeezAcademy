/* رمزٌ يُقرأ بالعين ويُنسخ باليد — أبجديّةٌ بلا التباس.

   ═══ لمَ ملفٌّ مشترك ═══

   رمزُ الدعوة (`WJ-XXXXXXXX`) كان يحمل أبجديّتَه في `referral.service.ts`،
   ثمّ لزم رمزٌ قصيرٌ للروابط (ط-٣). ونسختان من أبجديّةٍ واحدة تفترقان: يُحذف
   حرفٌ من إحداهما ويبقى في الأخرى، فيصير رمزٌ يُملى في الهاتف مقروءا وآخرُ
   ملتبسا — ولا شيءَ يقول إنّهما كانا واحدا.

   ═══ ولمَ هذه الحروفُ دون غيرها ═══

   سقط منها **الصفرُ وO** و**الواحدُ وI**: رمزٌ يُقرأ من ورقةٍ مطبوعةٍ أو
   يُملى في مكالمةٍ لا يحتمل حرفَين يُشبه أحدُهما الآخر. وسقطت الصغيرةُ كلُّها
   فلا يُسأل «أكبيرةٌ أم صغيرة؟».

   وبقيت **L** فيها: هي أبجديّةُ رمزِ الدعوة كما كانت يوم كُتب، ولم تُمسّ
   عند نقلها إلى هنا. فنقلُ مالكٍ شيءٌ وتغييرُ قاعدةٍ شيءٌ آخر — والرموزُ
   المسكوكةُ قبلَه منشورةٌ عند الناس.

   ═══ و`crypto` الويبِ لا `node:crypto` ═══

   هذا الملفُّ تحت `src/application/` — يقرؤه الخادمُ **والشاشة**. و
   `node:crypto` يكسر بناءَ Vite. و`getRandomValues` قائمٌ في الاثنين. */

/** اثنان وثلاثون حرفا: لا 0/O ولا 1/I، ولا صغيرة */
export const UNAMBIGUOUS_ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789'

/** رمزٌ عشوائيٌّ بطولٍ مطلوب من تلك الأبجديّة */
export function randomUnambiguousCode(length: number): string {
  const bytes = new Uint8Array(length)
  globalThis.crypto.getRandomValues(bytes)
  let out = ''
  for (const b of bytes) out += UNAMBIGUOUS_ALPHABET[b % UNAMBIGUOUS_ALPHABET.length]
  return out
}
