/* صفحاتُ الموقع العامّة — مصدرٌ واحدٌ لما يُفهرَس، وبأيّ عنوانٍ ووصف.

   ── العطبُ الذي وُلد هذا الملفُّ لأجله (١٨ سبتمبر ٢٠٢٦) ──

   الموقعُ لم يكن يظهر في قوقل البتّة. والسببُ لم يكن نقصَ وسومٍ ولا ضعفَ
   محتوى — بل أنّ **الوسومَ الصحيحةَ كانت تُكتب بعد فوات الأوان**.

   فالموقعُ تطبيقُ صفحةٍ واحدة (SPA): `deploy/Caddyfile` كان يردّ
   `dist/index.html` نفسَه — بايتا ببايت — لكلّ مسار. وذلك الملفُّ يحمل:

     <link rel="canonical" href="https://www.wajeezacademy.com/" />

   أي أنّ `/pathways` و`/courses` و`/stories` و`/methodology` وكلَّ عنوانٍ في
   خريطة الموقع كان **يُعلن للزاحف أنّ أصلَه هو الصفحةُ الرئيسة**. وقوقل يأخذ
   `canonical` جادّا: أربعةَ عشرَ عنوانا تُطوى كلُّها في عنوانٍ واحد، فلا
   يبقى في الفهرس إلّا صفحةٌ واحدة — ومحتواها في المصدر `<div id="root">`
   فارغة، بلا عنوانٍ ولا فقرةٍ ولا رابط.

   و`SeoHead` كان يصحّح ذلك — لكن بعد أن تعمل React، أي في طور التصيير
   المؤجَّل عند قوقل (أيّاما أو أسابيع، وقد لا يأتي). والتصحيحُ المتأخّر لا
   ينفع: الطيُّ يكون قد وقع من قراءةِ المصدر الأولى.

   ── فالعلاجُ: لكلّ صفحةٍ ملفُّها ──

   `scripts/prerender-seo.ts` يكتب بعد كلِّ بناءٍ ملفَّ HTML مستقلّا لكلّ
   صفحةٍ هنا، بعنوانها ووصفها و`canonical` الخاصِّ بها ومحتوى نصّيٍّ حقيقيّ.
   وهذا الملفُّ هو مصدرُ تلك القائمة — وهو نفسُه ما تقرؤه الصفحاتُ حيّةً عبر
   `seoFor`، فلا يفترق ما يراه الزاحفُ عمّا يراه الزائر.

   ── ولماذا مصدرٌ واحدٌ لا مصدران ──

   لو كُتب العنوانُ في الصفحة وكُتب ثانيةً في سكربت التهيئة، لافترقا بأوّل
   تعديل: فيقرأ الزاحفُ عنوانا ثمّ تستبدله React بآخر — وذلك أسوأُ من عنوانٍ
   واحدٍ رديء، لأنّه يُقرأ تذبذبا. فالعنوانُ يُكتب هنا مرّةً، ويُقرأ من
   موضعين.

   ⚠️ ومَن أضاف صفحةً عامّةً جديدة أضافها هنا — وإلّا فلها ملفُّ `index.html`
   العامّ بعنوان الرئيسة و`canonical` الرئيسة، أي أنّها لا تُفهرس. ويحرس ذلك
   `src/tests/seo/public-pages.test.ts`: كلُّ مسارٍ هنا مسارٌ في `App.tsx`. */

import { staticPages } from '../../data/siteContent'

/** اسمُ الموقع كما يُذيَّل به كلُّ عنوان */
export const SITE_NAME = 'أكاديمية وجيز'

/** صيغةُ العنوان الكاملة — واحدةٌ في الوسم الساكن وفي `SeoHead` معا.

    وكانت مفترقةً فعلا: `index.html` يكتب «أكاديمية وجيز — مسارك يبدأ من
    فهمك» و`SeoHead` يستبدله بـ«مسارك يبدأ من فهمك — أكاديمية وجيز». فيقرأ
    الزاحفُ الأوّلَ في المصدر والثانيَ بعد التصيير. */
export function pageTitle(title: string): string {
  return `${title} — ${SITE_NAME}`
}

