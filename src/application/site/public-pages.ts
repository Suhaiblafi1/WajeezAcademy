const BY_PATH = new Map(PUBLIC_PAGES.map((p) => [p.path, p]))

/** صفحةٌ عامّةٌ بمسارها، أو `undefined` إن لم تكن منها */
export function publicPageByPath(path: string): PublicPage | undefined {
  return BY_PATH.get(path)
}

/** خصائصُ `SeoHead` لصفحةٍ عامّة — فلا يُكتب عنوانٌ في موضعين.

    ويسقط على المسار نفسِه إن لم تُسجَّل الصفحةُ: خطأُ كتابةٍ في المسار يجب
    أن يُرى في الاختبار لا أن يُطفئ الوسومَ صامتا. */
export function seoFor(path: string): { title: string; description: string; path: string } {
  const page = BY_PATH.get(path)
  if (!page) throw new Error(`لا صفحةَ عامّةً بالمسار «${path}» في PUBLIC_PAGES`)
  return { title: page.title, description: page.description, path: page.path }
}
