/** الدورُ الذي تُقاس به هذه الحقول */
const LEARNER_ROLE = 'learner'

/**
 * أتُعرض حقولُ المتعلّم لصاحب هذه الأدوار؟
 *
 * والغيابُ ليس إذنا: قبل أن تصل الجلسةُ (`null`) لا تُعرض — فظهورُها ثمّ
 * اختفاؤها بعد جوابِ الخادم ارتجافٌ يراه المستخدمُ عطبا.
 */
export function showsLearnerFields(roles: readonly string[] | null | undefined): boolean {
  return Array.isArray(roles) && roles.includes(LEARNER_ROLE)
}
