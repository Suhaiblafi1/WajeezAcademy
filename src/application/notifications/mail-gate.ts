/* بوّابةُ الإرسال الحقيقيّ — أيخرج بريدٌ من هذه البيئة إلى إنسان؟

   ═══ الوعدُ الذي لم يكن له آلة ═══

   كان مكتوبا في هذه المنصّة: «لا إرسالَ حقيقيٌّ في التطوير أبدا». وهو وعدٌ
   صادقُ النيّة، لكنّ الذي كان يحرسه شيءٌ واحدٌ لا غير: **غيابُ مفتاحِ
   Resend** من قاعدة التطوير. فلو استُعيدت نسخةٌ من قاعدة الإنتاج على جهازٍ
   محلّيّ — وهو أوّلُ ما يفعله من يتتبّع عطلا في بيانات حقيقيّة — لخرج من
   ذلك الجهاز بريدٌ إلى متعلّمين ومدرّبين حقيقيّين، بلا أن يقصده أحد وبلا
   أن يعلم به أحد.

   والوعدُ الذي يحرسه غيابُ إعدادٍ ليس وعدا: هو صدفةٌ دامت.

   ═══ ولمَ الرفضُ افتراضٌ لا الإرسال ═══

   البوّابةُ **تُغلق على المجهول**: لا تسأل «أفي التطوير أنا؟» — فالجواب
   عليها بالنفي يحتاج معرفةً قد تنقص — بل تسأل «أثبت أنّ هذه بيئةُ إرسال».
   فبيئةٌ لم تقل شيئا لا تُرسل. وثمنُ الخطأ في الاتّجاهين غيرُ متساوٍ:
   بريدٌ لم يخرج في التطوير لا يراه أحد، وبريدٌ خرج منه يصل صندوقَ إنسان.

   ═══ والعلامتان تُقرآن معا بقصد ═══

   `APP_ENV` و`NODE_ENV` — وهو نفسُ ما يقبله حارسُ الديمو في
   `server/http/routes/demo.routes.ts`، ومكتوبٌ هناك لماذا: `NODE_ENV` وحدَه
   لم يكن مضبوطا يوما في هذه المنصّة فأجاب حارسٌ «لست إنتاجا» وهو فيه.
   واليومَ يُضبط الاثنان في `deploy/compose.prod.yml` و`Dockerfile`، ويُقرآن
   معا حتّى لا يعيد التاريخُ نفسَه في الاتّجاه الذي يُسكِت بريدَ الإنتاج.

   ═══ وبابٌ صريحٌ لمن أراد ═══

   `MAIL_LIVE=on` — لمن يريد أن يجرّب الإرسالَ من بيئةٍ غيرِ إنتاجيّة عن
   قصد. صريحٌ ومقصودٌ ومكتوبٌ في أمر التشغيل، لا صدفةُ إعدادٍ منسيّ. */

/** رفضُ البوّابة — يُسجَّل في سجلّ الإشعار كما يُسجَّل أيُّ فشلِ إرسال */
export const MAIL_GATE_REFUSAL_AR =
  'الإرسالُ الحقيقيّ موقوفٌ في هذه البيئة — اضبط MAIL_LIVE=on إن قصدتَه'

/** أتُرسِل هذه البيئةُ بريدا حقيقيّا؟ ولا تُرسل حتّى تُثبِت. */
export function liveMailAllowed(env: Record<string, string | undefined> = process.env): boolean {
  if (env.MAIL_LIVE === 'on') return true
  return env.APP_ENV === 'production' || env.NODE_ENV === 'production'
}
