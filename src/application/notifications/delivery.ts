/* خبرُ الإرسال كما يُقال للموظّف — و«تمّ» لا تُقال عن بريدٍ لم يخرج.

   ═══ العطبُ الذي كُتب له ═══

   مسالكُ البريد في الخادم تردّ حالَ الإرسال صراحةً (`DirectMailResult`):
   `sent` أو `failed` أو `not_configured`. وكانت شاشاتُ الإدارة ترمي الجوابَ
   وتعرض رسالةَ نجاحٍ مكتوبةً سلفا: «أُرسل التذكير»، «أُرسلت الدعوة»،
   «جُدولت المقابلة» — تُعرض كما هي ولو ردّ الخادمُ أنّ شيئا لم يخرج.

   وأثرُ ذلك لا يُرى يومَ يقع: قناةُ البريد تتعطّل أو يُنزع مفتاحُها، فيذكّر
   الموظّفُ عشرةَ متقدّمين ويقرأ عشرَ رسائلِ نجاح، ويظنّهم أُخبروا. ثمّ
   ينتظرهم أسبوعا وهم لم يعلموا بشيء.

   و`mail.ts` يقول القاعدةَ بنصّها: «لا يُبتلع ولا يُدّعى نجاحٌ لم يقع».
   وشاشةُ دعوةِ الحساب تعمل بها منذ كُتبت — تقرأ الحالَ وتقول «سلّم الرابطَ
   بيدك» حين لا يخرج البريد. فالنمطُ الصادقُ كان موجودا في موضعٍ وغائبا عن
   إخوته، وهذا الملفّ يوحّده.

   ═══ ولمَ «سُجّل الفعل» في كلّ جواب ═══

   لأنّ الفعلَ وقع فعلا: الأثرُ كُتب، والحالةُ تبدّلت إن كانت تتبدّل. الذي
   لم يقع هو **خروجُ البريد** وحدَه. فجوابٌ يقول «تعذّر» مجرّدا يجعل الموظّفَ
   يعيد الكرّةَ ظنًّا أنّ شيئا لم يحدث، فيتضاعف الأثرُ بلا فائدة. */

/** ما يردّه الخادمُ عن كلّ رسالة — و`DirectMailStatus` في الخادم نظيرُه */
export type MailDeliveryStatus = 'sent' | 'not_configured' | 'failed'

export interface MailOutcome {
  /** هل خرج البريدُ فعلا — تُقرأ في الشاشة لتُختار نبرةُ الخبر */
  ok: boolean
  /** ما يُعرض للموظّف */
  ar: string
}

/** خبرُ رسالةٍ واحدة. و`doneAr` جملةُ النجاح التي يكتبها المُنادي. */
export function mailOutcomeAr(doneAr: string, status: string | null | undefined): MailOutcome {
  if (status === 'sent') return { ok: true, ar: doneAr }
  if (status === 'not_configured') {
    return { ok: false, ar: 'سُجّل الفعل ولم يخرج البريد — قناةُ البريد غير مفعّلة، فعّلها من شاشة التكاملات' }
  }
  if (status === 'failed') {
    return { ok: false, ar: 'سُجّل الفعل وتعذّر خروجُ البريد — راجع شاشة التكاملات ثمّ أعد المحاولة' }
  }
  /* لا حالَ في الجواب: لا يُقال «أُرسل» على ظنّ. وهذا يقع حين يُنادى مسارٌ
     لا يردّ حالَ بريده، فيُقرأ الغيابُ غيابا لا نجاحا. */
  return { ok: false, ar: `${doneAr} — وحالُ البريد غيرُ معروف، تحقّق قبل أن تعدّه مُبلَّغا` }
}

/** خبرُ دفعةٍ — يقول كم خرج بريدُه وكم لم يخرج، ولا يبتلع الثاني في الأوّل */
export function mailBatchOutcomeAr(baseAr: string, statuses: (string | null | undefined)[]): MailOutcome {
  const undelivered = statuses.filter((s) => s !== 'sent').length
  if (undelivered === 0) return { ok: true, ar: baseAr }
  const why = statuses.some((s) => s === 'not_configured')
    ? 'قناةُ البريد غير مفعّلة'
    : 'تعذّر الإرسال'
  return { ok: false, ar: `${baseAr} — ولم يخرج البريدُ في ${undelivered} منها (${why})` }
}
