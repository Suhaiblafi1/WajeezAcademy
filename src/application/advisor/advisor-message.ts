/* اسمُ مستشار الطالب في رسالته — لمن يقرأ واتساب الأكاديمية (١٩ أكتوبر ٢٠٢٦).

   قرارُ صاحب المنصّة بين ثلاثة (الاسمُ وحدَه برقم الأكاديمية، أو رقمُ المستشار نفسِه، أو
   رسائلُ داخل المنصّة): **الاسمُ وحدَه** — «لأنّي سأربط واتساب بمنصّةٍ نوزّع منها العملاءَ على
   المستشارين». فالرقمُ واحدٌ للأكاديمية، والرسالةُ تحمل اسمَ المستشار فتصل إليه، ولا يخرج
   رقمُ مستشارٍ إلى عميل.

   والاسمُ في سطرٍ أخير بصيغةٍ ثابتة: من يوزّع يجده في موضعٍ واحدٍ من كلّ رسالة. */

export function withAdvisorName(text: string, advisorName: string | null | undefined): string {
  const name = advisorName?.trim()
  return name ? `${text}\n(مستشاري: ${name})` : text
}
