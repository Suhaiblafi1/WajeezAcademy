/** ما يوافق عليه بالإرسال — يُعرض تحت الزرّ ويُحفظ مع العميل المحتمل */
export const GUEST_CONTACT_CONSENT_AR =
  'بالإرسال توافق أن يتواصل معك مستشار من وجيز على هذا الرقم أو البريد بخصوص نتيجتك فقط.'

/** رقمُ واتساب بصيغةٍ واحدة — أو `null` إن لم يكن رقما.

    يُقبل ما يكتبه الناسُ فعلا: أرقامٌ عربيّةٌ هنديّة من لوحةٍ عربيّة، ومسافاتٌ
    وشرطاتٌ وأقواس، و`00` مكانَ `+`. ولا يُخمَّن مفتاحُ بلدٍ لرقمٍ محلّيّ
    (`079…`): الزائرُ قد يكون من أيّ بلد، ورقمٌ بمفتاحٍ مختلَقٍ أسوأُ من رقمٍ
    كما كُتب — فالمستشارُ يسأل عنه، والمختلَقُ يصل غيرَ صاحبه. */
export function normalizePhone(raw: string): string | null {
  /* والأرقامُ تُحوَّل هنا لا بـ`westernDigits`: هذا الملفُّ يقرؤه الخادمُ أيضا،
     وذاك يستورد بالاسم المستعار `@/` — ولا شيءَ في شيفرة الخادم يستورد به. */
  const latin = raw.replace(/[٠-٩۰-۹]/g, (d) => String(d.charCodeAt(0) - (d.charCodeAt(0) >= 0x06F0 ? 0x06F0 : 0x0660)))
  const s = latin.replace(/[\s\-().]/g, '').replace(/^00/, '+')
  return /^\+?\d{7,15}$/.test(s) ? s : null
}

/** أقصى حجمٍ لنتيجة التشخيص المرسَلة من بابٍ عامّ — والعلّةُ عند `guestSnapshot` (`advisor.service.ts`) */
export const GUEST_SNAPSHOT_MAX_CHARS = 200_000

const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/

/** أخطاءُ النموذج حقلا حقلا — تُقال عند الحقل لا في ذيله، وبقاعدة الخادم نفسِها */
export function contactErrors(v: { name: string; phone: string; email: string }) {
  const phone = v.phone.trim()
  const email = v.email.trim()
  return {
    name: v.name.trim().length < 2 ? 'اكتب اسمك' : null,
    phone: phone && !normalizePhone(phone) ? 'رقم واتساب غير صحيح — اكتبه بالأرقام' : null,
    email: email && !EMAIL_RE.test(email) ? 'صيغة البريد غير صحيحة' : null,
    contact: !phone && !email ? 'اكتب رقم واتساب أو بريدا' : null,
  }
}
