/* سياسة الخصومات — مصدر واحد لكل رقم يُعرض على المتعلم.

   ثلاث طبقات لا تتداخل، وهذا الترتيب هو الذي يُحسب به:
     ١) خصم البناء: يرتفع كلما أضاف دورة إلى مساره. لا كود له ولا شرط —
        جزء من التسعير نفسه.
     ٢) كود واحد فوق الناتج: إما كود التشجيع لأول شراء، وإما كود فئة يُصدَر
        بعد تحقق الأهلية. واحد لا اثنان — تكديس الأكواد يفتح بابا لا نغلقه.
     ٣) لا شيء بعد ذلك.

   ولماذا هنا لا في الصفحة: النسبة تُعرض في بطاقة السعر، وتُطبَّق في نافذة
   الدفع، وتُذكر في نص الأهلية، وتُخصم في الفاتورة. أربعة مواضع — ورقمٌ يفترق
   في أحدها وعدٌ مكسور. */

/* ─────────── ١) خصم البناء ─────────── */

/** أقصى ما يبنيه المتعلم بنفسه. الستة للمسارات الجاهزة المصمَّمة، لا للتركيب. */
export const MAX_BUILT_COURSES = 5

/* السلّم: نسبة الخصم على مجموع أسعار الشعب المفردة، بعدد الدورات.
   صاعدٌ لا يهبط، وثابتٌ عند السقف — فلا تخفض إضافةُ دورةٍ ما يدفعه.
   يحرسه اختبار على مدى الأسعار كله لا على مثال.

   والسقفُ ٣٠٪ بقرار صاحب المنصّة (كان ٢٧٪ ثمّ ٣٥٪): المسارُ الكامل هو المنتجُ
   الذي نريده مشترى، وفرقُه عن جمع الدورات المفردة يجب أن يُرى بالعين لا
   يُحسَب بالورقة. والرقمُ هنا وحده — تقرؤه بطاقةُ السعر والفاتورةُ معا.

   ⚠ **وخفضُ السقف يرفع ما يدفعه المتعلّم** — لأنّ الخصمَ نسبةُ ما لا يُدفع:
   بـ٣٥٪ يدفع ٦٥٪، وبـ٣٠٪ يدفع ٧٠٪. فنزولُ الرقم هنا من ٣٥ إلى ٣٠ رفع سعرَ
   كلّ مسارٍ جاهزٍ ٧٫٧٪ (٣٧٤←٤٠٣ في أرخصها، و٥٦٩←٦١٣ في أغلاها قبل السقف
   المبلغيّ أدناه). يُكتب هنا لأنّ من يقرأ «٣٠ أقلّ من ٣٥» يقرؤه خفضَ سعر،
   وهو عكسُه تماما.

   ورفعُ السقف من ٢٠ لم يكن يكفي وحدَه: القفزةُ تجعل **إضافةَ دورةٍ رخيصةٍ
   إلى أربعٍ غالية تُخفض الإجمالي** (٨٠٠ بـ٢٠٪ = ٦٤٠، وتسعُمئةٍ بـ٣٥٪ = ٥٨٥)
   — فمن زاد دورةً دفع أقلّ، وهو ما يحرسه اختبار «إضافة دورة لا تخفض
   الإجمالي». فرُفعت الدرجاتُ الوسطى معه (٨ · ١٨ · ٢٨) حتّى يبقى الإجمالي
   صاعدا على مدى أسعار الكتالوج كلِّه (١٠٠–٢٠٠). وتبقى كما هي بعد نزول السقف
   إلى ٣٠: نزولُه يقرّب الدرجةَ الأخيرة ممّا قبلها فيزيد الصعودَ أمانا لا
   خطرا. */
const BUILD_LADDER: readonly number[] = [0, 0, 8, 18, 28, 30]

/** نسبة خصم البناء لعدد دورات — صفر لدورة واحدة، وثابتة عند السقف */
export function buildDiscountPct(count: number): number {
  if (count < 1) return 0
  return BUILD_LADDER[Math.min(count, MAX_BUILT_COURSES)] ?? 0
}

/** خطوة السلّم التالية — لتقول له ماذا يكسب بدورة أخرى، أو null عند السقف */
export function nextBuildStep(count: number): { count: number; pct: number } | null {
  if (count >= MAX_BUILT_COURSES) return null
  const next = count + 1
  const pct = buildDiscountPct(next)
  return pct > buildDiscountPct(count) ? { count: next, pct } : null
}

/* وكان هنا سقفٌ ثالث: «لا يتجاوز البناءُ الحر سعرَ المسار الجاهز بالعدد
   نفسه». وُجد ليوفّق بين تسعيرتين مُختلَقتين: سعرِ مسارٍ مقطوع بالعدد
   (٥٠٠/٥٥٠/٦٠٠) ومجموعِ أسعارٍ مقدَّرة بمطابقة كلماتٍ في العناوين. وقد زالت
   الاثنتان: السعر الآن من الشعبة، والمسار الجاهز يُسعَّر بمجموع شعبه ثم
   بالسلّم نفسه — فالسقف صار يقارن الشيء بنفسه. حُذف لأنه لم يعد يحرس شيئا. */

/* ─────────── ١-ب) سقفُ المبلغ — بعد السلّم لا بدلا منه ─────────── */

/** أقصى ما تبلغه سلّةٌ واحدة بعد خصم الباقة. بقرار صاحب المنصّة:
    «إمّا ٣٠٪ أو ٦٠٠، أيّهما أقلّ».

    ولماذا سقفٌ بالمبلغ ومعه سقفٌ بالنسبة: النسبةُ وحدها تترك السعرَ يعلو مع
    الكتالوج — فمساراتٌ أعمقُ غدا تُخرج المسارَ عن المدى الذي أراده. والمبلغُ
    وحدَه يُلغي معنى السلّم لمن يشتري دورتين. فالاثنان معا: السلّمُ يكافئ من
    زاد، والسقفُ يمنع أن يتجاوز المسارُ حدَّه.

    وأثرُه اليوم بندٌ واحد: PW-EMP-005 (٦١٣ ← ٦٠٠). وسائرُ المسارات دونه —
    فهو حارسٌ لما يأتي أكثرُ منه تغييرا لما هو قائم. */
export const MAX_BUNDLE_TOTAL = 600

/** عملةُ السقف. سقفٌ بالمبلغ لا معنى له بلا عملة: «٦٠٠» في عملةٍ أخرى قد
    يكون ضعفَ السعر أو عُشرَه. والكتالوج كلُّه بهذه العملة اليوم، ويحرسه
    `src/tests/commerce/bundle-cap.test.ts` — فإن سُعِّرت دورةٌ بغيرها لم
    يُطبَّق السقفُ عليها بدل أن يُطبَّق خطأً. */
export const MAX_BUNDLE_TOTAL_CURRENCY = 'USD'

/** ما يُقتطع بحكم السقف وحدَه، بعد أن طُبِّق السلّم — وصفرٌ حين لا يُبلَغ.

    ويبقى بندا مستقلّا لا يُدمج في نسبة الباقة: «خصم الباقة ٣٠٪» و«حدّ سعر
    المسار» سببان مختلفان، ودمجُهما في نسبةٍ واحدة يُخرج رقما (٣٣٪ · ٤١٪) لا
    يقابله شيءٌ في السياسة، فيقرؤه المشتري وعدا لا نفي به في سلّةٍ أخرى. */
export function bundleCapDiscount(afterBundle: number, currency: string = MAX_BUNDLE_TOTAL_CURRENCY): number {
  if (currency !== MAX_BUNDLE_TOTAL_CURRENCY) return 0
  return Math.max(0, afterBundle - MAX_BUNDLE_TOTAL)
}

/** تقريبٌ إلى أصغر وحدةٍ في العملة — لا «تدوير جميل» في مبلغٍ يُقتطع.

    وموضعُه هنا لا في `cart-pricing.ts` لأنّ **قاعدتَي تقريبٍ تُخرجان رقمين**:
    كانت الشاشةُ تقرّب إلى الدولار (`Math.round`) والفاتورةُ إلى القرش، فعلى
    مسارٍ مجموعُه ٥٧٥ تعرض الشاشةُ ٤٠٣ وتُصدر الفاتورةُ ٤٠٢٫٥٠. نصفُ دولارٍ
    لا يشتكي منه أحد — لكنّه يثبت أنّ الحسابين اثنان، وما دام اثنين فسيفترقان
    غدا في رقمٍ يُشتكى منه. أمسكه `pathway-price-parity`. */
export const money = (n: number) => Math.round(n * 100) / 100

/** ما يدفعه على مجموعٍ وعدد: السلّمُ ثمّ السقف. مصدرٌ واحدٌ لكلّ شاشةٍ تعرض
    سعرَ باقةٍ قبل الدفع، وللفاتورة نفسِها عبر `cart-pricing.ts`.

    والتقريبُ على المدفوع لا على الخصم: الفاتورة تُصدر بالمدفوع، فتقريبُ
    الخصم ثمّ الطرح يُخرج قرشا لا يظهر في أيّ شاشة ويظهر في الفاتورة. */
export function bundlePayable(separate: number, count: number, currency: string = MAX_BUNDLE_TOTAL_CURRENCY): number {
  const afterBundle = money(separate * (1 - buildDiscountPct(count) / 100))
  return money(afterBundle - bundleCapDiscount(afterBundle, currency))
}

/* ─────────── ٢) أكواد الفئات ─────────── */

export interface DiscountCategory {
  id: string
  label_ar: string
  percentOff: number
  /** ما يُطلب إثباتا — يُقال صراحة قبل أن يراسلنا، لا بعد */
  evidence_ar: string
}

/* الفئات المؤهلة. الكود لا يُنشر: يُصدَر لكل مؤهَّل بعد التحقق، فلا يتسرّب
   خصمُ فئةٍ إلى من ليس منها. ونسبها هنا لا في نص صفحة الشراء.

   وكلُّ فئةٍ باقيةٍ تُطالَب بمستندٍ يُرى — لا إقرارَ ذاتيّا.

   ذهبت «الباحثون والباحثات عن عمل» بقرار صاحب المنصّة: لا خصمَ لها. وكان
   دليلُها «شهادة تعطّل أو **إقرار ذاتي**»، والإقرارُ الذاتيّ ليس تحقّقا —
   يقوله كلُّ أحد فيصير الخصمُ مفتوحا للجميع باسم فئةٍ مغلقة.

   وذهبت «ربّاتُ المنزل» بقرار صاحب المنصّة أيضا: صورةُ الهويّة الشخصيّة لا
   تُثبت الفئةَ — تُثبت الشخصَ وحده، فكان الخصمُ مفتوحا لكلّ من يرسل هويّته
   باسم فئةٍ مغلقة. وموضعُها في البطاقة صار لخصم أوّل شراء: عرضٌ لا يحتاج
   إثباتا، وكودُه يُعلَن لأنّه لكلّ أحدٍ في أوّل مرّة. */
export const DISCOUNT_CATEGORIES: readonly DiscountCategory[] = [
  { id: 'university_student', label_ar: 'طلبة الجامعات والكليات', percentOff: 20, evidence_ar: 'صورة الهوية الجامعية أو إثبات قيد ساري' },
  { id: 'government', label_ar: 'موظفو القطاع الحكومي', percentOff: 15, evidence_ar: 'صورة بطاقة العمل أو تعريف من جهة العمل' },
]

/** أعلى نسبة فئة — تُذكر في الدعوة («حتى ٢٥٪») بلا تعداد الفئات في كل صفحة */
export const MAX_CATEGORY_PCT = Math.max(...DISCOUNT_CATEGORIES.map((c) => c.percentOff))
