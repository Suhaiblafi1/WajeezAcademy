/* فئةُ مسار الكتالوج من عائلة معرّفه — `PW-BIZ-001` ← «قيادة وريادة الأعمال».

   كانت في `data/pathways.ts` وحدَها، وذاك ملفٌّ يقرأ الكتالوجَ والتشخيص فلا يستورده الخادم. ويحتاجها الخادمُ
   ليعرف فئةَ دورةٍ لا مسارَ عامًّا لها (`term-clash.service.ts`). فانتقلت هنا بلا تبعات، و`pathwayCategory`
   يقرؤها بعد المسارات العامّة كما كان. */

export function familyCategory(id: string): string {
  const fam = id.split('-')[1]
  switch (fam) {
    /* العائلاتُ الأربعُ الجديدةُ مع FND/STU لأنّ جمهورَها في ملفّاتِها التعريفيّة
       هو student · early_career · freelancer وأمثالُهم: التصميمُ الجرافيكيُّ
       والداخليُّ حرفتانِ يدخلهما الطالبُ والمستقلُّ قبل الموظّف، وفهمُ النفسِ
       والتعلّمِ يُقصَد لذاتِه لا لترقيةٍ في وظيفة. وENGR وحدَها تسقط إلى
       «موظفون ومختصون» لأنّ جمهورَها مهندسٌ أو مشرفُ موقعٍ في عملٍ قائم. */
    case 'FND':
    case 'STU':
    case 'GRPH':
    case 'INTR':
    case 'PSY':
    case 'EDU':
      return 'أفراد ومهن ناشئة'
    case 'GOV':
      return 'حكومي'
    case 'BIZ':
    case 'AUT':
    case 'LND':
      return 'قيادة وريادة الأعمال'
    default:
      return 'موظفون ومختصون'
  }
}
