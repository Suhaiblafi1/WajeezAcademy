/* مستوى التدريس — دلوان لا خمسة.

   الكتالوج يصف المستوى بنصّ مركّب («تأسيسي–تطبيقي»، «تطبيقي–ممارس»)، وهو دقيق
   للتصميم الأكاديمي ولا يصلح سؤالا للمتقدّم: من يعرف أنه يستطيع تدريس
   «تأسيسي–تطبيقي» ولا يستطيع «تطبيقي–ممارس»؟ فالسؤال دلوان يعرف كلٌّ أيّهما
   يُتقن، والتدرّج الدقيق قرارٌ أكاديمي يقع بعد الاعتماد لا في نموذج تقديم. */

export type TeachLevel = 'أساسي' | 'متقدم'

export const levelBucket = (levelAr: string): TeachLevel =>
  levelAr.includes('متقدم') || levelAr.includes('ممارس') ? 'متقدم' : 'أساسي'
