/* ═══ ساعاتُ الدورة: كم منها مباشرةٌ وكم مسجَّلة ═══

   ─────────── الطلبُ الذي وُلد منه ───────────

   صاحبُ المنصّة (٢٦ سبتمبر ٢٠٢٦): «هل عددُ الساعات للدورة موجودٌ بالعقد؟
   أعتقد أنّه مهمّ… ويختلف بوجود ساعاتٍ مسجّلة».

   وكان الملحقُ (أ) يعدّد عناوينَ الدورات وحدَها: «١. أساسيّاتُ المحاسبة».
   فيوقّع المدرّبُ على تأهيلٍ لدورةٍ لا يعرف حجمَها — ثمّ تُسنَد إليه فيجدها
   ثلاثةَ أضعاف ما قدّر.

   ─────────── ولمَ منفصلتان لا مخصومة ───────────

   التزامُه فيهما **مختلفُ الجنس**: المباشرةُ حضورُه في وقتٍ مضروب، والمسجَّلةُ
   مادّةٌ يُعدّها مرّةً وتُعاد. ووثيقةٌ تُقرأ بعد سنةٍ في نزاعٍ يُسأل فيها «كم
   سلّم؟» — والرقمُ المخصومُ («٢٠ ساعة») لا يُجيب، والمنفصلُ يُجيب.

   ─────────── والمدى بندٌ واحدٌ لا رقمان لكلّ دورة ───────────

   طلب صاحبُ المنصّة «ما بين وبين». وحدّان يُكتبان بيدٍ لكلّ دورةٍ في كلّ عقدٍ
   عملٌ يتكرّر ويُنسى، ويفترق عمّا في الكتالوج أوّلَ تعديل. فالعددُ من
   الكتالوج، ومعه **بندُ تسامحٍ واحدٌ** يقول إنّه تقدير. وهو أصدقُ: الرقمُ
   مصدرُه واحد، والمدى محسوبٌ منه لا مكتوبٌ إلى جانبه.

   ─────────── وما لا يُسكَت عنه ───────────

   مسجَّلةٌ أكثرُ من الإجمالي رقمٌ لا معنى له، ويُقرأ في وثيقةٍ تُوقَّع. فيُردّ
   عند الكتابة لا عند العرض. */

/** نسبةُ التسامح في عدد الساعات — قرارُ صاحب المنصّة (٢٦ سبتمبر ٢٠٢٦) */
export const HOURS_TOLERANCE_PERCENT = 20

export interface CourseHours {
  /** إجماليُّ ساعات الدورة كما في الكتالوج */
  totalHours: number
  /** كم منها مسجَّلة — و`null` تعني «كلُّها مباشرة» */
  recordedHours?: number | null
}

/** ما يمنع حفظَ هذين الرقمَين — و`null` إن صحّا */
export function hoursProblemAr(h: CourseHours): string | null {
  if (!Number.isInteger(h.totalHours) || h.totalHours < 1) {
    return 'ساعاتُ الدورة عددٌ صحيحٌ أكبرُ من صفر'
  }
  const rec = h.recordedHours
  if (rec === null || rec === undefined) return null
  if (!Number.isInteger(rec) || rec < 0) return 'الساعاتُ المسجَّلةُ عددٌ صحيحٌ لا يقلّ عن صفر'
  if (rec > h.totalHours) {
    return `الساعاتُ المسجَّلة (${rec}) أكثرُ من إجمالي ساعات الدورة (${h.totalHours})`
  }
  return null
}

/** الساعاتُ المباشرة — الإجماليُّ ناقصَ المسجَّل */
export function liveHours(h: CourseHours): number {
  return h.totalHours - (h.recordedHours ?? 0)
}

const hourWordAr = (n: number): string =>
  n === 1 ? 'ساعة واحدة' : n === 2 ? 'ساعتان' : `${n} ساعة`

/**
 * سطرُ الساعات كما يُطبَع في الملحق (أ).
 *
 * وبلا ساعاتٍ مسجَّلةٍ يُقال الإجماليُّ وحدَه: «٢٠ ساعة». ولا يُكتب «٢٠ مباشرة
 * + ٠ مسجَّلة» — فصفرٌ يُطبَع في وثيقةٍ يجعل القارئَ يبحث عمّا لا وجودَ له.
 */
export function courseHoursLineAr(h: CourseHours): string {
  const rec = h.recordedHours ?? 0
  if (rec <= 0) return hourWordAr(h.totalHours)
  return `${hourWordAr(h.totalHours)} (${liveHours(h)} مباشرة + ${rec} مسجَّلة)`
}
