/* عنوان الدورة كما يُعرض — «دورة» قبله، والمصطلح الإنجليزي بجانبه لا داخله.
   ------------------------------------------------------------------
   بقرار صاحب المنتج: تُسبق كلُّ دورة بكلمة «دورة» ليعرف القارئ نوع ما أمامه
   قبل أن يقرأ اسمه. وكانت السابقة تُضاف هنا عند العرض وحدها؛ ثمّ كُتبت في
   `title_ar` نفسه عند إعادة تسمية الكتالوج — ليراها من يقرأ الملفّ ومن يستورد
   الجدول لا من يفتح الصفحة فقط. فصارت وظيفة هذه الدالّة الحراسة: تضيفها لما
   لا يحملها، وتتركها لما يحملها. */

/** يُعيد العنوان مسبوقا بـ«دورة»، ولا يكرّرها إن كانت فيه أصلا.

    الحدّ `\b` كان هنا فأخفق صامتا: هو حدُّ كلمةٍ لاتينيّ يعرف [A-Za-z0-9_]
    وحدها، والحرف العربي غير كلميٍّ عنده — فلا حدَّ بين «ة» والفراغ بعدها،
    فيردّ الفحص «لا تبدأ بدورة» على عنوانٍ يبدأ بها. وما دامت العناوين في
    الكتالوج بلا السابقة لم يظهر شيء؛ فلمّا كُتبت «دورة» في `title_ar` نفسه
    صار كلُّ عنوانٍ يُعرض «دورة دورة …» على مئةٍ وواحد. */
export function courseTitleAr(name: string): string {
  const t = name.trim()
  if (!t) return t
  return t === 'دورة' || t.startsWith('دورة ') ? t : `دورة ${t}`
}

/* المصطلح الإنجليزي: يُعرض سطرا ثانويا صغيرا تحت العنوان لا داخله.
   وضعُه بين قوسين في العنوان نفسه يُطيل السطر ويكسر انسيابه في الشاشات
   الضيّقة، ويخلط اتجاهين في نصٍّ واحد. والسطر المستقلّ يُعزَل اتجاهه
   بـdir="ltr" فلا تنقلب فيه الأقواس ولا الأرقام — وهي مصيدة ثنائية الاتجاه
   المعروفة في العربية. */

/** هل للمصطلح قيمة؟ فارغٌ أو مطابقٌ للعربية لا يُعرض */
export function hasTermEn(termEn: string | null | undefined): termEn is string {
  return typeof termEn === 'string' && termEn.trim().length > 1
}
