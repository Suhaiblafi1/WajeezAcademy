/* سعرُ الدورة من عمقها — القاعدةُ التي كانت تُطاع ولا تُكتب.

   ── ما كان ──

   أسعارُ الدورات الـ٨١ مكتوبةٌ رقما رقما في `core-catalog.v2.json`. وهي
   **تُطيع قاعدةً واحدةً بلا استثناءٍ واحد** — لكنّ القاعدةَ لا وجودَ لها في
   الشيفرة. فدورةٌ تُضاف غدا تأخذ سعرَها بخطّ اليد: يصيبه المؤلّفُ أو يخطئه،
   ولا شيءَ يقول أيّهما فعل.

   ── والقاعدة، كما استُخرجت من البيانات لا كما اختُرعت ──

   فُحص كلُّ حقلٍ يصلح مقياسا للعمق، وقوبل بالأسعار القائمة:

     · **المستوى (`level_ar`) والساعات (`total_hours`)**: يفسّران الأسعار
       الـ٨١ كلَّها. استثناءات: صفر.
     · **عددُ الوحدات**: مطابقٌ تماما للساعات (٤ وحدات ↔ ٨ ساعات · ٨ ↔ ١٦).
       لا يضيف شيئا، فلا يدخل.
     · **ساعاتُ التطبيق**: مطابقةٌ كذلك. لا تدخل.
     · **الساعاتُ الموجَّهة والذاتيّة**: **تختلف داخل السعر الواحد** — سعرُ
       ١٧٥ يضمّ موجَّهةً ١٫٥ و٢ و٢٫٥ و٣. فإدخالُها يغيّر أسعارا قائمةً بلا
       سبب، فلا تدخل.

   ── وما تفعله هذه الوحدة وما لا تفعله ──

   لا تغيّر سعرا. تُعلن القاعدةَ فحسب، ويحرس `course-pricing.test.ts` أن
   كلَّ سعرٍ في الكتالوج يطيعها — فمخالفةٌ واحدةٌ تُسقط الفحص، سواءٌ أخطأ
   المؤلّفُ سعرا أم قرّر صاحبُ المنصّة قاعدةً جديدةً ونسي أن يكتبها هنا. */

/** أساسُ السعر بالمستوى — درجةٌ كلَّ ٢٥ دولارا */
export const LEVEL_BASE_PRICE: Readonly<Record<string, number>> = {
  'تأسيسي': 100,
  'تأسيسي–تطبيقي': 125,
  'تطبيقي': 150,
  'ممارس': 175,
}

/** الساعاتُ التي تُعدّ دورةً مضاعفةَ الطول — وما دونها الطولُ القياسيّ */
export const LONG_COURSE_HOURS = 16

/** ما يُضاف للدورة المضاعفة — درجةٌ واحدةٌ كدرجة المستوى، فلا سلّمان */
export const LONG_COURSE_SURCHARGE = 25

/** حدُّ السعر المُعلَن لأيّ دورةٍ مفردة — بقرار صاحب المنصّة */
export const COURSE_PRICE_RANGE = { min: 100, max: 200 } as const

/** سعرُ القائمة من عمق الدورة — أو null حين لا يُعرف مستواها.

    و`null` لا صفر: صفرٌ يُقرأ «مجّانا» في كلّ شاشةٍ يمرّ بها، و«لا سعرَ
    محسوبا» حالةٌ يجب أن تُقال لا أن تُسعَّر. */
export function coursePriceFromDepth(levelAr: string, totalHours: number): number | null {
  const base = LEVEL_BASE_PRICE[levelAr.trim()]
  if (base === undefined) return null
  return base + (totalHours >= LONG_COURSE_HOURS ? LONG_COURSE_SURCHARGE : 0)
}
