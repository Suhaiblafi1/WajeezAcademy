/** مجالُ الدورة المعرفيّ من معرّفها — «أخرى» لعائلةٍ لم تُسمَّ بعد */
export function courseDomain(courseId: string): string {
  const family = courseId.split('-')[1] ?? ''
  return COURSE_DOMAIN_AR[family] ?? 'أخرى'
}

/* الاسمُ العربيُّ ← كلماتُه. يُبنى من السجلَّين معا مرّةً واحدة، فلا تُكتب
   الأسماءُ مرّتين ولا تُبحَث العائلةُ في كلّ نداء. */
const KEYWORDS_BY_DOMAIN_AR = new Map(
  Object.entries(COURSE_DOMAIN_AR)
    .map(([family, ar]) => [ar, COURSE_DOMAIN_KEYWORDS_AR[family]] as const)
    .filter(([, words]) => Boolean(words)),
)

/** كلماتُ المجال المفتاحيّة — و`''` لمجالٍ لا كلماتِ له («أخرى») */
export function courseDomainKeywords(domainAr: string): string {
  return KEYWORDS_BY_DOMAIN_AR.get(domainAr) ?? ''
}

/** سطرُ القائمة كما يُقرأ: المجالُ ثمّ كلماتُه — واسمُه وحدَه إن لم تكن له كلمات */
export function courseDomainLabel(domainAr: string): string {
  const words = courseDomainKeywords(domainAr)
  return words ? `${domainAr} — ${words}` : domainAr
}

/** العائلاتُ المسمّاةُ كلُّها — يقرؤها الحارسُ ليمنع عائلةً بلا كلمات */
