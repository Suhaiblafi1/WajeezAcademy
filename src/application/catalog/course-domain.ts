/** عنوانُ عائلةٍ بمفتاحها — للحارس وحدَه، فالشاشاتُ تعرف الاسمَ لا العائلة */
export function courseDomainByFamily(family: string): string {
  return COURSE_DOMAIN_AR[family] ?? ''
}
