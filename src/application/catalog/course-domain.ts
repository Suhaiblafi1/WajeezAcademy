/** كلماتُ عائلةٍ بمفتاحها — للحارس وحدَه، فالشاشاتُ تعرف الاسمَ لا العائلة */
export function courseDomainKeywordsByFamily(family: string): string {
  return COURSE_DOMAIN_KEYWORDS_AR[family] ?? ''
}
