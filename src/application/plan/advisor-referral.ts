/* إحالة المستشار البشريّ — عَلَمٌ يسافر من التشخيص إلى صفحة المسار.

   حين تنخفض ثقة المحرّك في التوصية، أو يطلب المتعلّم استشارةً صراحةً، تُعرض
   له دعوةٌ لجلسةٍ مع مستشارٍ بشريّ قبل أن يدفع. وكانت تعيش في شاشة النتيجة
   وحدها؛ فلمّا صار التشخيص ينتقل مباشرةً إلى صفحة المسار — كما طلب صاحب
   المنتج: «لا داعي للصفحات التي قبلها» — سقطت تلك الشاشة.

   وإسقاطُ الإحالة معها ليس تفصيلا في العرض: هو أن يدفع مَن كان ينبغي أن
   يُستشار أوّلا. فالعَلَم يُكتب عند الاعتماد ويُقرأ في صفحة المسار.

   وsessionStorage لا localStorage: الإحالة تخصّ هذا التشخيص لا كلّ زيارة
   قادمة — تشخيصٌ جديد واثقٌ يمسحها، وإغلاق المتصفّح ينهيها. */

export const NEEDS_ADVISOR_KEY = 'wajeez_needs_advisor'

/** هل يحتاج صاحب هذه الجلسة إحالةً لمستشار بشريّ؟ */
export function needsAdvisorReferral(): boolean {
  try {
    return sessionStorage.getItem(NEEDS_ADVISOR_KEY) === '1'
  } catch {
    return false // خصوصيّة صارمة — لا إحالة، ولا عطب
  }
}
