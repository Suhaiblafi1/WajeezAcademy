/* ═══ جودةُ المحتوى النظريّ — ما تقرؤه المنصّةُ في متن المحور (١١ أكتوبر ٢٠٢٦) ═══

   سؤالُ صاحب المنصّة: «حسِّن جودةَ محتواهم وقدّم توصياتٍ إن أمكن». وكانت بطاقةُ
   المعايير (`plan-scorecard.ts`) تقيس هيكلَ الخطّة ومواعيدَها ولا تقرأ سطرا ممّا
   كُتب. فخُيّر بين فحصٍ بالقواعد ومراجعةٍ بالذكاء الاصطناعيّ، فاختار **القواعدَ
   أوّلا**: مجّانيّةٌ فوريّةٌ تقول الشيءَ نفسَه كلَّ مرّة.

   فيُقرأ المتنُ المكتوبُ على سياسة التأليف (`docs/AUTHORING-POLICY.md`) في ثلاثة:

   ① **العمق** (§٣): فكرةٌ تُشرح بـ`MIN_THEORY_WORDS` كلمةً على الأقلّ، ومثالٌ
      محلول، وخطأٌ شائعٌ يُنبَّه عليه — «أنفعُ ما في الدرس، وأوّلُ ما يُحذف».
   ② **اللغة** (§٤ ١، ٢، ٧، ٨): الحشو، والتعريفُ المعجميُّ في رأس الفقرة، والمبنيُّ
      للمجهول حيث يصحّ الفاعل، والنداءُ بـ«عزيزي المتعلّم».
   ③ **الأرقامُ والوعود** (§٤ ٤، ٩): نسبةٌ بلا مصدرٍ ولا سنةٍ في جملتها، ووعدٌ
      بوظيفةٍ أو دخلٍ خارجَ المنصّة.

   ── نصيحةٌ لا حاجز ──

   كلُّها `advice` في البطاقة: تُقال بسببها وبما يُصلحها، ولا تمنع إرسالا — على
   قاعدة «لا إجبارَ على فعل». فالفحصُ بالنمط يُخطئ أحيانا (كلمةُ «مثال» لا تصنع
   مثالا)، والحكمُ على التعليم نفسِه يبقى للمعتمِد (§١١).

   ── وما لا يُقرأ يُقال ──

   متنٌ مرفوعٌ ملفّا (PDF أو Word) لا تقرؤه المنصّةُ هنا؛ فيُعدّ ويُذكر في المقيس
   ولا يُدان. والنصُّ يُوحَّد (`normalizeAr`) قبل المطابقة: من كتب بلا تشكيلٍ أو
   بهمزةٍ غيرِ همزتنا يُطابَق كمن كتبها كما في القائمة. */

import { normalizeAr } from '../text/search-ar'
import { RED_PHRASES, proseOf } from '../content/red-rules'

/** أقلُّ ما تُشرح به فكرةُ المحور — حدُّ «الفكرة» في بنية الدرس (§٣: ٢٥٠–٤٠٠ كلمة) */
export const MIN_THEORY_WORDS = 250

export interface QualityModule {
  moduleId: string
  bodyAr?: string | null
  bodyFileKey?: string | null
  outcomeAr?: string | null
  activityAr?: string | null
}

export interface ContentQuality {
  /** محاورُ قُرئ متنُها المكتوب */
  read: number
  /** محاورُ متنُها ملفٌّ مرفوعٌ لا يُقرأ هنا */
  files: number
  depth: string[]
  style: string[]
  claims: string[]
}

interface Phrase { say: string; match: string; fixAr: string }

const phrase = (say: string, fixAr: string): Phrase => ({ say, match: normalizeAr(say), fixAr })

/* ═══ وشُدّت بعد أوّل مراجعةٍ على خططٍ حقيقيّة (١١ أكتوبر ٢٠٢٦) ═══

   قُرئت بها أربعُ خططٍ مرسَلة، وراجعها قارئٌ سطرا سطرا، فأخطأت في الاتّجاهين:
   · **فاتها** التعريفُ بصيغة «X هو/هي…» («رحلةُ المستفيد هي مجموعةُ المراحل»)، والفاتحةُ
     «في هذا المحور ستتعرّف على» في كلّ محور، و«من المهمّ أن» تتكرّر، و«عزيزي المدير».
   · **وأنذرت بالباطل**: هدفٌ («رفعُ الرضا إلى 85%») عُدّ رقما بلا مصدر، و«خطأ» طابقت
     «خطاب» و«تجنّبها» عُدّت خطأً شائعا — فالمطابقةُ بالكلمة التامّة (`wordRe`) لا بجزء كلمة. */

/** حروفُ الكلمة العربيّة — ما يُحدّ به أوّلُ الكلمة وآخرُها */
const AR = 'ء-ي'
/** كلمةٌ تامّةٌ في نصٍّ موحَّد، بسوابقها (و ف ب ك ل ال) ولواحقِ الضمير — لا جزءَ كلمةٍ أخرى */
function wordRe(stems: readonly string[]): RegExp {
  const alt = stems.map(normalizeAr).join('|')
  return new RegExp(`(?<![${AR}])(?:[وف]?(?:[بكل]?ال|لل|[بكل])?)(?:${alt})(?:ه|ها|هم|هن|ك|كم|نا|ا|ات|ين|ون)?(?![${AR}])`)
}

/** النداء — القاعدةُ ٨: «عزيزي/عزيزتي» قبل أيّ صفة، و«أخي/أختي» قبل الكريم ونحوِه لا قبل «الأكبر» */
const ADDRESS_RE = /(?:^|[^ء-ي])((?:عزيزي|عزيزتي)\s+ال[ء-ي]+|(?:أخي|أختي|اخي|اختي)\s+(?:الكريم|الكريمة|المتعلم|المتعلمة|المشارك|المشاركة|القارئ|القارئة))/

/* «يُعرَّف» وحدَها لا تُطابَق موحَّدةً: بلا تشكيلٍ هي «يعرف» — «لا يعرف العميلُ ما يريد»
   جملةٌ سليمة. فالتعريفُ المعجميُّ يُقرأ بموضعه (رأسُ الفقرة) لا بكلمته. والنداءُ بـ`ADDRESS_RE`،
   و«في هذا الدرس سوف» بـ`OPENER_RE` بوجوهها كلِّها — فلا تُقال مرّتين. */
const STYLE: Phrase[] = [
  ...RED_PHRASES.filter((p) => !normalizeAr(p).startsWith('يعرف') && !/عزيزي|أخي/.test(p) && !p.startsWith('في هذا'))
    .map((p) => phrase(p, 'حشوٌ — احذفها وقل المعنى مباشرةً')),
  phrase('يُنصَح بأن', 'سمِّ الفاعل: «انصح فريقَك بأن…»'),
  phrase('من المستحسن أن', 'قلها أمرا بفاعله: «افعل كذا لأنّ…»'),
]

/** فاتحةُ «في هذا المحور ستتعرّف/سنتعلّم…» — صيغةُ «في هذا الدرس سوف نتعلّم» الممنوعة (القاعدةُ ٢) بكلّ وجوهها */
const OPENER_RE = /في هذا (?:المحور|الدرس|الجزء|القسم|الفصل|اللقاء) (?:سوف|ست|سن|نت|تت)[ء-ي]*/
/** «من المهمّ أن» مرّةً تُحتمل، وتكرارُها حشو */
const IMPORTANT_RE = /(?:^| )[وف]?(?:من المهم|من الضروري) (?:جدا )?ان/g
/** ما يُعدّ في المحور الواحد تكرارا */
export const IMPORTANT_REPEAT = 2

/** وعودٌ خارجَ المنصّة — القاعدةُ ٩ */
const PROMISES: Phrase[] = [
  'ستحصل على وظيفة', 'وظيفة مضمونة', 'نضمن لك', 'راتبك سيتضاعف', 'سيتضاعف راتبك', 'دخل مضمون', 'ستصبح مليونيرا',
].map((p) => phrase(p, 'وعدٌ لا يقيسه المحور — قل ما يقدر عليه المتعلّمُ بعده'))

const EXAMPLE = wordRe(['مثال', 'امثله', 'مثلا', 'لنفترض', 'نفترض', 'افترض', 'تخيل', 'لنتخيل', 'حاله عمليه', 'دراسه حاله'])
const MISTAKE = wordRe([
  'خطا', 'اخطاء', 'اخطائ', 'خاطئ', 'خاطئه', 'خاطئا', 'يخطئ', 'تخطئ', 'نخطئ', 'يخطئون', 'مغالطه', 'سوء فهم',
  'لا تفترض', 'يظن كثيرون', 'يعتقد كثيرون', 'يظن البعض', 'يعتقد البعض', 'من الشائع', 'الشائع ان',
])
const PERCENT = /[%٪]|في المئة|في المائة|بالمئة|بالمائة/
/** ما يدلّ على مصدرٍ في الجملة — سنةٌ (§٤-٤: «مصدرُه وسنتُه في الجملة نفسِها»)، أو «المصدر:» صريحا.
    و«تؤكّد أحدثُ الدراسات» بلا سنةٍ ليست مصدرا — هي ما تمنعه القاعدة */
const SOURCE = [/\b(19|20)\d\d\b/, /(?:المصدر|المرجع)\s*:/]
/** ما ليس إحصاءً: هدفٌ يُطلب، أو افتراضٌ في مثال، أو شرطٌ على إجابة القارئ */
const NOT_A_CLAIM = wordRe([
  'هدف', 'مستهدف', 'معيار', 'رفع', 'خفض', 'على الاقل', 'لا تقل', 'لا يقل', 'لا يزيد', 'لا تزيد', 'بحد ادنى', 'خصم',
  'افتراض', 'نفترض', 'لنفترض', 'مثلا', 'مثال', 'مثل', 'اذا كانت', 'اذا كان', 'اذا كنت', 'اجاباتك',
])

const words = (s: string) => s.trim().split(/\s+/).filter(Boolean).length
const clip = (s: string) => {
  const t = s.replace(/\s+/g, ' ').trim()
  return t.length > 60 ? `${t.slice(0, 59)}…` : t
}
/** بلا علامات الترقيم — فلا تفصل الفاصلةُ «في هذا المحور، ستتعرّف» عن مطابقتها */
const bare = (s: string) => normalizeAr(s).replace(/[،,؛;:.!؟?«»"'()[\]–—…-]/g, ' ').replace(/\s+/g, ' ').trim()

/** رأسُ السطر بلا ترقيمه: «- » و«1. » و«أولًا: » */
const LEAD = /^\s*(?:[-*•▪]\s*|[0-9٠-٩]+\s*[.)-]\s*|(?:أولًا|أولا|ثانيًا|ثانيا|ثالثًا|ثالثا|رابعًا|رابعا|خامسًا|خامسا|سادسًا|سادسا|سابعًا|سابعا|ثامنًا|ثامنا)\s*[:،.-]?\s*)/
/** مبتدأٌ لا يُعرَّف به شيء: «السببُ هو…» و«الهدفُ هو…» خبرٌ لا تعريف */
const NOT_DEFINED = new Set(['السبب', 'الهدف', 'المشكله', 'الحل', 'النتيجه', 'السؤال', 'الجواب', 'الفرق', 'المهم', 'الاهم', 'الخطوه', 'الفكره', 'الغايه', 'المطلوب', 'الدرس', 'المحور'].map(normalizeAr))
/** أدواتٌ لا تكون مبتدأً يُعرَّف */
const NOT_SUBJECT = new Set(['ليس', 'ليست', 'لكن', 'ان', 'قد', 'لا', 'ما', 'هذا', 'هذه', 'ذلك', 'تلك', 'كل', 'بعض', 'اي', 'لان', 'حين', 'عندما', 'اذا'].map(normalizeAr))
/** رأسُ الخبر في التعريف المعجميّ — «عمليّةٌ» و«مجموعةٌ» و«قدرةٌ»… */
const DEF_HEAD = wordRe(['عمليه', 'مجموعه', 'مجموع', 'قدره', 'مفهوم', 'مصطلح', 'اسلوب', 'طريقه', 'فن', 'علم', 'نوع', 'منهج', 'نهج', 'اداه', 'نظام', 'عباره عن', 'ممارسه', 'مهاره', 'حاله', 'نشاط', 'تقييم', 'اساس'])

/** السطرُ يبدأ بتعريفٍ معجميّ — «يُعرَّف X بأنّه…»، أو «X هو/هي عمليّةُ…» و«X هم الأفرادُ الذين…» */
export function definitionOpener(line: string): string | null {
  /* العنوانُ ليس فقرة، وعلامةُ التغليظ ليست من الجملة */
  if (/^\s*#/.test(line)) return null
  const head = line.replace(/^[\s*_]+/, '').replace(LEAD, '').replace(/^[\s*_]+/, '')
  const first = (head.split(/(?<=[.!؟?:])\s/)[0] ?? '').trim()
  const n = normalizeAr(first)
  if (/^(و)?(يعرف|تعرف)\s/.test(n) && /(بانه|بانها|على انه|على انها)/.test(n)) return first
  const m = /^((?:\S+\s+){0,3}?\S+)\s+(?:هو|هي|هم)\s+(.+)$/.exec(n)
  if (!m) return null
  const subject = m[1].split(' ')
  /* المبتدأُ اسمٌ معرَّف أو مضافٌ إلى معرَّف — لا أداةٌ («ليست الحاجةُ هي…») ولا معطوفٌ يُكمل ما قبله («والمرحلةُ الثانية هي…») */
  if (NOT_DEFINED.has(subject[0]!) || NOT_SUBJECT.has(subject[0]!) || /^[وف]ال/.test(subject[0]!)) return null
  if (!/^(?:ال|[^\s]+\s+ال)/.test(m[1])) return null
  const pred = m[2]
  /* «هي التي…» توكيدٌ لا تعريف: «المرحلةُ الثانية هي التي تصدّق الأولى» */
  if (/^(?:ان|ما|من|ليس|كذلك|ايضا|الذي|التي|الذين)(?: |$)/.test(pred)) return null
  const lead = pred.split(' ').slice(0, 3).join(' ')
  return DEF_HEAD.test(lead) || /(?:^| )(?:الذي|التي|الذين|اللذين|اللتين)(?: |$)/.test(pred) ? first : null
}

export function contentQuality(modules: readonly QualityModule[]): ContentQuality {
  const out: ContentQuality = { read: 0, files: 0, depth: [], style: [], claims: [] }
  modules.forEach((m, i) => {
    const at = `المحور ${i + 1}`
    const raw = (m.bodyAr ?? '').trim()
    if (!raw) {
      if ((m.bodyFileKey ?? '').trim()) out.files++
      return
    }
    out.read++
    const body = proseOf(raw)
    const flat = normalizeAr(body)

    /* ① العمق */
    const w = words(body)
    if (w < MIN_THEORY_WORDS) out.depth.push(`${at}: ${w} كلمةً — اشرح الفكرةَ في ${MIN_THEORY_WORDS} كلمةً على الأقلّ`)
    if (!EXAMPLE.test(flat)) out.depth.push(`${at}: بلا مثالٍ محلول — أضف حالةً من سوقٍ عربيّ تُحلّ خطوةً خطوة`)
    if (!MISTAKE.test(flat)) out.depth.push(`${at}: لا يسمّي خطأً شائعا — اكتبه في فقرةٍ باسمه: ما يفعله المبتدئ، ولماذا يبدو صحيحا، وكيف يتجنّبه`)

    /* ② اللغة — في المتن وفي المخرَج والتطبيق، فكلُّها يقرؤها المتعلّم */
    const all = [body, proseOf(m.outcomeAr ?? ''), proseOf(m.activityAr ?? '')].join('\n')
    const allFlat = normalizeAr(all)
    const seen = new Set<string>()
    for (const p of STYLE) {
      if (seen.has(p.match) || !allFlat.includes(p.match)) continue
      seen.add(p.match)
      out.style.push(`${at}: «${p.say}» — ${p.fixAr}`)
    }
    const address = ADDRESS_RE.exec(all.replace(/[\u064B-\u0652\u0670\u0640]/g, ''))
    if (address) out.style.push(`${at}: «${address[1]}» — خاطِب المتعلّمَ مباشرةً بلا نداء`)
    const plain = bare(all)
    if (OPENER_RE.test(plain)) {
      out.style.push(`${at}: «في هذا المحور ستتعرّف على…» — احذفها؛ العنوانُ يقول ما في المحور، فابدأ بموقفٍ أو سؤال`)
    }
    const important = plain.match(IMPORTANT_RE)?.length ?? 0
    if (important >= IMPORTANT_REPEAT) {
      out.style.push(`${at}: «من المهمّ أن» ${important} مرّات — قل الأمرَ مباشرةً: «افعل كذا» بدل «من المهمّ أن تفعل كذا»`)
    }
    const definition = body.split('\n').map(definitionOpener).find(Boolean)
    if (definition) {
      out.style.push(`${at}: فقرةٌ تبدأ بتعريفٍ معجميّ «${clip(definition)}» — ابدأ بموقفٍ أو مشكلةٍ ثمّ سمِّ المفهوم`)
    }

    /* ③ الأرقامُ والوعود */
    /* سطرٌ واحدٌ للمحور بعدد ما فيه: النسبةُ في مثالٍ محلولٍ حسابٌ لا إحصاء («ردٌّ من تسعةٍ وعشرين
       = سبعةٌ في المئة»)، ولا تُفرَز من الإحصاء بنمط — فيُقال الفرقُ ويقرّر كاتبُها */
    const unsourced = all.split(/(?<=[.!؟?])\s+|\n+/).filter((s) => {
      if (!PERCENT.test(s)) return false
      const n = normalizeAr(s)
      return !SOURCE.some((r) => r.test(n)) && !NOT_A_CLAIM.test(n)
    })
    if (unsourced.length) {
      const more = unsourced.length > 1 ? ` و${unsourced.length - 1} غيرُها` : ''
      out.claims.push(`${at}: نسبةٌ بلا مصدرٍ ولا سنة «${clip(unsourced[0]!)}»${more} — ما كان حقيقةً عن الناس أو السوق فاذكر مصدرَه وسنتَه في الجملة نفسِها، وما كان حسابا في مثالٍ يبقى كما هو`)
    }
    for (const p of PROMISES) {
      if (allFlat.includes(p.match)) out.claims.push(`${at}: «${p.say}» — ${p.fixAr}`)
    }
  })
  return out
}
