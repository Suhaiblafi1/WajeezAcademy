/* الحالاتُ التي يجوز حذفُ طلبها نهائيّا — مصدرٌ واحدٌ للشاشة والخادم.

   ── لماذا القائمةُ هنا لا في الخادم وحدَه ──

   تُقرأ في موضعين: الخادمُ يرفض بها ما ليس منتهيا، والشاشةُ تقرّر بها هل
   تعرض «احذفه» أم «ارفضه ثمّ احذفه». وقائمتان لشيءٍ واحدٍ تفترقان يوما —
   فيَعِد الزرُّ بحذفٍ يرفضه الخادم، أو يُخفى بابٌ مفتوح. وهو الدرسُ نفسُه
   الذي جُمعت لأجله `approval.ts` و`rubric.ts` من قبل.

   ── ولماذا هذه الأربعُ وحدَها ──

   `draft` و`email_verification_pending`: طلبٌ لم يُرسَل أصلا، ولا قرارَ فيه
   يُحفَظ. و`rejected` و`withdrawn`: قرارٌ وقع وانتهى الطلبُ عنده.

   وللردّ بابُ رجوعٍ واحدٌ منذ ١٩ سبتمبر ٢٠٢٦ («تراجَعْ عن الرفض» يعيده إلى
   المراجعة)، وهو لا يُخرجه من هذه القائمة: المحوُ يقع على المردود **وهو
   مردود**، ومن نُقض ردُّه صار «قيد المراجعة» — فيخرج بحالته لا باستثناء.

   و`active` و`onboarding` و`suspended`: صاحبُها مدرّبٌ له ملفّ.

   ── ولماذا دخلت الثلاثُ بعد أن كانت خارجا (١٤ سبتمبر ٢٠٢٦) ──

   كان يُقال هنا: «صاحبُها صار مدرّبا وله ملفٌّ وعقود، والقاعدةُ نفسُها ترفض
   (`TrainerProfile` بلا `Cascade` عمدا)».

   وقال صاحبُ المنصّة: «أبلغك أنّنا لم نتعاقد مع أحدٍ إطلاقا، وأوّلُ شخصٍ
   حقيقيٍّ هي المدرّبةُ الأولى. فاسمح لي أن أحذف أيَّ شخصٍ آخرَ أبديّا
   وإلغاءِ كلِّ شيءٍ يتعلّق بحسابه — وهذا قراري أتحمّل مسؤوليّته».

   **ولم يكن أمامها بابٌ آخر أصلا**: خريطةُ الانتقالات تجعل `active` تصل إلى
   `suspended` وحدَها، و`suspended` تعود إلى `active`. فلا سبيلَ من إحداهما
   إلى `rejected` ولا إلى `withdrawn` — أي أنّ «ارفضه أوّلا ثمّ احذفه» طريقٌ
   لا يُسلَك لمدرّبٍ معتمَد. فإبقاؤها خارجَ القائمة كان يعني **لا حذفَ أبدا**،
   لا «حذفا بعد خطوة».

   والقاعدةُ لم تعد ترفض: `purge` تحذف الملفَّ في المعاملة نفسِها. والحارسُ
   الباقي ليس عن سجلّنا بل عمّا بيد متعلّم — شهادةٌ صادرةٌ رقمُها معلَن.

   وما عداها **قيدُ نظر**: بينه وبين المنصّة قرارٌ لم يُبَتّ، وحذفُه يمحو
   طلبَ إنسانٍ ينتظر جوابا. ومن أراد حذفَه رفضه أوّلا — فيصير الرفضُ فعلا
   مسجَّلا لا صمتا. */

export const PURGEABLE_STATUSES = [
  'draft',
  'email_verification_pending',
  'rejected',
  'withdrawn',
  /* ومدرّبٌ معتمَدٌ: يُحذف مباشرةً، إذ لا طريقَ له إلى حالةٍ منتهية */
  'active',
  'onboarding',
  'suspended',
] as const

export type PurgeableStatus = (typeof PURGEABLE_STATUSES)[number]
