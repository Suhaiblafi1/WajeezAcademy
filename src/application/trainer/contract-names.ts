/* ═══ الاسمان: ما طُبع في الوثيقة وما وُقّع به ═══

   ─────────── البلاغُ الذي وُلد منه ───────────

   صاحبُ المنصّة (٢٦ سبتمبر ٢٠٢٦): «اسم الطرف الثاني يجب أن يكون مطابقا
   للهوية». والوثيقةُ تُطبَع باسمٍ، ويكتب الموقِّعُ اسمَه عند التوقيع —
   واثنانِ لا يُقابَلان في شاشةٍ لا يُعرف افتراقُهما إلّا في نزاع.

   ─────────── ولمَ لا يُقابَلان حرفا بحرف ───────────

   الاسمُ العربيُّ يُكتب بوجوهٍ لا تختلف بها الهويّة: همزةُ القطع تُكتب ألفا
   («أحمد»/«احمد»)، والتاءُ المربوطةُ هاءً، والألفُ المقصورةُ ياءً، والتشكيلُ
   يُلقى ويُثبَت. فمقابلةٌ حرفيّةٌ تصرخ على كلِّ توقيعٍ صحيحٍ تقريبا —
   وتنبيهٌ يصرخ دائما لا يُقرأ، فيُتجاوَز الحقيقيُّ معه.

   فيُقابَل الاسمان **مطبَّعَين** بما تُطبَّع به أسماءُ البحث في المنصّة
   (`normalizeAr`)، وتُطوى المسافاتُ كلُّها بعده: «عبد الله» تُكتب موصولةً
   ومفصولةً في الهويّة نفسِها، و`normalizeAr` تطوي المتكرّرَ منها ولا تحذفه.
   ولا يُعلَن الفرقُ إلّا إذا بقي بعد ذلك — ومعناه حينئذ: كلمةٌ زائدةٌ أو
   ناقصةٌ أو اسمٌ آخر. وهذا ما يُنظر فيه.

   ─────────── وما لا يقوله هذا الملفّ ───────────

   لا يقول «ارفضْ» ولا «اعتمِدْ»: الحكمُ لمن بيده وثيقةُ الهويّة يقابلها
   بعينه. وهذا يقول **أنّ ثَمَّ ما يُنظَر فيه** فحسب. */

import { normalizeAr } from '../text/search-ar'

export interface ContractNameFacts {
  /** الاسمُ المطبوعُ في متن الوثيقة — الطرفُ الثاني كما يقرؤه قارئُها */
  documentNameAr: string | null
  /** ما كتبه الموقِّعُ بيده عند التوقيع */
  signedNameAr: string | null
}

export type NameMatch = 'unsigned' | 'same' | 'differs'

/** أيفترق الاسمُ الموقَّعُ به عن الاسم المطبوع؟ — بعد التطبيع لا قبله.
 *
 *  و`unsigned` حالةٌ ثالثةٌ لا `same`: ما لم يُوقَّع لا اسمَ موقَّعا به،
 *  فقولُ «مطابق» فيه كذبٌ صغيرٌ يُقرأ تطمينا. */
/** التطبيعُ نفسُه ثمّ طيُّ المسافات — و«عبدالله» و«عبد الله» اسمٌ واحد */
const fold = (s: string) => normalizeAr(s).replace(/\s+/g, '')

export function nameMatch(c: ContractNameFacts): NameMatch {
  const signed = (c.signedNameAr ?? '').trim()
  if (signed === '') return 'unsigned'
  const doc = (c.documentNameAr ?? '').trim()
  if (doc === '') return 'differs'
  return fold(doc) === fold(signed) ? 'same' : 'differs'
}
