/* ═══ أبوابُ بوّابة المدرّب — أيُّها يُفتح قبل الاعتماد النهائيّ ═══

   ─────────── العطبُ الذي وُلد منه هذا الملفّ ───────────

   `course-proposal.service.ts` كان يردّ كلَّ من ليست حالتُه `active`. أي أنّ
   المدرّبَ **لا يستطيع تقديمَ دورةٍ واحدةٍ قبل أن يصير مدرّبا كاملا** — فالبابُ
   الذي يُراد منه أن يسبق الاعتمادَ لا يُفتح إلّا بعده، وهي المصيدةُ بعينها.

   والعرضُ المشروط (قرارُ صاحب المنصّة، ٢٣ سبتمبر ٢٠٢٦) يقوم على أن يرفع
   موادَّه **قبل** أن يُعتمَد: يوقّع عرضَه فتُفتح بوّابتُه، فيرفع في مهلته، فإذا
   قُبلت موادُّه صار نشطا. فبلا فتحِ هذا الباب لا معنى للطور كلِّه.

   ─────────── ومزلقٌ يُسمّى صراحةً ───────────

   `trainer-change.service.ts` يردّ كذلك كلَّ حالةٍ غير `active` بـ«حسابك
   موقوف». فبلا توسعتِه **يوقّع المدرّبُ عرضَه ثمّ يُطرد من بوّابته** برسالةٍ
   تقول إنّ حسابَه موقوف — سهلُ الغفلة، قاتلٌ إن غُفل عنه.

   ─────────── وما لا يُفتح، ولمَ ───────────

   ما يلمس مالا أو شعبةً أو ظهورا عامّا يبقى للنشط وحدَه: كتابةُ الحساب
   البنكيّ، وقبولُ عروض الإسناد، والإسنادُ إلى شعبةٍ فيها متعلّمون. والبندُ
   2-11 من عرضه يقول ذلك بنصّه: «ولا يستحق المدرب قبل تحقق هذا الشرط إسناد
   شعبة، ولا أتعابا، ولا ظهورا». فما في الشيفرة هو ما في الوثيقة الموقَّعة.

   و**القراءةُ** مفتوحةٌ حيث كانت: يرى «مستحقّاتي» صفرا طوالَ الطور كما أراد
   صاحبُ المنصّة — فيعرف أنّ البابَ موجودٌ وأنّه لم يُفتح بعد.

   ─────────── ولمَ وحدةٌ خالصةٌ لا سطرٌ في كلّ خدمة ───────────

   ثمانيةُ مواضعَ في الخادم تسأل السؤالَ نفسَه، وكلُّها كانت تكتب الشرطَ
   بيدها. فمن أراد فتحَ بابٍ عدَّل موضعا ونسي سبعة، ومن قرأ سطرا لم يعرف
   أعن عمدٍ أُغلق أم عن نسخٍ. فصار الشرطان مسمَّيَين هنا، وتُسأل الدالّةُ. */

/** بابان لا أكثر: ما يُعمَل فيه على الموادّ، وما لا يقع إلّا لمدرّبٍ نشط */
export type PortalDoor = 'materials' | 'active_only'

/* ═══ من يعمل على موادّه ═══

   `onboarding` هو طورُ العرض المشروط: وقّع، وبوّابتُه مفتوحة، ويرفع. و`active`
   يبقى فوقَه — فمن اعتُمد يُضيف ويعدّل كما كان (ح-٢: يضيف اقتراحا في اليوم
   التالي لاعتماده).

   ولا `contract_pending` فيها: عرضٌ أُرسل ولم يُوقَّع بعد. ومن لم يوقّع لم
   يقبل شرطا ولا مهلةً، ففتحُ بابه يجعله يرفع موادَّه على وعدٍ لم يلتزم به
   أحد — ثمّ يعتذر عن العرض فيبقى عندنا عملُه ولا عقدَ بيننا. */
export const MATERIALS_STATUSES: readonly string[] = ['onboarding', 'active']

/** وما سوى ذلك: النشطُ وحدَه (البند 2-11 من عرضه) */
export const ACTIVE_ONLY_STATUSES: readonly string[] = ['active']

export function doorStatuses(door: PortalDoor): readonly string[] {
  return door === 'materials' ? MATERIALS_STATUSES : ACTIVE_ONLY_STATUSES
}

export interface PortalSubject {
  /** حالُ الطلب */
  status: string
  /** إيقافٌ إداريٌّ على الملفّ — يغلق كلَّ باب، ولو كان نشطا */
  suspendedAt?: Date | string | null
}

/* ═══ والإيقافُ يغلق قبل أن تُسأل الحالة ═══

   فمن أُوقف ملفُّه وهو في طور العرض المشروط لا يُقال له «بوّابتك مفتوحة
   للموادّ»: الإيقافُ قرارٌ فوق الطور. */
export function portalDoorProblemAr(door: PortalDoor, subject: PortalSubject): string | null {
  if (subject.suspendedAt) return 'حسابك التدريبي موقوف — تواصل مع الإدارة'
  if (doorStatuses(door).includes(subject.status)) return null
  if (door === 'materials') {
    /* ولا يُقال «موقوف» لمن لم يوقّع بعد: حسابُه سليمٌ، وإنّما بابُه يُفتح
       بتوقيعه. ورسالةٌ تقول «موقوف» تجعله يظنّ أنّ شيئا أُخذ منه. */
    return subject.status === 'contract_pending'
      ? 'بوّابتك تُفتح بتوقيع عرضك المشروط — وقّعْه ثمّ ادخلها لترفع موادَّك'
      : 'حسابك التدريبي موقوف — تواصل مع الإدارة'
  }
  return 'هذا البابُ يُفتح بعد اعتماد موادّك وتفعيل حسابك — ولا إسنادَ ولا أتعابَ قبل تحقّق شرط عرضك'
}

/** أيُعمَل على الموادّ؟ — سؤالٌ تسأله الشاشةُ قبل أن تعرض زرّا */
export function canWorkOnMaterials(subject: PortalSubject): boolean {
  return portalDoorProblemAr('materials', subject) === null
}
