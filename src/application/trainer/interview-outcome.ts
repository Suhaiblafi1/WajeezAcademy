/* نتيجةُ لقاء التعارف — وما يُعَدّ لقاءً وقع فعلا.

   ═══ العطبُ الذي كُتب له ═══

   نتائجُ اللقاء ثلاثٌ: ناجحٌ وتعليقٌ وراسب. **ومن لم يحضر ليس واحدا منها**،
   فيُترك بلا نتيجة. وثلاثةُ آثارٍ لذلك، كلُّها صامتة:

   ① **الطلبُ يقف في «حُدّد موعدُه» إلى الأبد.** الموعدُ مضى ولم يجلس إليه
      أحد، والحالةُ تقول إنّ له موعدا. فلا هو في طابور من ينتظر قرارا، ولا
      في قائمة من لم يحجز — بل في حالةٍ تصف ماضيا لا يعود.
   ② **ولا يُدعى إلى حجزٍ جديد.** مِحَكُّ التذكير يسأل: أله موعدٌ قائم؟ فيجد
      صفَّ الموعد الذي لم يحضره، فيمتنع. فمن نسي موعدَه — وهو أحوجُ الناس
      إلى تذكير — هو وحدَه من لا يصله.
   ③ **والقمعُ يعدّه ممّن جرى لقاؤهم.** «جرى اللقاء» كان: نتيجةٌ سُجّلت أو
      موعدٌ مضى ولم يُلغَ — وغيابُه يقع في الشقّ الثاني حرفا. فيُقاس اللقاءُ
      أكبرَ ممّا وقع، ويُقاس تسرُّبُ الغياب صفرا وهو لا يُرى.

   ═══ ولمَ الغيابُ نتيجةٌ لا حكم ═══

   «راسب» حكمٌ على إنسانٍ جلسنا إليه، والغيابُ ليس حكما: قد يكون عطلا في
   الاتّصال، أو موعدا نُسي، أو ظرفا طارئا. فيُسجَّل ما وقع — **لم يقع
   اللقاء** — ويعود الطلبُ إلى ما قبل الحجز ليحجز صاحبُه من جديد. والقرارُ
   في أمره يبقى لمن يراجعه، لا تقضيه آلةٌ بغيابٍ واحد.

   ولا يُرسَل إليه بريدٌ بهذا: تذكيرُ المتقدّم يدويٌّ بقرار صاحب المنصّة
   (١٩ سبتمبر ٢٠٢٦). وعودتُه إلى حالةٍ تقبل الحجز تُعيده إلى ملخّص الصباح
   وإلى مرشّح «لم يحجز موعدا» — فيصله التذكيرُ بيدٍ تضغط، كغيره. */

/** الغيابُ — قيمتُه في القاعدة، وتُكتب مرّةً واحدةً في المستودَع كلِّه */
export const NO_SHOW = 'no_show'

export interface InterviewOutcome {
  key: string
  labelAr: string
  /** ما يعنيه للطلب — يُقرأ في الشاشة قبل الضغط */
  whatAr: string
}

/* ═══ ولمَ «غير مناسب» لا «راسب» (٢٠ سبتمبر ٢٠٢٦) ═══

   قرارُ صاحب المنصّة: «بدّلْ كلمةَ راسب لشيءٍ أكثرَ أدبا». و«راسب» لفظُ
   امتحانٍ قيل في إنسانٍ دعوناه إلى حديث، لا في ورقةٍ صُحّحت — يحكم على
   صاحبه لا على موقعه منّا. و«غير مناسب» تقول ما وقع فعلا: أنّه لا يناسب
   ما نبحث عنه اليومَ، وهو حكمٌ على المطابقة لا على الرجل.

   وهي داخليّةٌ لا تغادر: `outcomeLabelAr` تُقرأ في شاشتَي الإدارة وحدَهما
   ولا تدخل بريدا ولا صفحةً يراها المتقدّم — فتبديلُها لا يمسّ أحدا خارجَنا.
   وإنّما بُدّلت لأنّ ما نكتبه عن الناس بيننا يصفنا نحن كذلك. */

/** النتائجُ الأربع — الشاشةُ تعرضها، والخادمُ يقبلها، من هذه القائمة وحدَها */
export const INTERVIEW_OUTCOMES: readonly InterviewOutcome[] = [
  { key: 'passed', labelAr: 'ناجح', whatAr: 'اجتاز اللقاء' },
  { key: 'hold', labelAr: 'تعليق', whatAr: 'يُعاد النظرُ فيه' },
  { key: 'failed', labelAr: 'غير مناسب', whatAr: 'لا يناسب ما نبحث عنه — ولا يُكمَل طلبُه' },
  { key: NO_SHOW, labelAr: 'لم يحضر', whatAr: 'لم يقع اللقاء — ويعود الطلبُ إلى ما قبل الحجز' },
]

/** المفاتيحُ وحدَها — يبني بها الخادمُ حارسَ طلبه، فلا قائمتان تفترقان */
export const INTERVIEW_OUTCOME_KEYS = INTERVIEW_OUTCOMES.map((o) => o.key) as [string, ...string[]]

/** عنوانُ النتيجة عربيّا — و«بلا نتيجة» لما لم يُسجَّل بعد.
 *
 *  ولا يُعرض المفتاحُ اللاتينيُّ لمن يقرأ الشاشة: كان يُعرض `passed` حرفا
 *  في بطاقة المقابلة، وهو عطبٌ لا يُحمِّر شيئا — الشاشةُ تعمل، والقيمةُ
 *  تُعرض، وإنّما تُعرض بلغة القاعدة. */
export function outcomeLabelAr(key: string | null | undefined): string {
  if (!key) return 'بلا نتيجة'
  return INTERVIEW_OUTCOMES.find((o) => o.key === key)?.labelAr ?? key
}

/** أله موعدٌ قائم؟ — لم يُلغَ ولم يُسجَّل غيابا.
 *
 *  والغيابُ يخرج من العدّ لأنّ الموعدَ لم يقع: من لم يحضر لا موعدَ له،
 *  فيُدعى إلى حجزٍ جديد كمن ألغى. */
export function isLiveInterview(i: { canceledAt?: Date | string | null; outcome?: string | null }): boolean {
  return !i.canceledAt && i.outcome !== NO_SHOW
}

/** أجرى اللقاءُ فعلا؟ — يقيس ما وقع لا ما كُتب في التقويم.
 *
 *  ونتيجةٌ سُجّلت تكفي، وكذلك موعدٌ مضى ولم يُلغَ: المُقابِلُ قد ينسى تسجيلَ
 *  النتيجة، ولقاءٌ جرى لا يصير لم يجرِ بنسيانه. **والغيابُ يُخرِجه** — وهو
 *  بعينه ما كان يُحسب لقاءً وقع. */
export function interviewHeld(
  i: { canceledAt?: Date | string | null; outcome?: string | null; scheduledAt: Date | string },
  now: Date = new Date(),
): boolean {
  if (i.canceledAt) return false
  if (i.outcome === NO_SHOW) return false
  if (i.outcome) return true
  const at = i.scheduledAt instanceof Date ? i.scheduledAt : new Date(i.scheduledAt)
  return !Number.isNaN(at.getTime()) && at < now
}
