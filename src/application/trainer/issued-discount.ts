/** التسوية: أيُّ الخصوم يسعها هذا الكشف، وأيُّها يُؤجَّل كاملا.

    الترتيبُ بالأقدم استعمالا: من انتظر أطولَ يُحسم أوّلا، فلا يبقى خصمٌ
    معلَّقا إلى الأبد لأنّ أحدثَ منه أصغرُ فيسعه الكشفُ كلَّ مرّة. */
export function settleAgainst<T extends { id: string; amount: number }>(
  gross: number,
  pending: readonly T[],
): { taken: T[]; deferred: T[]; net: number } {
  const taken: T[] = []
  const deferred: T[] = []
  let left = round2(gross)
  for (const d of pending) {
    if (d.amount <= left) {
      taken.push(d)
      left = round2(left - d.amount)
    } else {
      deferred.push(d)
    }
  }
  return { taken, deferred, net: left }
}

function round2(n: number): number {
  return Math.round(n * 100) / 100
}
