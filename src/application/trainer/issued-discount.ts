/* خصمُ المدرّب — مبلغٌ يصدره من عنده، ويُحسم من مستحقّاته لا من إيرادنا.

   ═══ القرار ═══

   قرارُ صاحب المنصّة (٢١ سبتمبر ٢٠٢٦): «لا يتحمّل أيّ خصومات تطرحها
   الأكاديميّةُ من نفسها، ولكن يتحمّل هو أيَّ خصوماتٍ قرّر إعطاءها لأشخاصٍ
   معيّنين من نفسه باستخدام الكود الخاصّ به… يحقّ له إصدارُ خصمٍ بقيمةٍ
   ماديّةٍ معيّنةٍ وليست نسبةً، لتُخصم من حسابه في مستحقّاتي لاحقا».

   وهو في العقد بندان: 4-9 (خصومُنا لا تمسّ أتعابَه) و4-10 (خصمُه يُحسم
   منه). وهذا الملفُّ قواعدُ الفعل لا بابُه.

   ═══ ولمَ مبلغٌ لا نسبة — وهو ليس تفصيلا في الواجهة ═══

   النسبةُ تجعل ما يتحمّله المدرّبُ دالّةً في **سعرٍ نملكه نحن**: يكتب
   «١٠٪» على سعرِ اليوم، فنرفع السعرَ بعد شهرٍ فيرتفع ما يُحسم منه بلا أن
   يقرّر شيئا. والمبلغُ يبقى ما كتبه: عشرون دولارا تبقى عشرين.

   وأثرٌ ثانٍ: النسبةُ تُطبَّق على **السلّة** كلِّها في `priceCart`، فمن دعا
   شخصا إلى دورةٍ واحدةٍ ثمّ اشترى ذاك خمسا وجد نفسَه يتحمّل خمسةَ أضعاف ما
   نوى. والمبلغُ مسقوفٌ بنفسه.

   ═══ ولمَ سقفٌ على ما يُصدر ═══

   الحسمُ لاحقٌ، والمستحقُّ مستقبَل. فبلا سقفٍ يُصدر مدرّبٌ ألفا من الخصوم
   على مئتَين من المستحقّات، فيُستعمَل المالُ ويبقى الفرقُ: لا تحسمه من
   كشفٍ لا يكفيه (والبند 4-10 يمنع أن يُطالَب به دَينا)، فتتحمّله الأكاديميّةُ
   — وهو عكسُ القرار نفسِه.

   والسقفُ **ما له عندنا**: ما اعتُمد ولم يُصرف، وما هو منتظَرٌ في كشوفه،
   وما يُتوقَّع من شعبه المفتوحة (وهو الرقمُ المعروضُ له في «مستحقّاتي»
   نفسِه، فلا رقمَ جديدٌ يُخترع). ويُطرح منه ما أصدره ولم يُسوَّ بعد.

   ولا يُبنى السقفُ على المدفوع: ذاك مالٌ خرج من عندنا إليه، ولا يُحسم منه.

   ═══ والتسويةُ لا تُجزَّأ ═══

   خصمٌ لا يسعه الكشفُ يُؤجَّل **كاملا** إلى الذي يليه، ولا يُشطَر نصفَين.
   والعلّة أنّ البند 4-10 يقول «المبلغ المستعمل… بندا مستقلا باسمه»: بندٌ
   نصفُه هنا ونصفُه هناك يجعل المدرّبَ يقابل كشفَين ليعرف ما حُسم عن رجلٍ
   واحد، ويجعل الحارسَ الذي يمنع الحسمَ مرّتين يعدّ مبالغَ لا صفوفا. */

/** أدنى ما يُصدَر — خصمٌ بأقلَّ من هذا صفٌّ في القاعدة لا منفعةَ فيه لأحد */
export const MIN_ISSUED_DISCOUNT = 1

/** أقصى ما يُصدَر في مرّةٍ واحدةٍ مهما اتّسع رصيدُه.

    ولمَ سقفٌ ثانٍ فوق الرصيد: غلطةُ صفرٍ زائدٍ (٢٠٠ بدل ٢٠) تلتهم رصيدَ
    فصلٍ كاملٍ في نقرةٍ واحدة، ولا يظهر أثرُها إلّا بعد شهرٍ في كشفه. وهذا
    حدٌّ يُقرأ في الشاشة قبل أن يُكتب الرقم. */
export const MAX_ISSUED_DISCOUNT = 500

/** حالاتُ الخصم — والدورةُ مكتوبةٌ هنا لتُقرأ مرّةً واحدة.

    · `live`    — صدر ولم يُستعمل، وللمدرّب إلغاؤه.
    · `used`    — استُعمل في شراءٍ دُفع، وينتظر الكشف.
    · `settled` — حُسم في كشفٍ بعينه، ولا يُحسم ثانيةً.
    · `revoked` — ألغاه المدرّبُ قبل أن يُستعمل، فلا أثرَ ماليّا له. */
export const ISSUED_DISCOUNT_STATUS_AR: Record<string, string> = {
  live: 'صالح — لم يُستعمَل بعد',
  used: 'استُعمل — يُحسم في كشفك القادم',
  settled: 'حُسم من كشفك',
  revoked: 'ألغيتَه',
}

/** ما يُحتسب دَينا عليه: ما هو صالحٌ قد يُستعمل، وما استُعمل ولم يُحسم بعد */
export const OUTSTANDING_STATUSES = ['live', 'used'] as const

export interface DiscountBudget {
  /** ما له عندنا: منتظَرٌ + معتمَدٌ + متوقَّعٌ من شعبه المفتوحة */
  allowance: number
  /** ما أصدره ولم يُسوَّ — صالحا كان أو مستعمَلا */
  outstanding: number
  /** الفرقُ، ولا ينزل تحت الصفر */
  remaining: number
  currency: string
}

export function discountBudget(input: {
  pending: number
  approved: number
  projected: number
  outstanding: number
  currency: string
}): DiscountBudget {
  const allowance = round2(input.pending + input.approved + input.projected)
  const outstanding = round2(input.outstanding)
  return {
    allowance,
    outstanding,
    remaining: round2(Math.max(0, allowance - outstanding)),
    currency: input.currency,
  }
}

/** لمَ لا يُصدَر — جملةٌ تُقال له، أو `null` إن جاز.

    والرسالةُ تخرج من هنا لا من الخادم ولا من الشاشة: الشاشةُ تعطّل الزرَّ
    بها، والخادمُ يردّ بها — فيقرأ الاثنين نصّا واحدا. ولو كُتبت مرّتين
    لقالت الشاشةُ «لا يتجاوز رصيدَك» ويقول الخادمُ «مبلغ غير صالح». */
export function issueBlockerAr(amount: number, budget: DiscountBudget): string | null {
  if (!Number.isFinite(amount) || amount <= 0) return 'اكتب مبلغَ الخصم بالأرقام.'
  if (round2(amount) !== amount) return 'المبلغُ بمنزلتين عشريّتين على الأكثر.'
  if (amount < MIN_ISSUED_DISCOUNT) {
    return `أقلُّ خصمٍ يُصدَر ${MIN_ISSUED_DISCOUNT} ${budget.currency}.`
  }
  if (amount > MAX_ISSUED_DISCOUNT) {
    return `أكبرُ خصمٍ يُصدَر في المرّة الواحدة ${MAX_ISSUED_DISCOUNT} ${budget.currency}.`
  }
  if (amount > budget.remaining) {
    return `رصيدُك القابل للخصم ${budget.remaining} ${budget.currency} — وهو ما لك عندنا `
      + `(${budget.allowance}) ناقصا ما أصدرته ولم يُحسم بعد (${budget.outstanding}). `
      + 'وما يُحسم يُحسم من مستحقّاتك أنت، فلا يُصدَر فوق ما لك.'
  }
  return null
}

/** التسوية: أيُّ الخصوم يسعها هذا الكشف، وأيُّها يُؤجَّل كاملا.

    الترتيبُ بالأقدم استعمالا: من انتظر أطولَ يُحسم أوّلا، فلا يبقى خصمٌ
    معلَّقا إلى الأبد لأنّ أحدثَ منه أصغرُ فيسعه الكشفُ كلَّ مرّة. */
export function settleAgainst<T extends { id: string; amount: number }>(
  gross: number,
  pending: readonly T[],
): { taken: T[]; deferred: T[]; net: number } {
  const taken: T[] = []
  const deferred: T[] = []
  let left = round2(gross)
  for (const d of pending) {
    if (d.amount <= left) {
      taken.push(d)
      left = round2(left - d.amount)
    } else {
      deferred.push(d)
    }
  }
  return { taken, deferred, net: left }
}

function round2(n: number): number {
  return Math.round(n * 100) / 100
}
