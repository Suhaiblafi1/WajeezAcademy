/* ═══ نصيحةُ البدء: ديسمبر، أو أواخرَ نوفمبر على الأقلّ (٤ أكتوبر ٢٠٢٦) ═══

   قال صاحبُ المنصّة: «انصح كلَّ مدرّبٍ أن يبدأ تدريبَه في ديسمبر، أو أواخرَ
   نوفمبر على الأقلّ — نصيحةً فقط — كي يتّسع لنا الوقتُ لنسوّق دوراته، فقد بدأنا
   متأخّرين. واجعلها نصيحةً ودودةً جدّا».

   فلا تمنع شيئا ولا تُلوَّن تحذيرا: سطرٌ ودودٌ بجانب تاريخ البدء، يقول ما يناسب
   ما اختاره. قبل أن يختار تقترح، وإن اختار أبكرَ من أواخر نوفمبر ذكّرت بلطفٍ
   وتركت القرارَ له، وإن اختار بعدَها شكرت.

   وهي لهذا الموسم وحدَه: إذا حلّ ديسمبر سكتت من نفسها — فكلُّ يومٍ يُختار بعده
   هو ما نصحت به، ونصيحةٌ عن موسمٍ مضى تُربك ولا تنفع. */

export const START_ADVICE = {
  /** «أواخرُ نوفمبر» — الأحدُ أوّلُ أسبوعه الأخير */
  lateNovember: '2026-11-22',
  /** «ديسمبر» — ومنه تسكت النصيحة */
  december: '2026-12-01',
} as const

export type StartAdvice = 'ask' | 'early' | 'thanks'

/** ما يُقال بجانب تاريخ البدء — أو `null` حين لا نصيحةَ لموسمٍ مضى */
export function startAdvice(startsOn: string | null | undefined, today: string): StartAdvice | null {
  if (today >= START_ADVICE.december) return null
  if (!startsOn) return 'ask'
  return startsOn < START_ADVICE.lateNovember ? 'early' : 'thanks'
}

