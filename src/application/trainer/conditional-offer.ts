/* ═══ العرضُ المشروط — مهلتُه، وحسابُها في موضعٍ واحد ═══

   ─────────── العطبُ الذي وُلد منه هذا الملفّ ───────────

   كان الاعتمادُ يصيّر المتقدّمَ «نشطا» في اللحظة نفسِها، ثمّ تُرى موادُّه.
   فإن كانت دون المستوى فلا مخرجَ إلّا فسخُ عقدٍ نافذ. وقرارُ صاحب المنصّة
   (٢٣ سبتمبر ٢٠٢٦) أن يكون القبولُ **مشروطا من أصله**: يوقّع عرضا مشروطا،
   فيرفع موادَّه في مهلةٍ معلومة، فإذا قُبلت صار عقدُه نهائيّا. وبهذا يصير
   «لم نقبل موادَّك» شرطا لم يتحقّق لا عقدا يُفسَخ.

   ─────────── ولمَ تبدأ المهلةُ من الجلسة لا من التوقيع ───────────

   بيانُ صاحب المنصّة: «السبعةُ أيّامٍ تبدأ من الجلسة» — جلسةُ تهيئةٍ جماعيّةٌ
   أسبوعيّةٌ يُعلَّم فيها استخدامُ المنصّة وإضافةُ الموادّ.

   وتبدأ من **تاريخِها المعلَنِ له** لا من حضورِه إيّاها. والفرقُ ليس تفصيلا:
   لو تعلّقت بالحضور لَاحتاجت نقرةَ إنسانٍ يسجّله، ومن نُسي بقي في الطور أبدا
   بلا مهلةٍ ولا تذكير. وبالتاريخ المعلَن يسير العاملُ وحدَه، ومن فاتته
   الجلسةُ فله التمديدُ أو التأجيلُ إلى الموسم القادم.

   ─────────── ولمَ دالّاتٌ خالصةٌ في `src/application` ───────────

   تُقرأ في أربعة مواضع: الخادمُ يكتب بها، وطابورُ الإدارة يعرض ما بقي،
   وبوّابةُ المدرّب تعرض شريطَها، والعاملُ يذكّر ويوسم بها. وأربعُ نسخٍ لحسابٍ
   واحدٍ تفترق يوما — فيُذكَّر من ذُكِّر، أو يُوسَم متأخّرا من في مهلته. وهذا
   عرفُ `readiness.ts` و`approval.ts` في هذا المجلّد نفسِه.

   ولا يقرأ هذا الملفُّ قاعدةً ولا يستدعي شيئا: يأخذ ما قُرئ ويحكم. */

/* ═══ خمسةُ أيّامٍ من **التوقيع** لا من جلسة التهيئة (٢٧ سبتمبر ٢٠٢٦) ═══

   قرارُ صاحب المنصّة: «معه ٥ أيّام من بعد التوقيع لإتمام الموادّ التعليميّة
   الخاصّة بدوراته». وكانت سبعةً تبدأ من جلسة التهيئة.

   وبدّل هذا **مبدأَ** المهلة لا مقدارَها وحدَه: كانت الجلسةُ أصلَ الأجل،
   فلزم أن تُحدَّد قبل تركيب العرض — وإلّا فعرضٌ بلا مهلة. والجلسةُ الآن
   **تُحدَّد بعد التوقيع** بقوله: «وأبلغهم أنّ هناك ستكون جلسةُ توتوريال
   تُحدَّد بعد التوقيع للتعريف بآليّة وضع المناهج». فالأصلُ صار التوقيعَ،
   وهو تاريخٌ لا يحتاج إلى وعدٍ من أحد: يقع بفعل المدرّب نفسِه ويُكتب في
   الصفّ لحظةَ وقوعه.

   وسقط به شرطٌ كان لازما يومَ ٢٦ سبتمبر — ألّا يُركَّب عرضٌ بلا جلسة. لم
   يكن حكما قائما بنفسه، بل نتيجةَ أنّ المهلةَ تُحسَب منها. */
export const MATERIALS_WINDOW_DAYS = 5

/** طولُ التمديد الواحد */
/* ═══ ومهلةُ الدورة الجديدة: ثلاثةُ أيّام (٢٧ سبتمبر ٢٠٢٦) ═══

   قرارُ صاحب المنصّة: «أنا سأؤهّله لكافّة الدورات التي اقترحها والتي هو أصلا
   مؤهّلٌ لها، فلن تكون هناك دوراتٌ يجب أن يقترحها إلّا إذا اقترح دورةً جديدةً
   خلال الفترة — عندها… يُمنَح مهلةَ ثلاثة أيّامٍ لإضافةِ… كافّةِ محاورها
   وموادّها، وبعدها نعتمد كلَّ شيءٍ مرّةً واحدة».

   فهي **لا تُنشئ مهلةً ثانيةً مستقلّة**: الأجلُ واحدٌ يُمَدّ إن لزم. ومن
   اعتُمدت له دورةٌ في يومه الرابع وأجلُه ينتهي في الخامس يبلغ أجلُه اليومَ
   السابع؛ ومن اعتُمدت له في يومه الأوّل لا ينقص أجلُه إلى الرابع. فالقاعدةُ
   `max(الأجل القائم، يومُ الاعتماد + ٣)` — تمدّ ولا تقصّر.

   والاعتمادُ واحدٌ في آخرها لكلّ موادّه، كما قال. */
export const NEW_COURSE_WINDOW_DAYS = 3

export const EXTENSION_DAYS = 2

/* ═══ ومرّتان لا مرّة (٢٧ سبتمبر ٢٠٢٦) ═══

   قرارُ صاحب المنصّة: «ويحقّ له طلبُ تمديدٍ ليومين **مرّتين**، أي النتيجةُ
   ٩ أيّامٍ لو مدّد» — خمسةٌ من التوقيع، ويومان، ويومان.

   وكان الحارسُ `conditionExtendedAt` وحدَه: وجودُه يعني «مُدّد» ولا يقول كم
   مرّة. فصار العدُّ في عمودٍ (`conditionExtensionsUsed`)، والتاريخُ يبقى
   آخرَ تمديدٍ مُنح — يُقرأ في الشاشة وفي بريد التذكير. */
export const MAX_EXTENSIONS = 2

/** أقصى ما تبلغه المهلةُ لو مُدّدت كلَّ مرّاتها — يُقرأ في العقد والشاشة */
export const MAX_TOTAL_WINDOW_DAYS = MATERIALS_WINDOW_DAYS + MAX_EXTENSIONS * EXTENSION_DAYS

/** قبل يومَين يذكّر العاملُ مرّةً واحدة */
export const REMINDER_LEAD_DAYS = 2

const DAY_MS = 86_400_000

export type DateLike = Date | string | null | undefined

const asDate = (v: DateLike): Date | null => {
  if (!v) return null
  const d = v instanceof Date ? v : new Date(v)
  return Number.isNaN(d.getTime()) ? null : d
}

/* ═══ تاريخُ الانتهاء يُحسب مرّةً ويُخزَّن ═══

   ولمَ يُخزَّن ولا يُحسب عند القراءة: لو حُسب لَتبدّلت مهلةُ عرضٍ **وُقّع**
   بتبدّلِ ثابتٍ في الشيفرة — فمن وقّع على سبعةٍ وجد نفسَه على خمسٍ بنشرةٍ لا
   يعلم بها. والمخزونُ يقول ما وُقّع عليه، والثابتُ يقول ما يُرسَل اليوم. */
export function deadlineFrom(
  signedAt: DateLike,
  windowDays: number = MATERIALS_WINDOW_DAYS,
): Date | null {
  const at = asDate(signedAt)
  return at ? new Date(at.getTime() + windowDays * DAY_MS) : null
}

/** ما يكفي من صفّ العقد ليُحكَم على شرطه — لا شكلَ الصفِّ كلَّه */
export interface ConditionFacts {
  /** تاريخُ جلسة التهيئة المعلَنُ له — وبلا هذا لا مهلةَ أصلا */
  orientationAt?: DateLike
  conditionDeadlineAt?: DateLike
  /** يُكتب حين يُعلن الاكتمال؛ ويُمحى عند الردّ بملاحظات */
  conditionPausedAt?: DateLike
  conditionExtendedAt?: DateLike
  /** كم مرّةً مُنح التمديد — والغائبُ صفر */
  conditionExtensionsUsed?: number | null
  conditionRemindedAt?: DateLike
  /** اعتُمدت موادُّه — انتهت المهلة */
  conditionMetAt?: DateLike
  /** يُمرَّر في الاختبار كي لا تتعلّق النتيجةُ بساعة الجهاز */
  now?: Date
}

/* ═══ أطوارُ الشرط الخمسة ═══

   · `none`      — لا مهلةَ له: عرضٌ بلا تاريخِ جلسة، أو مدرّبٌ نُقل بيدٍ إلى
                   التهيئة بلا عرضٍ وقّعه. ولا ساعةٌ صامتةٌ تبدأ على أحد.
   · `running`   — المهلةُ تسير، وأمامه أيّامٌ تُعَدّ.
   · `under_review` — أعلن الاكتمالَ فتجمّدت: فوقتُ مراجعتنا لا يُحسب عليه.
   · `met`       — اعتُمدت موادُّه.
   · `lapsed`    — انقضت ولم يُعلن. وهو **وسمٌ محسوبٌ لا حالةٌ جديدة**: لم
                   ينتقل مكانا، بل تأخّر في مكانه. */
export type ConditionPhase = 'none' | 'running' | 'under_review' | 'met' | 'lapsed'

export function conditionPhase(f: ConditionFacts): ConditionPhase {
  if (asDate(f.conditionMetAt)) return 'met'
  const due = asDate(f.conditionDeadlineAt)
  if (!due) return 'none'
  if (asDate(f.conditionPausedAt)) return 'under_review'
  const now = f.now ?? new Date()
  return now.getTime() > due.getTime() ? 'lapsed' : 'running'
}

/** ما بقي من الأيّام — و`null` لمن لا مهلةَ له أو انتهت */
export function daysLeft(f: ConditionFacts): number | null {
  if (conditionPhase(f) !== 'running') return null
  const due = asDate(f.conditionDeadlineAt)!
  const now = f.now ?? new Date()
  return Math.max(0, Math.ceil((due.getTime() - now.getTime()) / DAY_MS))
}

export function isLapsed(f: ConditionFacts): boolean {
  return conditionPhase(f) === 'lapsed'
}

/* ═══ أيُعرَض شريطُ الشرط أصلا ═══

   والجوابُ هنا هو بعينه شرطُ `openConditionContract` في الخادم: مهلةٌ
   مكتوبةٌ لم يُعتمَد ما بعدها. ولو افترقا لَظهر للمدرّب زرٌّ
   يردُّه الخادمُ بـ«لا مهلةَ قائمةً على حسابك»، أو اختفى زرٌّ يقبله.

   والأهمُّ ما يمنعه: `conditionPhase` يردّ `none` لمن لا مهلةَ له — ومدرّبٌ
   نشطٌ منذ سنةٍ عقدُه الأخيرُ بلا أعمدةِ شرطٍ أصلا طورُه `none`. فلو عُلّق
   الشريطُ على الطورِ وحدَه لَقرأ مدرّبو المنصّة كلُّهم «عرضٌ مشروط — ويصلك
   موعدُ جلسة التهيئة». */
export function hasOpenCondition(f: ConditionFacts): boolean {
  const phase = conditionPhase(f)
  return phase === 'running' || phase === 'under_review' || phase === 'lapsed'
}

/* زرُّ «أعلنتُ اكتمالها» — والمنقضيةُ منها بقصد

   فالخادمُ يقبلها متأخّرةً بنصّه: «من تأخّر يوما ثمّ أتمّ موادَّه أولى
   به أن تُقرأ من أن يُردّ بابُه». والمجمّدةُ وحدَها تُرَدّ (`already_declared`) —
   فزرٌّ يُعرَض لمن أعلن أصلا يعدُ بفعلٍ لا يقع. */
export function canDeclareMaterials(f: ConditionFacts): boolean {
  const phase = conditionPhase(f)
  return phase === 'running' || phase === 'lapsed'
}

/* ═══ التذكيرُ مرّةً واحدة، ولا تذكيرَ بلا مهلة ═══

   والشرطُ الأخيرُ هو ضمانُ الترحيل نفسُه: من في التهيئة اليومَ بلا عرضٍ
   موقَّعٍ مهلتُه `NULL`، فلا يطرق العاملُ بابَه برسالةٍ عن مهلةٍ لم يقبلها. */
export function dueReminder(f: ConditionFacts): boolean {
  if (conditionPhase(f) !== 'running') return false
  if (asDate(f.conditionRemindedAt)) return false
  const left = daysLeft(f)
  return left != null && left <= REMINDER_LEAD_DAYS
}

/* ═══ التجميدُ يزيد المهلةَ بمقدار مدّته بالضبط ═══

   فلو أعلن الاكتمالَ في اليوم السادس وأخذت المراجعةُ يومين لخرج من المهلة بلا
   ذنبٍ منه — وهي الشكوى الوحيدةُ التي تصمد في وجه عقدٍ كُتب للحماية. ولا
   يستطيع المدرّبُ إمساكَ التجميد: هو ينتهي في اللحظة التي تُعاد إليه الكرةُ
   فيها. */
export function deadlineAfterPause(f: ConditionFacts, resumedAt: Date): Date | null {
  const due = asDate(f.conditionDeadlineAt)
  const paused = asDate(f.conditionPausedAt)
  if (!due) return null
  if (!paused) return due
  const frozen = Math.max(0, resumedAt.getTime() - paused.getTime())
  return new Date(due.getTime() + frozen)
}

/* ═══ التمديدُ مرّتان ═══

   والثالثةُ تُردّ بنصٍّ يُقرأ، لا بصمتٍ ولا بزرٍّ مطفإ: من طلب ثالثةً يحتاج
   أن يعرف أنّ مرّتيه أُنفقتا وأنّ بابَه الآن التأجيلُ إلى الموسم القادم.

   والعدُّ من العمود لا من التاريخ: التاريخُ يقول «مُدّد» ولا يقول كم مرّة.
   ويُقرأ الغائبُ صفرا — فصفوفُ ما قبل العمود مضبوطةٌ في ترحيلها. */
export function extendProblemAr(f: ConditionFacts): string | null {
  const used = f.conditionExtensionsUsed ?? 0
  if (used >= MAX_EXTENSIONS) {
    return `أُنفقت مرّاتُ التمديد (${MAX_EXTENSIONS} × ${EXTENSION_DAYS} يومين) ولا تُمنح ثالثة — وبابُه الآن التأجيلُ إلى الموسم القادم.`
  }
  if (!asDate(f.conditionDeadlineAt)) {
    return 'لا مهلةَ لهذا العرض — وهي تبدأ بتوقيعه.'
  }
  if (asDate(f.conditionMetAt)) return 'اعتُمدت موادُّه — لا مهلةَ تُمدَّد.'
  return null
}

/** كم تمديدا بقي له — يُقرأ تحت الزرّ فلا يضغط ليعرف */
export function extensionsLeft(f: ConditionFacts): number {
  return Math.max(0, MAX_EXTENSIONS - (f.conditionExtensionsUsed ?? 0))
}

export function extendedDeadline(f: ConditionFacts): Date | null {
  const due = asDate(f.conditionDeadlineAt)
  return due ? new Date(due.getTime() + EXTENSION_DAYS * DAY_MS) : null
}

/* ═══ زرُّ التمديد — أضيقُ من قبول الخادم بقصد ═══

   `extendProblemAr` يأذن للمنقضية: لا تمديدَ سابقا، ومهلةٌ مكتوبةٌ، ولم
   تُعتمَد. لكنّ `extendedDeadline` يزيد يومَين على **تاريخِها هي** لا على
   اليوم — فمن انقضت مهلتُه قبل ثلاثةِ أيّامٍ يخرج من الزرّ إلى مهلةٍ
   انقضت قبل يوم. زرٌّ يعمل ولا ينفع.

   ولا يُحرَم صاحبُها طريقا: بابُه «أعلنتُ اكتمالها» والخادمُ يقبلها
   متأخّرةً بنصّه. والمجمّدةُ مثلُها: مهلةٌ واقفةٌ لا تُمدّد. */
export function canAskExtension(f: ConditionFacts): boolean {
  return conditionPhase(f) === 'running' && extendProblemAr(f) === null
}

/* ═══ ما يُقرأ في الشاشات — موضعٌ واحدٌ لا ثلاثة ═══

   والوسمُ «عرضٌ مشروط — قيد التجهيز» هو المقترَحُ المُقَرُّ: أدقُّ من «نشطٌ
   بشرط» لأنّ الظهورَ العامَّ يحكمه `publishApprovedAt` مستقلّا، فما يميّز
   الطورَ حقّا أنّه **لا تدريبَ فيه ولا أتعاب**. */
export const CONDITION_PHASE_LABELS_AR: Record<ConditionPhase, string> = {
  none: 'عرضٌ مشروط — بلا مهلة',
  running: 'عرضٌ مشروط — قيد التجهيز',
  under_review: 'موادُّه قيد التقييم',
  met: 'اكتمل الشرط',
  lapsed: 'لم يستوفِ الشروط بعد',
}

/** سطرُ الشريط في بوّابة المدرّب وفي صفّ الطابور */
export function conditionLineAr(f: ConditionFacts): string {
  const phase = conditionPhase(f)
  if (phase === 'running') {
    const left = daysLeft(f)!
    const days = left === 1 ? 'يومٌ واحد' : left === 2 ? 'يومان' : `${left} أيّام`
    return `عرضٌ مشروط — أمامك ${days} لرفع موادّك`
  }
  if (phase === 'under_review') return 'موادُّك قيد التقييم — والمهلةُ مجمَّدةٌ حتّى يصلك جوابُنا'
  if (phase === 'lapsed') return 'انقضت مهلتُك ولم تكتمل موادُّك — أجِّلْ إلى الموسم القادم، أو اطلب حذفَ حسابك'
  if (phase === 'met') return 'اعتُمدت موادُّك — واكتمل الشرط'
  return 'عرضٌ مشروط — ويصلك موعدُ جلسة التهيئة ومنها تبدأ مهلتُك'
}

/* ═══ متى يُشترَط العقدُ أصلا — قرارُ ٢٥ سبتمبر ٢٠٢٦ ═══

   ── ما كان، ولمَ سقط ──

   كان المقياسُ `app.status !== 'active'`: يُشترَط عقدُ من لم يُفعَّل حسابُه
   بعد. وهو يسأل سؤالا (**أنشطٌ حسابُه؟**) غيرَ الذي يُراد (**أاعتُمدت
   موادُّه؟**)، ويصدق أن يفترقا.

   ويفترقان في مسارٍ واقع: من قبل الدعوةَ وأنشأ حسابَه **قبل** أن يُركَّب
   عقدُه صار `active`. فيخرج عقدُه **بلا شرطٍ ولا خَتم** — لا بندَ 2-6 في
   متنه، ولا طورَ ثانٍ يُعتمَد فيه بعد رفع موادّه. ويفوته الطورُ كلُّه بلا
   أن يُنبَّه أحد. وهو ما وقع فعلا في عقدٍ رآه صاحبُ المنصّة.

   ── والمقياسُ الصحيح ──

   الشرطُ إنّما وُضع لاعتماد الموادّ، فيُسأل عنه: **أسبق لهذا المدرّب عقدٌ
   تحقّق شرطُه؟** فمن اعتُمدت موادُّه مرّةً لا يُعاد اشتراطُه، ومن لم
   تُعتمَد يُشترَط عقدُه مهما كان حالُ حسابه.

   و`conditionMetAt` هو الأثرُ الذي يكتبه اعتمادُ الموادّ نفسُه ساعةَ يقع
   (`completeConditionalOffer`)، فلا علامةَ أصدقُ منه: من كتبها هو من اعتمد.

   ولا عقودَ أصلا — مرشّحٌ جديد — فيُشترَط: فالعدمُ ليس اعتمادا. */

/* ═══ وختمان لا واحد ═══

   `conditionMetAt` يكتبه اعتمادُ الموادّ في المسار المشروط. لكنّ الخَتمَ
   المفرد (`approveSignature` في العقد غير المشروط) يكتب `countersignedAt` **ولا يكتبه** —
   وبه خُتمت عقودٌ قبل أن يوجد المسارُ المشروط أصلا.

   فلو اقتُصر على الأوّل لَأُعيد اشتراطُ كلّ مدرّبٍ خُتم عقدُه بالباب
   القديم — وهم من يعملون اليوم. وكلاهما ختمُ الأكاديميّة: أنّا نظرنا
   فقبلنا.

   ═══ إلّا خَتما وقع على عرضٍ مشروطٍ قبل اعتماد موادّه (١ أكتوبر ٢٠٢٦) ═══

   من ٢٧ سبتمبر إلى اليوم كان «اعتمِدِ التوقيع» يختم العرضَ المشروطَ ويفتح طورَ
   الموادّ في نقرةٍ واحدة (`countersignContract` يومَها). فصار `countersignedAt` يُكتب
   **قبل** أن تُقرأ موادُّه — والقاعدةُ أعلاه تقرؤه اعتمادا لها. فمن خُتم عرضُه
   ولم تُعتمَد موادُّه، لو رُكّب له عقدٌ جديدٌ لخرج غيرَ مشروطٍ ومرّ دون بوّابة
   الموادّ كلِّها.

   والفرقُ بينه وبين خَتم الباب القديم مكتوبٌ في الصفّ: خَتمُ ذلك الطور يكتب
   مهلةَ الموادّ معه (`conditionDeadlineAt`)، فهو عرضٌ مشروطٌ **طورُه مفتوح**
   ما لم تُكتب `conditionMetAt`. وصفوفُ الباب القديم لا مهلةَ لها — وإن حملت
   `gatesActivation = true`، فذاك افتراضُ العمود يومَ أُضيف (ترحيلُ ١٩ سبتمبر)
   لا قرارٌ فيها. والعقدُ غيرُ المشروط لا طورَ له أصلا، فخَتمُه خَتم.

   ومن اليوم لا يُكتب `countersignedAt` على عرضٍ مشروطٍ إلّا مع `conditionMetAt`
   — فالاستثناءُ يحكم صفوفَ ذلك الطور وحدَها، ويبقى صادقا بعدها. */
export interface PriorContractSeal {
  /** يُكتب باعتماد الموادّ — المسارُ المشروط */
  conditionMetAt: Date | string | null
  /** يُكتب بخَتم الأكاديميّة — وبه خُتمت عقودُ الباب القديم */
  countersignedAt: Date | string | null
  /** مطلوبان لا اختياريّان: قارئٌ يُسقطهما يعود إلى عدّ كلّ خَتمٍ اعتمادا */
  gatesActivation: boolean
  conditionDeadlineAt: Date | string | null
}

/** أسبق لهذا المدرّب عقدٌ اعتُمدت فيه موادُّه — بشرطه أو بخَتمٍ لا طورَ مفتوحا تحته؟ */
export function materialsEverApproved(prior: readonly PriorContractSeal[]): boolean {
  return prior.some((c) => c.conditionMetAt != null || (
    c.countersignedAt != null && !(c.gatesActivation && c.conditionDeadlineAt != null)
  ))
}

/* ═══ ما يفعله «اعتمِدِ التوقيع» — بحسب ما وقّعه صاحبُه (١ أكتوبر ٢٠٢٦) ═══

   قرارُ صاحب المنصّة: «لا أريد أن أتعاقد مع أحدٍ قبل أن أعتمد دوراته… نحن نعتمد
   توقيعَك وسوف نقوم بتوقيع العقد وتحويله إلى عقدٍ غير مشروط عندما نقوم باعتماد
   دوراتك». فاعتمادُ التوقيع في العرض المشروط يطابق الاسمَ ويفتح البوّابة **ولا
   يوقّع عنّا** (`approve_only`)، ونوقّع يومَ تُعتمَد دوراتُه.

   لكنّ الحكمَ لما وقّعه الرجلُ لا لما نريده اليوم. وقد قال المتنُ في هذا ثلاثا:

   · من v4 إلى v11: «وتوقع الأكاديمية هذا العرض من جهتها يوم يتحقق الشرط» — وهو
     قولُ اليوم بعينه.
   · من v12 إلى v23 (#308، ٢٧ سبتمبر): «تعتمد الأكاديمية توقيع المدرب… فتوقع من
     جهتها ويصير العقد نافذا بين الطرفين». فاعتمادُ توقيعِ من وقّع هذا النصَّ
     **هو** توقيعُنا بنصّ ما وقّعه، ولا يُعتمَد إلّا خاتما. فيُعاد إليه للتوقيع
     على النصّ الحاضر أوّلا (`resign_first`) — توصيةٌ عرضتُها فوافق عليها صاحبُ
     المنصّة.
   · ومن v24: قولُ اليوم، مكتوبا في الديباجة والبندَين 2-6 و2-12 والخلاصة والإقرار.

   والعقدُ غيرُ المشروط (`gatesActivation = false`) يُكتب لمن اعتُمدت موادُّه أصلا
   — فاعتمادُ توقيعه خَتمُه كما كان (`seal`): لا دوراتَ تنتظر اعتمادا.

   والحكمُ هنا مرّةً واحدة: الخادمُ يسأله حين يُضغط الزرّ، والشاشةُ تسأله لتقول
   على الصفّ ما سيقع قبل أن يُضغط. */
export type SignatureApproval = 'seal' | 'approve_only' | 'resign_first'

/** الأجيالُ التي قال متنُها إنّ اعتمادَ التوقيع توقيعُنا: من v12 إلى ما قبل v24 */
export const APPROVAL_SEALED_BODIES = { from: 12, before: 24 } as const

export function signatureApprovalOf(c: { gatesActivation: boolean; bodyVersion: string | null }): SignatureApproval {
  if (!c.gatesActivation) return 'seal'
  const m = /^v(\d+)-/.exec(c.bodyVersion ?? '')
  const generation = m ? Number(m[1]) : null
  if (generation !== null && generation >= APPROVAL_SEALED_BODIES.from && generation < APPROVAL_SEALED_BODIES.before) {
    return 'resign_first'
  }
  return 'approve_only'
}

/** لماذا لا يُعتمَد توقيعُ هذا العرض قبل إعادته — يقوله الخادمُ والشاشةُ بحرفٍ واحد */
export const RESIGN_FIRST_AR = 'وُقّع هذا العرضُ على نصٍّ سابقٍ يجعل اعتمادَ التوقيع توقيعا منّا عليه — '
  + 'فأعِدْه للتوقيع على النصّ الحاضر («حُدّث النصُّ — أعِدْه للتوقيع»)، ثمّ اعتمِدْ توقيعَه الجديد. '
  + 'ولا نوقّع العرضَ المشروطَ قبل أن نعتمد دوراتِ صاحبه.'

/** أيُشترَط عقدُه الجديدُ باعتماد الموادّ؟ */
export function offerGatesActivation(prior: readonly PriorContractSeal[]): boolean {
  return !materialsEverApproved(prior)
}

/* ═══════════ ولا يُعتمَد مَن لم تُقرأ موادُّه ═══════════

   ─────────── البلاغُ الذي وُلد منه ───────────

   صاحبُ المنصّة (٢٦ سبتمبر ٢٠٢٦): «اعتمد العقد المشروط وينتقل لمرحلة وضع
   المواد، وبعد أن يضع المواد كاملا أقول إنّه ١٠٠٪ نشط». ثمّ: «ما وجدتُ
   بالتجربة أنّك اعتمدتَ المدرّبَ رسميّا عند توقيعي — وهذا خطأ».

   وهو خطأٌ وقع منّي: قرارُ ٢٦ سبتمبر الأوّلُ كان «بعد أن أوقّع كأدمن يتحوّل
   إلى مدرّب نشط مباشرة»، فنُفِّذ بحرفه **بلا الحارس الذي يجعله اعتمادَ
   موادَّ لا تخطّيا لها**. فصار الزرُّ يعمل بعد توقيع المدرّب بثانية، وطورُ
   الموادّ كلُّه — وهو الذي بُني له العرضُ المشروط — يسقط بلا أن يمرّ به أحد.

   ─────────── والفرقُ بين هذا وبوّابة التجهيز ───────────

   `readiness.ts` تسأل: **أجهَّزناه نحن؟** — أتعابُه ودوراتُه وعقدُه الموقَّع.
   وهذه تسأل: **أتمَّ هو؟** — أوضع موادَّه وأعلن اكتمالَها فصارت بين يدَيك.

   وكلتاهما تمنع الاعتماد، ولا تغني إحداهما عن الأخرى: عقدٌ موقَّعٌ يُرضي
   بوّابةَ التجهيز في اللحظة التي يُوقَّع فيها، وموادُّه لم تُبدأ بعد.

   ─────────── ولمَ `under_review` وحدَها تُجيز ───────────

   هي الطورُ الذي أعلن فيه المدرّبُ اكتمالَ موادّه (`declareMaterialsComplete`)
   فتجمّدت مهلتُه ووصل الطابورَ أنّها تنتظر حكمَك. أي أنّها **بين يدَيك
   فعلا**. وما سواها:

   · `running` — يعمل، ولم يقل إنّه فرغ. فاعتمادُه حكمٌ على ما لم يُعرَض.
   · `lapsed` — انقضت مهلتُه ولم يعلن. وبابُه مفتوحٌ ليعلن ولو متأخّرا.

   ─────────── و`none` تُجيز، وهذا ما أوشك أن يُشحَن خطأً ───────────

   أوّلُ صياغةٍ لهذه البوّابة منعت `none` كذلك — «عرضٌ مشروطٌ بلا مهلة، فلا
   طورَ يُقاس عليه». **وأسقطت مئةً وستّةً وعشرين فحصا** في الجولة الكاملة.

   وعلّتُها أنّ المهلةَ تُحسَب من جلسة التهيئة (`deadlineFrom(orientationAt)`)
   **والجلسةُ اختياريّةٌ عند التركيب**. فعرضٌ مشروطٌ بلا جلسةٍ عرضٌ بلا مهلة —
   وهو حالٌ قائمةٌ لا شذوذ.

   والأخطرُ أنّ صاحبَه **لا يستطيع أن يُعلن** أصلا: `openConditionContract`
   تشترط `conditionDeadlineAt: { not: null }`. فمنعُه حبسٌ أبديٌّ خلف بابٍ
   لا مفتاحَ له — يُوقّع فلا يُعتمَد، ولا سبيلَ عنده إلى تغيير ذلك.

   فالقاعدةُ: تُحترَم مهلةٌ **قائمة**، ولا تُخترَع مهلةٌ لمن لا مهلةَ له.

   ─────────── وما لا يقوله هذا الملفّ ───────────

   لا يمنع منعا مطلقا: من ملك تجاوزَ بوّابة التجهيز يملك تجاوزَ هذه —
   بسببٍ يُكتب ويُقرأ بعد سنة. والمنعُ أن يقع الأمرُ **صامتا بلا أن يُقصَد**،
   لا أن يُسدَّ على من قصده. */

/** ما يمنع اعتمادَ صاحب هذا العرض اليومَ — و`null` إن كانت موادُّه بين يدَيك */
export function materialsGateProblemAr(f: ConditionFacts): string | null {
  const phase = conditionPhase(f)
  if (phase === 'met' || phase === 'under_review') return null
  if (phase === 'running') {
    const left = daysLeft(f)
    return left === null
      ? 'لم يُعلنْ اكتمالَ موادّه بعد — فلا موادَّ عندك لتحكم فيها'
      : `لم يُعلنْ اكتمالَ موادّه بعد — وأمامه ${left === 1 ? 'يومٌ واحد' : left === 2 ? 'يومان' : `${left} أيّام`}`
  }
  if (phase === 'lapsed') {
    return 'انقضت مهلتُه ولم يُعلنْ اكتمالَ موادّه — مدِّدْ مهلتَه، أو اطلبْ منه إعلانَها'
  }
  /* `none`: لا مهلةَ فلا طورَ فلا شيءَ يُنتظَر — ولا يُحبَس من لا يملك أن
     يُعلن (رأسُ هذه الدالّة). */
  return null
}

/** أموادُّه بين يدَيك؟ — سؤالٌ تسأله الشاشةُ قبل أن تعرض زرَّ الاعتماد */
export function materialsAreInHand(f: ConditionFacts): boolean {
  return materialsGateProblemAr(f) === null
}
