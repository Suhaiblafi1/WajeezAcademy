/* المثالُ الحسابيُّ — يُطبع في الملحق (ب) من العقد، ويُرسَل مع رابط التوقيع.

   ── الموضعُ انقلب، وما حماه لم يُترَك ──

   كان هذا المثالُ **خارجَ** الوثيقة الموقَّعة بقصد: البندُ 18-4 يجعل
   «الاتفاقيةَ وملاحقها» كاملَ ما اتّفق عليه الطرفان، فجدولٌ وُضع ليُقنع، إن
   دخل الملحق، صار بندا يُحتجّ به يومَ يخيب التسجيل.

   وقرارُ صاحب المنصّة (٢١ سبتمبر ٢٠٢٦) نقض الموضعَ لا العلّة: «المثال الذي
   أرفقته بالإيميل للمستحقات يجب أن يكون داخل العقد كمثال هناك، وأوضح أنّه
   مثال فقط». فدخل — ومعه ما كان يحميه، مكتوبا في الوثيقة نفسِها لا خارجَها:

   · **استثناءٌ صريحٌ في 18-4** يُخرج هذا المثالَ من «كامل ما اتّفق عليه
     الطرفان»، فلا يُقرأ بندا يُحتجّ به.
   · **وإحالةٌ من 4-1** تقول إنّه استرشاديّ قبل أن يبلغه القارئ.
   · **وصدرُ المثال نفسُه** يقول إنّ الأعدادَ مفترضةٌ وإنّه لا يَعِد بفتح
     شعبةٍ ولا بإسنادٍ ولا بعددِ مسجّلين.

   وتنويهٌ واحدٌ لا يكفي في وثيقةٍ من عشرين بندا — وثلاثةٌ في ثلاثة مواضعَ
   تُقرأ في ثلاثة مساقات هي ما يجعل «مثال» تُقرأ مثالا.

   ── وصيغتان لنصٍّ واحد ──

   الأرقامُ من محرّكٍ واحد (`perSeatBreakdown`)، والصياغتان تختلفان لأنّ
   القارئَ يختلف: `feeExampleFactsAr` للبريد بلسانه المشكول، و
   `feeExampleContractAr` للعقد بلسانه المجرَّد — فوثيقةٌ نصفُها مشكولٌ
   ونصفُها لا تُقرأ وثيقةً واحدة. ولا يُنسَخ حسابٌ في الصيغتين: كلتاهما
   تقرأ `FeeExample` نفسَه.

   ── وثلاثةٌ لا يُكتب فيها مثالٌ أصلا ──

   · **بلا قاعدةِ أتعابٍ** أو بأجرٍ مُعفًى: لا رقمَ يُبنى عليه.
   · **ونسبةُ الإيراد**: الرقمُ فيها دالّةٌ في سعرِ المقعد وهو رقمُنا نحن لا
     رقمُه، وإخراجُه يثبّت سعرَ الدورة في ذهنه قبل أن يوقّع.
   · **وبلا سعرٍ للإحالة**: يسقط ذكرُ الرابط كلُّه، فلا يُوعَد بقناةٍ لا
     تُحتسب له.

   ── وما لا يُسمّى هنا بقصد ──

   لا تُسمّى المقاعدُ العامّةُ «من تسويق الأكاديميّة». المحرّكُ لا يعرف ذلك:
   `general = total − referred` — كلُّ ما لم يسجّل عبر رابط **هذا** المدرّب،
   ومنه ما جاء به هو بلا رابطه، وما جاء برابط مدرّبٍ آخر. والحدُّ الأدنى
   يُكمَّل من هذه الخانة، فقد تحمل مقاعدَ لا يقابلها مسجَّلٌ أصلا. */

import type { ContractCompensation } from './contract-body'
import { perSeatBreakdown } from './seat-fee'

/** الشعبُ المفترَضةُ في المثال — أعدادٌ تُعلَن أنّها افتراض، لا توقُّعُ تسجيل */
const SCENARIO = [
  { seats: 20, referred: 10 },
  { seats: 12, referred: 3 },
  { seats: 5, referred: 2 },
] as const

export interface FeeExampleRow {
  labelAr: string
  amount: number
  /* ═══ والأرقامُ بجانب النصّ لا داخلَه وحدَه ═══

     الصفُّ كان نصّا واحدا يحمل حسابَه في تضاعيفه، فصيغةٌ ثانيةٌ لقارئٍ ثانٍ
     (العقدُ بلسانه المجرَّد) كانت تعني إمّا نسخَ الحلقة وحسابَها — وذاك
     رقمان لشيءٍ واحد يفترقان يوما — أو تفكيكَ النصّ بتعبيرٍ نمطيّ. فخرجت
     الأعدادُ إلى حقولها، والصياغةُ تُبنى عليها لا تُقرأ منها. */
  /** عددُ المسجّلين المفترَض في هذا الصفّ — غائبٌ في الأجر الثابت */
  seats?: number
  /** منهم عبر رابط إحالته */
  referred?: number
  /** والمحتسَبُ عامّا — قد يفوق الفعليَّ حين يُكمَّل الحدُّ الأدنى */
  generalSeats?: number
  floorApplied?: boolean
}

export interface FeeExample {
  rows: FeeExampleRow[]
  total: number
  currency: string
  noteAr: string
}

/** رقمٌ يُقرأ: منزلتان عند الحاجة، وبلا أصفارٍ معلّقة */
function num(n: number): string {
  return Number.isInteger(n) ? String(n) : n.toFixed(2).replace(/\.?0+$/, '')
}

export function buildFeeExampleAr(c: ContractCompensation | null): FeeExample | null {
  if (!c) return null
  const rate = Number(c.rate)
  if (!Number.isFinite(rate) || rate <= 0) return null

  if (c.type === 'fixed_per_cohort') {
    const rows = SCENARIO.map((_, i) => ({
      labelAr: `الشعبة ${['الأولى', 'الثانية', 'الثالثة'][i]}`,
      amount: rate,
    }))
    return {
      rows,
      total: rate * rows.length,
      currency: c.currency,
      noteAr: 'أتعابُك مبلغٌ ثابتٌ عن الشعبة، فلا يتغيّر بعدد المسجّلين. وعددُ الشعب أعلاه '
        + 'مفترضٌ للإيضاح وحدَه: لا تعِد هذه الصفحةُ بإسناد دورة ولا بفتح شعبة، '
        + 'والذي يلزم الطرفين هو الاتفاقيةُ وملاحقُها.',
    }
  }

  if (c.type !== 'per_seat') return null

  const referralRate = c.referralRate === null ? null : Number(c.referralRate)
  const minSeats = c.minSeats ?? 0
  const rows: FeeExampleRow[] = []

  for (const [i, s] of SCENARIO.entries()) {
    const referred = referralRate === null ? 0 : s.referred
    const b = perSeatBreakdown({
      general: s.seats - referred, referred, rate, referralRate, minSeats,
    })
    /* والأعلى أوّلا (٢١ سبتمبر ٢٠٢٦): «ابدأ بالأعلى وهو رابط الإحالة الخاص
       به وبعدها نذكر السعر الاعتيادي». والمقاعدُ بالإحالة تسبق العامّةَ هنا
       أصلا، فالقلبُ وقع في نصّ القاعدة أسفلُ لا في الصفوف. */
    const parts: string[] = []
    if (referred > 0) parts.push(`${referred} عبر رابط إحالتك`)
    parts.push(`${b.generalSeats} مقعدا عامّا${b.floorApplied ? ` (احتُسبت على الحدّ الأدنى ${minSeats} مقعدا)` : ''}`)
    rows.push({
      labelAr: `الشعبة ${['الأولى', 'الثانية', 'الثالثة'][i]} — ${s.seats} مسجّلا: ${parts.join('، و')}`,
      amount: b.total,
      seats: s.seats,
      referred,
      generalSeats: b.generalSeats,
      floorApplied: b.floorApplied,
    })
  }

  const referralNote = referralRate === null ? '' : ' والمقعدُ العامُّ هو كلُّ مقعدٍ لم يسجّل عبر رابطك.'
  return {
    rows,
    total: rows.reduce((t, r) => t + r.amount, 0),
    currency: c.currency,
    /* والأعلى يُذكَر أوّلا — قرارُ ٢١ سبتمبر ٢٠٢٦. وكان العامُّ يتقدّم فيقرأ
       المدرّبُ الأصغرَ أوّلا ويثبت في ذهنه، ويأتيه سعرُ رابطه ذيلا. */
    noteAr: `الأسعارُ أعلاه هي المثبتةُ في قاعدة أتعابك (`
      + `${referralRate === null ? '' : `${num(referralRate)} ${c.currency} للمقعد عبر رابطك، و`}`
      + `${num(rate)}${referralRate === null ? ` ${c.currency}` : ''} للمقعد العامّ`
      + `${minSeats > 0 ? `، وحدٌّ أدنى ${minSeats} مقعدا` : ''}).${referralNote}`
      + ' وأعدادُ المسجّلين مفترضةٌ للإيضاح وحدَها: لا تعِد هذه الصفحةُ بعددِ مسجّلين،'
      + ' ولا بإسناد دورة، ولا بفتح شعبة. والذي يلزم الطرفين هو الاتفاقيةُ وملاحقُها.',
  }
}

/* ═══ وحُذف من هنا مُنسِّقُ صفوف البريد (٢٣ سبتمبر ٢٠٢٦) ═══

   كان `feeExampleFactsAr` يبني صفوفَ «حقائق» للمثال في بريد العقد. وجوابُ
   صاحب المنصّة أن يكون المثالُ «في العقد وحدَه»، فخرج من البريد — فبقيت
   الدالّةُ بلا قارئٍ إلّا اختبارَها، وذاك حارسٌ يحرس نفسَه.

   وصياغةُ الوثيقة (`feeExampleContractAr` أدناه) هي الباقيةُ، وهي المقصودةُ
   أصلا: المثالُ يُقرأ بجانب القاعدة التي يشرحها في الملحق (ب). */

/** صدرُ المثال في العقد — العبارةُ التي تجعله يُقرأ مثالا لا بندا.

    وهي ثابتةٌ لا تُبنى: من بحث في الوثيقة عن «لا يرتب التزاما» وجدها، ومن
    قابلها بالبند 18-4 وجد الاستثناءَ نفسَه بحروفه. ولذلك تُصدَّر كي يحرسها
    الاختبارُ في موضعَيها معا. */
export const FEE_EXAMPLE_HEADING_AR = 'مثال حسابي توضيحي — استرشادي لا يرتب التزاما'

/** المثالُ كما يُطبع في الملحق (ب) — بلسان الوثيقة لا بلسان البريد.

    ولمَ صياغةٌ ثانيةٌ ولا يُنسخ نصُّ البريد: متنُ العقد مجرَّدٌ من الشكل من
    أوّله إلى آخره، ونصُّ البريد مشكول. ووثيقةٌ يُشكَل نصفُها وحدَه تُقرأ
    قطعتين ألصقتا. والأرقامُ واحدةٌ في الصيغتين: كلتاهما تقرأ `FeeExample`
    الذي بناه `perSeatBreakdown` مرّةً. */
export function feeExampleContractAr(ex: FeeExample, c: ContractCompensation): string {
  const order = ['الأولى', 'الثانية', 'الثالثة']
  const rows = ex.rows.map((r, i) => {
    const label = order[i] ?? String(i + 1)
    if (r.seats === undefined) return `${i + 1}. الشعبة ${label}: ${num(r.amount)} ${ex.currency}`
    const parts: string[] = []
    /* الأعلى أوّلا هنا أيضا — قرارُ ٢١ سبتمبر ٢٠٢٦ */
    if (r.referred) parts.push(`${r.referred} منهم عبر رابط إحالته`)
    parts.push(
      `${r.generalSeats} مقعدا عاما`
      + (r.floorApplied ? ` (احتسبت على الحد الأدنى ${c.minSeats} مقعدا)` : ''),
    )
    return `${i + 1}. الشعبة ${label} — ${r.seats} مسجلا، ${parts.join('، و')}: ${num(r.amount)} ${ex.currency}`
  })

  const basis = c.type === 'fixed_per_cohort'
    ? 'وأتعاب المدرب في هذا المثال مبلغ ثابت عن الشعبة، فلا تتغير بعدد المسجلين، وعدد الشعب أعلاه مفترض.'
    : `والأسعار المطبقة أعلاه هي المبينة في هذا الملحق (${
      c.referralRate ? `${c.referralRate} ${c.currency} للمقعد عبر رابط إحالته، و${c.rate} للمقعد العام` : `${c.rate} ${c.currency} للمقعد`
    }${c.minSeats && c.minSeats > 0 ? `، وحد أدنى ${c.minSeats} مقعدا` : ''}).`

  return [
    FEE_EXAMPLE_HEADING_AR,
    '',
    'هذا مثال يبين كيف تترجم قاعدة الأتعاب المبينة في هذا الملحق إلى أرقام. وأعداد المسجلين فيه'
    + ' مفترضة للإيضاح وحدها: لا يعد هذا المثال جزءا مما اتفق عليه الطرفان في تطبيق البند 18-4،'
    + ' ولا يرتب على الأكاديمية التزاما بإسناد دورة ولا بفتح شعبة ولا بعدد مسجلين، ولا يحتسب على'
    + ' أساسه مستحق. والملزم للطرفين هو قاعدة الأتعاب أعلاه وحدها.',
    '',
    ...rows,
    `مجموع هذا المثال: ${num(ex.total)} ${ex.currency}`,
    '',
    basis,
  ].join('\n')
}
