/* ═══ نسبُ العقد: من حلَّ محلَّ من ═══

   ─────────── البلاغُ الذي وُلد منه ───────────

   صاحبُ المنصّة (٢٦ سبتمبر ٢٠٢٦)، أمام ثلاثة صفوفٍ لمدرّبٍ واحد: «لم أفهم
   لماذا هذا التكرار؟».

   ولم تكن تكرارا: كان كلُّ صفٍّ **جيلا** من عقدٍ واحد. فوثيقةٌ مسَّها توقيعٌ
   لا تُحرَّر في مكانها — يُغلَق الأصلُ ويُركَّب بديلٌ. فثلاثةُ تصحيحاتٍ
   ثلاثةُ صفوف، وهو الصواب.

   ─────────── وأين كان العطب ───────────

   `replacesContractId` يُكتب منذ المرحلة الثالثة (`reissueWithCorrectedName`
   و`answerAmendmentWithNewContract`) **ولا يُقرأ في شاشةٍ قطّ**. فالنسبُ
   محفوظٌ في القاعدة ومقطوعٌ في العين: ثلاثةُ صفوفٍ هي قصّةٌ واحدةٌ تُعرَض
   قصصا ثلاثا لا رابطَ بينها.

   ─────────── وما يترتّب على قطعه ───────────

   أخطرُ من الحيرة: **الوعدُ المستوفى يبقى معروضا**. صفُّ من رُفض توقيعُه
   يعرض «صحّحِ الاسمَ وأعِدْ إرساله» — وقد أُرسل البديلُ فعلا وينتظر توقيعَه.
   فمن ضغطه ثانيةً ركّب جيلا رابعا لا يريده أحد، وأبطل رابطَ الثالث.

   فمعرفةُ **أنّ لهذا العقد خلَفا** هي التي تُغلق ذلك الباب.

   ─────────── وما لا يستطيعه النسبُ المسجَّل ───────────

   العمودُ يُكتب منذ المرحلة الثالثة، وما قبلَها **فارغ**: عقودُ التجربة
   التي سأل عنها صاحبُ المنصّة رُكّبت في ٢٤ و٢٥ سبتمبر بـ`composeContract`
   اليدويّة، فلا أبَ مسجَّلا لواحدٍ منها. فحصرُ الطيّ على النسب المسجَّل
   يترك سؤالَه بلا جواب على البيانات التي أمامه.

   ولا يُستنبَط نسبٌ بالتخمين: ربطُ وثيقتَين موقَّعتَين بقرينةِ وقتٍ وسببٍ
   مكتوبٍ حدْسٌ يُكتب في ملفٍّ قانونيّ، ويُقرأ بعد سنةٍ حقيقةً.

   فبابان لا واحد، ولا يدّعي أحدُهما ما عند الآخر:
   · **الجمعُ للعرض** بصاحب العقد — وهي حقيقةٌ مقروءةٌ لا استنباط: هذه
     عقودُ فلانٍ، أحدثُها حيٌّ وما قبله مضى.
   · **والجيلُ** لا يُقال إلّا حيث سُجّل الأبُ فعلا.

   ─────────── ولمَ هنا لا في الشاشة ───────────

   مشيٌ في سلسلةٍ قد تكون معطوبة: صفٌّ يشير إلى نفسه، أو حلقةٌ بين اثنين،
   أو أبٌ خارج ما حُمّل (القائمةُ تأخذ مئتَين). وثلاثتُها تُعلّق الشاشةَ
   لو مُشيت بسذاجة — فتُمشى هنا مرّةً واحدةً محروسةً، وتُقاس. */

export interface LineageFacts {
  id: string
  /** العقدُ الذي حلَّ هذا محلَّه — `null` لأوّل الأجيال */
  replacesContractId?: string | null
}

export interface LineageNode {
  /** رقمُ الجيل: ١ للأوّل، ثمّ ٢ و٣… ومن سقط سلفُه خارجَ المحمَّل بدأ من ١ */
  generation: number
  /** معرّفُ من حلَّ محلَّ هذا — و`null` يعني أنّه رأسُ سلسلته الحيّ */
  successorId: string | null
}

/** حدٌّ للمشي: لا سلسلةَ عقودٍ حقيقيّةٍ تبلغه، وهو يقطع حلقةً لو وقعت */
const MAX_DEPTH = 64

/** يقرأ النسبَ من الصفوف المحمَّلة — مرّةً واحدةً لكلّ حمولة.
 *
 *  والمشيُ **إلى الأعلى** (من الخلف إلى السلف) لا إلى الأسفل: العمودُ
 *  يشير إلى السلف، فالصعودُ قراءةٌ مباشرةٌ والنزولُ يحتاج بناءً معكوسا.
 *  والزيارةُ محروسةٌ بعمقٍ أقصى وبمجموعةِ ما مُرّ به، فحلقةٌ في البيانات
 *  تُقطَع ولا تعلّق. */
export function readLineage(rows: readonly LineageFacts[]): Map<string, LineageNode> {
  const byId = new Map<string, LineageFacts>()
  for (const r of rows) byId.set(r.id, r)

  /* من حلَّ محلَّ من — ولا يُعتدّ بإشارةٍ إلى سلفٍ غيرِ محمَّل */
  const successorOf = new Map<string, string>()
  for (const r of rows) {
    const parent = r.replacesContractId
    if (parent && parent !== r.id && byId.has(parent)) successorOf.set(parent, r.id)
  }

  const out = new Map<string, LineageNode>()
  for (const r of rows) {
    let depth = 1
    const seen = new Set<string>([r.id])
    let cur = r.replacesContractId
    while (cur && depth < MAX_DEPTH && !seen.has(cur)) {
      const up = byId.get(cur)
      if (!up) break
      seen.add(cur)
      depth += 1
      cur = up.replacesContractId
    }
    out.set(r.id, { generation: depth, successorId: successorOf.get(r.id) ?? null })
  }
  return out
}

/** مجموعةٌ تُعرَض صفّا واحدا: أحدثُها رأسا، وما قبله مطويّا تحته */
export interface ContractGroup<T> {
  head: T
  /** ما مضى — بترتيب المُدخَل نفسِه، أي من الأحدث إلى الأقدم */
  past: T[]
}

/** يجمع الصفوفَ بمفتاحٍ يُقرأ منها — صاحبُ العقد في الشاشة.
 *
 *  والرأسُ **أوّلُ ما ورد** لا أحدثُ تاريخ: القائمةُ تصل مرتَّبةً بالأحدث
 *  من الخادم، وإعادةُ ترتيبها هنا تجعل الشاشةَ تخالف ما رتّبه من رتّبه.
 *  ومن بدّل ترتيبَ الخادم بدّل الرأسَ معه بقصد.
 *
 *  ومن لا مفتاحَ له (`null`) يقف وحدَه: لا يُجمَع مع غيرِ المفاتيح في
 *  كومةٍ واحدة — فعقدان بلا صاحبٍ ليسا عقدَي صاحبٍ واحد. */
export function groupContracts<T>(
  rows: readonly T[], keyOf: (row: T) => string | null,
): ContractGroup<T>[] {
  const out: ContractGroup<T>[] = []
  const at = new Map<string, ContractGroup<T>>()
  for (const row of rows) {
    const key = keyOf(row)
    if (key === null) { out.push({ head: row, past: [] }); continue }
    const found = at.get(key)
    if (found) { found.past.push(row); continue }
    const group: ContractGroup<T> = { head: row, past: [] }
    at.set(key, group)
    out.push(group)
  }
  return out
}
