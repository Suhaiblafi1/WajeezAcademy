/* ═══ أربعُ مرشِّحاتٍ تخرج من القائمة إلى الشاشة (٢١ سبتمبر ٢٠٢٦) ═══

   قال صاحبُ المنصّة: «أريد أن تُخرج ٤ ليبلاتٍ للفرز خارجا، وهم الأكثرُ
   استخداما، تضعهم بوضوحٍ لسهولة الوصول: نشط ← مرفوض ← قيد المراجعة ←
   قبول داخلي».

   وكانت الستَّ عشرةَ كلُّها في قائمةٍ منسدلةٍ واحدة: مرشِّحُ كلِّ جلسةٍ
   يلزمه فتحُ القائمة وقراءةُ ستَّ عشرةَ سطرا ليجد أحدَ أربعة.

   ── والترتيبُ ترتيبُه هو لا ترتيبُ دورة الحياة ──

   «نشط» آخرُ الرحلة و«قيد المراجعة» أوّلُها، وهو مع ذلك وضعهما هكذا —
   لأنّ الترتيبَ هنا **بكثرة الاستعمال** لا بموضعٍ في مسار. ولو رُتّبت
   بدورة الحياة لَصارت قائمةً ثانيةً تقول ما تقوله الأولى.

   ── والعنوانُ مختصرٌ هنا وكاملٌ هناك ──

   «قبولٌ داخليّ — قيد التجهيز» عنوانٌ يصف حالةً في صفٍّ، ولا يصلح زرّا
   في شريط. فالمختصرُ للزرّ، والكاملُ يبقى في الصفّ وفي القائمة — ومفتاحُهما
   واحدٌ يُحرَس. */
export interface QuickStatus {
  /** مفتاحُ الحالة — ويُحرَس أنّه من `STATUS_LABELS` لا من خيال */
  status: string
  /** عنوانٌ قصيرٌ يسع زرّا — لا يغني عن الكامل في الصفّ */
  shortAr: string
}

