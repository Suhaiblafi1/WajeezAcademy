/* كيف يستعدّ المتقدّم للقاء التعارف — ما يقع فيه، وما يُجهَّز، وما لا يلزم.

   ═══ الصمتُ الذي كُتب له ═══

   بطاقةُ الحجز تقول المدّةَ والمكانَ **قبل** أن يختار وقتَه. فإذا حجز
   اختفت البطاقةُ وحلّ مكانها سطران: «موعدُ لقاء التعارف — الخميس ١١
   صباحا، عن بُعد». ثمّ صمت.

   ومن هنا إلى الموعد يومان أو عشرة، يملؤهما المتقدّمُ بالتخمين: أهو
   اختبار؟ أأُحضِّر عرضا؟ أآتي بسيرتي مطبوعة؟ فيأتي أحدُهم بعرضِ ثلاثين
   شريحةً لا وقتَ لها، ويأتي آخرُ بلا شيءٍ يُريه، ويتغيّب ثالثٌ لأنّه لم
   يشعر أنّه جاهز. وثلاثتُهم كانوا يستحقّون لقاءً أفضل.

   ═══ وما تفعله هذه الأسطر ═══

   ترفع جودةَ اللقاء بلا أن تزيد كلفتَه: من يعرف أنّ المطلوبَ **مثالٌ
   واحدٌ درّبه بيده** يأتي بمثالٍ جاهزٍ بدل أن يبحث عنه في اللحظة. وتقلّل
   الغيابَ: أكثرُ من يتغيّب لا يهرب من اللقاء بل من الشعور بأنّه غيرُ
   مستعدّ — فخفضُ السقف («ممّا لديك، ولا يلزمك إعدادُ جديد») يُحضِره.

   ═══ وثلاثةُ حدودٍ في الصياغة ═══

   ① **لا تُعاد المدّةُ رقما مكتوبا** — تُقرأ من `TRAINER_INTERVIEW.minutes`
      كما تقرؤها بطاقةُ الحجز ودعوةُ التقويم. ورقمٌ يُكتب ثلاثَ مرّاتٍ
      ينحرف مرّةً بلا أن يُحمِّر شيئا.
   ② **ولا يُطلب ما لا يُنظر فيه** — «عرضٌ» و«سيرةٌ مطبوعة» ليسا من اللقاء
      في شيء: الملفُّ يصل المُقابِلَ مقروءا قبله. فيُقال ذلك صراحةً، وإلّا
      حضّره المتقدّمُ احتياطا وأنفق وقتَه في غير موضعه.
   ③ **وما يقع عند الغياب يُقال قبل أن يقع** — من لم يحضر يعود طلبُه إلى
      الانتظار حتّى يحجز غيرَه (`interview-outcome.ts`). وذاك عدلٌ، وقولُه
      سلفا أعدلُ: يُعطي من طرأ عليه أمرٌ سببا ليضغط «عدّل» بدل أن يختفي. */

