/* ═══ ولامُ الجرّ تُدغم ولا تُكتب بشرطة ═══

   العنوانُ يُبنى من اسم اللقاء كما يسمّيه المتقدّم، لا من نصٍّ ثابتٍ يتخلّف
   عن تسميته يوم تتغيّر. ولامُ الجرّ على «لقاء التعارف» تُلصق فتصير «للقاء»،
   وعلى اسمٍ معرَّفٍ بأل تُدغم فتذهب ألفُها: «المقابلة» ← «للمقابلة». وكتابةُ
   «لـ» بالشرطة حيلةُ برمجةٍ تُقرأ في الشاشة عيبَ طباعة. */
const withLam = (noun: string): string => `ل${noun.startsWith('ال') ? noun.slice(1) : noun}`

