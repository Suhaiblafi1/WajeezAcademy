/* «طلبُ تأهيل» أم «دورةٌ يعدّها»؟ — صفّان بحالٍ واحدةٍ (`pending`) ومعنيين (١٣ أكتوبر ٢٠٢٦).

   سأل صاحبُ المنصّة عن شاشة «التأهيل والإسناد»: «ماذا عن هذه الصفحة؟» — وفيها
   ٥٥ بطاقةً تحت «طلبات التأهيل المعلّقة»، أكثرُها «من طلب الانضمام — الدورات
   التي قال إنّه يستطيع تدريسها، قيد تقييم موادّها». وليست طلبا من أحد:

     · **طلبٌ** (`request`): طلبه من يجدول شعبةً لمدرّبٍ غيرِ مؤهَّل
       (`requestQualification`)، وفيه الشعبةُ المطلوبة. والموافقةُ تؤهّل وتسند.
     · **دورةٌ يعدّها** (`preparing`): بُذرت من طلب انضمامه أو من ملحق عقده،
       ولا شعبةَ مطلوبة. يقرّر فيها **اعتمادُ خطّة شعبة إعدادها** في «شعبي»
       (`trainer-prep.service.ts`) — وزرُّ «أهّله وأسنده» عليها كان يعتمدها
       قبل أن تُقرأ خطّتُها، ولا شعبةَ يسنده إليها.

   فاختار صاحبُ المنصّة أن تُفصلا: الطابورُ للطلبات وحدَها، والدوراتُ قيد
   الإعداد قائمةٌ وحدَها بحالها ورابطِ خطّتها، وزرٌّ صريحٌ لمن أراد اعتمادها
   دون انتظار الخطّة.

   والفارقُ **بنيةٌ لا نصّ**: الطلبُ لا يُنشأ إلّا بشعبته (`requestedCohortId`)،
   وما يُبذَر من الطلب أو الملحق لا شعبةَ فيه. لا تُقرأ الملحوظة. */

import { countAr } from '../text/count-ar'

export type PendingKind = 'request' | 'preparing'

export const pendingKind = (q: { requestedCohortId: string | null }): PendingKind =>
  q.requestedCohortId ? 'request' : 'preparing'

/** سطرُ ملفّ المدرّب: كم دورةً يعدّها — ولا تُسمّى «طلبات تأهيل» */
export const preparingCoursesAr = (n: number): string =>
  `وله ${countAr(n, { one: 'دورة', two: 'دورتان', few: 'دورات', many: 'دورة' })} قيد الإعداد — تعتمد حين تعتمد خطّتها.`
