/** وصفُ أساس الأتعاب نثرا — لكلّ نوعٍ عبارتُه، فالرقمُ وحدَه لا يُفهَم */
function feeBasisAr(c: ContractCompensation): string {
  const unit = `${c.rate} ${c.currency}`
  if (c.type === 'fixed_per_cohort') {
    return `مبلغ ثابت مقداره ${unit} عن الشعبة الواحدة التي يقبلها ويقدمها كاملة.`
  }
  if (c.type === 'per_seat') {
    const floor = c.minSeats && c.minSeats > 0
      ? ` وتحتسب الأتعاب على ${c.minSeats} مقعدا على الأقل ولو قل عدد المسجلين فعلا عن ذلك.`
      : ''
    const referral = c.referralRate
      ? ` وللمقعد الذي يسجل عبر رابط الإحالة الخاص بالمدرب ${c.referralRate} ${c.currency} بدلا من ذلك.`
      : ''
    return `${unit} عن كل متعلم مسجل في الشعبة التي يقبلها ويقدمها.${floor}${referral}`
  }
  if (c.type === 'revenue_share') {
    return `نسبة مقدارها ${c.rate}% من صافي إيراد الشعبة التي يقبلها ويقدمها، محسوبة على المبالغ المحصلة فعلا بعد الاسترداد والخصومات.`
  }
  return `${unit} على أساس «${RULE_TYPE_AR[c.type] ?? c.type}».`
}

/** بدلُ التحضير حين تُلغي الأكاديميّةُ داخل النافذة — معلومٌ سلفا لكلّ أساس.

    ولمَ حدٌّ أدنى مقطوع: الأساسُ بعدد المتعلّمين يجعل أتعابَ شعبةٍ أُلغيت قبل
    أن تبدأ دالّةً في مقاعدَ لم تُحجَز — أي صفرا. وبدلٌ قيمتُه صفرٌ ليس بدلا. */
function lateCancellationFeeAr(c: ContractCompensation | null): string {
  const floor = `وفي كل حال لا يقل هذا البدل عن ${ACADEMY_LATE_CANCELLATION_FLOOR_USD} دولارا أمريكيا.`
  if (!c) return `بدل تحضير يتفق عليه الطرفان كتابة عند الاتفاق على الأتعاب. ${floor}`
  if (c.type === 'fixed_per_cohort') return `ربع الأتعاب الثابتة المبينة في الملحق (ب). ${floor}`
  if (c.type === 'per_seat') {
    const seats = c.minSeats && c.minSeats > 0 ? c.minSeats : 5
    return `قيمة المقعد الواحد مضروبة في ${seats}، مقسومة على أربعة. ${floor}`
  }
  if (c.type === 'revenue_share') return `مبلغ مقطوع تحدده الأكاديمية في الملحق (ب). ${floor}`
  return floor
}

function coursesTableAr(courses: readonly ContractCourseRow[]): string {
  if (courses.length === 0) {
    return 'لا دورات مدرجة بتاريخ هذا العقد. وتضاف الدورات التي يؤهل لها لاحقا وفق البند 2-4 دون حاجة إلى تعديل هذا العقد.'
  }
  return courses.map((c, i) => `${i + 1}. ${c.titleAr}`).join('\n')
}

function documentsListAr(docs: readonly RequiredDocument[]): string {
  if (docs.length === 0) return 'لا وثائق مطلوبة مع التوقيع.'
  return docs
    .map((d, i) => `${i + 1}. ${d.labelAr}${d.required ? '' : ' (اختيارية)'}`)
    .join('\n')
}

