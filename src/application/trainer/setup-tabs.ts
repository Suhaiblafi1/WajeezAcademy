/* ═══ من في طور الإعداد يرى ما يعمل به وحدَه (الخطوة H، ١٩ أكتوبر ٢٠٢٦) ═══

   درس صاحبُ المنصّة جانبَ المدرّب واختار («All, in order»): المدرّبُ الذي اعتمدنا توقيعَه ولم تُعتمد
   دوراتُه بعدُ (شرطُ العرض قائمٌ عليه — `hasOpenCondition`) كان يرى القائمةَ كلَّها: «طلبتي» بلا طلبة،
   و«طابور التقييم» بلا تسليم، و«جدولي» بلا لقاء. أبوابٌ يفتحها فيجدها فارغةً ولا يدري لماذا.

   فيرى في طوره ما يعمل به: لوحتَه، و«شعبي» حيث يعدّ شعبَ دوراته، و«دوراتي» حيث يقبلها، و«التسويق»،
   و«مستحقاتي» حيث عقدُه. و«التسويق» باقٍ بقول صاحب المنصّة حين رأى الصور: «ابقِ التسويقَ خارجا» —
   صورُه ومقاطعُه تُعَدّ من أوّل يوم. والأبوابُ الأخرى لا تُغلق — من جاءها برابطٍ فتحها — وتعود إلى
   القائمة يومَ يتمّ الشرط. */

/** ألسنةُ طور الإعداد — وما سواها يعود حين يتمّ الشرط */
export const SETUP_TABS: readonly string[] = [
  '/trainer',
  '/trainer/board',
  '/trainer/qualifications',
  '/trainer/marketing',
  '/trainer/earnings',
  /* ومن مُنح مراجعةَ اختبار المستوى يعمل بها من يومه — ليست من الطور */
  '/trainer/placement-review',
]

export function tabsForStage<T extends { to: string }>(tabs: readonly T[], inSetup: boolean): T[] {
  return inSetup ? tabs.filter((t) => SETUP_TABS.includes(t.to)) : [...tabs]
}
