/* الاعتمادُ بنقرةٍ واحدة — من أيّ حالةٍ حيّة.

   كان الاعتمادُ ثمانَ نقراتٍ متتابعة: مراجعة ← اختصار ← درسٌ تجريبيّ ←
   مراجعةٌ أكاديميّة ← قبولٌ مشروط ← عقد ← تهيئة ← تفعيل. وكلُّ خطوةٍ حالةٌ في
   القاعدة وزرٌّ في الشاشة، وكلُّ واحدةٍ تُنسى — فيبقى من اجتاز التقييمَ عالقا
   في منتصف السلسلة ولا يعلم أحدٌ أين وقف.

   وقرّر صاحبُ المنصّة أن يكون الاعتمادُ **بنقرةٍ واحدة**، وأن يجري ما عداه
   خارج المنصّة (مقابلةً ومراجعةً يُجريها هو). **ولم تُحذف السلسلة**: من أراد
   توثيقَ مقابلةٍ أو روبركٍ أو عقدٍ فالمسارُ قائم، والطلباتُ العالقةُ في منتصفه
   لا تنكسر. الفرقُ أنّ النقرةَ الواحدة صارت ممكنةً من أيّ نقطة.

   ── ولماذا القائمةُ هنا لا في الخادم ──

   تُقرأ في موضعين: خريطةُ الانتقالات في الخادم (فيُقبل الانتقال)، وشاشةُ
   الإدارة (فيَظهر الزرّ). وقائمتان لشيءٍ واحدٍ تفترقان: فيَظهر زرٌّ يرفضه
   الخادم، أو يُخفى مسارٌ يقبله. فالمصدرُ واحد، ويحرس تطابقَه مع الخريطة
   `server/tests/trainer/one-click-approval.test.ts`.

   ── وما لا يجوز الاعتمادُ منه ──

   · `draft` و`email_verification_pending`: لم يُثبت أنّ البريدَ بريدُه، فلا
     يُفتح له حساب — والاعتمادُ يفتحه.
   · `rejected` و`withdrawn`: قرارٌ وقع، ولا يُعتمَد صاحبُه بنقرةٍ من هنا.
     وللردّ بابٌ واحدٌ منذ ١٩ سبتمبر ٢٠٢٦: «تراجَعْ عن الرفض» يعيده إلى
     «قيد المراجعة» بسببٍ يصل صاحبَه — ثمّ يُعتمَد من هناك إن رُئي ذلك.
     فخطوتان مقصودتان لا واحدة. و`withdrawn` بابُه طلبٌ جديد كما كان.
   · `suspended`: له بابُه — «ارفع الإيقاف»، لا اعتمادٌ من جديد.
   · `active`: معتمَدٌ أصلا. */

