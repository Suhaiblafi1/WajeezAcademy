/* ═══ ورابطُ توقيعٍ انقضى — اعتذارٌ نهائيٌّ يُبقي بابَ الفصول القادمة (٧ أكتوبر ٢٠٢٦) ═══
 *
 * سؤالُ صاحب المنصّة على صفّ «انقضى رابطُه»: «هل لديّ خيارُ أن أرسل له اعتذارا
 * نهائيّا لأنّ الوقت مضى، وسنتواصل معك للفصول القادمة، وإن رغب بحذف بياناته إن
 * لم يكن مهتمّا؟ اجعله مختصرا». وكان على الصفّ بابان: «جدِّدِ الرابط» و«ألغِ» —
 * والإلغاءُ يرسل سببَه بحرفه ولا خيارَ معه في البيانات.
 *
 * فعُرض عليه بديلان واختار «B»: الرسالةُ نفسُها التي تصل المعتذِرَ (نصٌّ يُحرَّر،
 * وزرٌّ إلى صفحة الخيار) — **ويصير طلبُه «مؤجَّلا» ساعةَ تُرسَل**، فيُسأل عن
 * اهتمامه بعد شهرين ويُذكَّر الفريق (`deferral.ts`) بلا يدٍ تتذكّر.
 *
 * ولماذا ساعةَ الإرسال لا ساعةَ يختار «أبقِ»: من لم يضغط شيئا يبقى طلبُه في
 * «بانتظار العقد» على عقدٍ مُغلَق — حالٌ لا خطوةَ بعدها. والرسالةُ وعدته بأن
 * نتواصل معه في الفصول القادمة، فالوعدُ يُكتب موعدا في الحال؛ ومن اختار الحذفَ
 * حُذف كما يُحذف المعتذِر.
 *
 * ولا يُعرض إلّا لمن لم يُعتمَد بعد: المدرّبُ النشطُ الذي انقضى رابطُ تجديده لا
 * يُؤجَّل — طلبُه ليس في طابور المراجعة أصلا.
 */
