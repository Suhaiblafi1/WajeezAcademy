/* ═══ ردُّنا على مدرّبٍ اعتذر عن عقده — وخيارُه في بياناته (٣ أكتوبر ٢٠٢٦) ═══
 *
 * قرارُ صاحب المنصّة على صفّ عقدٍ معتذَرٍ عنه: «ألا يكون لنا هنا ردٌّ على
 * اعتذاره لنشكره… ويسعدنا عودتُكم لاحقا للمواسم القادمة… وأعطِه فرصةَ التواصل
 * معنا في أيّ وقت». واختار «B»: زرٌّ يفتح الرسالةَ معبّأةً فتُحرَّر ثمّ تُرسَل
 * وتُحفَظ. ثمّ زاد: «نعطيه خيارَ حذف بياناته أو إبقائها للفصول القادمة، وهو
 * يقرّر بكبسة زرّ، ونحن نحذف مباشرة».
 *
 * فالرسالةُ لا تَعِد بحذفٍ نقرّره نحن — تضع القرارَ في يده: رابطٌ إلى صفحةٍ
 * فيها زرّان، والحذفُ يقع لحظةَ يؤكّده (`trainer-decline-reply.service.ts`).
 * ولماذا صفحةٌ لا رابطان يفعلان مباشرة: ماسحاتُ البريد تفتح الروابطَ قبل
 * صاحبها — فرابطٌ يحذف بفتحه يحذف بيانات من لم يقرّر شيئا.
 */

export const DECLINE_REPLY_SUBJECT_MAX = 200
export const DECLINE_REPLY_BODY_MIN = 20
export const DECLINE_REPLY_BODY_MAX = 6000
/** صلاحيةُ رابط الخيار — شهران: من لم يقرّر فيهما تبقى بياناتُه كما هي */
export const DATA_CHOICE_LINK_DAYS = 60

export type DataChoice = 'keep' | 'delete'

export const DEFAULT_DECLINE_REPLY_SUBJECT_AR = 'شكرا لك — وبابُنا مفتوحٌ لك دائما'

/** نصُّ الرسالة الأوّل — يُحرَّر قبل الإرسال. والخيارُ في البيانات يُلحَق بها
    زرّين في البريد، فلا يُكتب هنا رابط. */
export function defaultDeclineReplyAr(fullName: string): string {
  const first = fullName.trim().split(/\s+/)[0] || ''
  return [
    `الأستاذ ${first} المحترم،`,
    'نشكرك جزيلَ الشكر على الوقت والجهد اللذين بذلتهما معنا حتّى اليوم، من التقديم والمقابلة إلى قراءة الاتفاقيّة ومراجعتها بعناية، ونقدّر صراحتك في توضيح أسباب اعتذارك. فقد وصلتنا ملاحظاتُك كاملةً، وسنأخذها بعين الاعتبار ونحن نطوّر سياساتنا.',
    'نحترم قرارك تماما. ويسعدنا أن نرحّب بك مجدّدا في المواسم القادمة، آملين أن تتطوّر سياساتُنا بما يلبّي توقّعاتك. وبابُنا مفتوحٌ لك في أيّ وقت، فلا تتردّد في التواصل معنا بالردّ على هذه الرسالة متى شئت.',
    'ولك أن تقرّر ما نفعله ببياناتك: أن نُبقيها لنتواصل معك في المواسم القادمة، أو أن نحذفها الآن نهائيّا. اختر بالزرّ أدناه، وننفّذ اختيارَك مباشرة.',
    'نتمنّى لك كلَّ التوفيق في مسيرتك المهنيّة.',
  ].join('\n\n')
}

export const DATA_CHOICE_AR: Record<DataChoice, string> = {
  keep: 'أبقِ بياناتي للمواسم القادمة',
  delete: 'احذف بياناتي نهائيّا',
}
