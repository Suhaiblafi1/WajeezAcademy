/* أيُثقُ الطابورُ بما يعرفه عن الحجز؟ — سؤالٌ واحدٌ بجوابٍ واحد.

   ═══ العطبُ الذي كُتب له (٢٠ سبتمبر ٢٠٢٦) ═══

   وجد صاحبُ المنصّة «المقابلات (0)» في كلّ ملفّ، ثمّ وجد في «صحّة النظام»:
   «مزامنةُ مواعيد Calendly — آخرُ دورةٍ سقطت (ردّ 401)». والرمزُ مرفوض:
   انتهى أو أُبطل أو نُسخ ناقصا. فلا حجزَ يُقرأ، ولا صفَّ مقابلةٍ يُنشأ —
   **وثلاثةُ أشياءَ تنهار بصمتٍ خلفه**:

   ① لا شيءَ تُسجَّل عليه نتيجةُ لقاء، فتبقى أزرارُ النتيجة بلا موضع.
   ② فلا نتيجةَ تُكتب، فلا شارةَ في صفّ الطابور — وهي ما يُفرز به.
   ③ و«لم يحجز موعدا» يصدق على الجميع، فيُقرأ عددٌ واثقٌ لا يعني شيئا.

   ═══ ولماذا لم يُعلَم إلّا بالبحث ═══

   العطبُ **كان مكتوبا** في بطاقة «صحّة النظام» بنصّه وسببه ودوائه. لكنّ
   تلك الشاشةَ خلف `settings.manage`، ومن يقرأ الطابورَ لا يملكها. فالخبرُ
   موجودٌ في مكانٍ لا يمرّ به صاحبُ الشكوى — **وخبرٌ لا يصل من يحتاجه ليس
   خبرا**.

   فهذا الحكمُ يُقرأ بصلاحيّة الطابور نفسِها، ولا يحمل سرّا: أيعمل أم لا،
   ومتى كانت آخرُ دورة. لا رمزَ ولا جزءَ رمز.

   ═══ وحدُّ الثقة هو حدُّ «صحّة النظام» نفسُه ═══

   `SYNC_STALE_MS` يُقرأ هنا وهناك معا. ولو نُسخ رقمُه في الموضعين لَأمكن
   أن تقول بطاقةُ الصحّة «معطَّل» ويقول الطابورُ «يعمل» في اللحظة نفسِها —
   وهو أسوأُ من ألّا يقول أحدُهما شيئا. */

/** ثلاثُ دوراتٍ ونصف — والدورةُ خمسُ دقائق. فما جاوزها فالعاملُ واقف */
export const SYNC_STALE_MS = 16 * 60_000

export interface SyncFacts {
  /** أمحفوظٌ رمزُه؟ */
  hasToken: boolean
  /** أمؤشَّرٌ «مفعَّل»؟ */
  enabled: boolean
  /** وقتُ آخر دورة — `null` إن لم تجرِ دورةٌ بعد */
  at: string | null
  /** خطأُ آخر دورةٍ كما كتبه العامل — `null` إن نجحت */
  errorAr: string | null
  now: Date
}

export interface SyncTrust {
  /** أيُعتمَد على ما نعرفه عن الحجز الآن؟ */
  trusted: boolean
  /** لماذا لا — جملةٌ تُقرأ في الطابور، و`null` حين يُوثَق */
  reasonAr: string | null
}

/**
 * أيَثِقُ الطابورُ بما يعرفه عن الحجز؟
 *
 * والجوابُ «لا» أوسعُ من «سقطت الدورة»: رمزٌ غائبٌ، أو تكاملٌ مطفأ، أو
 * عاملٌ واقف — كلُّها تُنتج الصمتَ نفسَه. ومن قرأ «لم يحجز موعدا» في أيٍّ
 * منها قرأ عددا لا يعني شيئا.
 */
export function interviewSyncTrust(f: SyncFacts): SyncTrust {
  if (!f.hasToken) {
    return {
      trusted: false,
      reasonAr: 'لا رمزَ محفوظٌ لـCalendly — فلا حجزَ يصل الطابورَ، ومن حجز لا يُعرف.',
    }
  }
  if (!f.enabled) {
    return {
      trusted: false,
      reasonAr: 'تكاملُ Calendly مطفأ — فالحجوزاتُ لا تصل كأن لا تكاملَ أصلا.',
    }
  }
  if (!f.at) {
    return {
      trusted: false,
      reasonAr: 'لم تجرِ دورةُ مزامنةٍ بعد — فما يُعرف عن الحجز غيرُ مكتمل.',
    }
  }
  if (f.errorAr) {
    return {
      trusted: false,
      reasonAr: `مزامنةُ مواعيد Calendly ساقطة (${f.errorAr}) — فلا حجزَ يُقرأ، و«لم يحجز موعدا» لا يُعتمد عليه.`,
    }
  }
  const staleMs = f.now.getTime() - new Date(f.at).getTime()
  if (staleMs > SYNC_STALE_MS) {
    return {
      trusted: false,
      reasonAr: 'انقطع نبضُ مزامنة المواعيد — فآخرُ ما نعرفه عن الحجز قديم.',
    }
  }
  return { trusted: true, reasonAr: null }
}
