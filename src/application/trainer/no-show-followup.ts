/** ما يلزم للحكم — لا الصفُّ كلُّه، فتُختبَر الدالّةُ بلا تركيب طلبٍ تامّ */
export interface FollowupSubject {
  status: string
  /** أحدثُ نتيجةٍ سُجّلت له — `no_show` وحدَها غيابٌ */
  interviewOutcome: string | null
}

/* ═══ ومن يُتابَع: من سُجِّل غيابُه ولم يُبَتّ أمرُه ═══

   والحالاتُ التي يُحجَز فيها هي المِحَكّ (`BOOKABLE_STATUSES`) — لأنّها
   نفسُها الحالاتُ التي يعود إليها الطلبُ بعد الغياب (`revertWhenNoLiveInterview`).
   فمن سُجِّل غيابُه ثمّ رُدّ طلبُه أو سُحب أو اعتُمد لا يُتابَع: ①تدعوه إلى
   بابٍ أُغلق، و②تنقله إلى قائمة الانتظار من حالةٍ بُتَّ فيها.

   ومن حجز موعدا جديدا بعد غيابه فأمرُه أوضحُ من متابعة: `interviewOutcome`
   يقرأ **أحدثَ نتيجةٍ سُجّلت**، وموعدُه الجديدُ بلا نتيجةٍ بعد — فيبقى
   الغيابُ آخرَ ما سُجّل، ومع ذلك يخرج بالحالة: من حجز صار في
   «حُدّد موعدُه» وهي ليست من `BOOKABLE_STATUSES`. */
export function canFollowUpNoShow(app: FollowupSubject): boolean {
  return app.interviewOutcome === NO_SHOW && BOOKABLE_STATUSES.includes(app.status)
}
