/* متابعةُ من لم يحضر لقاءَ التعارف — رسالتان تُختار إحداهما، ونصٌّ يُعدَّل.

   ═══ ما طُلب (٢٣ سبتمبر ٢٠٢٦) ═══

   قال صاحبُ المنصّة: «للمتقدّم الذي لم يحضر اللقاء أريد زرّا يُرسل له رسالةً
   نقول فيها إنّنا افتقدناه، ونطمئنّ عليه، ونرجو أن نلتقيه مستقبلا إن كان
   ما زال مهتمّا. وليكن النصُّ قابلا للتعديل: فبعضُهم نريده أن يعود ويحجز
   موعدا آخر، وبعضُهم لا نريد عودتَه — فنشكره بلطفٍ ولا ندعوه».

   ═══ والعطبُ الذي كُتب له: الغيابُ يُقابَل بالصمت ═══

   تسجيلُ «لم يحضر» لا يُرسل شيئا (بقصدٍ مكتوبٍ في `interview-outcome.ts`:
   لا تُطارِد الآلةُ أحدا)، ويعود الطلبُ إلى ما قبل الحجز. فمن غاب لعذرٍ
   قاهرٍ لا يصله منّا حرفٌ واحد: لا اطمئنانٌ ولا دعوةٌ إلى موعدٍ آخر — ولم
   يكن بيد الإدارة إلّا تذكيرُ الحجز، ونصُّه «بقيت خطوةٌ واحدة» لا يذكر
   غيابا ولا يطمئنّ على أحد.

   ═══ ورسالتان لا واحدة — لأنّ المقصدَين مختلفان ═══

   ① **نحبّ أن نلتقيه** — بابٌ يبقى مفتوحا: يحجز موعدا آخرَ من صفحة طلبه.
   ② **اطمئنانٌ وشكر** — بابٌ يُغلق بلطف: لا دعوةَ ولا تقويم.

   ═══ والنصُّ يُعدَّل قبل أن يُرسَل — والباقي لا ═══

   ما يُعدَّله الموظّفُ هو **متنُ الرسالة** وحدَه، كما في «اطلب معلومات
   إضافية». وأمّا العنوانُ والزرُّ ورقمُ الطلب والتذييلُ فمن القالب: لو تُركت
   للتحرير لَخرجت رسالةٌ بلا رقمِ طلبٍ يُسأل به، أو بزرٍّ يقود إلى لا شيء.

   **ولا اسمَ في المتن**: القالبُ يبني «مرحبا فلان،» بنفسه — فلو كُتب الاسمُ
   في النصّ القابل للتعديل لَقُرئ مرّتين، أو بقي اسمُ من قبله لمن بعده وهو
   أسوأُ ما يقع في رسالةٍ تُرسَل إلى إنسان.

   ═══ و② تنقل الحالةَ إلى قائمة الانتظار — قرارُ صاحب المنصّة ═══

   سُئل: ماذا يصير حالُ الطلب بعد ②؟ فاختار **قائمةَ الانتظار**. وبدونها
   يقع تناقضٌ يقرؤه المتقدّم بنفسه: رسالتُنا تقول «نتطلّع إلى فرصٍ أخرى
   مستقبلا» وصفحتُه تعرض تقويما وتقول «احجز موعد لقاء التعارف»، ويبقى في
   ملخّص الصباح وفي مرشّح «لم يحجز موعدا» — فيُذكّره فريقُنا بعد أسبوعٍ
   بحجزِ موعدٍ لا نريده.

   و`waitlisted` أصدقُ من `rejected` هنا: الغيابُ ليس حكما على أحد، وقائمةُ
   الانتظار تقول ما وقع فعلا — لم يُغلَق طلبُه، ولا شيءَ يناسبه الآن. */

