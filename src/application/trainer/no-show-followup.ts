/** المفاتيحُ وحدَها — يبني بها الخادمُ حارسَ طلبه، فلا قائمتان تفترقان */
export const NO_SHOW_FOLLOWUP_KEYS = NO_SHOW_FOLLOWUPS.map((f) => f.key) as [string, ...string[]]

/** الرسالةُ بمفتاحها — و`undefined` لمفتاحٍ لا نعرفه، فيردّه الخادم */
export function followupOf(key: string): NoShowFollowup | undefined {
  return NO_SHOW_FOLLOWUPS.find((f) => f.key === key)
}

