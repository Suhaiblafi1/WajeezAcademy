  /** عنوانُها في المتن */
  headingAr: string
  /** المتنُ المقترَح — يُعرض في الحوار ويُعدَّل، ولا اسمَ فيه */
  bodyAr: string
  /** اسمُ الزرّ في الرسالة — و`null` لرسالةٍ بلا زرّ (② لا تدعو إلى شيء) */
