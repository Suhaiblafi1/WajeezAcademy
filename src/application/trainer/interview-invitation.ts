/* دعوةُ لقاء التعارف — ما يُقال لمن لم يحجز موعدا، ولمن يُقال.

   ═══ ما طُلب (٢٢ سبتمبر ٢٠٢٦) ═══

   قال صاحبُ المنصّة: «أضفْ خاصيّةَ ‹احجز موعد› خاصّةً لمن لم يقوموا بحجز
   موعد: أن نطلب منهم — إنّنا مهتمّون بملفّك ونرغب بلقائك، واحجز موعدا
   لنتعرّف عليك وعلى خبراتك أكثر».

   ═══ ولمَ كان يلزم — نوعان من الكلام وليس فيهما دعوة ═══

   ① **«بقيت خطوةٌ واحدة»** — بريدُ من لم يحجز. نبرتُه نبرةُ **إجراءٍ ناقص**:
      من قرأه فهم أنّ استمارتَه لم تكتمل، لا أنّنا نريد أن نلتقيه. وهو صادقٌ
      فيما يقول ولا يقول أنفعَ ما عندنا.
   ② **و«نودّ أن نلتقيك مرّةً أخرى»** — دعوةٌ حقيقيّةٌ، لكنّها للقاءٍ **ثانٍ**
      (`inviteToBookInterview`): «مرّةً أخرى» لا تُقال لمن لم يلتقِنا بعد.

   وبطاقةُ الحجز في صفحته تفتح بـ«احجز لقاء التعارف — اختر الوقت الذي
   يناسبك»: تقويمٌ بلا سببٍ يُقرأ. فمن لم يُقَل له إنّ أحدا نظر في ملفّه لم
   يفرّق بين موعدٍ نريده نحن وحقلٍ بقي فارغا في نموذج — فأغلق الصفحةَ «ليعود
   لاحقا»، وهو الذي ذُكر أعلاه أنّه لا يعود.

   ═══ ولمَ وحدةٌ مشتركةٌ لا نصٌّ في كلّ موضع ═══

   الدعوةُ تُقرأ مرّتين: في البريد الذي يُرسله المراجعُ من الطابور، وفي
   البطاقة حين يفتح صفحةَ حالته. ولو كُتبت في الموضعَين لافترقتا عند أوّل
   تعديل — فيقرأ في بريدنا شيئا وفي موقعنا غيرَه، وهي دعوةٌ واحدةٌ إلى موعدٍ
   واحد. والوحدةُ نقيّةٌ — لا React ولا Prisma — فيستوردها الخادمُ والشاشة.

   ═══ ومن يُدعى — ولمَ لا يُدعى كلُّ من لم يحجز ═══

   «مهتمّون بملفّك» **خبرٌ عن فعلٍ وقع عندنا** لا مجاملةٌ تُقال للجميع. وهو
   يصدُق في بابَين:

   ① **من اجتاز الفرزَ الأوّليّ** (`shortlisted`) — نظرٌ وقع وقُدّم صاحبُه.
   ② **ومن خرجت إليه الدعوةُ بالبريد** — يدٌ بشريّةٌ ضغطت، واسمُها في الأثر.

   وما دونهما «مقدَّم» و«قيد المراجعة»: طلبٌ في الطابور لم يُقل فيه قولٌ بعد.
   وشاشةُ «مقدَّم» تقول لصاحبها صراحةً «ونقرأ طلبك قبله» — فبطاقةٌ فوقها تقول
   «اهتممنا بملفّك» تكذّبها في الشاشة الواحدة. فيبقى لهؤلاء نصُّ البطاقة
   المحيَّد: تقويمٌ يُحجَز منه بلا دعوى.

   ═══ ووقفُ الحجز يبدّل المطلوبَ لا الاهتمام ═══

   `INTERVIEW_BOOKING_PAUSE` يُغلق التقويم. والاهتمامُ يبقى صادقا حين يُوقَف
   — بل هو أنفعُ ما يُقال لمن ينتظر شهرا. فالمبدَّلُ **ما نطلبه**: لا يُقال
   «احجز» لبابٍ مغلق، ويُقال متى يُفتح. وهو فرعٌ في دالّةٍ لا في شاشة، ليُفحص
   طرفاه معا — فطرفُ العودة لا يُنسى يومَ تُفتح المواعيد. */

import {
  INTERVIEW_BOOKING_PAUSE, TRAINER_INTERVIEW, canRemindToBook,
} from './application-options'

/** نصُّ الدعوة — يُقرأ في البطاقة وفي البريد، ويُكتب هنا وحدَه */
export const INTERVIEW_INVITATION = {
  /** عنوانُها، وهو موضوعُ البريد نفسُه — يصدُق مفتوحا كان الحجزُ أو موقوفا */
  headingAr: 'مهتمّون بملفّك — ونرغب بلقائك',
  /** ولماذا نكتب إليه: «نظر فيه» لا «قرأه كاملا» — خبرٌ بقدر ما وقع */
  interestAr: 'نظر فريقُنا الأكاديميُّ في ملفّك، وهو يثير اهتمامَنا — ونرغب أن نلتقيك.',
  /** وما نطلبه منه حين يكون البابُ مفتوحا — بلفظ صاحب المنصّة */
  askAr: `احجز موعدَ ${TRAINER_INTERVIEW.labelAr} في الوقت الذي يناسبك، لنتعرّف عليك وعلى خبراتك أكثر.`,
  /** وحين يُوقَف الحجز: لا يُدعى إلى بابٍ مغلق، ويُقال متى يُفتح */
  waitAr: `وحجزُ المواعيد موقوفٌ مؤقّتا لامتلائها هذا الشهر (${INTERVIEW_BOOKING_PAUSE.monthAr})`
    + ` — ويصلك رابطُ حجز الموعد في ${INTERVIEW_BOOKING_PAUSE.resumeMonthAr}، ولا يلزمك شيءٌ الآن.`,
} as const

/**
 * ما يُطلب منه — حجزٌ حين يُحجَز، وانتظارٌ بشهرٍ مسمّى حين يُوقَف الحجز.
 *
 * والمعامَلُ يُمرَّر ليُفحص الطرفان معا، وافتراضُه حالُ المنصّة — فلا يقرأ
 * مُنادٍ المفتاحَ بنفسه فيفترق فرعُه عن هذا.
 */
export function invitationAskAr(paused: boolean = INTERVIEW_BOOKING_PAUSE.active): string {
  return paused ? INTERVIEW_INVITATION.waitAr : INTERVIEW_INVITATION.askAr
}

/* ═══ فعلُ الأثر — مصدرٌ واحدٌ للكاتب والقارئ ═══

   الدعوةُ تُكتب في الأثر حين تخرج (`trainer-review.service.ts`)، وتُقرأ منه
   في صفحة المتقدّم (`myApplication`) وفي ملخّص الإدارة. والاسمُ `remind`
   لا `invite` لأنّ `trainer.interview.invite` محجوزٌ لدعوة **اللقاء الثاني**
   — ولو جُمعا في فعلٍ واحدٍ لَاختلط في الأثر من دُعي أوّلَ مرّةٍ بمن دُعي
   ثانيةً، وهما خبران مختلفان عن رجلٍ في طورَين مختلفَين.

   وهو هنا لا حرفا في كلّ استعلام: لو بُدّل يوما وبقي أحدُ المواضع على القديم
   لَخرج البريدُ ولم تظهر الدعوةُ في الصفحة — عطبٌ لا يُحمِّر شيئا. */
export const INVITATION_ACTION = 'trainer.interview.remind'

/** الحالاتُ التي يصدُق فيها الاهتمامُ بلا بريدٍ خرج — الفرزُ الأوّليُّ نظرٌ وقع */
export const INTEREST_SHOWN_STATUSES: readonly string[] = ['shortlisted']

/** ما يلزم للحكم — لا الطلبُ كلُّه، فتُختبَر الدالّةُ بلا تركيب صفٍّ تامّ */
export interface InvitationSubject {
  status: string
  /** مواعيدُه القائمة — والملغى لا يُحسب موعدا، فمن ألغى لم يحجز */
  liveInterviews: number
  /** متى خرجت إليه الدعوةُ بالبريد — من الأثر، و`null` لمن لم تخرج إليه */
  invitedAt?: string | Date | null
}

/**
 * أتُعرض له الدعوةُ في صفحته؟
 *
 * والطرفُ الأوّلُ هو **مِحَكُّ الإرسال بعينه** (`canRemindToBook`): حالةٌ
 * يُحجَز فيها ولا موعدَ قائم. فمن حجز ذهبت الدعوةُ من صفحته — ولو بقيت
 * لقرأ «احجز موعدا» فوقَ موعدٍ محجوزٍ له، فحجز ثانيا ووجد المُقابِلُ موعدَين.
 */
export function isInvitedToBook(app: InvitationSubject): boolean {
  if (!canRemindToBook({ status: app.status, liveInterviews: app.liveInterviews })) return false
  return app.invitedAt != null || INTEREST_SHOWN_STATUSES.includes(app.status)
}
