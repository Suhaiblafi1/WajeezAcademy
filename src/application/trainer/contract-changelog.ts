/* ما تغيّر في كلّ إصدارٍ من المتن — نقاطا يقرؤها المدرّب.
 *
 * ═══ السؤالُ الذي تجيب عنه ═══
 *
 * **عرضٌ بين يديه قرأه، ثمّ حدّثناه — فما الذي تبدّل؟**
 *
 * وأمرُ صاحب المنصّة (٣٠ سبتمبر ٢٠٢٦): «ايميل جديد بالعقد المحدث… يجب ان
 * يقول ما هي التحديثات التي حدثت على الذي قرأه سابقاً في نقاط سهلة القراءة».
 *
 * ═══ ولمَ تُكتب بيدٍ ولا تُشتقّ بمقابلة النصّين ═══
 *
 * مقابلةُ المتنَين آليّا تُخرج ضجيجا: «تغيّر البند 4-1» لا يقول لمدرّبٍ شيئا،
 * و«أُضيف 1-7» أسوأُ — رقمٌ بلا معنى. وما ينفعه جملةٌ واحدةٌ تقول **ما صار
 * في صالحه أو عليه**: «مدّةُ الشعبة صارت تقترحها أنت».
 *
 * وذلك حكمٌ لا يُستخرَج من فرقِ حروف: يعرفه من كتب التغيير، فيكتبه معه.
 *
 * ═══ ويحرسه فحصٌ: إصدارٌ بلا نقاطه لا يخرج ═══
 *
 * `contract-changelog.test.ts` يشترط أن يحمل `CONTRACT_BODY_VERSION` نقاطَه.
 * فمن رفع الإصدارَ ونسيها سقط عنده الحاجزُ قبل أن يصل مدرّبا بريدٌ يقول
 * «حُدّث عرضُك» ولا يقول بمَ.
 */

/** نقاطُ إصدارٍ واحد — جملٌ قصيرةٌ في صيغة المخاطَب، لا أرقامَ بنودٍ عاريةً */
export interface VersionChanges {
  /** الإصدارُ كما في `CONTRACT_BODY_VERSION` */
  version: string
  /** ما تغيّر فيه — لكلّ نقطةٍ جملةٌ تامّة */
  pointsAr: readonly string[]
}

/* والترتيبُ من الأحدث إلى الأقدم — كما يُقرأ. */
export const CONTRACT_CHANGELOG: readonly VersionChanges[] = [
  {
    version: 'v17-2026-09-30',
    pointsAr: [
      'صار مكتوبا صراحةً أنّ التدريب كلَّه عن بُعد أونلاين عبر منصّة الأكاديمية:'
      + ' لا تدريبَ حضوريّ، ولا انتقالَ عليك، ولا نفقةَ سفر.',
      'عددُ ساعات الدورة صار إرشادا لا شرطا: لك أن تنقصه أو تزيده بالاتّفاق معنا'
      + ' بما يناسب مادّتك — ولا تتغيّر أتعابُك بذلك، فهي على أساس الملحق (ب) لا على الساعة.',
      'ووجودُ موادَّ مسجّلةٍ يعين على تقليل الساعات المباشرة، وهو ممّا نشجّع عليه.',
      'مدّةُ الشعبة وتوزيعُ جلساتها والمدى بينها صارت تقترحها أنت بما يناسب واجبات دورتك.',
      'والحدُّ الأعلى لعدد مقاعد شعبتك صار بيدك تحدّده، ولا نفتح مقاعدَ تتجاوزه.',
      'وبُسّطت كلماتٌ في المتن ليقرأها من ليس متمكّنا من العربيّة الفصيحة،'
      + ' ولم يتغيّر بها معنى ولا رقم.',
    ],
  },
]

/** نقاطُ إصدارٍ بعينه — و`[]` لإصدارٍ لا نقاطَ له (كالأوّل) */
export function changesForVersion(version: string): readonly string[] {
  return CONTRACT_CHANGELOG.find((c) => c.version === version)?.pointsAr ?? []
}

/* ═══ وما بين إصدارَين لا إصدارٌ واحد ═══

   من يحمل عرضُه `v15` ويُحدَّث إلى `v17` يقرأ نقاطَ `v16` و`v17` معا — وإلّا
   قيل له بعضُ ما تغيّر تحته. والترتيبُ من الأقدم إلى الأحدث ليُقرأ سردا.

   ولا يُفترَض أنّ القديمَ مذكورٌ في الجدول: عرضٌ من إصدارٍ سابقٍ للجدول
   يُقرأ له كلُّ ما فيه، وهو الصوابُ — إذ لا نعرف ما كان قبله. */
export function changesBetween(fromVersion: string | null, toVersion: string): readonly string[] {
  const order = [...CONTRACT_CHANGELOG].reverse()
  const toAt = order.findIndex((c) => c.version === toVersion)
  if (toAt < 0) return []
  const fromAt = fromVersion ? order.findIndex((c) => c.version === fromVersion) : -1
  return order.slice(fromAt + 1, toAt + 1).flatMap((c) => c.pointsAr)
}
