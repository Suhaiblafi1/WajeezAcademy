/** نقاطُ إصدارٍ بعينه — و`[]` لإصدارٍ لا نقاطَ له (كالأوّل) */
export function changesForVersion(version: string): readonly string[] {
  return CONTRACT_CHANGELOG.find((c) => c.version === version)?.pointsAr ?? []
}

/* ═══ وما بين إصدارَين لا إصدارٌ واحد ═══

   من يحمل عرضُه `v15` ويُحدَّث إلى `v17` يقرأ نقاطَ `v16` و`v17` معا — وإلّا
   قيل له بعضُ ما تغيّر تحته. والترتيبُ من الأقدم إلى الأحدث ليُقرأ سردا.

   ولا يُفترَض أنّ القديمَ مذكورٌ في الجدول: عرضٌ من إصدارٍ سابقٍ للجدول
   يُقرأ له كلُّ ما فيه، وهو الصوابُ — إذ لا نعرف ما كان قبله. */
export function changesBetween(fromVersion: string | null, toVersion: string): readonly string[] {
  const order = [...CONTRACT_CHANGELOG].reverse()
  const toAt = order.findIndex((c) => c.version === toVersion)
  if (toAt < 0) return []
  const fromAt = fromVersion ? order.findIndex((c) => c.version === fromVersion) : -1
  return order.slice(fromAt + 1, toAt + 1).flatMap((c) => c.pointsAr)
}
