/* ═══ نافذةُ الجدولة — متى تُفتح، وكم بقي فيها ═══

   ── العطبُ الذي يزيله هذا الملفّ، بالحرف ──

   كان الشرطُ مكتوبا في موضعَين بيده، وفي كليهما بـ«و» ثلاثيّة:

     open = Boolean(start && end && maxSessions)          // scheduleWindowFor
     if (!from || !to || !cap) throw 'لم تفتح الإدارةُ نافذةَ جدولة'  // assertWithinWindow

   و`setTerm` يكتب `start` و`end` من حدود الفصل ولا يكتب `maxSessions` — ولا
   يكتبه أحدٌ غيرُها إلّا الإدارةُ إن شاءت. فالمدرّبُ يختار فصلَه، ويصله
   «حُدِّد فصلُ الشعبة» أخضرَ، ثمّ يمشي إلى خطوة اللقاءات فيقرأ **«لم يُحدَّد
   فصلُ هذه الشعبة بعد — اخترْه في خطوة الاسم والمواعيد»**. المنصّةُ تأمره
   بإعادة ما فعله للتوّ. حلقةٌ مغلقةٌ لا مخرجَ منها.

   وثانيةٌ فوقها في الشاشة: `full = win.remaining <= 0` و`remaining` يُحسب
   `cap ? cap - used : 0` — فالصفرُ يعني «بلا سقف» و«بلغتَ السقف» معا. فشعبةٌ
   **بلا لقاءٍ واحد** يُقال لمدرّبها «بلغتَ سقفَ اللقاءات الذي وضعته الإدارة —
   احذف لقاءً»، وهو لا يملك ما يحذف، ولم يكن في الواجهة البرمجيّة مسلكُ حذفٍ
   أصلا.

   ── وأينَ صار البابُ بعدَها (١٧ سبتمبر ٢٠٢٦) ──

   ما فوقَ يحكي عطبا وقع حين كان الفصلُ يُختار من شاشة المدرّب. ثمّ صحّح
   صاحبُ المنصّة أنّه ليس اختيارَه أصلا: «عندما نقوم بإسناد دورةٍ لمدرّب
   نحدّد لأيّ فصلٍ ستكون». فبابُ الفصل عند الإدارة (`CohortService.setTerm`
   و`openForTrainer`)، وما هنا قاعدةُ **قراءةٍ** لا تتبدّل بذلك: من فُتحت
   نافذتُه جدول فيها، ومن لا فصلَ لشعبته يقرأ «لم تُفتَح بعد».

   ── والقاعدةُ التي تحلّها ──

   **البابُ والسقفُ شيئان لا شيء.** الفصلُ يفتح البابَ (`start` و`end`)،
   والسقفُ حدٌّ اختياريٌّ تضعه الإدارةُ إن شاءت. فغيابُ السقف يعني **بلا
   سقف** — لا «مغلق». وهو ما قاله تعليقُ `cohort-plan.service.ts` نفسُه حين
   كُتب: «وقد صار الفصلُ هو الإذن — من اختار فصلا فتحت له أشهرُه. والسقفُ
   يبقى للإدارة **إن وضعته**». الشيفرةُ خالفت تعليقَها، ولم يمشِ أحدٌ في
   المسار من أوّله إلى آخره.

   ── ولمَ ملفٌّ لقاعدةٍ من سطرَين ──

   لأنّ الموضعَين افترقا مرّةً فوقع ما وقع، ولأنّ شاشةَ المدرّب تقرأ القاعدةَ
   نفسَها: `remaining` رقمٌ يُعرض، و«بلغتَ السقف» جملةٌ تُقال. ورقمان يقولان
   الشيءَ نفسَه في مكانَين يفترقان — وهذه المنصّةُ جمعت لهذا السبب بعينه
   بوّابةَ الاعتماد في `plan-gate.ts` وبوّابةَ ظهور المدرّب في
   `trainer-visibility.ts`. */

/** أفُتح بابُ الجدولة؟ — الفصلُ وحدَه يفتحه، لا السقف */
export function windowOpen(c: {
  scheduleWindowStart?: Date | string | null
  scheduleWindowEnd?: Date | string | null
}): boolean {
  return Boolean(c.scheduleWindowStart && c.scheduleWindowEnd)
}

