/* أيُحتسب هذا المقعدُ للمدرّب؟ — البند 4-15 (١ أكتوبر ٢٠٢٦)

   ═══ القرار ═══

   طلب مدرّبٌ «ألّا تنقص أتعاب المقعد بما تردّه الأكاديمية إلى متعلّمٍ بعد
   انعقاد الجلسة الأولى، وأن يُبيَّن أثرُ الاسترداد قبل ذلك». فأقرّ صاحبُ
   المنصّة الوجهَين: من حضر الأولى فمقعدُه محفوظ، ومن لم يحضرها **ورُدّ إليه
   ثمنُه كاملا** خرج من الحساب — مقعدٌ لم يُقدَّم عنه شيء.

   ═══ وما كان قبله ═══

   كان المقعدُ يُحتسب بالتسجيل وحدَه (`enrolled | completed`)، والردُّ لا يُسقط
   التسجيل: `processRefund` يمسّ الدفعةَ والطلبَ ولا يمسّ التسجيل. فمن اشترى ثمّ
   استردّ كاملا في يومه، قبل أن يُقدَّم له شيء، بقي يُدفع عنه للمدرّب. وكان
   المُسقَطُ (`dropped`) لا يُحتسب أبدا — ولو حضر الأولى ثمّ أُسقط بعد ردّ ثمنه،
   وذلك عينُ ما يمنعه البند: «ومن حضر الجلسة الأولى احتسب مقعده في كل حال».

   ═══ والحكمُ في أربعة أسطر ═══

   · `waitlisted` ليس مقعدا.
   · `dropped` يُحتسب إن حضر الأولى، ولا يُحتسب إن لم يحضرها — فقد غادر
     الشعبةَ قبل أن يُقدَّم له شيء، ومن نُقل إلى شعبةٍ أخرى يُحتسب فيها هي.
   · `enrolled | completed` يُحتسب إن حضر الأولى، وإلّا فيُحتسب ما لم يُردّ
     إليه ثمنُه كاملا.
   · «رُدّ كاملا» = له طلبٌ مموِّلٌ واحدٌ على الأقلّ، وكلُّ طلباته المموِّلة
     لهذه الشعبة `refunded`. فمن اشترى فاستردّ فعاد فاشترى يُحتسب.

   ═══ وما لا يعرفه المحرّكُ — فيقع في صالح المدرّب ═══

   الردُّ مبلغٌ على دفعةٍ لا على بند (`Refund` لا يعرف بنودَه)، فطلبٌ فيه
   شعبتان رُدّ ثمنُ إحداهما يُقرأ `partially_refunded` — فيُحتسب مقعدُ كلٍّ
   منهما. وهو ما يقوله البندُ نفسُه: «والرد الجزئي لا يخرج المقعد من
   الاحتساب». فالخطأُ الممكنُ هنا في جهة المدرّب لا علينا. */

/** حالاتُ التسجيل التي قد تُحتسب — وما سواها (`waitlisted`) ليس مقعدا */
export const SEAT_STATUSES = ['enrolled', 'completed', 'dropped'] as const

/** والحضورُ ما سجّلته المنصّة: حاضرٌ أو متأخّر. والغيابُ بعذرٍ ليس حضورا */
export const ATTENDED_STATUSES = ['present', 'late'] as const

/** الطلباتُ التي موّلت مقعدا — وما لم يُدفَع (`pending_payment | cancelled`) لا يموّل شيئا */
export const FUNDING_ORDER_STATUSES = ['paid', 'partially_refunded', 'refunded'] as const

export interface SeatEvidence {
  /** حالةُ التسجيل */
  status: string
  /** أحضر الجلسةَ الأولى غيرَ الملغاة من الشعبة؟ */
  attendedFirstSession: boolean
  /** حالاتُ الطلبات المموِّلة لهذا المقعد — فارغةٌ لمقعدٍ بلا طلبٍ (تسجيلٌ بيد الإدارة) */
  fundingOrderStatuses: readonly string[]
}

/** أيُحتسب هذا المقعد؟ — البند 4-15 */
export function seatCounts(e: SeatEvidence): boolean {
  if (e.status === 'dropped') return e.attendedFirstSession
  if (e.status !== 'enrolled' && e.status !== 'completed') return false
  if (e.attendedFirstSession) return true
  const fullyRefunded = e.fundingOrderStatuses.length > 0
    && e.fundingOrderStatuses.every((s) => s === 'refunded')
  return !fullyRefunded
}
