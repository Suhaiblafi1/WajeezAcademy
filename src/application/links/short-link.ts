/* الرابطُ القصير — قاعدتُه يقرؤها الخادمُ والشاشة (ط-٣).

   ═══ ما يُحَلّ ═══

   روابطُ البريد تحمل رموزا طويلةً معتِمة (`/auth/verify?token=…`)، وكلُّ زرٍّ
   يطبع عنوانَه كاملا تحته — وذلك مقصودٌ لا سهو: من يطبع الرسالةَ أو تُعطَّل
   عنده الروابطُ لا يبلغه الزرُّ وحدَه. فالعنوانُ لازمٌ تحته، وطولُه يقبُح.

   فالقصيرُ يجمع الاثنين: يُقرأ تحت الزرّ في سطر، ويُنسخ باليد، ويُملى في
   مكالمةٍ إن لزم.

   ═══ ولمَ `‎/s/` لا `‎/r/` ═══

   `‎/r/:token` مأخوذٌ من قبلُ: سجلُّ المتقدّم برابطٍ باسمِ قارئه (قرارُ ١٣
   سبتمبر). فلو أُخذ لَتنازع البابان على عنوانٍ واحد.

   ═══ والوجهةُ مسارٌ داخليٌّ لا عنوانٌ مطلق ═══

   وهذا **حدُّ أمانٍ لا ذوق**: جدولٌ يحفظ عنوانا يكتبه أحدٌ ويُحوِّل إليه
   الزائرَ بلا شرطٍ هو «تحويلٌ مفتوح» — يُرسَل الضحيّةُ رابطا على نطاق
   الأكاديمية فيثق به، ثمّ يجد نفسَه في موقعٍ آخرَ يطلب كلمةَ مرورها.

   فالشرطُ بنيويّ: يبدأ بشرطةٍ مائلةٍ واحدة، ولا شرطتَين (`//evil.com` عنوانٌ
   مطلقٌ بلا مخطَّط)، ولا شرطةً عكسيّةً (بعضُ المتصفّحات تعدّها مائلة)، ولا
   حرفَ تحكّمٍ ولا فراغا. */

import { randomUnambiguousCode } from '../text/unambiguous-code'

/** بادئةُ الرابط القصير في المنصّة */
export const SHORT_LINK_PREFIX = '/s/'

/** ستّةُ أحرفٍ من اثنَين وثلاثين = نحوُ مليارٍ — ويبقى سطرا يُقرأ */
export const SHORT_CODE_LENGTH = 6

/** رمزٌ جديدٌ للرابط القصير */
export function newShortCode(): string {
  return randomUnambiguousCode(SHORT_CODE_LENGTH)
}

/** مسارُ الرابط القصير في المنصّة — يبني الخادمُ المطلقَ منه */
export function shortLinkPath(code: string): string {
  return `${SHORT_LINK_PREFIX}${code}`
}

/** أوجهةٌ يجوز التحويلُ إليها؟ — مسارٌ داخليٌّ وحدَه، ولا شيءَ سواه */
export function isSafeTarget(target: string): boolean {
  if (target.length === 0 || target.length > 512) return false
  /* مسارٌ لا عنوان: شرطةٌ واحدةٌ في أوّله */
  if (!target.startsWith('/')) return false
  /* `//host` عنوانٌ مطلقٌ يرث مخطَّطَ الصفحة — وهو بابُ التحويل المفتوح */
  if (target.startsWith('//')) return false
  /* الشرطةُ العكسيّةُ تُقرأ مائلةً عند بعض المتصفّحات: `/\evil.com` */
  if (target.includes('\\')) return false
  /* فراغٌ أو حرفُ تحكّمٍ — يُستعمل لتمويه ما بعده.

     ويُفحَص بالرمز لا بنمطٍ يحمل حروفَ التحكّم: نمطٌ كذلك يُحمّر حاجزَ
     التلويم (`no-control-regex`) بحقّ — فحروفُ التحكّم في نصِّ نمطٍ تُقرأ
     خطأً وتُنسخ خطأً. والحلقةُ تقول ما تعنيه. */
  for (let i = 0; i < target.length; i += 1) {
    const c = target.charCodeAt(i)
    if (c <= 0x20 || c === 0x7f) return false
  }
  /* والفراغُ غيرُ اللاتينيّ (مثلُ U+00A0) يموّه كما يموّه الفراغ */
  if (/\s/u.test(target)) return false
  return true
}
