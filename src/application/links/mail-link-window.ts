/* مهلةُ الروابط التي نرسلها بالبريد — رقمٌ واحدٌ وجملةٌ واحدة.

   ═══ القرار ═══

   قرارُ صاحب المنصّة (١٩ سبتمبر ٢٠٢٦): «الرابط صالح لمدّة ٧ أيّام غير
   احترافيّة. يجب أن يكون لـ٢٤ ساعة بحدّ أقصى». وكان المدى ثلاثةً لا واحدا:
   سبعةُ أيّامٍ لرابط طلب الانضمام، وثمانٍ وأربعون ساعةً لرابط توثيق الحساب،
   وسبعةُ أيّامٍ لدعوة إنشاء حساب الموظّف. فصارت رقما واحدا هنا، وهو **سقفٌ**
   لا اقتراح — يحرسه `src/tests/mail-link-window.test.ts`.

   وكانت الدعوةُ خارجَ السقف يومَ كُتب هذا الملفّ، بحجّة أنّها بابُ حسابٍ لا
   توثيقُ عنوان. ثمّ أدخلها صاحبُ المنصّة فيه صراحةً (٢٠ سبتمبر ٢٠٢٦):
   «غيّر رابط دعوة الموظفين لـ٢٤ ساعة أيضا». **فالسقفُ للبابِ المرسَلِ بالبريد
   أيًّا كان ما يفتحه**، ولهذا صار الاسمُ عامًّا بعد أن كان للتوثيق وحدَه.

   ═══ ولماذا الجملةُ مع الرقم ═══

   المدّةُ تُقال للقارئ في سبعة مواضع: ثلاثُ رسائلَ (تأكيدُ طلب الانضمام،
   وتوثيقُ الحساب، وتذكيرُه)، ورسالةُ الدعوة، وشاشتان للموظّف (إنشاءُ الحساب
   وخبرُ إعادة الإرسال)، وشاشةُ الرابط المنتهي. وكانت مكتوبةً بيدٍ في كلٍّ
   منها — فيتغيّر الرقمُ في الخدمة وتبقى الجملةُ تَعِد بسبعة أيّام، ولا يحمرّ
   شيء. وهذا وقع فعلا في هذا المستودَع مع مدّةٍ أخرى (مدّةُ إعادة التقديم في
   رسالة الاعتذار). فالرقمُ والجملةُ يخرجان من هنا معا.

   ودعوةُ حساب المدرّب المعتمَد (`INVITATION_TTL_MS`) دخلته في اليوم نفسِه:
   «نعم غيّره أيضا لـ٢٤ ساعة». فلم يبقَ فوق السقف رابطٌ يُرسَل بالبريد.

   ═══ ورابطُ الاستعادة أضيقُ من السقف بقصد ═══

   له مهلتُه هنا لا هناك: **ثلاثون دقيقة** بقرار صاحب المنصّة (٢٠ سبتمبر
   ٢٠٢٦)، وكانت ساعة. وهو الرابطُ الوحيدُ الذي لا يُقاس بالسقف، لأنّ ما
   يفتحه غيرُ ما تفتحه إخوتُه: البابُ الذي يُبدَّل منه قفلُ الحساب. فمن وصل
   بريدَه أحدٌ ساعتَئذٍ ملك الحسابَ كلَّه، والنافذةُ الضيّقةُ هي الفرقُ بين
   سرقةِ صندوقِ بريدٍ وسرقةِ حساب.

   وهو إجراءُ طوارئ: يُطلب ويُستعمل في دقائق، ومن فاتته المهلةُ يطلبه من
   جديدٍ بنقرة — فالثمنُ نقرةٌ والعائدُ نصفُ ساعةٍ أقلَّ من الخطر.

   **ولا يُرفع إلى السقف قياسا على إخوته**: إخوتُه تُطيل لتُيسّر، وهذا
   يُقصَّر ليؤمّن. وما يجوز هنا خفضُه لا رفعُه. */

