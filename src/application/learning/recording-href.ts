/* ═══ رابطُ تسجيلِ اللقاء: مصدران، وقاعدةٌ واحدةٌ تقرؤهما ═══

   لتسجيلِ الجلسة بابان في `Recording` منذ أوّل يوم:

     · `storageKey` — ملفٌّ مرفوعٌ عندنا، يصل الشاشةَ رابطا موقَّعا ينتهي
       (`readUrl`). وهو ما يفعله المدرّبُ بيده.
     · `externalUrl` — رابطٌ خارجيّ. ومنذ (١٨ سبتمبر ٢٠٢٦) يكتبه
       `recording.completed` من Zoom بلا يد.

   والشاشتان اللتان تعرضان التسجيلَ — شاشةُ المدرّب ورحلةُ المتعلّم — كانتا
   تقرآن `readUrl` وحدَه وتكتبان `href={readUrl ?? "#"}`. فكلُّ تسجيلٍ يصل
   من Zoom كان سيصير سطرا يُرى ولا يفتح: `#` تعيد الصفحةَ إلى رأسها. وهو
   عطبٌ صامتٌ تامّ — التسجيلُ **وصل**، والسطرُ **ظاهر**، ولا شيءَ يقول إنّ
   النقرَ لا يفعل شيئا.

   ── ولمَ هنا لا في كلّ شاشةٍ على حدة ──

   قاعدةٌ في شاشتَين تُصلَح في واحدةٍ وتُنسى في الأخرى. فتُكتب مرّةً،
   وتقرؤها الشاشتان.

   ── وما لا رابطَ له يُسقَط ولا يُعرض ──

   صفُّ تسجيلٍ بلا `storageKey` ولا `externalUrl` ليس تسجيلا يُنقر عليه.
   وعرضُه معطَّلا خيرُ ما يُقال فيه إنّه ضجيج، وعرضُه حيًّا كذبٌ على من
   ينقره. فيُحذف من القائمة، وتعود القائمةُ فارغةً — فيقول طابورُ العمل
   `recording_missing` كلمتَه ويُرفع الملفُّ بيد. */

export interface RecordingRow {
  id: string
  title: string
  /** رابطٌ موقَّعٌ لملفٍّ مرفوعٍ عندنا — يُشتقّ من `storageKey` في الإسقاط */
  readUrl?: string | null
  /** رابطٌ خارجيّ — تسجيلُ Zoom السحابيّ يصل هنا */
  externalUrl?: string | null
  durationSec?: number | null
}

/** الرابطُ الفعليُّ لصفٍّ واحد — و`null` حين لا باب له */
export function recordingHref(r: RecordingRow): string | null {
  /* المرفوعُ أوّلا: هو عندنا، ولا ينتهي بانتهاء اشتراكِ خدمةٍ خارجيّة */
  return r.readUrl || r.externalUrl || null
}

/** الصفوفُ التي تُعرض — كلٌّ ومعه رابطُه، وما لا رابطَ له ساقط */
export function openableRecordings<T extends RecordingRow>(rows: readonly T[]): (T & { href: string })[] {
  return rows.flatMap((r) => {
    const href = recordingHref(r)
    return href ? [{ ...r, href }] : []
  })
}
