/* ما لا يُقلَّم من سجلّ الأثر — ولمَ استُثني.

   `enforceRetention` تحذف من `AuditEvent` كلَّ ما تجاوز سنتين
   (`RETENTION_DAYS.audit = 730`)، والمدّةُ صحيحةٌ لما كُتبت له: «من غيّر
   هذا؟» سؤالٌ تشغيليٌّ لا يُسأل عن فعلٍ عمرُه سنتان.

   ═══ والعقدُ ليس من ذلك الجنس ═══

   أثرُ العقد **دليلٌ في نزاعٍ قد يقع بعد سنتين**: من وقّع، ومتى، وعلى أيّ
   صياغة، ومن اعتمد توقيعَه، ومن نظر في وثيقة هويّته. ومُدَدُ التقادم في
   الالتزامات العقديّة تتجاوز السنتين بكثير في الأردنّ وفي غيره — فحذفُ
   الأثر بعدهما يمحو دفاعَنا ودفاعَه معا، ويقع **صامتا** في دورةِ عاملٍ
   ليلا لا يراها أحد.

   وليس البديلُ مدّةً أطولَ يُخمَّن رقمُها: عددُ هذه الصفوف صغيرٌ أصلا —
   حفنةٌ لكلّ مدرّب، لا صفٌّ لكلّ نقرةٍ كما في `AnalyticsEvent`. فبقاؤها
   أبدا لا يُثقل قاعدةً ولا نسخةً احتياطيّة، وحذفُها لا يوفّر شيئا يُذكر.

   ═══ ولمَ عائلةٌ بالبادئة لا قائمةُ أفعالٍ تُعَدّ ═══

   قائمةٌ تُعَدُّ واحدا واحدا تنسى الفعلَ الذي يُضاف غدا: يُكتب فعلُ عقدٍ
   جديدٌ في `labels.ts`، ولا يتذكّر كاتبُه أن يزيده هنا، فيُقلَّم بعد سنتين
   بلا أن يُنتبَه. والبادئةُ تغطّي ما لم يُكتب بعد.

   والعروضُ معها: قبولُ عرضٍ التزامٌ بوقتٍ ومال، واعتذارٌ عنه جوابٌ يُحتجّ
   به. وهما فرعٌ عن العقد لا شأنٌ تشغيليّ.

   والحارس: `server/tests/trainer/phase5-contract-lifecycle.test.ts` — يُشيخ
   ثلاثةَ صفوفٍ من الجدول نفسِه وبالعمر نفسِه (اثنان من العائلة وشاهدٌ من
   خارجها)، ويُجري التقليمَ فعلا، فيُقاس البقاءُ لا ورودُ نصٍّ في ملفّ.
   وشاهدٌ من جدولٍ آخرَ لا يصلح: يُقلَّم في نداءٍ مستقلٍّ فيمرّ الحارسُ ولو
   حُذف تقليمُ الأثر كلُّه. */

/** عائلاتُ الأثر التي لا يمسّها التقليم — بالبادئة، فتشمل ما يُضاف بعدُ */
export const PERMANENT_AUDIT_PREFIXES = [
  'trainer.contract.',
  'trainer.offer.',
] as const

/** أيُحفَظ هذا الفعلُ أبدا؟ — تُقرأ في الخادم وفي الاختبار معا */
export function isPermanentAuditAction(action: string): boolean {
  return PERMANENT_AUDIT_PREFIXES.some((p) => action.startsWith(p))
}

/** شرطُ الاستثناء كما يُركَّب في `where` — ولا يُكتب بيدٍ في موضعين.

    ولمَ دالّةٌ لا ثابتٌ: `Prisma.AuditEventWhereInput` نوعٌ من الخادم، وهذا
    الملفُّ يُقرأ من الشاشة كذلك. فتُعاد قيمةٌ عاديّةٌ يقبلها `where`. */
export function notPermanentAuditWhere(): { NOT: { OR: { action: { startsWith: string } }[] } } {
  return { NOT: { OR: PERMANENT_AUDIT_PREFIXES.map((p) => ({ action: { startsWith: p } })) } }
}
