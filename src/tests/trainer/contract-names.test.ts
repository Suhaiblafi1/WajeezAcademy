/* الاسمان: ما طُبع في الوثيقة وما وُقّع به.
 *
 * ── البلاغُ الذي وُلد منه ──
 *
 * صاحبُ المنصّة (٢٦ سبتمبر ٢٠٢٦): «اسم الطرف الثاني يجب أن يكون مطابقا
 * للهوية.. الاسم هنا هو ما أُخذ من حسابه وعادةً ليس اسما ثلاثيّا ولا يشبه
 * جواز السفر أو الهوية».
 *
 * ── وأدقُّ ما يُقاس: أنّ التنبيهَ لا يصرخ على الصواب ──
 *
 * تنبيهٌ يقع على كلّ توقيعٍ لا يُقرأ، ومن تجاوزه مئةَ مرّةٍ يتجاوزه في
 * الحادية والمئة وفيها الفرقُ الحقيقيّ. والاسمُ العربيُّ يُكتب بوجوهٍ لا
 * تختلف بها الهويّة — همزةً وتاءً وألفا مقصورةً وتشكيلا ووصلا. فيُقاس أنّ
 * هذه كلَّها **لا** تُنبّه، وأنّ كلمةً زائدةً أو اسما آخرَ **يُنبّه**.
 *
 * ── و«لم يُوقَّع» ليست «مطابق» ──
 *
 * عرضٌ أُرسل ولم يُوقَّع لا اسمَ موقَّعا به فيه. فقولُ «مطابق» فيه تطمينٌ
 * على لا شيء، ولوحةٌ خضراءُ تقول «مطابق» على عقدٍ لم يمسّه أحدٌ كذبةٌ
 * صغيرةٌ تُقرأ كلَّ يوم.
 */

import { describe, expect, it } from 'vitest'
import { nameMatch } from '@/application/trainer/contract-names'

const m = (documentNameAr: string | null, signedNameAr: string | null) =>
  nameMatch({ documentNameAr, signedNameAr })

describe('ما لم يُوقَّع لا يُقال فيه مطابق', () => {
  it('بلا توقيعٍ: `unsigned` لا `same`', () => {
    expect(m('سهيب عبد الله الخوالدة', null)).toBe('unsigned')
    expect(m('سهيب عبد الله الخوالدة', '')).toBe('unsigned')
    expect(m('سهيب عبد الله الخوالدة', '   ')).toBe('unsigned')
  })
})

describe('ولا يُنبّه على وجهٍ في الكتابة', () => {
  it('الهمزةُ تُكتب ألفا ولا تختلف بها هويّة', () => {
    expect(m('أحمد إبراهيم آدم', 'احمد ابراهيم ادم')).toBe('same')
  })

  it('والتاءُ المربوطةُ هاءً، والألفُ المقصورةُ ياءً', () => {
    expect(m('عائشة مصطفى', 'عائشه مصطفي')).toBe('same')
  })

  it('والتشكيلُ يُلقى ويُثبَت', () => {
    expect(m('سُهَيْبٌ الخَوَالِدَة', 'سهيب الخوالده')).toBe('same')
  })

  it('و«عبد الله» تُكتب موصولةً ومفصولةً في الهويّة نفسِها', () => {
    expect(m('سهيب عبد الله الخوالدة', 'سهيب عبدالله الخوالدة')).toBe('same')
  })

  it('والمسافةُ الزائدةُ ليست فرقا', () => {
    expect(m('  سهيب   الخوالدة ', 'سهيب الخوالدة')).toBe('same')
  })
})

describe('ويُنبّه على ما يُنظَر فيه', () => {
  it('كلمةٌ زائدةٌ — وهي عينُ البلاغ: اسمُ الحساب ليس ثلاثيّا', () => {
    expect(m('سهيب الخوالدة', 'سهيب عبد الله الخوالدة')).toBe('differs')
  })

  it('وكلمةٌ ناقصة', () => {
    expect(m('سهيب عبد الله الخوالدة', 'سهيب الخوالدة')).toBe('differs')
  })

  it('واسمٌ آخرُ جملةً', () => {
    expect(m('سهيب الخوالدة', 'محمد العمري')).toBe('differs')
  })

  it('وترتيبٌ مختلفٌ يُنظَر فيه — فليس كلُّ تقديمٍ هو هو', () => {
    /* لا تُطابَق الكلماتُ مجموعةً: «محمد علي» و«علي محمد» اسمان في الهويّة،
       وأحدهما أبٌ والآخرُ ابنٌ في عائلةٍ واحدة. */
    expect(m('محمد علي', 'علي محمد')).toBe('differs')
  })

  it('ووثيقةٌ بلا اسمٍ مطبوعٍ ومعها توقيع: `differs` لا `same`', () => {
    /* لا يقع في الشاشة (الاسمُ يُطبَع دائما)، ويقع في صفٍّ قديمٍ أو عطبٍ في
       هجرة. والفراغُ ليس مطابقا لشيء — ولو رُدّ `same` لَقالت الشاشةُ
       «مطابق» على وثيقةٍ لا اسمَ فيها. */
    expect(m(null, 'سهيب الخوالدة')).toBe('differs')
    expect(m('', 'سهيب الخوالدة')).toBe('differs')
  })
})
