/* صفحةُ الشعبة الواحدة — مراحلُ على خطّ، ومرحلتان: تجهيزٌ وتشغيل.

   قرارُ صاحب المنصّة (٨ سبتمبر ٢٠٢٦): صفحةٌ واحدةٌ للشعبة بدل شاشتين،
   وفيها «مراحلُ ينجزها لكلّ شعبة» — الاسمُ والمواعيدُ، والمحاورُ، والمصادرُ،
   واللقاءاتُ، والتكاليفُ، والاعتمادُ — ثمّ التشغيل. و«شعبي» بطاقاتٌ بحلقة
   تقدّمٍ من الخادم.

   والفحصُ على البنية:
   · المراحلُ تُقرأ من قائمة الخادم (`ws.checklist`) لا تُخمَّن في الواجهة،
     والمرحلةُ المفتوحةُ معلَنةٌ بـ`aria-current="step"`.
   · المرحلتان من `TabBar` لا شريطٌ مكتوبٌ بيده.
   · التشغيلُ مكوّنٌ واحد (`CohortOps`) يقرأ الشعبةَ بعينها لا القائمةَ كلَّها.
   · «شعبي» يقرأ الموجزَ ولا يحمل أدواتِ التشغيل.
   · والخادمُ يحسب القائمةَ بدالّةٍ واحدةٍ للورشة والموجز معا. */
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

const root = process.cwd()
const code = (p: string) =>
  readFileSync(join(root, p), 'utf8').replace(/\{?\/\*[\s\S]*?\*\/\}?/g, '').replace(/^\s*\/\/.*$/gm, '')

const WS = 'src/pages/trainer/CohortWorkspace.tsx'
const OPS = 'src/pages/trainer/CohortOps.tsx'
const BOARD = 'src/pages/trainer/CohortBoard.tsx'
const SVC = 'server/services/cohort-plan.service.ts'
const ROUTES = 'server/http/routes/learning-portal.routes.ts'

describe('صفحةُ الشعبة — مراحلُ على خطّ', () => {
  const ws = code(WS)

  /* ═══ ستٌّ، وأولاها المعلوماتُ الأساسيّة (٢٧ سبتمبر ٢٠٢٦) ═══

     كانت ستًّا وأولاها «الاسمُ والمواعيد»، ثمّ انطوت الأولى (ق٧ · ١٧ سبتمبر
     ٢٠٢٦) إلى بابٍ في اسم الشعبة يُفتح بقلم: لم يبقَ فيها قرار.

     ثمّ عاد فيها القرارُ الأكبر — مدّةُ الشعبة من متى إلى متى صارت للمدرّب —
     وقال صاحبُ المنصّة: «المرحلةُ الأولى هي تعديلُ المعلومات الأساسيّة للشعبة
     وليس زرَّ القلم». فانقلب الحارسُ ولم يُحذف: كان يمنع عودتَها درجة،
     وصار يمنع عودتَها بابا بقلم.

     والمحروسُ الأصليُّ باقٍ: **صفُّ `identity` في قائمة الخادم له مفتاحٌ في
     الشاشة** — درجةٌ أولى الآن لا لوحةٌ تنبثق. */
  /* ═══ وصار ترتيبُها ترتيبَ المنهج (٢٧ سبتمبر ٢٠٢٦) ═══

     «المعلوماتُ الأساسيّة ← المحاورُ ومواعيدُها ← الكرّاسات ← اللقاءات
     (المسجّلةُ والمباشرةُ معا) ← المهامُّ وغيرُها ← المرحلةُ الأخيرة». فحلّت
     «الكرّاسات» محلَّ «المصادر»، وصار صفّا المهامّ والمصادر في درجةٍ واحدة.

     والمحروسُ الأصليُّ يتّسع ولا ينقص: **كلُّ صفٍّ إلزاميٍّ في قائمة الخادم
     له درجةٌ في الشاشة** — فلا يبقى صفٌّ يحجب الإرسالَ ولا بابَ يُفتح إليه. */
  it('المراحلُ الستُّ بمفاتيح قائمة الخادم، والتكاليفُ بينها', () => {
    for (const key of ['identity', 'modules', 'workbooks', 'sessions', 'assignments', 'approval']) {
      expect(ws, `مرحلةٌ مفقودة: ${key}`).toMatch(new RegExp(`key: "${key}"`))
    }
    expect(ws, 'الحالةُ لا تُقرأ من قائمة الخادم').toMatch(/new Map\(ws\.checklist\.map\(/)
    /* وكلُّ صفٍّ في قائمة الخادم في درجةٍ من درجات الشاشة */
    const svcKeys = [...code(SVC).matchAll(/\{\s*key: '(\w+)'/g)].map((m) => m[1])
    expect(svcKeys.length, 'لم تُقرأ صفوفُ القائمة').toBeGreaterThanOrEqual(7)
    const map = ws.slice(ws.indexOf('const STAGE_KEYS'), ws.indexOf('const stageOfKey'))
    for (const k of svcKeys) expect(map, `صفُّ «${k}» بلا درجة`).toContain(`"${k}"`)
  })

  it('⚠️ والمعلوماتُ الأساسيّةُ درجةٌ أولى — لا بابٌ بقلمٍ ولا لوحةٌ تنبثق', () => {
    const order = [...ws.matchAll(/\{ key: "(\w+)", label:/g)].map((m) => m[1])
    expect(order[0], 'المعلوماتُ الأساسيّةُ ليست أوّلَ السلّم').toBe('identity')
    expect(code(SVC), 'سقط صفُّ الهُويّة من قائمة الخادم').toMatch(/key: 'identity'/)
    expect(ws, 'رجع بابُ القلم إلى حقول الهُويّة').not.toMatch(/setIdentityOpen/)
    expect(ws, 'رجعت لوحةٌ منبثقةٌ للهُويّة').not.toMatch(/<Modal\b/)
    /* ودرجتُها تُصيَّر كسائر الدرجات، وفيها المدّة */
    const step = ws.slice(ws.indexOf('stage === "identity" &&'), ws.indexOf('stage === "modules" &&'))
    expect(step, 'لا حقلَ لبدء الشعبة في درجتها').toContain('content.startsOn')
    expect(step, 'لا حقلَ لانتهاء الشعبة في درجتها').toContain('content.endsOn')
  })

  it('والمرحلةُ المفتوحةُ معلَنة', () => {
    expect(ws).toMatch(/aria-current=\{selected \? "step" : undefined\}/)
  })

  /* وكانت الشعبةُ طورين بلسانَين: «التجهيز» و«مركز التواصل». ونقل صاحبُ المنصّة
     المركزَ إلى «طلبتي» (٣٠ سبتمبر ٢٠٢٦) — فالشعبةُ تجهيزٌ وحدَه، والمخاطبةُ
     مكوّنٌ للشعبة بعينها يُعرض حيث المتعلّمون. */
  it('الشعبةُ تجهيزٌ وحدَه، ومركزُ التواصل في «طلبتي» مكوّنا للشعبة بعينها', () => {
    expect(ws, 'عاد لسانُ الطورين إلى صفحة الشعبة').not.toMatch(/<TabBar[\s\S]*?id: "run"/)
    expect(ws, 'عاد مركزُ التواصل إلى صفحة الشعبة').not.toMatch(/<CohortOps\b/)
    const learners = code('src/pages/trainer/MyLearners.tsx')
    expect(learners, 'لا مركزَ تواصلٍ في «طلبتي»').toMatch(/<CohortOps key=\{`[^`]+`\} cohortId=\{talk\.cohortId\} initialTo=\{talk\.to\}/)
    expect(learners, '«خاطِبه» لا يوجّه المركزَ إلى المتعلّم').toMatch(/onClick=\{\(\) => talkTo\(r\.cohortId, r\.enrollmentId\)\}/)
    expect(code(OPS)).toContain('/api/trainer/cohorts/${cohortId}/ops')
    expect(code(OPS), 'التشغيلُ يقرأ القائمةَ كلَّها لشعبةٍ واحدة').not.toContain('/api/trainer/my-cohorts')
  })

  it('و«شعبي» بطاقاتٌ من الموجز — بلا أدواتِ تشغيل', () => {
    const board = code(BOARD)
    expect(board).toContain('/api/trainer/cohorts/summary')
    expect(board).toContain('/trainer/cohort/${c.id}')
    expect(board, 'الحضورُ ما زال في «شعبي»').not.toContain('ATTENDANCE_OPTIONS')
    expect(board, 'الرسائلُ ما زالت في «شعبي»').not.toContain('/messages')
  })
})

describe('الخادم — قائمةٌ واحدةٌ للورشة والموجز', () => {
  const svc = code(SVC)

  it('دالّةُ القائمة واحدةٌ يقرؤها كلُّ من يحكم — لا نسخٌ تفترق', () => {
    expect(svc).toMatch(/export function buildChecklist\(/)
    /* ثلاثةُ قرّاءٍ منذ ١٥ سبتمبر ٢٠٢٦: الورشةُ، والموجزُ، و**الإرسالُ
       نفسُه**. وكان `submit` يقبل بلا أن يسأل القائمةَ — فالحاجزُ زرٌّ
       مطفأٌ في الشاشة وحدَها، لا يمنع طلبا يُرسَل بيدٍ أخرى.

       والمحروسُ عددُ النسخ لا عددُ النداءات: دالّةٌ واحدةٌ مصدَّرة، ومن
       أرادها ناداها. فلو نُسخت قاعدةٌ ثانيةٌ في `submit` لافترقت عمّا
       تعرضه الشاشة. */
    expect((svc.match(/buildChecklist\(\{/g) ?? []).length, 'الورشةُ والموجزُ والإرسالُ لا يقرؤون الدالّةَ نفسَها').toBe(3)
    expect((svc.match(/function buildChecklist\(/g) ?? []).length, 'نسخةٌ ثانيةٌ من الدالّة').toBe(1)
    /* ═══ والمهامُّ صارت شرطا (ق٨ · ١٧ سبتمبر ٢٠٢٦) ═══
       كانت `optional: true` — تُؤلَّف أثناء الشعبة. وذاك يناقض ما تبيعه
       المنصّة: «لا تكون المحاضرةُ إلزاميّةً والمُخرَجُ اختياريّا». */
    expect(svc, 'عادت المهامُّ اختياريّةً — فتُعتمَد شعبةٌ تبيع حضورا لا حُكما')
      .toMatch(/key: 'assignments'[^}]*optional: false/)
  })

  it('ومحاورُ الكتالوج الثابت تسند الورشةَ حين تخلو القاعدة', () => {
    expect(svc).toMatch(/dbModules\.length > 0 \? dbModules : await staticModulesFor\(/)
  })

  it('والمساران مسجَّلان بصلاحيّة التشغيل', () => {
    const routes = code(ROUTES)
    for (const path of ['/api/trainer/cohorts/summary', '/api/trainer/cohorts/:id/ops']) {
      const at = routes.indexOf(`app.get('${path}'`)
      expect(at, `المسارُ مفقود: ${path}`).toBeGreaterThan(0)
      expect(routes.slice(at, at + 200)).toContain("requirePermission('trainer.cohort.operate')")
    }
  })
})

/* الطورُ يسبق خطواتِه — وإلّا قُرئ «التشغيل» خانةً تتكرّر عند كلّ خطوة.

   كان خطُّ الخطوات الستّ يُصيَّر أوّلا واللسانُ تحته، ويبقى الخطُّ ظاهرا في
   التشغيل. فيراه المدرّبُ فوق «التشغيل» في كلّ خطوةٍ يفتحها ولا يدري
   أيُّهما يحوي الآخر. */
describe('الطورُ قبل خطواته', () => {
  const ws = code(WS)

  /* ═══ ودواءُ الالتباس تبدّل: من الترتيب إلى فصلِ السطحَين (ق٧) ═══

     العلّةُ الأصليّة: كان خطُّ الخطوات واللسانُ **سطرَين متجاورَين في
     بطاقةٍ واحدة**، فيُقرأ «التجهيز/التشغيل» خانةً تتكرّر عند كلّ خطوة.
     وكان الدواءُ يومَها ترتيبا: اللسانُ أوّلا ثمّ الخطوات.

     ثمّ صار الشريطُ صفًّا واحدا (الشكل «ب»)، وخرج اللسانُ منه إلى المتن —
     فلم يعودا في سطحٍ واحدٍ أصلا. والدواءُ الآن **الفصل**: للشريط حدُّه
     السفليُّ وخيطُ تقدّمه يُغلقانه، واللسانُ بعده في المتن لا فيه.

     والمحروسُ هو هو: ألّا يُقرأ الطورُ تابعا لخطوة. */
  it('⚠️ لسانُ «التجهيز/التشغيل» خارجَ سطح الخطوات — لا سطرا تحتها فيه', () => {
    const head = ws.slice(ws.indexOf('<Bar'), ws.indexOf('</Bar>'))
    expect(head, 'لا سلّمَ في الشريط').toContain('STAGES.map')
    expect(head, 'اللسانُ رجع داخلَ سطح الخطوات — فيُقرأ تابعا لها').not.toContain('<TabBar')
    /* وحدُّ الشريط وخيطُه يُغلقانه دون ما بعده */
    expect(head, 'الشريطُ بلا خيطِ تقدّمٍ يُغلق حافّتَه').toMatch(/stage-fill/)
  })

  /* ═══ ونُقض شطرُ هذا الحارس بقرارٍ (١٥ سبتمبر ٢٠٢٦) ═══

     كان هنا: «وخطُّ الخطوات لا يظهر إلّا في التجهيز» — يشترط
     `phase === "prepare" &&` قبل الخطّ مباشرةً.

     وطلبُ صاحب المنصّة: «الشريطُ العلويُّ لتعديل الشعب يجب أن يبقى ظاهرا
     للمدرّب حتّى يخرج من خانة الشعب كلِّها». فالخطُّ يبقى في الطورين معا،
     ونقرةُ خطوةٍ تردّه إلى التجهيز عندها.

     **والعلّةُ التي وُضع لأجلها لم تُهمَل**: كان يُقرأ «التشغيل» خانةً
     تتكرّر عند كلّ خطوة لأنّ الخطَّ كان يُصيَّر **قبل** اللسان. وذاك
     يحرسه الاختبارُ الذي فوقه — والترتيبُ هو الدواء، لا الإخفاء.

     وحارسُ بقاءِ الخطّ وضمورِه في `sticky-stepper.test.ts`. */
  it('⚠️ وخطُّ الخطوات يبقى في الطورين — ونقرتُه تردّ إلى التجهيز', () => {
    const steps = ws.indexOf('STAGES.map')
    const before = ws.slice(Math.max(0, steps - 400), steps)
    expect(before, 'عاد الخطُّ يختفي في «مركز التواصل»').not.toContain('phase === "prepare" &&')
    expect(ws, 'نقرةُ الخطوة لا تفتحها — فسلّمٌ يُرى ولا يُصعد')
      /* وتحفظ ما في اليد قبل أن تفتحها (٥ أكتوبر ٢٠٢٦) — فالمحروسُ أنّها تنتهي بفتحها */
      .toMatch(/const openStage = async \(s: Stage\) => \{[\s\S]*?\n {4}setStage\(s\);\n {2}\};/)
  })

  /* ═══ حدُّ المحور المفتوح ═══

     شكوى ١٣ سبتمبر ٢٠٢٦: «لا أميّز متى تنتهي الشاشةُ المنسدلة». وثمانيةُ
     محاورَ بأرضيّةٍ واحدةٍ وحافّةٍ واحدةٍ خافتة، فإذا فُتح أحدُها امتدّ خمسةَ
     حقولٍ لا يُرى طرفاه.

     والحارسُ على **الاختلاف** لا على لونٍ بعينه: من أراد نبرةً أخرى فله
     ذلك ما دام المفتوحُ يختلف عن المطويّ. ولو ثُبّت اللونُ هنا لصار الحارسُ
     يمنع تحسينَ التصميم بدل أن يمنع عودةَ العطب. */
  it('⚠️ والمحورُ المفتوح بنبرةٍ غيرِ المطويّ — وإلّا لم يُعرف أين ينتهي', () => {
    const m = ws.match(/<Card as="li"[^>]*tone=\{open \? "(\w+)" : "(\w+)"\}/)
    expect(m, 'نبرةُ بطاقة المحور لا تتبع كونَه مفتوحا').toBeTruthy()
    expect(m![1], `المفتوحُ والمطويُّ على نبرةٍ واحدة (${m![1]})`).not.toBe(m![2])
  })
})
