/* كم تبويبا يسعه شريطُ المدرّب — والباقي خلف «المزيد» (٢٧ سبتمبر ٢٠٢٦).

   قرارُ صاحب المنصّة: «اجعل قائمةَ العناوين مكتملةً ليست داخلَ المزيد، إلّا
   إذا استُخدم الهاتفُ والشاشةُ صغيرة — هناك نستخدم المزيدَ لمن لا يظهر».

   والقرارُ في دالّةٍ نقيّة (`ui/nav-fit.ts`) يُمرَّر إليها ما قاسه المتصفّح،
   فيُحرَس بأرقامٍ لا بمتصفّحٍ ولا بجلسة مدرّب. والأرقامُ مصغّرةٌ للقراءة:
   ثلاثُ حبّاتٍ بمئة، وفراغٌ بعشرة، و«المزيد» بثمانين — فالثلاثُ بفراغَيها ٣٢٠.

   ونُقضت الدالّةُ خمسَ مرّاتٍ فسقط في كلٍّ منها حارسٌ هنا (أعرافُ `CLAUDE.md`):
   تركُ مكان «المزيد» بلا حجز، والملءُ بالقفز فوق العريض، والمقارنةُ بلا سماحٍ
   لكسر البكسل، وإظهارُ الكلّ دائما، و`<` مكان `<=` على الحدّ مع نزع السماح —
   وأمّا `<` والسماحُ باقٍ فلا يُرى، ولا يضرّ: الفرقُ دون نصف بكسل. */

import { describe, expect, it } from 'vitest'
import { fitCount } from '@/components/ui/nav-fit'

const TABS = [100, 100, 100] as const
const GAP = 10
const MORE = 80

describe('كم تبويبا يسعه الشريط', () => {
  it('⚠️ الكلُّ يُرى متى وسعه الشريط — ولا «مزيدَ» على شاشةٍ واسعة', () => {
    expect(fitCount(TABS, GAP, MORE, 1000)).toBe(3)
    /* والحدُّ نفسُه يسع: شريطٌ بعرض الثلاث وفراغَيها تماما لا يُطرَد منه أحد */
    expect(fitCount(TABS, GAP, MORE, 320)).toBe(3)
  })

  it('⚠️ ومتى نقص الشريطُ بكسلا واحدا ظهر «المزيد» — لا تبويبٌ مقصوصُ الطرف', () => {
    /* ٣١٩: الثلاثُ لا تسع. ومع الزرّ: ٨٠ + ١١٠ + ١١٠ = ٣٠٠ ← اثنان */
    expect(fitCount(TABS, GAP, MORE, 319)).toBe(2)
  })

  it('⚠️ ومكانُ «المزيد» يُحجَز قبل العدّ — وإلّا قصَّ الزرُّ آخرَ ما عُدّ', () => {
    /* ٢٥٠: اثنان يسعان وحدَهما (٢١٠)، فمن عدّ أوّلا قال «اثنان» ثمّ جاء
       الزرّ (٩٠ بفراغه) فبلغ ٣٠٠ وقصَّ الثاني. والصحيحُ واحدٌ و«المزيد». */
    expect(fitCount(TABS, GAP, MORE, 250)).toBe(1)
  })

  it('وعلى أضيق شاشةٍ «المزيد» وحدَه — لا تبويبٌ مقصوص', () => {
    expect(fitCount(TABS, GAP, MORE, 150)).toBe(0)
    /* وشريطٌ لم يُرسَم بعدُ (عرضُه صفر) لا يعرض شيئا يُقَصّ */
    expect(fitCount(TABS, GAP, MORE, 0)).toBe(0)
  })

  it('⚠️ والترتيبُ أولويّة — يخرج آخرُ القائمة، ولا يُقفَز فوق عريضٍ إلى ضيّقٍ بعده', () => {
    /* الثاني عريض. ولو مُلئ الشريطُ بما يسع كيفما اتّفق لعُرض الأوّلُ والثالث
       وخرج الثاني — والإطارُ يعرض «أوّلَ N» فيقصّ الثانيَ العريض، ويتبدّل ما
       يبقى على الهاتف بعرض الشاشة لا بالأولويّة. */
    expect(fitCount([100, 300, 100], GAP, MORE, 350)).toBe(1)
  })

  it('وكسرُ البكسل لا يُخرج تبويبا يسعه الشريط', () => {
    /* ٣٢٠٫٤ في شريطٍ ٣٢٠: قصُّ خُمسَي بكسلٍ لا يُرى، و«المزيد» لأجله يُرى */
    expect(fitCount([100.2, 100.1, 100.1], GAP, MORE, 320)).toBe(3)
  })

  it('ولا قائمةَ فلا شيء — ولا «مزيد»', () => {
    expect(fitCount([], GAP, MORE, 500)).toBe(0)
  })
})
