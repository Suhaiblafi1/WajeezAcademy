/* لوحُ الشعبة — ما يؤلّفه المدرّب يُرى، وحالةُ الزرّ تُقال لا تُلوَّن.

   ثلاثةٌ رصدَتها جولةُ البند ③ في ملفَّين، وكلُّها تسقط صامتةً:

   ١) **التكاليفُ لا تظهر.** `TrainerCohort` كانت تحمل `sessions`
      و`enrollments` و`materials` ولا تحمل تكاليف، وكلمةُ `assessment`
      ترد في الملفّ مرّةً واحدةً: في `POST` الذي يُنشئها. فيؤلّف المدرّبُ
      تكليفا ويصل المسجَّلين ولا يراه هو — ولا بعد إعادة التحميل.

   ٢) **أزرارُ الحضور تقول حالتَها باللون وحدَه.** أربعةُ أزرارٍ لكلّ
      متعلّمٍ في كلّ جلسة، والمختارُ يُعرَف بـ`border-teal` فقط: لا
      `aria-pressed` ولا اسمٌ يربط الزرَّ بصاحبه. فمن لا يرى يسمع «حاضر»
      أربعَ مرّاتٍ في الجلسة الواحدة لا يعرف لمن، ولا أيُّها مضبوط.

   ٣) **«سجّل الدرجة» مفعَّلٌ قبل المراجعة**، والخادمُ يردّه ٤٠٩.

   ── والقياسُ على البنية لا على ورودِ حرف ──

   التعليقاتُ تُمحى أوّلا: شرحُ هذه الإصلاحاتِ في الشاشتَين يذكر
   `assessments` و`aria-pressed` و`under_review` بأسمائها، فلو قيس على
   النصّ الخامّ لعدّ الحارسُ **شرحَ الإصلاح** إصلاحا — ومرّ عندي ثلاثةُ
   حرّاسٍ خضراءَ لهذا السبب في هذه الجولة وحدَها. */

import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..')
/** بلا تعليقات: يُقاس ما يُنفَّذ لا ما يُشرح */
const readCode = (p: string) => readFileSync(join(root, p), 'utf8')
  .replace(/\/\*[\s\S]*?\*\//g, ' ')
  .replace(/^\s*\/\/.*$/gm, ' ')

/* التشغيلُ انتقل من «شعبي» إلى مرحلة «التشغيل» في صفحة الشعبة الواحدة
   (٨ سبتمبر ٢٠٢٦) — والحارسُ يتبع الشيفرةَ إلى موضعها الجديد بحمولته نفسِها. */
const BOARD = 'src/pages/trainer/CohortOps.tsx'
/* واللقاءاتُ والحضورُ انتقلا من التشغيل إلى «لقاءات مباشرة» (د-٤ · ١٤ سبتمبر
   ٢٠٢٦) — والحارسُ يتبعهما بحمولته نفسِها، ولا يُخفَّف لأنّ الملفَّ تبدّل. */
const SESSIONS = 'src/pages/trainer/SessionsAndAttendance.tsx'
const LIST = 'src/pages/trainer/CohortAssignments.tsx'
const QUEUE = 'src/pages/trainer/GradingQueue.tsx'
const SUBMISSIONS = 'src/pages/trainer/CohortSubmissions.tsx'

/* ═══ ع-١: «التشغيل» صار «مركزَ التواصل» — ولا يبقى فيه إلّا المخاطبة ═══

   نصُّ ع-١: «أبقِ مخاطبةَ الشعبة، وأضف مخاطبةَ المستشارين، واحذف كلَّ ما
   عداه، وسمِّه مركزَ التواصل، وأضف سطرَ حجزِ الاجتماع».

   وما كان فيه لم يُحذف كلُّه بل ذهب إلى موضعه: اللقاءاتُ والحضورُ إلى
   «لقاءات مباشرة» (د-٤)، والموادُّ إلى «المصادر»، وما سُلّم إلى «المهامّ».
   وواحدةٌ وحدَها سقطت بلا بديل — «من التحق وتقدّمُه» — لأنّ «طلبتي» تحملها
   بأسمائها ونسبها وبحثٍ ليس هنا.

   والفحصُ على **نداءات الخادم** لا على نصٍّ في عنوان: شاشةٌ تُبقي زرًّا
   يرفع مادّةً ما زالت تحمل الموادَّ مهما سُمّيت. */
describe('مركزُ التواصل لا يحمل إلّا المخاطبة', () => {
  const ops = readCode(BOARD)

  it('لا يرفع مادّةً ولا يضيف رابطَها', () => {
    expect(ops, 'موادُّ الشعبة ما زالت في مركز التواصل').not.toContain('/materials')
  })

  it('ولا يعرض تسليماتِ المهامّ', () => {
    expect(ops, 'ما سُلّم ما زال في مركز التواصل').not.toContain('<CohortAssignments')
  })

  it('ولا يسرد المتعلّمين وتقدّمَهم — و«طلبتي» تحملهم', () => {
    expect(ops, 'قائمةُ التقدّم ما زالت في مركز التواصل').not.toContain('courseProgress')
    expect(readCode('src/pages/trainer/MyLearners.tsx'), 'و«طلبتي» لا تحملهم').toContain('courseProgress')
  })

  it('والمخاطبةُ باقيةٌ بأجمهتها الثلاثة', () => {
    expect(ops).toContain('/messages')
    /* ⚠ أوّلُ صياغةٍ طلبت ورودَ «advisors» في الملفّ — فمرّت وقد نُزع الخيارُ
       من القائمة، لأنّ الكلمةَ باقيةٌ في منطق الإرسال. فصار الفحصُ على
       **ما يراه المدرّب**: خيارٌ مصيَّرٌ يختاره، ومنطقٌ يترجمه، ونصٌّ يؤكّده. */
    expect(ops, 'خيارُ مخاطبة المستشارين ليس في القائمة').toMatch(
      /<option value="advisors">[^<]+<\/option>/,
    )
    expect(ops, 'الخيارُ لا يُترجَم إلى جمهورٍ عند الإرسال').toMatch(
      /audience: msgForm\.enrollmentId === "advisors" \? "advisors"/,
    )
  })

  it('وسطرُ حجزِ الاجتماع فيه — بالمكوّن لا بنسخةٍ ثانية', () => {
    expect(ops).toContain('<BookAdminMeeting')
  })
})

describe('المؤلِّفُ يرى ما ألّف', () => {
  /* ═══ ويتبع الحارسُ الشيفرةَ إلى موضعها (ع-١ · ١٤ سبتمبر ٢٠٢٦) ═══

     «ما سُلّم وما ينتظر» انتقلت من «التشغيل» إلى مرحلة «المهامّ والتطبيق
     العمليّ»: من كتب المهمّةَ يرى تحتها من استجاب لها.

     وقد ظُنّت أوّلا تكرارَ «طابور التقييم» فحُذفت — **فأسقط هذا الحارسُ
     الحذف، وكان محقًّا**: الطابورُ صفُّ تسليماتٍ تُصحَّح واحدا واحدا، وهذه
     تقول لكلّ مهمّةٍ كم سلّم وكم ينتظر بالمقام الصحيح. سؤالان لا واحد.

     فحُمل الحارسُ كما هو إلى الموضع الجديد، ولم يُخفَّف حرفٌ منه. */
  it('المرحلةُ تُمرّر تكاليفَ الشعبة إلى قسمها — لا تعلنها في النوع ثمّ تُهملها', () => {
    const code = readCode(SUBMISSIONS)
    const i = code.indexOf('<CohortAssignments')
    expect(i, 'قسمُ التكاليف ليس في المرحلة أصلا — فالمؤلِّفُ لا يرى ما ألّف').toBeGreaterThan(0)
    /* والمقياسُ ما يُمرَّر لا ورودُ الوسم: قسمٌ بلا بياناتٍ يعرض فراغا دائما */
    const props = code.slice(i, code.indexOf('/>', i))
    expect(props, 'القسمُ مصيَّرٌ بلا تكاليف').toContain('items={row.cohort.assessments}')
    expect(
      props,
      'مقامُ «سلّم ٣ من ١٢» غيرُ ممرَّر — فيصير «من ٠» أو عددَ قائمة الانتظار معهم.',
    ).toContain('learners=')
    /* والمقامُ يستثني المنتظرين صراحةً — وهو ما كان اللوحُ يحسبه بـ`active` */
    expect(code, 'المقامُ يعدّ قائمةَ الانتظار مع من التحق').toContain('!== "waitlisted"')
  })

  it('والمرحلةُ تُصيّرها فعلا — لا ملفٌّ بلا شاشة', () => {
    const ws = readCode('src/pages/trainer/CohortWorkspace.tsx')
    const from = ws.indexOf('stage === "assignments" &&')
    const to = ws.indexOf('stage === "approval" &&')
    expect(from, 'لا مرحلةَ تكاليف').toBeGreaterThan(-1)
    expect(ws.slice(from, to), 'المرحلةُ لا تُصيّر ما سُلّم').toContain('<CohortSubmissions')
  })

  it('والقسمُ يصيّرها ويقول كم سلّم وكم ينتظر تصحيحَه', () => {
    const code = readCode(LIST)
    expect(/items\.map\(/.test(code), 'القسمُ يستقبل التكاليفَ ولا يصيّرها').toBe(true)
    expect(code, 'لا عددَ تسليماتٍ في القائمة').toContain('a.submissions.length')
    expect(
      /submissions\.filter\([\s\S]{0,200}?under_review/.test(code),
      'ما ينتظر التصحيحَ لا يُحسب — والمقبولُ والمرفوضُ خرجا من يد المدرّب، '
      + 'فعدُّ التسليمات كلِّها يقول له عملا فرغ منه.',
    ).toBe(true)
  })

  it('والحالةُ الفارغةُ تقول الحقيقةَ — لا تُترك بياضا', () => {
    /* «التكاليف» صارت «المهامّ والتطبيق العمليّ» بقرار صاحب المنصّة (١٣
       سبتمبر ٢٠٢٦)، فتبدّل نصُّ الحالة الفارغة معها. والمحروسُ هو هو: أن
       تقول الشاشةُ الفارغةُ ما فيها بدل أن تُترك بياضا. */
    expect(readCode(LIST)).toContain('لا مهمّةَ في هذه الشعبة بعد')
  })
})

describe('أزرارُ الحضور تقول حالتَها لمن لا يرى', () => {
  /** كتلةُ الأزرار الأربعة وحدَها */
  const attendanceBlock = () => {
    const code = readCode(SESSIONS)
    const i = code.indexOf('ATTENDANCE_OPTIONS.map')
    expect(i, 'لم تُوجد أزرارُ الحضور').toBeGreaterThan(0)
    return code.slice(i, i + 900)
  }

  it('المضبوطُ يُعلَن بـ`aria-pressed` لا باللون وحدَه', () => {
    expect(
      /aria-pressed=\{current === opt\.value\}/.test(attendanceBlock()),
      'الحالةُ باللون وحدَه: من لا يرى لا يعرف أيُّ الأربعةِ مضبوط. '
      + 'و`ChoiceGrid` في `FormKit` يضبطها — فهذا عُرفُ المستودَع.',
    ).toBe(true)
  })

  it('وكلُّ زرٍّ يحمل اسمَ صاحبه — «حاضر» أربعَ مرّاتٍ بلا اسمٍ لا تدلّ', () => {
    expect(
      /aria-label=\{`\$\{e\.user\.displayName\}/.test(attendanceBlock()),
      'لا اسمَ يربط الزرَّ بالمتعلّم — فقائمةُ عشرين متعلّما تُقرأ ثمانين زرّا متشابها.',
    ).toBe(true)
  })
})

describe('«سجّل الدرجة» بعد المراجعة لا قبلها', () => {
  it('الزرُّ معطَّلٌ ما لم تبدأ المراجعة — والخادمُ يردّه ٤٠٩ (محروسٌ في الخادم)', () => {
    const code = readCode(QUEUE)
    const i = code.indexOf('سجّل الدرجة')
    expect(i, 'لم يُوجد زرُّ الدرجة').toBeGreaterThan(0)
    /* شرطُ التعطيل يسبق نصَّ الزرّ مباشرةً — يُقرأ من أقربِ `<Button` قبله */
    const tag = code.slice(code.lastIndexOf('<Button', i), i)
    expect(
      /q\.status !== "under_review"/.test(tag),
      'الحقلُ والزرُّ مفعَّلان على `submitted` كذلك، فيكتب المدرّبُ الرقمَ '
      + 'ويضغط ويُردّ ٤٠٩ — والحالةُ معروفةٌ في الشاشة قبل الضغط.',
    ).toBe(true)
  })

  it('ويُقال لماذا — زرٌّ معطَّلٌ بلا سببٍ لغزٌ لا إرشاد', () => {
    expect(readCode(QUEUE)).toContain('اضغط «ابدأ المراجعة» أوّلا')
  })
})
