/* ═══ لا مسارَ تحت `/c/` إلّا رمزُ التوقيع ═══
 *
 * `/c/:token` مسارٌ ذو متغيّرٍ يبتلع كلَّ ما تحته: فـ`/c/استعادة` يُقرأ
 * رمزا اسمُه «استعادة»، فيُنادى به الخادمُ ويُردّ «الرابطُ غيرُ صالح» —
 * وصاحبُه يظنّ العطبَ في عقده لا في مسارٍ كُتب خطأ.
 *
 * وقد وقع هذا فعلا في هذه الجلسة: كُتب زرُّ رسالة التحديث إلى
 * `${publicSiteUrl()}/c/استعادة` ثمّ نُقل إلى `/contract-link` قبل أن
 * يُدفَع. ولا اختبارَ كان يمسكه — فصار هذا.
 *
 * ولا يُقاس بتصيير الصفحة: خطأُ المسار لا يظهر في تصييرٍ واحد، إنّما في
 * **جدول المسارات** — فالمقيسُ بنيةُ الجدول.
 */

import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

const APP = resolve(__dirname, '../../App.tsx')
const src = readFileSync(APP, 'utf8')

/** كلُّ ما في `path="…"` من جدول المسارات */
const paths = [...src.matchAll(/<Route\s+path="([^"]+)"/g)].map((m) => m[1])

describe('مسارُ رمز التوقيع لا يشاركه أحد', () => {
  it('المسحُ يقرأ الجدولَ فعلا — فلا يمرّ بصفرٍ كاذب', () => {
    /* حارسُ الحارس: تبدّلُ اسمِ الملفّ أو صيغةِ المسار يجعل العددَ صفرا
       فيخضرّ المنعُ على الفراغ — وقد مرّ في هذه المنصّة ثلاثُ جولاتٍ هكذا. */
    expect(paths.length, 'لم يُقرأ أيُّ مسار — تعطّل المسحُ نفسُه').toBeGreaterThan(20)
    expect(paths, 'مسارُ التوقيع نفسُه غائب — فالمقيسُ ليس هو').toContain('/c/:token')
  })

  it('⚠️ ولا مسارَ آخرَ تحت `/c/` — فـ`:token` يبتلع ما تحته', () => {
    const under = paths.filter((p) => p.startsWith('/c/') && p !== '/c/:token')
    expect(under, 'مسارٌ تحت `/c/` يُقرأ رمزا فيُردّ صاحبُه «الرابطُ غيرُ صالح»')
      .toEqual([])
  })

  it('وصفحةُ استعادة الرابط خارجَه ومُسجَّلة', () => {
    expect(paths, 'ذهبت صفحةُ الاستعادة، وزرُّ رسالة التحديث يقصدها')
      .toContain('/contract-link')
  })

  /* وزرُّ الرسالة يقصد ما سُجّل فعلا — لا مسارا كُتب في موضعٍ وسُجّل بغيره */
  it('والمسلكُ يقصد المسارَ المسجَّلَ بعينه', () => {
    const svc = readFileSync(
      resolve(__dirname, '../../../server/services/trainer-review.service.ts'), 'utf8',
    )
    const m = /publicSiteUrl\(\)\}(\/contract-link)`/.exec(svc)
    expect(m?.[1], 'وجهةُ زرِّ رسالة التحديث ليست المسارَ المسجَّل').toBe('/contract-link')
    expect(svc, 'عاد زرُّ الرسالة إلى مسارٍ تحت `/c/` فيُقرأ رمزا')
      .not.toContain('publicSiteUrl()}/c/استعادة')
  })
})
