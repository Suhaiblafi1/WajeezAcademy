/* ═══ سلّمُ الخطوات يبقى في اليد، ويضمر كي لا يبتلع الشاشة ═══

   طلبُ صاحب المنصّة (١٥ سبتمبر ٢٠٢٦):

   ① «الشريطُ العلويُّ لتعديل الشعب يجب أن يبقى ظاهرا للمدرّب حتّى يخرج من
      خانة الشعب كلِّها».

      وكان يُصيَّر تحت شرطِ `phase === "prepare"` وحدَه، فيختفي بتبديل الطور
      إلى «مركز التواصل» — فيفقد المدرّبُ سلّمَه ولا يجد طريقَ العودة إلّا
      بلسانٍ فوقه لا يدلّ عليه شيء. وكان يمضي مع التمرير كذلك.

   ② «اجعل الستبر أصغرَ عندما نرفع للأعلى ليتبقّى مساحةٌ جيّدةٌ للمدرّب
      بتعبئة ما هو مطلوبٌ منه».

      فالالتصاقُ وحدَه لا يكفي: رأسٌ لاصقٌ بحلقته وعنوانه وأسطرِ حالته يأكل
      ثلثَ الشاشة في كلّ تمرير، وهو أسوأُ من رأسٍ يمضي.

   ═══ ثمّ صار الشريطُ صفًّا واحدا — الشكل «ب» (ق٧ · ١٧ سبتمبر ٢٠٢٦) ═══

   وهذا الوصفُ أُعيد اشتقاقُه يومَها، لا عُدِّل ليمرّ: العهودُ الأربعةُ هي
   هي، وما تبدّل **كيفيّةُ الوفاء بها**.

     · كان الضمورُ يُطوي «النصفَ الأعلى» بـ`display:none` ويُصغّر الدوائرَ
       من ١٠ إلى ٧. وصار الشريطُ صفًّا واحدا ابتداءً، فلا نصفَ أعلى يُطوى
       ولا دائرةَ تُصغَّر: الضمورُ يبدّل الاسمَ بموضع الخطوة ويُسقط سطرَ
       الحقائق — وكلُّ ما يسقط **يسقط بمحتواه وهامشِه معا**.
     · وذاك بعينه ما يزيل الفراغَ الميّت من أصله: العطبُ القديمُ كان هامشا
       على أخٍ يُخفى بـ`display:none` فلا ينطوي معه. ولمّا صار ما يغيب
       **لا يُصيَّر أصلا**، لم يبقَ هامشٌ يتيمٌ يمكن أن يتخلّف.
     · ولسانا الطور خرجا من الشريط إلى المتن، فلم يعودا يُنفقان من سقفه.

   والفحصُ على البنية لا على ورودِ صنفٍ في ملفّ. */
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

const root = process.cwd()
const code = (p: string) =>
  readFileSync(join(root, p), 'utf8').replace(/\{?\/\*[\s\S]*?\*\/\}?/g, '').replace(/^\s*\/\/.*$/gm, '')

const WS = code('src/pages/trainer/CohortWorkspace.tsx')
const LAYOUT = code('src/pages/trainer/TrainerLayout.tsx')

/** رأسُ الشعبة — من فتحِ `<Bar>` إلى إغلاقه */
const head = WS.slice(WS.indexOf('<Bar'), WS.indexOf('</Bar>'))
/** جسدُ سلّمِ الخطوات — من فتحِ `<ol>` داخلَ الرأس إلى إغلاقه */
const rail = head.slice(head.indexOf('<ol '), head.indexOf('</ol>'))

describe('① السلّمُ يبقى ظاهرا حتّى يخرج من الشعبة', () => {
  it('⚠️ لا يُصيَّر تحت شرطِ الطور — كان يختفي في «مركز التواصل»', () => {
    /* والرأسُ صار `<Bar>` لا `<Panel>` (١٧ سبتمبر ٢٠٢٦): شكلُ جلوسٍ يُلحَم
       بالحافّة لا بطاقةٌ تجلس في الصفحة — وبه يلتصق بالسقف كما طلب صاحبُ
       المنصّة. والقاعدةُ المحروسةُ هنا لم تتغيّر، والمقتطَعُ وحدَه تبع اسمَه. */
    expect(rail, 'سلّمُ الخطوات غاب عن الرأس').toContain('STAGES.map(')

    /* وما قبلَ السلّم في الرأس: لو دخله شرطُ طورٍ لعاد يختفي في «مركز
       التواصل». والقطعةُ هي الحكم لا الملفُّ كلُّه — فالشرطُ نفسُه مشروعٌ في
       مواضعَ أخرى من الشاشة، ومشروعٌ **داخلَ** السلّم لحساب المنشطة. */
    const beforeRail = head.slice(0, head.indexOf('<ol '))
    expect(beforeRail, 'سلّمُ الخطوات صار مشروطا بطور التجهيز')
      .not.toMatch(/phase === "prepare" &&/)
  })

  it('والرأسُ لاصقٌ تحت شريط البوّابة — لا فوقه ولا بأعلى الإطار', () => {
    expect(head.slice(0, head.indexOf('>') + 1), 'الرأسُ يمضي مع التمرير').toMatch(/sticky z-30/)
    /* والمقدارُ من المتغيّر المنشور لا رقما مكتوبا بيد: الشريطُ يلفّ سطرَه
       على الهاتف فيطول، ويتبدّل بمعامل التكبير — فرقمٌ هنا يفترق عنه. */
    expect(WS, 'المقدارُ رقمٌ مكتوبٌ بيده').toMatch(/var\(--staff-sticky-top, 0px\)/)
  })

  it('والشريطُ يقيس نفسَه وينشر ارتفاعَه — وإلّا فالمتغيّرُ لا يُكتب', () => {
    expect(LAYOUT).toMatch(/new ResizeObserver\(publish\)/)
    expect(LAYOUT).toMatch(/setProperty\("--staff-sticky-top"/)
    expect(LAYOUT, 'المقاسُ لا يُربَط بالشريط').toMatch(/<header ref=\{headerRef\}/)
  })

  it('ونقرةُ خطوةٍ تعيده إلى التجهيز — وإلّا فسلّمٌ يُرى ولا يُصعد', () => {
    expect(WS).toMatch(/const openStage = \(s: Stage\) => \{ setPhase\("prepare"\); setStage\(s\); \}/)
    expect(rail).toMatch(/onClick=\{\(\) => openStage\(s\.key\)\}/)
  })

  it('⚠️ ملاصقٌ للسقف: بلا فراغٍ ميّتٍ فوقه، ولا انحناءَ يجلسه في الصفحة', () => {
    /* ثلاثةُ أشياءَ طلبها صاحبُ المنصّة (١٧ سبتمبر ٢٠٢٦) في جملةٍ واحدة:
       «ألغِ الفراغَ فوقها واجعلها ملاصقةً للسقف». ولكلٍّ سببٌ في الشيفرة. */
    const openTag = head.slice(0, head.indexOf('>') + 1)

    /* ① الفراغُ الميّت: كان هامشا على أخٍ يُخفى بـ`display:none` فلا ينطوي
          معه — عشرون بكسلا معلّقة. ولمّا صار الشريطُ صفًّا واحدا لم يبقَ
          «أخٌ يُخفى» أصلا: ما يغيب بالضمور **لا يُصيَّر**، فيذهب هامشُه معه.

          فالمحروسُ صار أدقّ: لا `hidden` في الرأس. من عاد يُخفي عنصرا بصنفٍ
          بدل أن يمتنع عن تصييره أعاد العطبَ بعينه. */
    expect(head, 'عاد الإخفاءُ بصنفٍ — وهامشُ المُخفى لا ينطوي معه')
      .not.toMatch(/compact \? "hidden"/)

    /* ② الالتصاقُ بنيةٌ لا صنفٌ يُمرَّر: `Bar` بلا انحناءٍ وحدُّها السفليُّ
          وحدَه، وتفيض عن حشو حاضنها لتبلغ حافّتَي الإطار. */
    expect(openTag, 'الشريطُ لا يفيض عن حشو حاضنه فلا يبلغ حافّتَي الإطار').toMatch(/-mx-5/)
    expect(openTag, 'انحناءٌ أو حدٌّ مُمرَّرٌ في `className` — قاعدةُ `Surface` تمنعه')
      .not.toMatch(/rounded-|border-(?!b\b)/)

    /* ③ أرضيّةٌ صمّاء: المتنُ يمرّ تحت الشريط، والقياسُ لا يجوز أن يتبع
          ما يمرّ خلفه. و`bg-paper/95` كانت شفّافةً بحكمها. */
    expect(openTag, 'أرضيّةٌ شفّافةٌ تحت متنٍ يمرّ').not.toMatch(/bg-\w+\/\d+/)
    expect(openTag, 'لا نغمةَ صلبةٌ تُعطي أرضيّةً صمّاء').toMatch(/tone="solid"/)
  })

  it('⚠️ ولسانا الطور خرجا من الشريط — فلا يُنفقان من سقفه اللاصق', () => {
    /* كانا داخلَه فيأخذان من كلّ تمريرٍ سطرَهما. وليسا ملاحةً دائمة: يُنقران
       مرّةً في الجلسة. والفحصُ على **موضعهما** لا على وجودهما. */
    expect(head, 'لسانا الطور ما زالا داخلَ الشريط اللاصق').not.toContain('<TabBar')
    expect(WS, 'لسانا الطور سقطا من الشاشة رأسا').toContain('ariaLabel="طورا الشعبة"')
    expect(WS.indexOf('</Bar>'), 'لسانا الطور فوق الشريط لا تحته')
      .toBeLessThan(WS.indexOf('ariaLabel="طورا الشعبة"'))
  })
})

describe('② ويضمر بالتمرير — مقاسان لا مقاسٌ واحد', () => {
  it('حالةُ الضمور تُشتقّ من التمرير فعلا', () => {
    expect(WS).toMatch(/const \[compact, setCompact\] = useState\(false\)/)
    expect(WS, 'لا مستمعَ تمريرٍ — فالضمورُ لا يقع').toMatch(/window\.addEventListener\("scroll", onScroll/)
    /* وعتبةٌ فوق الصفر: عند الصفر تبدّل ارتعاشةُ إصبعٍ الحالةَ فيهتزّ الرأس */
    const threshold = /setCompact\(window\.scrollY > (\d+)\)/.exec(WS)
    expect(threshold, 'لا عتبةَ للضمور').toBeTruthy()
    expect(Number(threshold![1]), 'العتبةُ صفرٌ — فالرأسُ يهتزّ').toBeGreaterThan(0)
  })

  it('⚠️ والضمورُ يُسقط سطرَ الحقائق ويبدّل الاسمَ بموضع الخطوة', () => {
    /* كان الضمورُ يطوي «النصفَ الأعلى» (حلقةً وعنوانا وأسطرَ حالة) ويُصغّر
       الدوائر. وصار الشريطُ صفًّا واحدا ابتداءً، فلا نصفَ أعلى ولا دائرةَ
       تُصغَّر — والفرقُ بين الحالين صار شيئين اثنين لا غير:

         ① سطرُ الحقائق لا يُصيَّر (فيذهب بهامشه)،
         ② واسمُ الشعبة يصير «الخطوة ن من ٥ · اسمُها» — فالمضمورُ يجيب
           «أين أنا» لا «ما شعبتي».

       ولولا الثاني لكان الضمورُ حذفا لا اختصارا. */
    expect(head, 'سطرُ الحقائق لا يسقط بالضمور — فالشريطُ لا يضمر').toMatch(/\{!compact && \(/)
    expect(head, 'المضمورُ لا يقول أين هو من السلّم').toMatch(/الخطوة \{stepNo\} من \{STAGES\.length\}/)
  })

  it('⚠️ و«لم يُحفَظ» لا تُطوى مع ما يُطوى — تعديلٌ في اليد لا يُكتم', () => {
    /* أسهلُ ما يقع هنا: طيُّ السطر الثاني كلِّه توفيرا للمساحة، فيضمر
       الرأسُ وقد كتب المدرّبُ ما لم يحفظه — فيغادر الصفحةَ ولا شيءَ يقول. */
    /* ولمّا سقط السطرُ الثاني كلُّه من الشريط (صفٌّ واحدٌ لا صفّان)، صارت
       النقطةُ الذهبيّةُ **هي** الإشارةَ الوحيدة. فيُفحَص أنّها تُصيَّر بلا
       شرطِ ضمورٍ أصلا، وأنّ حالَها مسموعٌ لمن لا يرى اللون. */
    expect(rail, 'النقطةُ الذهبيّةُ سقطت مع الضمور').toMatch(/\{dirty\[s\.key\] && \(/)
    expect(rail, 'النقطةُ صارت مشروطةً بالضمور').not.toMatch(/!compact[^\n]*dirty\[s\.key\]/)
    expect(rail, 'حالُ الخطوة لا يُقال إلّا بلون').toMatch(/dirty\[s\.key\] \? "فيها تعديلٌ لم يُحفَظ"/)
    expect(rail, 'الاسمُ المسموعُ لا يحمل موضعَ الخطوة ولا حالَها')
      .toMatch(/aria-label=\{`الخطوة \$\{i \+ 1\} من \$\{STAGES\.length\}: \$\{s\.label\} — \$\{stateAr\}`\}/)
  })
})

/* ═══ ③ الشكل «ب» — صفٌّ واحدٌ، وخيطٌ لا يرتفع به الشريط ═══

   ما يجعل ٦٠٦ تصير مئتَين ليس تصغيرَ خطٍّ ولا حذفَ سطر، بل ثلاثةُ قراراتٍ
   بنيويّة. وكلُّ واحدٍ منها يُنقَض وحدَه، فيُحرَس وحدَه:

     ① ثلاثةُ صفوفٍ صارت صفًّا: الهُويّةُ والسلّمُ وزرُّ التالي في `flex`
       واحد. ولو عاد أحدُها صفًّا مستقلًّا رجع ثلثُ ما ذهب.
     ② وحلقةُ التقدّم — ٧٦ بكسلا مربّعة — صارت **خيطا هو الحدُّ السفليّ**:
       مطلقُ الموضع فلا يُضيف إلى الارتفاع شيئا. ولو رجع عنصرا في السياق
       لرفع الشريطَ بمقداره كاملا.
     ③ ولسانا الطور خرجا (ويحرسه الوصفُ ①).

   ═══ وعهدٌ رابعٌ لا يُشترى بالمساحة ═══

   الأسماءُ تغيب عن العين لتتّسع، وتعود بالتحويم. ومن يتنقّل بلوحة المفاتيح
   لا يُحوِّم — فإن لم تعد له بالتركيز، فقد اشتُري الضيقُ بإخراجه من الشاشة.
   ولذلك يُفحَص `group-focus-visible` مع `group-hover` معا لا أحدُهما. */
describe('③ الشكل «ب»: صفٌّ واحدٌ وخيطٌ لا يرتفع', () => {
  it('⚠️ الهُويّةُ والسلّمُ وزرُّ التالي في صفٍّ واحد — لا ثلاثةِ صفوف', () => {
    const row = head.slice(head.indexOf('<div className="flex items-center gap-3">'), head.indexOf('</ol>'))
    expect(row, 'لا صفَّ يجمعها').toBeTruthy()
    expect(row, 'اسمُ الشعبة خرج من الصفّ').toMatch(/ws\.cohort\.title/)
    expect(row, 'السلّمُ خرج من الصفّ').toContain('STAGES.map')
  })

  it('⚠️ وخيطُ التقدّم مطلقُ الموضع — لا يرفع الشريطَ بكسلا', () => {
    /* نقضُه: إرجاعُ الحلقة أو جعلُ الخيط عنصرا في السياق. */
    expect(head, 'رجعت حلقةُ التقدّم — ٧٦ بكسلا في رأسٍ لاصق').not.toMatch(/<ProgressRing\b/)
    const thread = head.slice(head.indexOf('stage-fill') - 300, head.indexOf('stage-fill') + 120)
    expect(thread, 'الخيطُ عنصرٌ في السياق فيرفع الشريطَ بارتفاعه').toMatch(/absolute[^"]*bottom-/)
  })

  it('⚠️ والاسمُ يعود بالتركيز كما يعود بالتحويم — لا يُشترى الضيقُ بإخراجه', () => {
    expect(rail, 'الاسمُ لا يتّسع بالتحويم أصلا').toMatch(/group-hover:max-w-/)
    expect(rail, 'من يتنقّل بلوحة المفاتيح لا يرى اسمَ الخطوة').toMatch(/group-focus-visible:max-w-/)
    /* والنشطةُ تحمل اسمَها بلا تحويمٍ ولا تركيز */
    expect(rail, 'النشطةُ لا تحمل اسمَها').toMatch(/selected[\s\S]{0,60}max-w-\[11rem\]/)
  })
})
