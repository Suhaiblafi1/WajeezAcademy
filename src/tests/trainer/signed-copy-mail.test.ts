/* بريدُ النسخة الموقَّعة — الخدمةُ تسلّم الحقائقَ، والرسالةُ تُبنى في دالّةٍ خالصة.
 *
 * ── العطبُ الأوّلُ الذي وُلد منه هذا الحارس (٢٥ سبتمبر ٢٠٢٦) ──
 *
 * كانت الرسالةُ تسكب `bodyAr` كلَّه في فقرةٍ واحدة: ثلاثُمئةِ سطرٍ بلا بنيةٍ
 * ولا أثرٍ لأنّه وقّعها. فقال صاحبُ المنصّة: «يصله نصا طويلا غير موقع!! اين
 * نضع توقيعنا؟». وعملاءُ البريد يقطعون الرسائلَ الطويلةَ ويكسرون أسطرَها،
 * فوثيقةٌ تُطبَع وتُحفَظ لا تُسلَّم في متن رسالة. **وهذا القيدُ باقٍ ويُقاس
 * هنا** — فموضعُه جسمُ الخدمة، وهو ما تحرسه هذه الجولة.
 *
 * ── وما نُقل من هذا الملفّ، ولماذا (٢٦ سبتمبر ٢٠٢٦) ──
 *
 * كان هنا ثلاثةُ فحوصٍ تقرأ **نصَّ الرسالة** من جسم `signContractByToken`
 * مسحا على الشيفرة: بصمتُها، ووصلتُها، وشرطُ زرِّها. وقد سُحبت الرسالةُ إلى
 * `signedCopyMail` دالّةً خالصةً في `trainer-decision-mail.ts`، فصار نصُّها
 * يُقاس بفحصٍ **يستدعيها ويقرأ ما ردّت** — كما يقرؤه صاحبُها — في
 * `contract-mail-truth.test.ts`. وهو أصدقُ: مسحُ الشيفرة يخضرّ على تعليقٍ
 * فيها أو على سطرٍ جار، وقد وقع ذلك في هذه المنصّة ثلاثَ مرّات.
 *
 * فبقي هنا ما يخصّ **الخدمةَ** وحدَها: ألّا تسكب المتن، وأن تسلّم إلى
 * الرسالة حقائقَ صحيحةً مقروءةً من الصفّ لا مخترَعةً.
 *
 * ── وفحصٌ حُذف ولم يُنقَل: «ويُحيل إلى عقدي في بوّابته» ──
 *
 * كان يشترط أن تحمل الرسالةُ وصلةً إلى `/trainer/contract`. وقرارُ صاحب
 * المنصّة (٢٦ سبتمبر) نسخه: «يصل للمدرّب إيميل سُجّل توقيعُك وهذه نسختُك
 * والتي تقول له اطبع العقد، وهذا لا يجوز الآن إلّا بعد أن نقوم بالتوقيع من
 * جهتنا». فالوصلةُ إلى صفحةٍ فيها زرُّ طباعةٍ وعدٌ سابقٌ لأوانه: العقدُ لا
 * ينفذ إلّا بختمنا. وموضعُها رسالةُ الاعتماد، حيث تصير صادقة.
 *
 * ── وبابٌ آخرُ غيرُ ذاك (٣٠ سبتمبر ٢٠٢٦) ──
 *
 * بأمر صاحب المنصّة صار في الرسالة زرٌّ — وليس هو الزرَّ الذي نسخه، فيُفرَّق:
 *
 * · المنسوخُ وصلةٌ إلى `/trainer/contract`: بوّابةٌ لا تُفتح قبل اعتمادنا،
 *   وفيها زرُّ طباعةٍ يَعِد بنفاذٍ لم يقع.
 * · والقائمُ وصلةٌ إلى `/c/<رمز>`: الرابطُ الذي وقّع منه، يفتح لوحا يقول
 *   «تراجعه الأكاديميّةُ ثمّ يُفتح حسابُك» ولا طباعةَ فيه.
 *
 * فعلّةُ النسخ — وعدُ نفاذٍ سابقٌ لأوانه — لا تقع على الثاني. والمقيسُ هنا
 * صار الخصلةَ لا عددَ الأزرار: **لا زرَّ إلى البوّابة**، وما كان فإلى نسخته.
 */

import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { signedCopyMail } from '../../../server/services/trainer-decision-mail'

const root = join(dirname(fileURLToPath(import.meta.url)), '../../..')
const read = (p: string) => readFileSync(join(root, p), 'utf8')
const bare = (p: string) => read(p).replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')

/** جسمُ دالّةٍ بعينها لا إلى آخر الملفّ — على نمط حارس عدّ ما ينتظر ختمَنا */
function fnBody(src: string, name: string): string {
  const at = src.indexOf(`async ${name}(`)
  if (at < 0) return ''
  const next = src.indexOf('\n  async ', at + 1)
  return src.slice(at, next < 0 ? src.length : next)
}

const SVC = bare('server/services/trainer-review.service.ts')
const SIGN = fnBody(SVC, 'signContractByToken')

describe('بريدُ النسخة الموقَّعة يُحيل ولا يسكب', () => {
  it('وجسمُ دالّة التوقيع مقروءٌ — وإلّا فالحارسُ يقيس الفراغ', () => {
    expect(SIGN, 'لم يُقرأ جسمُ `signContractByToken`').not.toBe('')
    expect(SIGN, 'الجسمُ المقروءُ ليس جسمَ التوقيع').toContain('signerLegalName: legalName')
    expect(SIGN.length, 'الجسمُ المقروءُ أقصرُ من أن يكون هو').toBeGreaterThan(1500)
  })

  it('لا يُسكَب المتنُ في كتلةِ رسالة', () => {
    /* والصيغةُ التي كانت: `{ kind: 'p', text: c.bodyAr ?? '' }` */
    expect(SIGN, 'عاد المتنُ يُسكَب في البريد').not.toMatch(/text:\s*c\.bodyAr/)
    expect(SIGN, 'عاد المتنُ يُسكَب في البريد بصيغةٍ أخرى').not.toMatch(/text:[^\n]*bodyAr/)
  })

  it('والرسالةُ تُبنى في الدالّة الخالصة لا في جسم الخدمة', () => {
    /* فلو عادت كتلُ الرسالة تُكتب هنا لَعاد نصُّها بلا حارسٍ يقرؤه نصّا */
    expect(SIGN, 'لم تعد الرسالةُ تُبنى في `signedCopyMail`').toContain('signedCopyMail({')
    expect(SIGN, 'عادت كتلُ الرسالة تُكتب في جسم الخدمة').not.toMatch(/blocks:\s*\[/)
  })

  it('وتُسلَّم إليها حقائقُ الصفّ لا قيمٌ مخترَعة', () => {
    /* ═══ وهذا ما بقي للخدمة من الرسالة ═══

       الدالّةُ الخالصةُ تُختبَر بما يُعطى لها، فتخضرُّ على مُدخلٍ صحيحٍ ولو
       كانت الخدمةُ تسلّمها غيرَه. فيُقاس هنا **ما تسلّمه**: بصمةُ الصفّ
       لا حسابٌ آخر، والاسمُ الذي وقّع به، واشتراطُ العرض من عموده. */
    expect(SIGN, 'بصمةُ النصّ لا تُقرأ من الصفّ').toMatch(/bodyHash:\s*c\.bodyHash/)
    expect(SIGN, 'الاسمُ القانونيُّ لا يُسلَّم للرسالة').toMatch(/legalName,/)
    expect(SIGN, 'اشتراطُ العرض لا يُقرأ من عموده').toMatch(/conditional:\s*c\.gatesActivation/)
    /* وبابُ نسخته من مسكّ الروابط نفسِه لا من نصٍّ يُركَّب هنا: لو رُكّب
       بيدٍ لَانحرف عن `/c/<رمز>` في أوّل تغييرٍ للمسار. */
    expect(SIGN, 'لم يُسلَّم للرسالة بابُ نسخته').toMatch(/contractUrl:\s*this\.signingUrl\(token\)/)
  })

  /* ═══ والوعدُ يُقال بشرطه ═══

     من وقّع قبل أن يُنشئ حسابَه لا يفتح بوّابتَه: `profile.userId` فارغٌ
     حتّى نعتمد توقيعَه. فزرٌّ يُرسَل إليه يردُّه إلى شاشة دخول — وهو أسوأُ
     من لا زرّ: وعدٌ يُخلَف في أوّل نقرة.

     ═══ وقد سقط الشرطُ لأنّ الزرَّ سقط (٢٧ سبتمبر ٢٠٢٦) ═══

     كان `hasPortal` يمنع الزرَّ عمّن لا حسابَ له، ويُعطيه لمن له حساب. وقد
     صار فتحُ البوّابة **باعتمادنا** لا بتوقيعه، فلا أحدَ يفتحها لحظةَ هذه
     الرسالة — فما كان ممنوعا عن بعضهم صار ممنوعا عن الجميع، وسقط الحقلُ
     والشرطُ معا.

     فيُقاس ما حلّ محلَّه: **لا زرَّ في هذه الرسالة البتّة**. */
  it('ولا زرَّ إلى البوّابة في رسالة التوقيع — والقائمُ إلى نسخته', () => {
    expect(SIGN, 'عاد يُسأل عن حسابٍ لا زرَّ له').not.toMatch(/hasPortal/)
    const LINK = 'https://www.wajeezacademy.com/c/tok-sample-0123456789abcdef'
    const mk = (conditional: boolean, contractUrl: string | null) => signedCopyMail({
      legalName: 'صهيب الخوالدة', title: 'عرضٌ مشروط',
      signedOnAr: '27 سبتمبر 2026', bodyHash: 'abc', conditional, contractUrl,
    })
    const hrefs = (m: ReturnType<typeof signedCopyMail>) => m.doc.blocks
      .filter((b) => b.kind === 'cta')
      .map((b) => (b as { href: string }).href)

    for (const conditional of [true, false]) {
      const got = hrefs(mk(conditional, LINK))
      expect(got.length, `لا زرَّ إلى نسخته (conditional=${conditional})`).toBe(1)
      /* والبابُ المنسوخُ يُمنَع بعينه: أيُّ وصلةٍ إلى البوّابة وعدٌ سابقٌ لأوانه */
      expect(got[0], `زرٌّ إلى بوّابةٍ لم تُفتح (conditional=${conditional})`)
        .not.toMatch(/\/trainer(\/|$|\?)/)
      expect(got[0], `الزرُّ لا يفتح نسخته (conditional=${conditional})`).toContain('/c/')

      /* ولا زرَّ البتّة حين لا رمزَ — فلا يُرسَم زرٌّ إلى لا شيء */
      expect(hrefs(mk(conditional, null)).length,
        `زرٌّ بلا رابطٍ يقصده (conditional=${conditional})`).toBe(0)
    }
  })
})
