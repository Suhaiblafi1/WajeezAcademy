/* ثلاثةُ تعديلاتٍ أمر بها صاحبُ المنصّة (٣٠ سبتمبر ٢٠٢٦).
 *
 * ── ① اعتراضُ المدرّب على كشف المستحقّات ──
 *
 * «٤-٢. هل ممكن أن يكون اعتراض للمدرب على الكشف؟ خاصة اذا كان هناك حسم؟ اذا
 * نعم كيف تكون الصياغه وما هي مهله الاعتراض؟» — ثمّ أقرّ سبعةَ أيّامٍ وأمر:
 * «اضف الحارس الان».
 *
 * **ولمَ سبعةٌ لا أكثر.** السقفُ الخارجيُّ للصرف (٤٥) يساوي مجموعَ
 * الأوّلَين (١٥ + ٣٠) بالحرف، ويحرسه `contract-term-and-payout`. فلا فضلَ
 * فيه يوما، والاعتراضُ لا بدّ أن يسكن داخلَ مهلة الاعتماد لا بعدها.
 *
 * **وأخطرُ ما فيه البند 4-14.** لولاه لَجمّد الاعتراضُ مالَ المدرّب كلَّه،
 * فلا يعترض أحدٌ على حسمٍ صغير — فيصير الحقُّ ورقةً لا تُستعمَل. فما لا
 * نزاعَ فيه يُصرَف في مواعيده، ولا يُوقَف إلّا المتنازَع فيه.
 *
 * ── ② الإلغاءُ أثناء الدورة يُقال صراحةً على الجهتَين ──
 *
 * «٧-٢ يفضل ذكر بند في حال الإلغاء أثناء الدورة بشكل صريح على الجهتين وكم
 * قيمة الحسم سواء من قبل المدرب أو من قبل الأكاديمية».
 *
 * وكان البند 7 لا يعرف إلّا إلغاءً **قبل أوّل جلسة** (7-1 يخطر «قبل سبعة
 * أيّامٍ من تاريخ أوّل جلسة معلنة»)، وتوقّفُ المدرّب بعد البدء في 6-3
 * بعبارةٍ عامّةٍ لا تقول كم يبقى له ولا كم يُستردّ منه.
 *
 * ── ③ بيئةٌ تدريبيّةٌ آمنةٌ شاملة (9-7) ──
 *
 * نصُّه بحرفِ صاحب المنصّة، وثلاثةُ تغييراتٍ لا رابع: «المتدربين» صارت
 * «المتعلمين» بأمره («وغير المتدربين الى المتعلمين») — فالوثيقةُ تسمّيهم
 * بهذا الاسم في بنودها كلِّها، واسمان لقومٍ واحدٍ في عقدٍ يُسأل عنه؛
 * وحُذفت الحركاتُ فالمتنُ كلُّه بلا حركة؛ وأُضيفت إحالةٌ إلى البندَين 12
 * و13 كي تُقرأ جملةُ التواصل والبيانات معهما لا قاعدةً رابعةً تخالفهما.
 *
 * ── وتُقاس على المتن المصيَّر لا على الشيفرة ──
 *
 * على نمط `contract-v17-amendments`: فحصٌ يطابق سطرا في ملفّ مصدرٍ يخضرّ ولو
 * لم يبلغ ذلك السطرُ الوثيقة.
 */

