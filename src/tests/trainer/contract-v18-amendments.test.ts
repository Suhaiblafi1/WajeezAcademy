const body = renderContractBodyAr(BASE)
const withHours = renderContractBodyAr({ ...BASE, hoursNoteAr: 'نحو 16 ساعة' })

const clause = (no: string, src = body): string => {
  const l = src.split('\n').find((x) => x.trimStart().startsWith(`${no} `))
  if (!l) throw new Error(`لا بندَ بالرقم «${no}» في المتن`)
  return l
}
const has = (no: string, src = body): boolean =>
  src.split('\n').some((x) => x.trimStart().startsWith(`${no} `))

describe('① الاعتراضُ على الكشف مكتوبٌ في الوثيقة', () => {
  it('و4-2 يدلّ عليه — فمن قرأ الكشفَ والمواعيدَ علِم أنّ له اعتراضا', () => {
    expect(clause('4-2'), 'قُرئت المواعيدُ ولا يُدرى أنّ للاعتراض بابا')
      .toContain('وللمدرب الاعتراض على الكشف وفق البند 4-11')
  })

  it('و4-11 يقول المهلةَ والقناةَ وما يُبيَّن في الاعتراض', () => {
    const c = clause('4-11')
    expect(c, 'لا يقول إنّ الكشفَ يُرى قبل اعتماده').toContain('قبل اعتماده')
    expect(c, 'المهلةُ ليست من الثابت').toContain(`${PAYOUT_OBJECTION_DAYS} أيام`)
    expect(c, 'لا يمنع الاعتمادَ في المهلة').toContain('ولا يعتمد الكشف قبل مضي')
    expect(c, 'لا قناةَ يُعترض بها').toContain(ACADEMY_EMAILS.billing)
    expect(c, 'لا يُطلب بيانُ ما ينازع فيه ومقداره').toContain('ما ينازع فيه ومقداره')
  })

  /* ═══ وهذا أخطرُها ═══

     البند 4-6 يمنع الحسمَ إلّا بنصّ، و4-12 يزيد **كيف يُعلَم**: مبيَّنا في
     الكشف بمقداره وسببه وبنده. فحسمٌ صحيحٌ في أصله ومكتومٌ في بيانه يُخصَم
     من إنسانٍ لا يدري لِمَ نقص مالُه. */
  it('و4-12 لا يُنفَّذ حسمٌ غيرُ مبيَّنٍ بمقداره وسببه وبنده', () => {
    const c = clause('4-12')
    for (const part of ['بمقداره', 'وسببه', 'والبند الذي يستند إليه']) {
      expect(c, `الحسمُ يُنفَّذ ولا يُبيَّن ${part}`).toContain(part)
    }
    expect(c, 'لا يقول ما يجري لحسمٍ لم يُبيَّن').toContain('لا يحتسب على المدرب')
    expect(c, 'لا يُقرأ مع 4-6').toContain('4-6')
  })

  it('و4-13 يُوجب جوابا مسبَّبا في مهلةٍ، ويترك البابَ 20 مفتوحا', () => {
    const c = clause('4-13')
    expect(c, 'مهلةُ الجواب ليست من الثابت').toContain(`${PAYOUT_OBJECTION_REPLY_DAYS} أيام`)
    expect(c, 'يُردّ الاعتراضُ بلا سبب').toContain('كتابة مع سببه')
    expect(c, 'لا يقول ما يجري إن قُبل').toContain('صححت الكشف وصرفت الفرق')
    expect(c, 'يُسَدّ بابُ النزاع بعد الردّ').toContain('البند 20')
  })

  /* والأهمُّ: حقٌّ يُجمّد المالَ كلَّه حقٌّ لا يُستعمَل */
  it('و4-14 يصرف ما لا نزاعَ فيه في مواعيده ولا يوقف إلّا المتنازَع فيه', () => {
    const c = clause('4-14')
    expect(c, 'الاعتراضُ يؤخّر الصرفَ كلَّه').toContain('ولا يؤخر الاعتراض صرف ما لا نزاع فيه')
    expect(c, 'لا يقول إنّ غيرَ المتنازع فيه يمضي على مواعيد 4-2').toContain('في المواعيد المبينة في البند 4-2')
    expect(c, 'لا يقصر الوقفَ على المتنازع فيه').toContain('ويبقى المتنازع فيه وحده موقوفا')
    expect(c, 'مدّةُ صرف ما ثبت ليست من الثابت').toContain(`${PAYOUT_DISPUTED_TRANSFER_DAYS} يوما`)
  })

  /* ═══ وحسابُ المهلة يُثبَت لا يُفترَض ═══

     الاعتراضُ يسكن داخلَ مهلة الاعتماد. ولو صار أطولَ منها لَوجب على
     الأكاديمية إمّا أن تعتمد قبل انقضائه (فتخالف 4-11)، أو أن تتجاوز
     مهلةَ 4-2 (فتخالف 4-2). فالشرطُ عددٌ لا رأي. */
  it('والمهلةُ تسكن داخل مهلة الاعتماد — لا تُخرجها عن البند 4-2', () => {
    expect(PAYOUT_OBJECTION_DAYS, 'مهلةُ الاعتراض تساوي مهلةَ الاعتماد أو تتجاوزها')
      .toBeLessThan(PAYOUT_APPROVAL_DAYS)
    expect(PAYOUT_OUTER_DAYS, 'السقفُ الخارجيُّ نزل عن مجموع المهلتَين')
      .toBeGreaterThanOrEqual(PAYOUT_APPROVAL_DAYS + PAYOUT_TRANSFER_DAYS)
  })

  it('وحديثُ الساعات انتقل إلى 4-15، والخلاصةُ تتبعه', () => {
    expect(has('4-15', withHours), 'بقي حديثُ الساعات على رقمٍ أخذه غيرُه').toBe(true)
    expect(clause('4-15', withHours)).toContain('حجم العمل المتوقع')
    expect(withHours, 'الخلاصةُ تحيل إلى رقمٍ صار لبندٍ آخر')
      .toContain('حجم العمل المتوقع (للإرشاد، البند 4-15)')
    expect(withHours, 'بقيت إحالةُ 4-11 القديمةُ في الخلاصة')
      .not.toContain('(للإرشاد، البند 4-11)')
  })

  it('ولا يتكرّر رقمُ بندٍ في المتن ولا في المشروط', () => {
    for (const src of [body, withHours]) {
      const nos = src.split('\n')
        .map((l) => l.trimStart().match(/^(\d+-\d+) /)?.[1])
        .filter((x): x is string => !!x)
      expect(new Set(nos).size, 'تكرّر رقمُ بندٍ في المتن').toBe(nos.length)
    }
  })
})

describe('② الإلغاءُ أثناء الدورة — على الجهتَين وبقيمةٍ معلومة', () => {
  it('وعنوانُ البند 7 يشمل ما بعد البدء', () => {
    expect(body, 'العنوانُ يقصر البندَ على إلغاء الأكاديمية قبل البدء')
      .toContain('البند 7 — إلغاء الشعبة قبل بدئها وأثناءها')
  })

  it('و7-3: ألغت الأكاديميةُ بعد البدء — نسبةُ ما قُدّم، ولا حسمَ، ولا ردٌّ عليه', () => {
    const c = clause('7-3')
    expect(c, 'لا يقول متى يسري — بعد بدء الجلسات').toContain('بعد بدء جلساتها')
    expect(c, 'لا أساسَ لحساب ما استحقّ').toContain('بنسبة عدد الجلسات المباشرة التي قدمها')
    expect(c, 'لا يحيل إلى أساس الأتعاب').toContain('البند 4-1')
    expect(c, 'لم يُنصَّ على أن لا حسمَ عليه').toContain('ولا يجري على ذلك حسم')
    expect(c, 'يُحمَّل المدرّبُ ما تردّه الأكاديميةُ للمتعلّمين')
      .toContain('ولا يتحمل المدرب شيئا مما ترده الأكاديمية إلى المتعلمين')
  })

  /* ═══ والوجهُ الأوّلُ: لا عذرَ مقبول ═══

     أمرُ صاحب المنصّة: «he will get nothing and his total revenue if any from
     other courses will be deducted of $300». فالنسبةُ تسقط كلَّها، والاستيفاءُ
     يخرج من شعبته إلى غيرها — وهما نقضان لِما كان، فلا يمرّان بلا نصٍّ يقولهما
     صراحةً ولا بلا استثناءٍ يُكتب في 4-6 و6-5. */
  it('و7-4: توقّف بلا عذرٍ مقبول — لا شيءَ له، ومبلغٌ من شعبه الأخرى', () => {
    const c = clause('7-4')
    expect(c, 'لا يشترط انتفاءَ العذر المقبول').toContain('دون عذر تقبله الأكاديمية')
    expect(c, 'بقيت له أتعابٌ عن الشعبة').toContain('لم يستحق عن هذه الشعبة أتعابا')
    expect(c, 'لا يقطع أنّ تقديمَ بعض الجلسات لا يورث شيئا')
      .toContain('ولو كان قد قدم بعض جلساتها')
    expect(c, 'المبلغُ ليس من الثابت').toContain(String(STOPPAGE_CHARGE_USD))
    expect(c, 'لا يقول إنّه يُستوفى من شعبه الأخرى')
      .toContain('من مستحقاته عن أي شعبة أخرى')
    expect(c, 'لا يذكر ما يتخلّف إن لم تكفِ مستحقاتُه').toContain('دينا في ذمته')
  })

  /* ═══ والاستثناءُ يُكتب حيث يُقرأ المنع، لا في البند الجديد وحدَه ═══

     4-6 يقول «لا حسمَ من أتعابٍ عن عملٍ أُدّي إلّا ما نصّت عليه البنود…»،
     و6-5 يقول «لا غرامةَ ولا اقتطاعَ من عملٍ أُدّي». فبندٌ جديدٌ يخالفهما
     ولا يُذكَر فيهما يجعل الوثيقةَ تناقض نفسَها: من قرأ 6-5 قال لا يُقتطع،
     ومن قرأ 7-4 قال يُقتطع — ولا مرجّح. */
  it('ونقضُ 4-6 و6-5 مكتوبٌ فيهما لا في 7-4 وحدَه', () => {
    expect(clause('4-6'), 'بقي 4-6 يعدّ المستثنَيات ولا يعرف 7-4').toContain('7-4')
    expect(clause('6-5'), 'بقي 6-5 يمنع مطلقا وفي الوثيقة ما يخالفه').toContain('البند 7-4')
    expect(clause('7-4'), 'لم يقل 7-4 إنّه استثناءٌ ممّا قبله')
      .toContain('استثناء من البندين 4-6 و6-5')
    expect(clause('7-4'), 'لم يستثنِ قصرَ الاستيفاء في 6-4 وهو يخالفه')
      .toContain('قصر الاستيفاء المبين في البند 6-4')
  })

  it('و7-5: العذرُ المقبولُ يردّ النسبةَ ويقصر الاستيفاءَ على شعبته', () => {
    const c = clause('7-5')
    expect(c, 'لا يعلّق على قبول العذر').toContain('عذر تقبله الأكاديمية')
    expect(c, 'لا يرفع عنه ما في 7-4').toContain('لم يجر عليه شيء مما في البند 7-4')
    expect(c, 'لا يردّ له نسبةَ ما قدّم').toContain('استحق أتعابه عما قدمه فعلا')
    expect(c, 'لا يحيل إلى نسبة 7-3').toContain('البند 7-3')
    expect(c, 'السقفُ ليس من الثابت').toContain(String(WITHDRAWAL_RECOVERY_CAP_USD))
    expect(c, 'لم يُقصَر الاستيفاءُ على شعبته').toContain('ولا يقتطع من مستحقات شعبة أخرى')
    expect(c, 'بقي تضاربُ 6-3 مفتوحا في هذا الوجه')
      .toContain('ولا يراد بعدم استحقاق أتعاب الشعبة في البند 6-3 ما قدمه فعلا منها')
  })

  /* ═══ وتقديرٌ بلا اسمٍ ولا مهلةٍ ولا مراجعةٍ تحكُّم ═══

     البندُ يعلّق مالَ إنسانٍ على «عذرٍ تقبله الأكاديمية». فمن يقبل؟ ومتى
     يُعلَم؟ وبمَ يُراجَع؟ وأمرُ صاحب المنصّة يجيب الأولى: «the manager
     decide». والثنتان الباقيتان لا تُترَكان، وإلّا نُفّذ الحسمُ قبل أن
     يُخبَر صاحبُه بأنّ عذرَه رُدّ. */
  it('و7-6: يُسمّى من يقدّر، ومهلتُه، وأنّ التنفيذ بعد الإخطار', () => {
    const c = clause('7-6')
    expect(c, 'لا يُسمّى من يقدّر العذر').toContain('المدير الأكاديمي')
    expect(c, 'القرارُ بلا سببٍ مكتوب').toContain('كتابة مع سببه')
    expect(c, 'المهلةُ ليست من الثابت').toContain(`${PAYOUT_OBJECTION_REPLY_DAYS} أيام`)
    expect(c, 'يُنفَّذ الحسمُ قبل أن يُخبَر صاحبُه').toContain('ولا ينفذ ما في البند 7-4 قبل هذا الإخطار')
    expect(c, 'لا سبيلَ للمدرّب إلى مراجعته').toContain('4-11 إلى 4-14')
    expect(c, 'سُدّ بابُ البند 20').toContain('البند 20')
  })

  /* والثلاثةُ لا تدخل التقدير: لو دخلته لَجاز ردُّ عذرِ من مات قريبُه */
  it('و7-7: المرضُ والوفاةُ والقوّةُ القاهرةُ مقبولةٌ بحكم العقد لا بالتقدير', () => {
    const c = clause('7-7')
    for (const part of ['مرض', 'وفاة قريب', 'قوة قاهرة']) {
      expect(c, `لا يذكر ${part}`).toContain(part)
    }
    expect(c, 'تُركت الثلاثةُ لتقدير المدير').toContain('فلا يترك ذلك للتقدير')
    expect(c, 'لا يحيل إلى 6-6 فتُقرأ شروطُ الإخطار').toContain('البند 6-6')
    expect(c, 'لا يعمّ الطرفَين').toContain('على أي من الطرفين')
  })

  /* ولا يُنقَض ما كان: 7-1 و7-2 يحكمان ما قبل البدء، وزيادةُ الثلاثة
     لا تُخرجهما — فلو ذهب أحدُهما صار الإلغاءُ قبل البدء بلا حكم. */
  it('وما قبل البدء باقٍ كما كان — 7-1 و7-2 لم يُمسّا', () => {
    expect(clause('7-1'), 'ذهب إخطارُ الإلغاء قبل أوّل جلسة').toContain('أول جلسة معلنة')
    expect(clause('7-2'), 'ذهب أنّ موادَّه تبقى له').toContain('تبقى ملكا له')
  })
})

describe('③ 9-7 — بيئةٌ آمنةٌ شاملةٌ بحرفِ صاحب المنصّة', () => {
  const c = () => clause('9-7')

  it('وأركانُه الأربعةُ كلُّها في الوثيقة', () => {
    expect(c(), 'لا بيئةَ آمنةً شاملة').toContain('بيئة تدريبية آمنة وشاملة')
    expect(c(), 'لا مساواةَ في المعاملة وفرص المشاركة').toContain('المساواة في المعاملة وفرص المشاركة والتعلم')
    expect(c(), 'لا حظرَ للإساءة وأخواتها').toContain('الإساءة أو التحرش أو التنمر أو الاستغلال أو العنف')
    expect(c(), 'لا حظرَ لاستغلال العلاقة التدريبيّة').toContain('استغلال العلاقة التدريبية')
    expect(c(), 'لا قصرَ للتواصل على قنوات الأكاديمية').toContain('عبر القنوات المعتمدة من الأكاديمية')
  })

  it('وأسبابُ التمييز السبعةُ مذكورةٌ بأسمائها', () => {
    for (const g of ['الجنس', 'العرق', 'اللون', 'الدين', 'الأصل', 'الإعاقة']) {
      expect(c(), `سقط سببُ «${g}» من أسباب التمييز`).toContain(g)
    }
    expect(c(), 'سقط البابُ المفتوحُ لما لم يُسَمَّ').toContain('أي وضع شخصي أو اجتماعي')
  })

  /* ═══ واسمٌ واحدٌ لقومٍ واحد ═══

     أمرُ صاحب المنصّة: «وغير المتدربين الى المتعلمين». وليست لفظا: عقدٌ
     يسمّي قوما باسمَين يُسأل بعد سنةٍ أهما واحدٌ أم اثنان، ويُقرأ الالتزامُ
     على أضيقِ الاسمَين. */
  it('ويسمّيهم «المتعلمين» كبقيّة الوثيقة، لا «المتدربين»', () => {
    expect(c(), 'عاد اسمٌ ثانٍ لقومٍ واحدٍ في وثيقةٍ تُوقَّع').not.toContain('المتدربين')
    expect(c(), 'لا يسمّيهم بما تسمّيهم به بقيّةُ البنود').toContain('المتعلمين')
    expect(body.includes('المتدربين'), 'تسرّبت «المتدربين» إلى المتن في موضعٍ آخر').toBe(false)
  })

  it('ولا يُقرأ وحده — يحيل إلى 12 و13 فلا قاعدةَ رابعةٌ تخالفهما', () => {
    expect(c(), 'جملةُ التواصل والبيانات بلا إحالةٍ إلى بابَيها').toContain('البندين 12 و13')
  })

  it('ولا حركةَ فيه — فالمتنُ كلُّه بلا حركة', () => {
    expect(c(), 'دخلت حركةٌ في بندٍ من المتن').not.toMatch(/[ً-ْ]/)
  })

  it('و9-2 باقٍ — فالجديدُ يزيد عليه ولا يحلّ محلَّه', () => {
    expect(clause('9-2'), 'ذهبت معاملةُ المتعلّمين باحترامٍ من 9-2')
      .toContain('ومعاملة المتعلمين باحترام دون تمييز')
  })
})

