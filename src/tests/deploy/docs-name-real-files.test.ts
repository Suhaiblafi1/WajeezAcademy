/* البند ٧ · وثيقةٌ تسمّي ملفّا غيرَ موجودٍ تكذب على قارئها.

   ── العطبُ الذي أمسكه هذا الحارسُ أوّلَ مرّةٍ ──

   `docs/RUNBOOK_AR.md` كان يقول للمشغّل إنّ استيرادَ الكتالوج «يجري تلقائيا
   في `scripts/vercel-build.sh`» — ملفٌّ **محذوفٌ منذ الخروج من Vercel** —
   ثمّ يأمره بأن ينشر اللقطةَ بيده من `/admin/publishing`. وكلاهما خطأ:
   الاستيرادَ والنشرَ صارا خطوةً واحدةً في `deploy/deploy.sh`.

   فمن اتّبع الدليلَ حرفا بحث عن سكربتٍ لا وجودَ له، ثمّ نشر لقطةً ثانيةً بلا
   داعٍ. **والوثيقةُ التي تعطي إجراءً خاطئا أخطرُ من غيابها**: الغائبةُ تُرسل
   قارئَها إلى الشيفرة، والكاذبةُ تُقنعه أنّه لا يحتاج.

   ── ولماذا على المسارات لا على الكلمات ──

   حارسٌ يبحث عن كلمة «Vercel» يحمرّ على كلّ وثيقةٍ تشرح **لماذا** خرجنا منها
   — وهي وثائقُ صادقةٌ يجب أن تبقى. والمقياسُ الصحيح: **كلُّ مسارِ ملفٍّ
   تسمّيه وثيقةٌ تشغيليّةٌ يجب أن يوجد على القرص.**

   والتقاريرُ المؤرَّخةُ (`docs/review-*`، `docs/audit-*`) مستثناةٌ بقصد:
   تقريرُ يومٍ يصف حالَ ذلك اليوم، وتصحيحُه بأثرٍ رجعيٍّ يمحو الدليلَ على ما
   كان. والوثائقُ التشغيليّةُ وحدَها تُقرأ لتُتَّبع اليوم. */

import { describe, expect, it } from 'vitest'
import { existsSync, readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '../../..')

/** الوثائقُ التي تُقرأ لتُتَّبع — لا التقاريرُ التي تُقرأ لتُعرَف */
const OPERATIONAL = [
  'docs/RUNBOOK_AR.md',
  'docs/DEPLOYMENT.md',
  'docs/OPS_AR.md',
  'docs/SERVER_ENV_AR.md',
  /* ⚠ أُضيف بعد نقضٍ كشف غيابَه: صحّحتُ وعدا كاذبا في هذا الملفّ، ثمّ نقضتُ
     الحارسَ بإعادة الوعد — **فمرّ أخضر**. لأنّ الملفّ لم يكن في القائمة أصلا.
     وهو أشدُّ وثائق المستودَع تشغيليّةً: منه يُركَّب الخادمُ ويُنشر ويُستعاد. */
  'deploy/README.md',
]

/* مسارٌ داخل ` ` يبدأ بمجلّدٍ من مجلّدات المستودَع وينتهي بلاحقةٍ معروفة.
   والقيدُ مقصود: `npm run x` و`/admin/publishing` ليسا مسارَي ملفّ. */
const PATH_IN_CODE = /`((?:src|server|scripts|deploy|docs|prisma)\/[A-Za-z0-9._/-]+\.(?:ts|tsx|sh|yml|yaml|json|md|sql))`/g

/* ما يُذكر ليُقال إنّه **زال** — لا ليُتَّبع.

   ── والاستثناءُ مقيَّدٌ بالوثيقة، وهذا ليس تدقيقا زائدا ──

   كتبتُ هذه القائمةَ أوّلَ مرّةٍ مجموعةً واحدةً لكلّ الوثائق، ثمّ نقضتُ الحارسَ
   لأراه يسقط: **أعدتُ الجملةَ الكاذبةَ بعينها إلى دليل التشغيل فمرّت خضراء.**
   لأنّ الاستثناءَ العامَّ يُجيز ذكرَ الملفّ المحذوف **في أيّ سياق**، بما فيه
   الإجراءُ الحيُّ الذي كُتب هذا الحارسُ لمنعه.

   فصار لكلّ وثيقةٍ استثناؤها: `DEPLOYMENT.md` هي سجلُّ «ما حُذف» فذكرُها له
   صدقٌ، و`RUNBOOK_AR.md` دليلُ عملٍ يُتَّبع فذكرُه فيه أمرٌ بالبحث عن معدوم.

   وهو الدرسُ نفسُه المتكرّرُ في هذه المنصّة: **حارسٌ يقيس نصفَ الساحةِ يُطمئن
   بلا حقّ.** ولا يُعرف نصفُه من كلِّه إلّا بنقضِه. */
const NAMED_AS_GONE: Record<string, string[]> = {
  /* سجلُّ «ما حُذف بعد الخروج من Vercel وCloudways» — موضعُه الصحيحُ الوحيد.
     من يبحث عن أحدها في المستودَع يجد هنا الجوابَ لماذا لا يجده. */
  'docs/DEPLOYMENT.md': [
    'scripts/vercel-build.sh',
    'server/http/vercel-handler.ts',
    'scripts/audit-csp.ts',
    'scripts/deploy-cloudways.sh',
  ],
}

/* ── وصيغةٌ أخطرُ من تسمية ملفٍّ محذوف: **وعدٌ بآليّةٍ لا تعمل** ──

   كان `deploy/README.md` يقول: «`.github/workflows/deploy.yml` ينشر عند نجاح
   CI على `main`». والملفُّ **غيرُ موجودٍ في `main`** — هو في فرعٍ لم يُدمج قطّ.

   وأثرُ ذلك ليس بحثا عن ملفٍّ مفقود، بل ما هو أسوأ: **يُدمج العملُ ويُظنّ
   أنّه وصل الموقعَ، وهو لم يبرح المستودَع.** لا شيءَ يحمرّ، ولا شاشةَ تقول.

   فيُحرَس هنا الأمرُ نفسُه بالبنية: أيُّ مسارِ سيرِ عملٍ (`.github/workflows/…`)
   تسمّيه وثيقةٌ تشغيليّةٌ **يجب أن يوجد** — إلّا حيث تقول الوثيقةُ صراحةً
   إنّه غيرُ موجود. */
describe('ولا تَعِد بسيرِ عملٍ لا وجودَ له', () => {
  it.each(OPERATIONAL)('%s', (rel) => {
    const src = readFileSync(join(root, rel), 'utf8')
    const missing: string[] = []
    for (const m of src.matchAll(/`(\.github\/workflows\/[A-Za-z0-9._-]+\.ya?ml)`/g)) {
      if (existsSync(join(root, m[1]))) continue
      /* تُستثنى الفقرةُ التي تعلن غيابَه — فذكرُ المعدوم بوصفه معدوما صدق.

         ⚠ والنافذةُ **سطران لا فقرة**. كتبتُها أوّلا ±٤٠٠ حرفٍ ثمّ نقضتُ
         الحارس: أعدتُ الوعدَ الكاذبَ إلى الوثيقة **فمرّ أخضر** — لأنّ تصويحَ
         الوثيقة نفسَه يقول «لا وجودَ له»، فأعفت النافذةُ الواسعةُ كلَّ ما
         حولَه. أي أنّ التصويحَ صار يحرس الكذبةَ بدل أن يفضحها.

         وهو العطبُ المتكرّرُ في هذه الجلسة بعينه: **استثناءٌ أوسعُ ممّا يلزم
         يُفرغ الحارسَ في الموضع الذي كُتب له.** */
      /* ⚠ `m.index` لا `indexOf(m[0])`. كتبتُها أوّلا `indexOf` فأعادت **أوّلَ
         ورودٍ دائما**: فلمّا تكرّر المسارُ نفسُه مرّتين — مرّةً في التصويح
         المعفى ومرّةً في وعدٍ كاذب — قِيس الثاني بسياق الأوّل فمرّ أخضر.
         نقضتُ الحارسَ ثلاث مرّاتٍ قبل أن أراها. */
      const at = m.index ?? 0
      const lines = src.slice(0, at).split('\n').length - 1
      const window = src.split('\n').slice(lines, lines + 2).join('\n')
      if (/لا وجودَ له|غيرُ موجود|غير موجود|لم يُدمج/.test(window)) continue
      missing.push(m[1])
    }
    expect(
      missing,
      `${rel} يَعِد بسيرِ عملٍ لا وجودَ له — فيُظنّ أنّ النشرَ تلقائيٌّ وهو ليس كذلك:\n  ${missing.join('\n  ')}`,
    ).toEqual([])
  })
})

/* ── وصيغةٌ ثالثة: **عنوانٌ رقميٌّ يُكتب فيتقادم** ──

   في ٧ سبتمبر ٢٠٢٦ انتقل الإنتاجُ إلى خادمٍ آخر. وبقي العنوانُ القديم مكتوبا
   في **إحدى عشرةَ موضعا** عبر ستّ وثائق. فأرسلتُ صاحبَ المنصّة مرّتين إلى
   خادمٍ ليس خادمَه، ثمّ قلتُ له إنّ عملَ يومه لم يصل الموقعَ — وقد وصل.

   وأطرفُ المواضع سطرٌ في `deploy/README.md` نصُّه: «**والقياسُ يكذّبه**:
   النطاقُ يُحلّ إلى …». جملةٌ كُتبت لتصحيح كذبةٍ سابقة، **فصارت هي الكذبة**.

   ── والعلاجُ ألّا يُكتب العنوانُ أصلا ──

   العنوانُ ليس معرفةً تُحفظ، بل حالةً تُقاس: `dig +short www.wajeezacademy.com`.
   وكلُّ مرّةٍ يُكتب فيها يبدأ بالتقادم من لحظة صدقه. وهذه ثالثةُ مرّةٍ تتقادم
   فيها بنيةُ الاستضافة في هذه الوثائق: Vercel ← Cloudways ← الخادم القديم.

   فيُمنع العنوانُ الرقميُّ القابلُ للتوجيه في الوثائق التشغيليّة. وتبقى
   عناوينُ التوثيق والشبكاتُ الخاصّةُ مسموحةً — فهي **لا تدلّ على خادمٍ بعينه
   فلا تتقادم**: الحلقةُ المحلّيّة، و`0.0.0.0`، وشبكاتُ RFC 1918،
   ونطاقاتُ الأمثلة في RFC 5737.

   ── وما لا يشمله هذا الحارس، بقصد ──

   السكربتات. ففي `deploy/migrate-in.sh` عنوانُ الخادم القديم بوصفه **مصدرَ
   النقل** — وهو صحيحٌ هناك، والقديمُ هو المقصود. وفي `scripts/deploy-watch.sh`
   قياسٌ مؤرَّخٌ يشرح لماذا تغيّر السكربت. والفرقُ أنّ الوثيقةَ التشغيليّةَ
   تُقرأ لتُتَّبع **اليوم**. */
describe('ولا تُثبِّت عنوانَ خادمٍ رقميّا — يُقاس ولا يُكتب', () => {
  /* ما لا يدلّ على خادمٍ بعينه فلا يتقادم */
  const HARMLESS = [
    /^127\./,                       // الحلقة المحلّيّة
    /^0\.0\.0\.0$/,                // «كلُّ الواجهات»
    /^10\./,                        // RFC 1918
    /^192\.168\./,                  // RFC 1918
    /^172\.(1[6-9]|2\d|3[01])\./,   // RFC 1918
    /^192\.0\.2\./,                // RFC 5737 — أمثلة
    /^198\.51\.100\./,             // RFC 5737 — أمثلة
    /^203\.0\.113\./,              // RFC 5737 — أمثلة
  ]
  const octet = String.raw`(?:25[0-5]|2[0-4]\d|1\d\d|[1-9]?\d)`
  const IPV4 = new RegExp(String.raw`\b${octet}(?:\.${octet}){3}\b`, 'g')

  it.each(OPERATIONAL)('%s', (rel) => {
    const src = readFileSync(join(root, rel), 'utf8')
    const pinned = [...new Set([...src.matchAll(IPV4)].map((m) => m[0]))]
      .filter((ip) => !HARMLESS.some((re) => re.test(ip)))
    expect(
      pinned,
      `${rel} يثبّت عنوانَ خادمٍ — وهو يتقادم بلا أن يحمرّ شيء.\n`
      + `  اكتب بدله: dig +short www.wajeezacademy.com\n  ${pinned.join('\n  ')}`,
    ).toEqual([])
  })
})

describe('البند ٧ · الوثائقُ التشغيليّةُ لا تسمّي ملفّا غيرَ موجود', () => {
  it.each(OPERATIONAL)('%s', (rel) => {
    const src = readFileSync(join(root, rel), 'utf8')
    const missing: string[] = []
    for (const m of src.matchAll(PATH_IN_CODE)) {
      const p = m[1]
      if (NAMED_AS_GONE[rel]?.includes(p)) continue
      if (!existsSync(join(root, p))) missing.push(p)
    }
    expect(
      missing,
      `${rel} يسمّي ملفّاتٍ لا وجودَ لها — من اتّبع الدليلَ بحث عمّا حُذف:\n  ${missing.join('\n  ')}`,
    ).toEqual([])
  })

  it('والمذكورُ بوصفه زائلا زائلٌ فعلا — وإلّا فالاستثناءُ هو الكذب', () => {
    /* لو عاد أحدُ هذه الملفّاتِ إلى الوجود لصار استثناؤه هنا هو ما يخفي
       الحقيقة: وثيقةٌ تقول «حُذف» عن ملفٍّ يعمل. */
    for (const p of Object.values(NAMED_AS_GONE).flat()) {
      expect(existsSync(join(root, p)), `${p} عاد إلى الوجود — يُرفع من قائمة الزائل`).toBe(false)
    }
  })
})
