/* `pg` يبقى على الثامنة — حتّى يزول ما يجعل التاسعةَ تكسر النشر.

   ═══ ما يُحرَس، ولمَ هو مؤجَّلٌ لا قائم ═══

   `deploy.sh` ينشر لقطةَ الكتالوج بـ`npm run catalog:publish`، وهي معاملةٌ
   واحدة. ومفسّرُ استعلامات Prisma (`client-engine-runtime`) يوزّع أبناءَ
   العقدة بـ`Array.map` داخلها، والمعاملةُ مثبّتةٌ على اتّصالٍ واحد — فيقع
   استعلامان على اتّصالٍ مشغول.

   و`pg` الثامنةُ **تحتمل** ذلك: تصفّها وتُخرج تحذيرا:

     Calling client.query() when the client is already executing a query is
     deprecated and will be removed in pg@9.0

   فهو اليومَ سطرٌ في السجلّ لا أكثر. **ويوم تصير `pg@9`** يصير خطأً —
   **فتسقط نشرةُ اللقطة**، ويبقى الموقعُ على لقطته السابقة بعد كلّ نشر.

   ═══ ولمَ حارسٌ لا إصلاح ═══

   العلّةُ داخلَ Prisma لا في شيفرتنا: استعلاماتُ المعاملة عندنا `update`
   و`updateMany` متتاليةٌ بسيطة، لا كتابةَ متشعّبةً تُعاد صياغتُها.

   وقِيست الترقيةُ ولم تُفترض: `@prisma/client` ٧٫٩٫١ ← ٧٫١٠٫٠ (أحدثُ السابعة)
   **لم تُزل التحذير** — نشرٌ ناجحٌ وتحذيرٌ واحدٌ في النسختَين، على مُظهِرٍ
   حقيقيٍّ (أُبطلت اللقطةُ محلّيّا ليعمل النشرُ فعلا، إذ يقفز حين تتطابق
   البصمة — وأوّلُ قياسٍ أعطى صفرا كاذبا لهذا السبب).

   والطريقُ الباقي Prisma ٨، وأحدثُه `8.0.0-rc.15`: **مرشَّحُ إصدارٍ ونقلةٌ
   كبرى** في طبقة البيانات كلِّها. وقرارُ صاحب المنصّة (١٤ سبتمبر ٢٠٢٦) حين
   عُرض عليه: لا يُوضع مرشَّحٌ في الإنتاج لأجل تحذيرٍ لا يكسر شيئا.

   ═══ فما الذي يفعله هذا الحارسُ إذن ═══

   يمنع أن يصير المؤجَّلُ قائما **بلا أن يعلم أحد**: رفعُ `pg` إلى التاسعة
   يبدو تحديثا روتينيّا، فمن يفعله لا يرى صلتَه بنشر اللقطة. فيسقط هنا
   بالرسالة التي تقول ما ينكسر وما يُفعل قبله.

   ولا يمنع الترقيةَ أبدا: من أراد التاسعةَ يُثبت أوّلا أنّ التحذيرَ زال
   (بترقية Prisma أو بغيرها)، ثمّ يرفع هذا الحارسَ معها في التزامٍ واحد.

   ═══ وكيف رُئي ساقطا ═══

   غُيّر المدى في `package.json` إلى `^9.0.0` فسقط، ثمّ أُعيد. */

import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

const pkg = JSON.parse(
  readFileSync(join(__dirname, '..', '..', '..', 'package.json'), 'utf8'),
) as { dependencies?: Record<string, string>; devDependencies?: Record<string, string> }

const range = pkg.dependencies?.pg ?? pkg.devDependencies?.pg ?? ''

/** أصغرُ إصدارٍ رئيسيٍّ يقبله المدى — يُقرأ عددا لا نصّا */
function majorOf(semverRange: string): number {
  const m = semverRange.match(/(\d+)\./)
  if (!m) throw new Error(`مدى «pg» غير مقروء: «${semverRange}»`)
  return Number(m[1])
}

describe('الاعتماديّةُ «pg» تبقى على الثامنة', () => {
  it('المدى مُعلَنٌ أصلا — وإلّا فالحارسُ يقيس فراغا', () => {
    expect(range, 'لا «pg» في package.json — تعطّل الحارسُ نفسُه').not.toBe('')
  })

  it('ولا يبلغ التاسعةَ — فهي تُسقط نشرَ اللقطة', () => {
    expect(
      majorOf(range),
      'رُفع «pg» إلى التاسعة: التحذيرُ الذي يصدر من مفسّر Prisma داخل معاملة '
      + 'النشر يصير خطأً، فتسقط «catalog:publish» ويبقى الموقعُ على لقطته السابقة. '
      + 'أثبِت أوّلا أنّ التحذيرَ زال، ثمّ ارفع هذا الحارسَ مع الترقية في التزامٍ واحد.',
    ).toBeLessThan(9)
  })

  it('والمدى مفتوحٌ داخلَ الثامنة — فالترقياتُ الصغرى لا تُمنع', () => {
    expect(range.startsWith('^'), `مدى «pg» مثبَّتٌ لا مفتوح: «${range}»`).toBe(true)
  })
})
