/* «لا يُرشَّح إصداران لرمزٍ واحدٍ في مسارٍ واحد» — بالبنية لا بالسياسة (س-٢ · ح-٣).

   ═══ الدعوى ═══

   نصُّ ح-٣: «على النظام ألّا يعامل النسختين عرضَين مستقلَّين ولا يرشّحهما
   معا في مسارٍ واحد — هما بديلان لا مكمّلان».

   ═══ وما وُجد حين فُحصت ═══

   الدعوى **قائمةٌ بالبناء لا بقاعدةٍ مكتوبة**، ولم يكن أحدٌ يعرف ذلك:

   · `PathwayCourse` مفتاحُه `@@id([pathwayId, courseId])` — فالدورةُ تدخل
     المسارَ مرّةً واحدة.
   · `TemplateCourse` مفتاحُه `@@id([templateId, courseId, listType])`.

   و**النسخُ تتشارك `courseId`** (هذا تعريفُها: `CourseVersion` صفٌّ تحت
   `Course` واحدة). فإصداران من رمزٍ واحدٍ لا يمكن أن يدخلا مسارا واحدا —
   ليس لأنّ شيئا يمنعهما، بل لأنّهما **ليسا صفَّين مختلفَين** في جدول الربط.

   ═══ ولماذا حارسٌ على ما هو قائم ═══

   لأنّ ما يحفظها ترحيلٌ قد يُكتب غدا بلا أن يعرف كاتبُه ما يحرسه: من أضاف
   `versionId` إلى `PathwayCourse` أو وسّع مفتاحَه ظانًّا أنّه «يزيد مرونة»
   فتح البابَ الذي أُغلق بلا قصد. فالحارسُ يجعل الضمانَ **مقروءا ومسمًّى** —
   وهو ما يطلبه س-٢ بنصّه: «تُفرَض ح-٣ في الشيفرة لا في السياسة».

   ═══ والفحصُ على المخطّط نفسِه ═══

   لا على شيفرةِ خدمةٍ تستطيع أن تلتفّ، ولا على تعليق. */

import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

const schema = readFileSync(join(process.cwd(), 'prisma/schema.prisma'), 'utf8')

/** نصُّ نموذجٍ بعينه من المخطّط */
function model(name: string): string {
  const start = schema.indexOf(`model ${name} {`)
  expect(start, `لا نموذجَ ${name}`).toBeGreaterThan(-1)
  return schema.slice(start, schema.indexOf('\n}', start))
}

describe('رمزٌ واحدٌ لا يدخل مسارا مرّتين — فالنسختان لا تتزاحمان', () => {
  it('`PathwayCourse` مفتاحُه المسارُ والدورة — فلا صفَّان لدورةٍ في مسار', () => {
    const m = model('PathwayCourse')
    expect(m, 'ضاع المفتاحُ المركّب — صار المسارُ يقبل الدورةَ مرّتين').toMatch(
      /@@id\(\[pathwayId,\s*courseId\]\)/,
    )
  })

  it('ولا يحمل الربطُ إصدارا — وإلّا صار الإصداران صفَّين', () => {
    /* هذا هو البابُ بعينه: عمودُ إصدارٍ في جدول الربط يجعل نسختَي الرمز
       الواحد صفَّين مختلفَين، فيدخلان المسارَ معا وينقضان ح-٣. */
    const m = model('PathwayCourse')
    expect(m, 'أُضيف إصدارٌ إلى ربط المسار — فصار الإصداران يدخلان معا').not.toMatch(
      /^\s*(courseVersionId|versionId|version)\s/m,
    )
  })

  it('وقالبُ التركيب كذلك — مفتاحُه لا يفرّق بين إصدارين', () => {
    const m = model('TemplateCourse')
    /* المفتاحُ يسمح بتكرار الدورة بأدوارٍ مختلفة (`listType`) — وهو مقصود:
       دورةٌ تكون «أساسيّة» في قائمةٍ و«بداية» في أخرى. لكنّه **لا يفرّق
       بين إصدارين**، فالضمانُ قائم. */
    expect(m).toMatch(/@@id\(\[templateId,\s*courseId,\s*listType\]\)/)
    expect(m, 'أُضيف إصدارٌ إلى ربط القالب').not.toMatch(/^\s*(courseVersionId|versionId|version)\s/m)
  })

  /* ن-٨: والقاعدةُ تلزم ما يبنيه الناسُ لا ما نكتبه نحن وحدَه.
     «إن حوى مسارُه نسخَه من الدورات، فالقاعدةُ التي تمنع إصدارَين لرمزٍ واحدٍ
     في مسارٍ واحد تسري هنا كما تسري على المسارات المنسَّقة». */
  it('ومسارُ المدرّب مثلُها — مفتاحُه المسارُ والدورة (ن-٨)', () => {
    const m = model('TrainerPathCourse')
    expect(m, 'ضاع المفتاحُ المركّب — صار مسارُ المدرّب يقبل الدورةَ مرّتين').toMatch(
      /@@id\(\[pathId,\s*courseId\]\)/,
    )
    expect(m, 'أُضيف إصدارٌ إلى ربط مسار المدرّب — فصار الإصداران يدخلان معا').not.toMatch(
      /^\s*(courseVersionId|versionId|version)\s/m,
    )
  })

  it('والنسخةُ صفٌّ تحت الدورة لا دورةٌ إلى جانبها — وعليه يقوم كلُّ ما سبق', () => {
    const m = model('CourseVersion')
    expect(m).toMatch(/courseId\s+String/)
    expect(m).toMatch(/@@unique\(\[courseId,\s*version\]\)/)
    /* فلو صارت النسخةُ `Course` مستقلّةً بمعرّفٍ خاصّ سقط الضمانُ كلُّه،
       وهذا ما يمنعه ح-٣ نصًّا: «النسخةُ رقم ٢ لا دورةٌ مستقلّة». */
  })
})
