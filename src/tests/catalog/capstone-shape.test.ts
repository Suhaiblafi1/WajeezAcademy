/* «تتخرّج بـ» — سطرٌ يراه المشتري قبل الشراء، فيُحرَس بشيئين: أن يُقرأ، وأن
   يكون صادقا.

   ── ما وجدناه حين قيس (١٧ سبتمبر ٢٠٢٦) ──

   الستّةُ والعشرون سطرا كانت تتراوح بين ٤٧ حرفا و١٩٧ — أربعةُ أضعاف. وبطاقةُ
   الكتالوج تقصّ عند سطرَين (`line-clamp-2`) والرئيسةُ عند ثلاثة، فستّةٌ منها
   كانت **تُقصّ حيث تصير محدَّدة**: يقرأ المشتري «ملفُّ مشروعٍ تنفيذيّ: حزمةُ
   مخطّطاتٍ مرقّمةٌ سُلّمت لمنفّذ…» ثمّ ينقطع الوعدُ عند أنفعِ ما فيه.

   وأخطرُ من الطول: تسعةٌ فقط من الستّةِ والعشرين كانت تسمّي **من يفحص العمل**.
   والبقيّةُ تَعِد بكومةِ مستنداتٍ لم يرها أحد. ووجدنا سطرَين يسمّيان شاهدا
   **لا وجودَ له في دورات المسار**: `PW-SAL-001` كان يَعِد بـ«مراجعة لجنة»
   ودوراتُه لا تذكر لجنة، و`PW-GRPH-001` بدليلٍ «يطبّقه غيرُك» ولا تطبيقَ من
   غيرِك في متنِها. ووعدٌ لا تسنده الدورةُ دَينٌ على الأكاديميّة لا ميزةٌ لها.

   ── ولماذا يفحص هذا الحارسُ مصدرَين لا ملفّا ──

   فحصُ «هل في السطر كلمةُ لجنة» زينةٌ: يخضرّ على وعدٍ كاذبٍ ما دام مكتوبا.
   فالفحصُ هنا **مقابلةٌ بين مصدرين**: إن سمّى السطرُ شاهدا، فلا بدّ أن تسمّيه
   دوراتُ المسار نفسِها في مشروعها أو تقييمها. فما لا تنتجه الدورةُ لا يَعِد
   به الكتالوج. */

import { describe, expect, it } from 'vitest'
import { getCoreCatalogRaw } from '../../data/core-catalog-source'

const raw = getCoreCatalogRaw()
const courseById = new Map(raw.courses.map((c) => [c.course_id, c]))

/** ما تنتجه دوراتُ المسار فعلا — مشروعُها وتقييمُها، لا عنوانُها */
function pathwayEvidence(courseIds: string[]): string {
  return courseIds
    .map((id) => courseById.get(id))
    .filter(Boolean)
    .map((c) => `${c!.practical_project_ar ?? ''} ${c!.summative_assessment_ar ?? ''}`)
    .join(' ')
}

/* شهودٌ بشريّون يفحصون عملَ المتعلّم. ولا يدخل هنا «مورّد» ولا «مراجعةُ تحيّز»
   وأشباهُهما: تلك أشياءُ يفحصها المتعلّم لا أناسٌ يفحصونه. */
const WITNESSES = ['لجنة', 'عميل', 'زميل', 'منفّذ', 'الإدارة', 'مستمعين', 'جمهور'] as const

/** «منفّذ» اسمُ من يستلم، و«منفّذة» وصفُ ما نُفِّذ — وأوّلُ صيغةٍ لهذا الحارس
 *  خلطت بينهما فاتّهمت سطرا صادقا. فالبحثُ على الكلمة لا على حروفِها. */
function namesWitness(text: string, w: string): boolean {
  const re = new RegExp(`${w}(?![\\u0621-\\u064A])`)
  return re.test(text)
}

/* أنّ العملَ **حُكم عليه**: إمّا شاهدٌ رآه، وإمّا أثرٌ يُقاس أو يُوثَّق. وهذا
   فحصُ مفرداتٍ بخلاف الذي فوقَه، وهو مقبولٌ هنا لأنّه يطلب من السطر أن يقول
   شيئا — لا يصدّق دعوى. والتصديقُ وظيفةُ الفحص الذي يقابل المصدرَين. */
const JUDGED = [
  'قبل وبعد', 'خط أساس', 'مؤشرات', 'قياس', 'قيست', 'نتائج', 'نتيجته', 'نتيجتها',
  'أثر', 'مسجّلة', 'موثّق', 'مختبَر', 'نُفّذت', 'دافعتَ', 'إحاطة', 'راجعه',
] as const

describe('«تتخرّج بـ» يُقرأ على البطاقة', () => {
  it('لا سطرَ يتجاوز ما تسعه البطاقة — وإلّا قُصّ الوعدُ عند تحديده', () => {
    /* البطاقةُ تقصّ عند سطرَين، والسطرُ نحوُ خمسين حرفا. فمئةٌ هي السقف. */
    const tooLong = raw.launch_pathways
      .filter((p) => (p.capstone ?? '').length > 100)
      .map((p) => `${p.id}: ${(p.capstone ?? '').length} حرفا`)
    expect(tooLong, 'سطرٌ أطولُ ممّا تعرضه البطاقة:\n' + tooLong.join('\n')).toEqual([])
  })

  it('ولا سطرَ فارغٌ ولا قصيرٌ حتّى لا يقول شيئا', () => {
    for (const p of raw.launch_pathways) {
      expect((p.capstone ?? '').length, `${p.id} بلا مخرَجٍ مفهوم`).toBeGreaterThan(30)
    }
  })
})

describe('«تتخرّج بـ» صادقٌ — لا يَعِد بما لا تنتجه دوراتُه', () => {
  it('كلُّ شاهدٍ يسمّيه السطرُ تسمّيه دوراتُ المسار', () => {
    const unfounded: string[] = []
    for (const p of raw.launch_pathways) {
      const line = p.capstone ?? ''
      const evidence = pathwayEvidence(p.course_ids)
      for (const w of WITNESSES) {
        if (namesWitness(line, w) && !evidence.includes(w)) {
          unfounded.push(`${p.id}: يَعِد بـ«${w}» ولا تذكره دوراتُه`)
        }
      }
    }
    expect(unfounded, 'وعدٌ لا تسنده الدورة:\n' + unfounded.join('\n')).toEqual([])
  })

  it('والقراءةُ تجد الأدلّةَ فعلا — فلا يمرّ الفحصُ على نصٍّ فارغ', () => {
    /* لو عادت نصوصُ الدورات فارغةً لخضرّ الفحصُ أعلاه على كلِّ وعدٍ كاذب. */
    for (const p of raw.launch_pathways) {
      expect(pathwayEvidence(p.course_ids).length, `لا متنَ لدورات ${p.id}`).toBeGreaterThan(80)
    }
  })

  it('ولا سطرَ يقول ماذا أنجزتَ ويسكت عن كيف حُكم عليه', () => {
    /* لا يُشترط شاهدٌ على كلِّ مسار — منها ما يُثبَت بقياسٍ قبل وبعد لا بعين.
       والمشترَطُ أن يقول السطرُ **شيئا** عن الحكم: شاهدا رآه أو أثرا يُقاس أو
       توثيقا يُراجَع. وكومةُ مستنداتٍ بلا أيٍّ من ذلك وعدٌ لا يُصدَّق.

       وقد سقط هذا الفحصُ على أربعةٍ حين كُتب (AUT · SCM · GRPH · ENGR): كانت
       تعدّد ما يُسلَّم ولا تقول من فحصه. فأُصلحت الأربعةُ بما في دوراتها من
       دليلٍ كان مهدورا — لا بخفضِ الشرط. */
    const silent = raw.launch_pathways
      .filter((p) => {
        const line = p.capstone ?? ''
        return !WITNESSES.some((w) => namesWitness(line, w)) && !JUDGED.some((j) => line.includes(j))
      })
      .map((p) => `${p.id}: ${p.capstone}`)
    expect(silent, 'سطرٌ يعدّد المخرَجات ولا يقول كيف حُكم عليها:\n' + silent.join('\n')).toEqual([])
  })
})
