#!/usr/bin/env bash
# أفي القرص ما يسع نشرةً؟ — يُسأل قبل أن يُلمَس شيء.
#
#   bash deploy/preflight-disk.sh            يقيس قرصَ Docker (وإلّا الجذر)
#   bash deploy/preflight-disk.sh /مسار      يقيس قرصَ مسارٍ بعينه
#
# ═══ العطبُ الذي كُتب له (٢٤ سبتمبر ٢٠٢٦) ═══
#
# امتلأ القرصُ في منتصف نشرة: نسخةُ ما قبل النشر تُكتب، والصورةُ تُبنى، ثمّ لم
# يبقَ بايتٌ واحد. فلم تجد القاعدةُ ما تكتب فيه ملفَّ قفلها فسقطت، وبقيت تسقط
# عند كلّ إعادة تشغيلٍ عشرَ ساعات — والخادمُ يردّ على كلّ دخولٍ بـ«خطأ داخلي».
# **النشرةُ هي التي أسقطت الموقعَ الذي جاءت لتحدّثه.**
#
# والصوابُ أن تُرفض النشرةُ قبل أن تبدأ: الموقعُ القائمُ يبقى يخدم، والفشلُ
# يُصرَخ به في سجلّ النشر (ومراقبُه يُنذر) — بدل قاعدةٍ تسقط في صمت.
#
# ═══ ولماذا خمسةُ غيغابايتات ═══
#
# نسخةُ ما قبل النشر تُكتب مرّتين قبل أن تستقرّ (في مجلّدٍ مؤقّت ثمّ في
# وجهتها) وكانت نحوَ ٧٠٠ ميغابايت، وطبقةُ `npm ci` وحدَها نحوُ ١٫٤ غيغابايت
# كلّما تغيّر ملفُّ القفل، ثمّ هامشٌ تكتب فيه القاعدةُ سجلَّها وهي تعمل. ويُضبط
# الحدُّ بـ`DEPLOY_MIN_FREE_GB` في البيئة أو في ملفّ بيئة الإنتاج.
#
# ═══ ويُقاس «المتاح» لا «غيرُ المستعمَل» ═══
#
# عمودُ Avail في `df` يطرح ما يحجزه نظامُ الملفّات للجذر. والقاعدةُ تكتب
# بمستخدمٍ غيرِ الجذر، فهذا بعينه ما تراه هي — وقد كان يقول صفرا وعمودُ
# المستعمَل يقول ٧٢ من ٧٥.
#
# ═══ وتعذُّرُ القياس لا يمنع النشر ═══
#
# حارسٌ يُعطَب فيوقف كلَّ نشرةٍ أسوأُ من غيابه. فإن لم يُقرأ رقمٌ قيل ذلك ومُضي.

set -euo pipefail
cd "$(dirname "$0")/.."

# الحدُّ: من البيئة أوّلا، ثمّ من ملفّ بيئة الإنتاج، وإلّا خمسة
MIN_GB="${DEPLOY_MIN_FREE_GB:-}"
if [ -z "$MIN_GB" ] && [ -f deploy/.env.production ]; then
  MIN_GB="$(grep -E '^DEPLOY_MIN_FREE_GB=' deploy/.env.production | tail -1 | cut -d= -f2- | tr -d "\"' " || true)"
fi
case "$MIN_GB" in ''|*[!0-9]*) MIN_GB=5 ;; esac

# القرصُ المقيس: ما يحمل صورَ Docker وذاكرةَ بنائه وحجمَ القاعدة معا
TARGET="${1:-}"
if [ -z "$TARGET" ]; then
  TARGET="$(docker info --format '{{.DockerRootDir}}' 2>/dev/null || true)"
  [ -n "$TARGET" ] && [ -d "$TARGET" ] || TARGET=/
fi

AVAIL_KB="$(df -Pk "$TARGET" 2>/dev/null | awk 'NR==2 {print $4}' || true)"
case "$AVAIL_KB" in
  ''|*[!0-9]*)
    echo "⚠ تعذّر قياسُ المساحة الحرّة على $TARGET — يُمضى بلا هذا الفحص" >&2
    exit 0 ;;
esac

AVAIL_GB=$((AVAIL_KB / 1048576))
if [ "$AVAIL_GB" -lt "$MIN_GB" ]; then
  cat >&2 <<MSG

✗ القرصُ يكاد يمتلئ: ${AVAIL_GB}GB متاحة على $TARGET، والنشرةُ تحتاج ${MIN_GB}GB على الأقلّ.
  لم يُلمَس شيء — الموقعُ باقٍ على إصداره القائم.

  أين ذهبت المساحة:
    du -xh --max-depth=2 / 2>/dev/null | sort -h | tail -12
    docker system df

  وما ملأه يومَ كُتب هذا الفحص:
    bash deploy/backup.sh --prune      نسخُ ما قبل النشر — يُبقي أحدثَها
    docker builder prune -af           ذاكرةُ البناء — لا تمسّ القاعدة

MSG
  exit 1
fi

echo "✓ القرص: ${AVAIL_GB}GB متاحة على $TARGET (والحدُّ ${MIN_GB}GB)"
