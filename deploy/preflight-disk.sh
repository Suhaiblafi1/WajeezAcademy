#!/usr/bin/env bash
# فحصُ ما قبلَ النشر — المساحةُ التي لا يقوم النشرُ بدونها.
#
#   bash deploy/preflight-disk.sh [المسار] [الحدُّ الأدنى بالميغابايت]
#
# يخرج بصفرٍ إن كانت المساحةُ كافية، وبواحدٍ يقول كم بقي وكم يلزم. ويحاول
# قبل أن يسقط: يُسقط ذاكرةَ البناء والصورَ المعلَّقة، ثمّ يقيس ثانيةً.
#
# ── العطبُ الذي وُضع له، وقد وقع ──
#
# `deploy.sh` يبني صورةً جديدةً في كلّ نشرة (الخطوة ٣) **ولا يُسقط قديما**:
# فتتراكم الصورُ المعلَّقةُ وذاكرةُ البناء بلا حدّ. وخمسُ نشراتٍ في مساءٍ
# واحدٍ تكفي لملء قرصٍ صغير.
#
# وحين يمتلئ القرصُ يقع أمران معا، ويُقرآن عطبَين منفصلَين فيُبحث في غير
# موضعهما:
#
#   · **PostgreSQL لا تُقلع.** واسمُ `db` لا يُحَلُّ ما دامت حاويتُه واقفة،
#     فيردّ الخادمُ `EAI_AGAIN` على كلّ مسارٍ يمسّ القاعدة — الدخولُ وبوّابةُ
#     المدرّب والشراء. ويُقرأ خطأَ شبكةٍ وليس بالشبكة علّة.
#
#   · **و`docker compose build` يفشل**، فتقف كلُّ نشرةٍ عند الخطوة ٣ بتصميمها
#     («الموقعُ القديم ما زال يعمل»). والحاوياتُ القديمةُ تبقى تخدم الصفحاتِ
#     الساكنة: فالموقعُ يبدو حيّا، وواجهةُ التطبيق ميّتة، ولا نشرةَ تصل —
#     ويُدمج أخضرُ بعد أخضرَ ولا يبلغ الخادمَ منها شيء.
#
# وقع هذا في الإنتاج ليلةَ ٢٣ سبتمبر ٢٠٢٦: عشرُ ساعاتٍ والواجهةُ ترد 500،
# وثلاثُ دمجاتٍ خضراءَ لم تصل. فصار الفحصُ قبل أن يُلمَس شيء، والإسقاطُ بعد
# كلّ نشرةٍ ناجحةٍ حتّى لا يعود.
#
# ── ولا يُمَسُّ مُجلَّدٌ مسمّى أبدا ──
#
# `docker system prune --volumes` يحذف المُجلَّداتِ غيرَ المستعمَلة، و`pgdata`
# **يصير غيرَ مستعمَلٍ في اللحظة التي تقف فيها حاويةُ القاعدة** — أي في
# الحالة التي يُشغَّل فيها هذا الفحصُ بالضبط. فالمسحُ هنا على المعلَّق وذاكرةِ
# البناء وحدَهما: صورٌ بلا وسمٍ لا يشير إليها شيء، وذاكرةٌ تُبنى من جديد.

set -euo pipefail

TARGET="${1:-.}"
# ٣ غيغا: بناءُ صورة Node مع `npm ci` يحتاج دونها بقليل، والهامشُ لقاعدةٍ
# تكتب سجلَّها أثناء النشر.
MIN_MB="${2:-3000}"

[ -d "$TARGET" ] || { printf '✗ لا يوجد المسار %s\n' "$TARGET" >&2; exit 1; }

# المتاحُ بالميغابايت. و`--output=avail` يعطيه بالكيلوبايت في coreutils.
free_mb() {
  df -Pk "$TARGET" 2>/dev/null | awk 'NR==2 {print int($4/1024)}'
}

FREE="$(free_mb || true)"
[ -n "$FREE" ] || { printf '✗ تعذّر قياسُ المساحة على %s\n' "$TARGET" >&2; exit 1; }

if [ "$FREE" -ge "$MIN_MB" ]; then
  printf '  المساحةُ المتاحة: %s م.ب (الحدُّ الأدنى %s)\n' "$FREE" "$MIN_MB"
  exit 0
fi

printf '  المساحةُ المتاحة %s م.ب دون الحدّ %s — يُسقَط ما يُستغنى عنه\n' "$FREE" "$MIN_MB"

# ── والإسقاطُ متدرّجٌ: الأقدمُ أوّلا ──
#
# وإن لم يكن docker موجودا (كما في عدّة الاختبار) فلا إسقاطَ ولا سقوطَ لأجله:
# المقيسُ هنا حسابُ المساحة وحكمُه، لا وجودُ محرّكِ حاويات.
if command -v docker >/dev/null 2>&1; then
  docker builder prune -f --filter 'until=168h' >/dev/null 2>&1 || true
  docker image prune -f >/dev/null 2>&1 || true
  FREE="$(free_mb || echo "$FREE")"
  if [ "$FREE" -lt "$MIN_MB" ]; then
    # لم تكفِ القديمةُ وحدَها: تُسقَط ذاكرةُ البناء كلُّها. والبناءُ التالي
    # أبطأُ مرّةً واحدةً — وهو أهونُ من نشرةٍ لا تقع.
    docker builder prune -af >/dev/null 2>&1 || true
    FREE="$(free_mb || echo "$FREE")"
  fi
fi

if [ "$FREE" -ge "$MIN_MB" ]; then
  printf '  صارت %s م.ب — يمضي النشر\n' "$FREE"
  exit 0
fi

cat >&2 <<EOF
✗ لا مساحةَ تكفي للنشر: المتاح ${FREE} م.ب، والحدُّ الأدنى ${MIN_MB} م.ب.

  ولم يُلمَس شيء — الموقعُ القديم ما زال يعمل كما كان.

  وما يُنظَر فيه على الخادم:
    bash deploy/status.sh       ← حجمُ النسخ الاحتياطيّة على القرص — وهي أوّلُ ما يُنظر فيه
    bash deploy/backup.sh --prune  ← نسخُ ما قبل النشر: يُبقي أحدثَها ويحذف ما سواها
    docker system df            ← ما يأخذه Docker
    docker image prune -af      ← الصورُ التي لا حاويةَ تستعملها
    du -xh --max-depth=2 /      ← إن بقي الامتلاء بلا تفسير

  ويومَ امتلأ القرصُ (٢٤ سبتمبر ٢٠٢٦) كانت النسخُ ٥٦ غيغابايتا من ٧٢،
  وDocker كلُّه ١٦ — فمن نظر في Docker وحدَه لم يجد العلّة.

  ولا تُمرَّر --volumes إلى أيّ مسحٍ هنا: pgdata مُجلَّدٌ مسمّى، ويصير
  «غيرَ مستعمَل» متى وقفت حاويةُ القاعدة — فيُحذف بها قاعدةُ البيانات.
EOF
exit 1
