#!/usr/bin/env bash
# فحصُ ما قبلَ النشر — المتغيّراتُ التي لا يقوم الإنتاجُ بدونها.
#
#   bash deploy/preflight-env.sh [ملفُّ البيئة]
#
# يخرج بصفرٍ إن كانت كلُّها مضبوطةً، وبواحدٍ يسمّي الناقصَ منها.
#
# ── لماذا ملفٌّ مستقلٌّ لا أسطرٌ في deploy.sh ──
#
# لأنّه يُشغَّل وحدَه فيُختبَر وحدَه. وحارسُ CI يناديه على ملفّاتٍ مصطنعةٍ
# ويقرأ رقمَ خروجه — فيثبت أنّ البوّابةَ **تسقط فعلا** حين يغيب المتغيّر، لا
# أنّ سطرا يشبهها موجودٌ في ملفّ. وشتّان: قد مرّ في هذه المنصّة ثلاثةُ حرّاسٍ
# خضراءَ لأنّهم طابقوا نصّا في تعليق.
#
# ── ولماذا هنا لا في CI ──
#
# القيمةُ الحقيقيّةُ تسكن `deploy/.env.production` على الخادم، ولا تدخل Git
# أبدا («لا أسرارَ في Git مطلقا»). فـCI لا تراها ولا ينبغي أن تراها: نسخةٌ
# منها في أسرار GitHub تُقاس ثمّ تتقادم بصمت، وهو أسوأُ من لا فحص. فالفحصُ
# يقع حيث تسكن القيمة — وCI تحرس أنّ الفحصَ نفسَه ما زال قائما ويعمل.

set -euo pipefail

ENV_FILE="${1:-deploy/.env.production}"

[ -f "$ENV_FILE" ] || { printf '✗ لا يوجد %s — انسخه عن deploy/.env.production.example\n' "$ENV_FILE" >&2; exit 1; }

# آخرُ إسنادٍ للمفتاح يغلب ما قبله، كما يفعل docker-compose بـ`env_file`
envv() { grep -E "^[[:space:]]*$1=" "$ENV_FILE" | tail -1 | cut -d= -f2- ; }

# ── والفراغُ كالغياب ──
#
# `publicSiteUrl()` يقيس بـ`process.env.APP_URL?.trim()`: فسطرٌ `APP_URL=`
# أو قيمةٌ من مسافاتٍ تسقط إلى `http://localhost:7100` تماما كغيابِ السطر.
# فيُقاس هنا بالمقياس نفسِه — وإلّا مرّ من الفحصِ ما يسقط في التشغيل.
missing=()
for key in SITE_DOMAIN APP_URL; do
  value="$(envv "$key" || true)"
  # تجريدُ المسافات من الطرفين
  value="${value#"${value%%[![:space:]]*}"}"
  value="${value%"${value##*[![:space:]]}"}"
  [ -n "$value" ] || missing+=("$key")
done

if [ ${#missing[@]} -gt 0 ]; then
  printf '\n\033[31m✗ متغيّراتٌ إلزاميّةٌ غيرُ مضبوطةٍ في %s: %s\033[0m\n' "$ENV_FILE" "${missing[*]}" >&2
  printf '  APP_URL منه تُبنى روابطُ الرسائل (التوثيق · الدعوة · استعادةُ الكلمة)\n' >&2
  printf '  وعنوانُ العودة بعد الدفع. وبلا ضبطِه تصل الرسائلُ برابطٍ لا يفتح\n' >&2
  printf '  عند أحد، ويعود المشتري بعد دفعٍ ناجحٍ إلى localhost.\n' >&2
  printf '  اضبطه في %s ثمّ أعد النشر.\n' "$ENV_FILE" >&2
  exit 1
fi
