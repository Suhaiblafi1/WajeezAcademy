#!/usr/bin/env bash
# نشرُ إصدارٍ جديد على الخادم — بترتيبٍ يجعل الفشل غير مؤذٍ.
#
#   bash deploy/deploy.sh            نشر من الفرع الحالي
#   SKIP_PULL=1 bash deploy/deploy.sh   نشر ما في مجلد العمل بلا جلب
#
# الترتيب مقصود: تُبنى الصورة الجديدة **قبل** لمس أيّ شيء يعمل. فإن فشل
# البناء أو الهجرة، الموقع القديم ما زال يخدم وكأن شيئا لم يكن. ولا يُبدَّل
# الحاويات إلا بعد أن تنجح الهجرة وتُبنى الصورة كاملة.

set -euo pipefail

cd "$(dirname "$0")/.."
COMPOSE="docker compose -f deploy/compose.prod.yml --env-file deploy/.env.production"

step() { printf '\n\033[1m── %s ──\033[0m\n' "$1"; }
fail() { printf '\n\033[31m✗ %s\033[0m\n' "$1" >&2; exit 1; }

[ -f deploy/.env.production ] || fail "لا يوجد deploy/.env.production — انسخه عن .env.production.example"

# ── المتغيّراتُ الإلزاميّةُ تُفحص قبل أن يُلمَس شيء ──
#
# كان `SITE_DOMAIN` وحدَه يُفحص هنا، و`APP_URL` يمرّ بلا سؤال: فيُنشَر خادمٌ
# يعمل ويبني كلَّ روابطِ رسائله على `http://localhost:7100` — ولا يظهر ذلك
# في سجلٍّ ولا اختبار، بل عند من وصلته رسالةٌ برابطٍ لا يفتح، وعند مشترٍ
# دفع ثمّ أُعيد إلى عنوانٍ لا وجودَ له عنده.
#
# والفحصُ في ملفٍّ مستقلٍّ ليُشغَّل وحدَه فيُختبَر وحدَه — يحرسه
# `app-url-required.test.ts` تحت `src/tests/deploy/`، بتشغيله فعلا على
# ملفّاتِ بيئةٍ مصطنعةٍ وقراءةِ رقم خروجه.
#
# ⚠ ولا يُكتب في هذا الملفّ — ولو داخل تعليق — اسمُ المجلّد `deploy` متبوعا
#   بشرطةٍ مائلةٍ واسمِ ملفّ، إلّا لملفٍّ موجودٍ فيه فعلا. فحارسُ
#   `deploy-set-intact` يلتقط كلَّ ما جاء على تلك الصورة هنا ويطلب وجودَه،
#   ولا يميّزها حين تكون ذيلَ مسارٍ أطولَ صدرُه مجلّدٌ آخر — فيحمرّ على مسارٍ
#   صحيحٍ اقتُطع صدرُه. (وقع مرّتين في الجولة التي كُتب فيها هذا السطر.)
bash deploy/preflight-env.sh deploy/.env.production || exit 1

# ── مصدر أصل الموقع للفحص الصحي وللإصدار ──
SITE_DOMAIN="$(grep -E '^SITE_DOMAIN=' deploy/.env.production | cut -d= -f2-)"

# ── والنطاقُ بلا www يُشتقّ حين لا يُضبط ──
#
# `deploy/.env.production` يسكن الخادمَ ولا يدخل Git. فمتغيّرٌ جديدٌ يُنتظَر
# من يدٍ بشريّةٍ تفتح الملفَّ يبقى معطّلا إلى أن تفعل — وعطبُ النطاق المجرّد
# قائمٌ حتّى تفعل. فيُشتقّ هنا: النشرةُ القادمةُ تُصلحه بلا انتظارِ أحد،
# ومن أراد اسما آخر كتبه في الملفّ فغلب المشتقَّ (قيمةُ الصدفة تسبق
# `--env-file` في docker compose).
#
# و`|| true` لازمةٌ: `set -o pipefail` أعلاه، وgrep بلا مطابقةٍ يخرج بواحد
# فيُسقط الإسنادَ والسكربتَ معه — على متغيّرٍ **اختياريٍّ** لا يُشترط وجوده.
SITE_ALT_DOMAIN="$(grep -E '^SITE_ALT_DOMAIN=' deploy/.env.production | tail -1 | cut -d= -f2- || true)"
if [ -z "$SITE_ALT_DOMAIN" ]; then
  case "$SITE_DOMAIN" in
    www.*) SITE_ALT_DOMAIN="${SITE_DOMAIN#www.}" ;;
    # لا `www.` يُحذف: النطاقُ الحيُّ مجرّدٌ أصلا، فلا ثانيَ له يُحوَّل
    *)     SITE_ALT_DOMAIN="localhost" ;;
  esac
fi

# ── وحارسُ الاسمَين المتطابقَين ──
#
# كتلتان بالعنوان نفسِه تُسقطان إعدادَ Caddy كلَّه لا الكتلةَ الزائدةَ
# وحدَها — أي **الموقعُ كلُّه** ثمنا لتحويلٍ لا يلزم. فيُقاس قبل أن يُصدَّر.
#
# وهذا قياسٌ لا ظنّ — شُغّل `caddy validate` على هذا الملفّ بالاسمَين
# متطابقَين (٢٠ سبتمبر ٢٠٢٦) فردّ وخرج بواحد:
#
#   Error: adapting config using caddyfile: ambiguous site definition: …
[ "$SITE_ALT_DOMAIN" != "$SITE_DOMAIN" ] || SITE_ALT_DOMAIN="localhost"
export SITE_ALT_DOMAIN

step "١/٧ · جلب الشيفرة"
if [ "${SKIP_PULL:-0}" != "1" ]; then
  git pull --ff-only

  # ── ثمّ يُعاد تشغيلُ النسخةِ المسحوبة، مرّةً واحدة ──
  #
  # ═══ العطبُ الذي كُتب له هذا ═══
  #
  # bash يقرأ السكربتَ **على دفعاتٍ وهو ينفّذه**، لا دفعةً واحدةً قبلَه.
  # و`git pull` أعلاه يعيد كتابة هذا الملفِّ تحته: فيستأنف بعدها القراءةَ من
  # إزاحةٍ بالبايت حُسبت على النصّ القديم، داخلَ نصٍّ جديدٍ أطولَ أو أقصر.
  # فتُتخطّى أسطرٌ وسطى أو تُقرأ أنصافُها.
  #
  # وهذا ما وقع مرّتين (١٢ سبتمبر ٢٠٢٦): أُضيفت إعادةُ تحميل Caddy في وسط
  # الملفّ فلم تُنفَّذ قطّ، ثمّ أُبدلت بإعادة إنشاءٍ فلم تُنفَّذ كذلك. وكان
  # الظاهرُ أنّ الأمرَ يفشل، والحقيقةُ أنّه لا يُقرأ أصلا — فالنشرةُ تنجح،
  # واللقطةُ تُنشَر، والترويسةُ وحدَها لا تتغيّر.
  #
  # والعلاجُ أن يُستأنف من النسخة الجديدة كاملةً: `exec` تستبدل العمليّة،
  # فتُقرأ من أوّلها. والحارسُ يمنع الدوران — السحبُ الثاني بلا جديد.
  if [ "${DEPLOY_REEXEC:-0}" != "1" ]; then
    export DEPLOY_REEXEC=1
    exec bash "$0" "$@"
  fi
fi
COMMIT="$(git rev-parse --short HEAD)"
echo "الإصدار: $COMMIT"

step "٢/٧ · نسخة احتياطية قبل الهجرة"
# هجرةٌ تفشل في منتصفها أسوأ من هجرةٍ لا تبدأ. النسخة هنا لا هناك.
if $COMPOSE ps db --status running --quiet | grep -q .; then
  bash deploy/backup.sh --pre-deploy || fail "تعذّرت النسخة الاحتياطية — أُوقف النشر. لا تُهاجَر قاعدةٌ بلا نسخة."
else
  echo "القاعدة لا تعمل بعد (أوّل نشر؟) — لا نسخة تُؤخذ"
fi

step "٣/٧ · بناء الصورة الجديدة"
# البناء أولا: الموقع القديم يخدم طوال هذه الخطوة
#
# وبصمةُ الالتزام تُصدَّر إلى البناء: `.dockerignore` يستثني `.git`، فلا
# يستطيع `write-build-stamp.ts` قراءتَها من داخل الصورة. وبلا ذلك يقول
# `/api/version` «الالتزام: null» — فلا يُعرف أوصلت النشرةُ أم لا، وهو
# السؤالُ الذي بُني ذلك المسارُ للجواب عنه.
export GIT_COMMIT_SHA="$(git rev-parse HEAD 2>/dev/null || true)"
export GIT_COMMIT_REF="$(git rev-parse --abbrev-ref HEAD 2>/dev/null || true)"
$COMPOSE build app || fail "أخفق البناء — الموقع القديم ما زال يعمل، لم يتغيّر شيء"

step "٤/٧ · تشغيل القاعدة وانتظار جاهزيتها"
$COMPOSE up -d db
for i in $(seq 1 30); do
  if $COMPOSE exec -T db pg_isready -q 2>/dev/null; then break; fi
  [ "$i" = 30 ] && fail "القاعدة لم تجهز خلال ٣٠ محاولة"
  sleep 2
done

step "٥/٧ · نشر الهجرات"
$COMPOSE run --rm --no-deps app npx prisma migrate deploy \
  || fail "أخفقت الهجرة — الحاويات لم تُبدَّل بعد، والموقع القديم يعمل. راجع السجل ثم أعد."

step "٦/٧ · تبديل الحاويات"
$COMPOSE up -d --remove-orphans

# ── وإعادةُ تحميل Caddy صراحةً ──
#
# `Caddyfile` مربوطٌ لا مبنيٌّ في الصورة (`./Caddyfile:/etc/caddy/Caddyfile:ro`).
# و`up -d` لا يُبدّل حاويةً إلا إن تغيّر **وصفُها**، وتحريرُ ملفٍّ مربوطٍ ليس
# تغييرا في الوصف. وCaddy يقرأ إعدادَه مرّةً عند الإقلاع ولا يراقب الملفّ.
#
# فكانت النتيجةُ صامتة: يُدمج تعديلُ السياسة ويصل الخادمَ على القرص، ويبقى
# Caddy على إعدادِ ما قبله إلى أن يُعاد تشغيلُ الحاوية لسببٍ آخر. وهكذا بقي
# `frame-src https://calendly.com` أربعةَ أيّامٍ في المستودَع لا في الترويسة،
# وبقي إطارُ الحجز مستطيلا أبيضَ للمتقدّمين (١٢ سبتمبر ٢٠٢٦).
# ── ولماذا `--force-recreate` لا `reload` ولا `restart` ──
#
# جُرّب `caddy reload` عبر `exec` أوّلا، ومعه `restart` احتياطا (١٢ سبتمبر
# ٢٠٢٦). ونزلت النشرةُ وبقيت الترويسةُ بلا `frame-src` — فلم يقع أثرُهما،
# وسببُ ذلك لا يُعرف من هنا: `2>/dev/null` ابتلعت الخطأ، ولا سبيلَ إلى
# سجلّ الخادم من مقعد المطوّر.
#
# فبدل تخمينِ العلّة، يُختار ما لا يعتمد على واجهة إدارةٍ داخل الحاوية ولا
# على قراءةِ عمليّةٍ قائمةٍ لملفِّها: إعادةُ إنشاء الحاوية. تُبنى من جديد
# فتقرأ المربوطَ حتما — والأثرُ يُقاس بعده في الفحص الصحيّ لا يُفترض.
#
# ولا تُبتلع الأخطاءُ بعد اليوم: ما سقط يُقرأ في سجلّ النشر.
$COMPOSE up -d --force-recreate caddy

step "٧/٧ · الكتالوج ثم الفحص الصحي"
# الكتالوج لا يُسقط النشر: المحرّك يقرأ اللقطة المنشورة، فإخفاق الاستيراد
# لا يغيّر حرفا لدى المستخدم — بينما إسقاط النشر يمنع الموقع كله.
if $COMPOSE exec -T app npm run catalog:import; then
  $COMPOSE exec -T app npm run catalog:publish || echo "⚠️  أخفق نشر اللقطة — الموقع على اللقطة السابقة"
else
  echo "⚠️  أخفق استيراد الكتالوج — الموقع الحيّ لم يتأثر. أعده يدويا لاحقا."
fi

# ── الفحصان: داخليٌّ ثمّ عامّ، ولكلٍّ حكمُه ──
#
# كان الفحصُ واحدا على `https://$SITE_DOMAIN`. وخطّةُ النقل تقول صراحةً إنّ
# الحزمةَ الجديدة **تعمل بالتوازي على عنوانٍ مؤقّت قبل تحويل النطاق** — وفي
# تلك المدّة لا يشير النطاقُ إلى هذا الخادم بعد، فيسقط الفحصُ وينصح السكربتُ
# بالرجوع، **والنشرُ ناجحٌ تماما**. ونصيحةُ رجوعٍ في غير موضعها أسوأُ من لا
# نصيحة: تُدرّب المشغّلَ على تجاهل آخر سطرٍ في المخرَج.
#
# فصار الفحصُ داخليّا أوّلا (الخادمُ نفسُه يجيب في شبكة Docker)، ثمّ عامّا
# من الخارج. والحكمُ يفرّق بين ثلاث حالات لا حالتين.

internal=0
for i in $(seq 1 20); do
  if $COMPOSE exec -T app node -e \
      "fetch('http://127.0.0.1:'+(process.env.API_PORT||7101)+'/api/version').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))" \
      >/dev/null 2>&1; then internal=1; break; fi
  sleep 3
done

if [ "$internal" != 1 ]; then
  printf '\n\033[31m✗ الخادم نفسُه لا يجيب — هذا إخفاقُ نشرٍ حقيقيّ\033[0m\n' >&2
  echo "السجل:  $COMPOSE logs --tail=80 app" >&2
  echo "للرجوع: git checkout <الإصدار السابق> && bash deploy/deploy.sh" >&2
  exit 1
fi

public=0
for i in $(seq 1 20); do
  if curl -fsS --max-time 5 "https://${SITE_DOMAIN}/api/version" >/dev/null 2>&1; then public=1; break; fi
  sleep 3
done

if [ "$public" = 1 ]; then
  # ── والترويسةُ تُقرأ كما تُرسَل، لا كما كُتبت في الملفّ ──
  #
  # حارسُ `frame-src` في `src/tests` يفحص `deploy/Caddyfile` — أي النيّةَ لا
  # الواقع. فبقي أخضرَ وCaddy يرسل سياسةً بلا `frame-src`، والإطارُ محجوب.
  # وهذا الفحصُ يسأل الخادمَ الحيَّ عمّا أرسله فعلا، فلا يختبئ فرقٌ بينهما.
  csp="$(curl -fsSI --max-time 5 "https://${SITE_DOMAIN}/" 2>/dev/null | tr -d '\r' | grep -i '^content-security-policy:' || true)"
  case "$csp" in
    *frame-src*calendly.com*) : ;;
    "") printf '\033[33m⚠️  لم تُقرأ ترويسةُ السياسة — افحصها يدويّا\033[0m\n' ;;
    *) printf '\033[31m⚠️  السياسةُ المُرسَلة بلا frame-src لـCalendly — إطارُ الحجز سيظهر أبيضَ للمتقدّمين\033[0m\n' >&2
       printf '    المُرسَل: %s\n' "$csp" >&2
       printf '    جرّب: %s restart caddy\n' "$COMPOSE" >&2 ;;
  esac

  # ── والتحويلُ من النطاق المجرّد يُقاس كما يُجيب ──
  #
  # درسُ الترويسة أعلاه نفسُه: `Caddyfile` نيّةٌ، والمُرسَلُ حقيقة. وهذا
  # الاسمُ خاصّةً يسقط صامتا — لا اختبارَ يراه، ولا صفحةَ تحمرّ، ولا أحدَ
  # يكتشفه إلّا زائرٌ ظنّ الموقعَ ميّتا فذهب.
  #
  # ولا يُسقط النشرةَ: الموقعُ على `SITE_DOMAIN` يخدم، والشهادةُ الجديدةُ
  # تُجلب عند أوّل طلبٍ فقد تتأخّر ثوانيَ. فيُقال ولا يُهدَم ما نجح.
  if [ "$SITE_ALT_DOMAIN" != "localhost" ]; then
    alt="$(curl -sS -o /dev/null -w '%{http_code} %{redirect_url}' --max-time 8 "https://${SITE_ALT_DOMAIN}/" 2>/dev/null || true)"
    case "$alt" in
      "301 https://${SITE_DOMAIN}/"*)
        printf '\033[32m✓ %s يحوّل إلى %s\033[0m\n' "$SITE_ALT_DOMAIN" "$SITE_DOMAIN" ;;
      000*|"")
        printf '\033[33m⚠️  لا تصافحَ مع %s بعد — الشهادةُ تُجلب عند أوّل طلب. أعد الفحص بعد دقيقة:\033[0m\n' "$SITE_ALT_DOMAIN" >&2
        printf '    curl -sSI https://%s/\n' "$SITE_ALT_DOMAIN" >&2 ;;
      *)
        printf '\033[31m⚠️  %s لا يحوّل كما يجب — المُقاس: %s\033[0m\n' "$SITE_ALT_DOMAIN" "$alt" >&2
        printf '    السجل: %s logs --tail=40 caddy\n' "$COMPOSE" >&2 ;;
    esac
  fi

  printf '\n\033[32m✓ نُشر الإصدار %s على https://%s\033[0m\n' "$COMMIT" "$SITE_DOMAIN"
  echo
  echo "لم يبقَ إلا التحقّق اليدويّ من المال:"
  echo "  · أرسل حدث اختبار من لوحة سترايب وتأكّد من ٢٠٠"
  echo "  · $COMPOSE logs -f app   لمتابعة السجل"
elif ! getent hosts "$SITE_DOMAIN" >/dev/null 2>&1; then
  # النطاقُ لا يُترجَم بعد: هذه مرحلةُ التوازي، والنشرُ ناجح
  printf '\n\033[32m✓ نُشر الإصدار %s — والخادم يجيب داخليّا\033[0m\n' "$COMMIT"
  printf '\033[33m…و%s لا يُترجَم بعد، فلا يُفحَص من الخارج. هذا متوقَّعٌ قبل تحويل النطاق.\033[0m\n' "$SITE_DOMAIN"
  echo "افحصه بعنوان الخادم المؤقّت، أو أضف سطرا في /etc/hosts للفحص وحدَه."
else
  # النطاقُ يُترجَم ولا يجيب: الخادمُ يعمل والطريقُ إليه مقطوع
  printf '\n\033[31m✗ الخادم يجيب داخليّا، ولا يجيب على https://%s\033[0m\n' "$SITE_DOMAIN" >&2
  echo "فابحث في الطريق لا في التطبيق: شهادةُ Caddy · جدارُ النار (٤٤٣) · سجلّ DNS" >&2
  echo "السجل:  $COMPOSE logs --tail=80 caddy" >&2
  exit 1
fi
