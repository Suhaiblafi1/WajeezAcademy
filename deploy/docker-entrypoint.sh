#!/bin/sh
# نقطة الدخول: تنشر ملفات الواجهة إلى الحجم المشترك ثم تسلّم للخادم.
#
# لماذا النسخ لا الوصل: Caddy يقدّم dist من حجمٍ مشترك، والحجم يبقى بين
# الإصدارات. فلو اكتفينا بالإضافة لبقيت ملفات الإصدار السابق بأسمائها
# المُبصمة — لا تضرّ، ولكنها تتراكم بلا نهاية. والمسح ثم النسخ يجعل الحجم
# صورةً طبق الأصل من الإصدار العامل، فما على القرص هو ما في الصورة.
set -e

if [ -d /srv/web ]; then
  rm -rf /srv/web/* /srv/web/.[!.]* 2>/dev/null || true
  cp -a /app/dist/. /srv/web/
  echo "✓ نُشرت ملفات الواجهة إلى /srv/web"
fi

exec "$@"
