#!/bin/sh
# نقطة الدخول: تنشر ملفات الواجهة إلى الحجم المشترك ثم تسلّم للخادم.
#
# لماذا النسخ لا الوصل: Caddy يقدّم dist من حجمٍ مشترك، والحجم يبقى بين
# الإصدارات. فلو اكتفينا بالإضافة لبقيت ملفات الإصدار السابق بأسمائها
# المُبصمة — لا تضرّ، ولكنها تتراكم بلا نهاية. والنسخ ثم مسحُ ما ليس في
# الإصدار يجعل الحجم صورةً طبق الأصل من الإصدار العامل، فما على القرص هو ما
# في الصورة.
#
# ═══ والواجهةُ الجديدةُ لا تُنشر قبل أن يجيب خادمُها (٢٠ أكتوبر ٢٠٢٦) ═══
#
# سأل صاحبُ المنصّة: «لماذا يجب أن أعمل رفرش كلّ مرّة لتظهر أسماءُ المدرّبين؟».
# وكان من أسبابه أنّ النسخ يقع **أوّلَ** ما تقلع الحاوية، في كلّ حاويةٍ من
# هذه الصورة:
#   · `deploy.sh` يشغّل الهجرةَ بـ`compose run app …` — فتصير الواجهةُ الجديدةُ
#     حيّةً في خطوة الهجرة، قبل تبديل الحاويات، والخادمُ القديمُ يخدمها.
#   · ثمّ `up -d` يعيد إنشاءَ الحاوية: يمسح الحجمَ وينسخ ويقلع الخادم — وبين
#     المسح والنسخ لا ملفَّ يقدّمه Caddy، وحتّى يجيب الخادمُ تطلب الواجهةُ
#     الجديدةُ واجهةً برمجيّةً لا تجيب (٥٠٢)، فتبقى صفحاتُها تقول «لا أحد».
#
# فصار النسخُ في الخلفية **بعد أن يجيب خادمُ هذه الحاوية نفسِها**
# (`/api/version` كفحص الصحّة في Dockerfile): الهجرةُ وكلُّ `compose run`
# لا خادمَ فيها فلا تنشر شيئا، والعاملُ بلا `/srv/web` أصلا. وحتّى يجيب يبقى
# Caddy يقدّم الواجهةَ السابقة كاملة. والنسخُ يضع الجديدَ فوق القديم ثمّ يمسح
# ما ليس منه — لا مسحَ أوّلا يترك الحجمَ فارغا.
#
# والمساراتُ متغيّراتٌ لاختبارها خارج الصورة (`src/tests/deploy/web-publish-after-api.test.ts`).
set -e

WEB_ROOT="${WEB_ROOT:-/srv/web}"
WEB_DIST="${WEB_DIST:-/app/dist}"
# أقصى ما يُنتظر الخادم: إن لم يجب فالنشرُ ساقطٌ أصلا (فحصُ `deploy.sh` الداخليّ)،
# والواجهةُ السابقةُ أسلمُ من جديدةٍ بلا خادم
WEB_PUBLISH_WAIT="${WEB_PUBLISH_WAIT:-600}"

api_answers() {
  node -e "fetch('http://127.0.0.1:'+(process.env.API_PORT||7101)+'/api/version').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))" >/dev/null 2>&1
}

publish_web() {
  # ١) الأصولُ المُبصمةُ أوّلا — أسماؤها جديدة، فلا تمسّ ما تقدّمه الصفحةُ السابقة
  if [ -d "$WEB_DIST/assets" ]; then
    mkdir -p "$WEB_ROOT/assets"
    cp -a "$WEB_DIST/assets/." "$WEB_ROOT/assets/"
  fi
  # ٢) ثمّ الباقي، ومنه `index.html` الذي يشير إليها
  cp -a "$WEB_DIST/." "$WEB_ROOT/"
  # ٣) ثمّ ما ليس في هذا الإصدار يُمحى — فالحجمُ صورةٌ طبقُ الأصل
  (cd "$WEB_ROOT" && find . -mindepth 1) | while IFS= read -r f; do
    [ -e "$WEB_DIST/$f" ] || rm -rf "${WEB_ROOT:?}/$f"
  done
  echo "✓ نُشرت ملفات الواجهة إلى $WEB_ROOT"
}

publish_when_api_answers() {
  waited=0
  until api_answers; do
    if [ "$waited" -ge "$WEB_PUBLISH_WAIT" ]; then
      echo "⚠️  لم يجب الخادم خلال ${WEB_PUBLISH_WAIT} ثانية — بقيت الواجهة السابقة في $WEB_ROOT" >&2
      return 0
    fi
    sleep 1
    waited=$((waited + 1))
  done
  publish_web
}

if [ -d "$WEB_ROOT" ]; then
  # تفرّعٌ مزدوج: المنتظِرُ يتيمٌ يتبنّاه tini (PID 1) فيحصده — لا يبقى عالقا تحت الخادم
  ( publish_when_api_answers & )
fi

exec "$@"
