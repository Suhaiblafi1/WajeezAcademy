-- ═══ C-COMX-107 دورةً مساندةً في «الأسرة والتربية» (PW-FAM-001) — بأمر صاحب المنصّة (٣٠ سبتمبر ٢٠٢٦) ═══
--
-- أُعيدت الدورةُ إلى الكتالوج (`20260930190000_restore_c_comx_107`) قائمةً بنفسها:
-- بلا مسارٍ ولا ترشيحٍ مباشر، فيجدها من يتصفّح ولا يرشّحها التشخيصُ لأحد. فقال
-- صاحبُ المنصّة: «add it to the family dialogue pathway».
--
-- ── مساندةً لا أساسيّة ──
--
-- أساسيّاتُ المسار في الملفّ (`core-catalog.v2.json`)، وعليها يُقاس التشخيص —
-- `course_ids` يقرؤها pathwaySkills — وتحرسها بواباتُ CI على الملفّ: الرحلاتُ
-- والهدرُ والتغطية. فرابطٌ أساسيٌّ من القاعدة وحدَها يغيّر ما يرشّحه المسارُ في
-- الإنتاج ولا يمتحنه حارسٌ واحد. والمساندةُ تُقصى من `course_ids` بقصد
-- (`snapshot-builder.ts` و`public-catalog.service.ts`) فلا تمسّ حسابَ التشخيص،
-- وتظهر في صفحة المسار ضمن «المسار الجاهز»: أربعُ أساسيّاتٍ ثمّ ثلاثُ مساندات،
-- كما تُعرض وتُسعَّر (`readyPathwayCourseIds`) — كما C-EDU-101 وC-EDU-106 في المسار
-- نفسِه. وهي الثالثةُ التي يتّسع لها (`MAX_PATHWAY_COURSES`).
--
-- ── والسعرُ يُقال ──
--
-- سعرُ المسار الجاهز مجموعُ أسعار شعب دوراته، ولا يُعرض ما لم يُعرف سعرُ كلٍّ منها.
-- فمتى فُتحت لهذه شعبةٌ دخل سعرُها مجموعَه — سبعُ دوراتٍ لا ستّ. ويومَ كُتب هذا لا
-- شعبةَ مفتوحةً لأيٍّ من دورات المسار ولا لها، فلا رقمَ على الشاشة يتغيّر الآن.
--
-- ── ويبقى بعد كلّ نشر ──
--
-- المستوردُ لا يقلّم إلّا روابطَ دورات الملفّ (`course: { createdBy: null }`)،
-- وهذه دورةُ لوحة. وترتيبُها بعد آخر رابطٍ في المسار. ولا يُكتب إلّا والدورةُ
-- منشورةٌ والمسارُ قائم، ولا يُضاف ثانٍ إن وُجد الرابط — فالجملةُ تُعاد فلا تفسد.
INSERT INTO "PathwayCourse" ("pathwayId", "courseId", "sequence", "kind", "reasonAr")
SELECT
  'PW-FAM-001',
  'C-COMX-107',
  COALESCE((SELECT MAX(pc."sequence") FROM "PathwayCourse" pc WHERE pc."pathwayId" = 'PW-FAM-001'), 0) + 1,
  'support',
  'الحوارُ الذي يُبنى في البيت يمتدّ إلى الحديث أمام الناس — وهذه الدورةُ تُعِدّ الوالدَ ليدرّب ابنه على الخطابة والإلقاء.'
WHERE EXISTS (SELECT 1 FROM "Course" c WHERE c."id" = 'C-COMX-107' AND c."status" = 'published')
  AND EXISTS (SELECT 1 FROM "Pathway" p WHERE p."id" = 'PW-FAM-001')
ON CONFLICT ("pathwayId", "courseId") DO NOTHING;
