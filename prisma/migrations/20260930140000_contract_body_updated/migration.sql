-- أمرُ صاحب المنصّة: من أراد أن يصل الناسَ عقدٌ محدَّثٌ كان عليه أن يُلغيَ
-- عقدَهم ويركّب غيرَه فيصلهم رابطٌ جديد. وسأل: أفلا يُحدَّث ما بين أيديهم
-- بالرابط نفسِه؟
--
-- فيُكتب هنا متى حُدّث ومن أيّ إصدار:
-- · `bodyUpdatedAt` يُظهر الشريطَ على صفحة التوقيع، فمن قرأ العرضَ أمس وعاد
--   اليوم يعرف أنّ نصَّه تبدّل قبل أن يوقّع — ولا يوقّع على غير ما قرأ.
-- · و`bodyPrevVersion` يُعرَف به ما بين الإصدارَين من نقاطٍ تُقال له، فمن كان
--   على إصدارٍ أقدمَ يقرأ ما تغيّر في الإصدارات كلِّها لا في الأخير وحدَه.
--
-- وكلاهما فارغٌ لكلّ عقدٍ قائم: لم يُحدَّث واحدٌ منها بعد.
