-- الشتاءُ بسنتيه (١٩ أكتوبر ٢٠٢٦): «موسم الشتاء 2027» كان يعني نوفمبر 2027 إلى يناير 2028 ويُقرأ الشتاءَ الذي في
-- أوّل 2027. فما سُمّي بالاسم الآليّ القديم يصير «موسم الشتاء 2027/2028» — كما يسمّيه `termTitleAr` الآن.
-- وما سمّته الإدارةُ بيدها باسمٍ آخرَ لا يُمسّ. والجملةُ تُعاد فلا تفسد.
UPDATE "Term"
SET "titleAr" = 'موسم الشتاء ' || "year" || '/' || ("year" + 1)
WHERE "season" = 'nov_jan' AND "titleAr" = 'موسم الشتاء ' || "year";
