-- حذفُ ثلاثِ حالاتٍ من طلب المدرّب، ونقلُ صفوف الانتظار
--
-- طلبُ صاحب المنصّة (٢٦ سبتمبر ٢٠٢٦): «أرى أنّ الحالاتِ كثيرةٌ الآنَ أصبحت
-- لطلب المدرّب… لخّصْ لي إيّاها كلَّها وشرحا عن كلّ حالة، واقترحْ حذفَ جزءٍ
-- منها وأنا أعطيك رأيي قبل التنفيذ». ثمّ قال في الصفوف: «والصفوفُ انقلها
-- لـ﴿رأيٌ ثانٍ — قبل قرار المقابلة﴾».
--
-- والقولُ في كلّ حالةٍ ولمَ ذهبت أو بقيت: `TRAINER_STATUSES` في
-- `server/services/trainer-application.service.ts`.
--
-- ولا يُمَسُّ `TrainerStatusHistory`: هو خبرٌ عمّا وقع، ونقضُه تزويرُ سجلٍّ
-- لا تنظيفُ بيانات. فسطرٌ يقول «صار مختارا أوّليّا في ١٢ سبتمبر» يبقى صادقا
-- وإن لم يعد أحدٌ يصير كذلك بعد اليوم.

-- ① قائمةُ الانتظار → رأيٌ ثانٍ (بنصّ أمره — خمسةُ صفوفٍ وقتَ كتابته)
UPDATE "TrainerApplication" SET "status" = 'academic_review' WHERE "status" = 'waitlisted';

-- ② وبريدٌ لم يُوثَّق → مسوّدة.
--    كلتاهما «طلبٌ لم يُرسَل ولا بريدٌ ثبت أنّه بريدُه»، وتُعامَلان معاملةً
--    واحدةً في كلّ موضعٍ يفرّق. و`submitted` لا تصلح وجهةً: تدفع بريدا
--    مجهولا إلى الطابور، وهو ما بُنيت البوّابةُ كلُّها لمنعه.
UPDATE "TrainerApplication" SET "status" = 'draft' WHERE "status" = 'email_verification_pending';

-- ③ ومختارٌ أوّليٌّ وبانتظار الديمو → قيد المراجعة.
--    كلتاهما صفرُ صفوفٍ في الإنتاج بشارات الشاشة، فهذا احتياطٌ لا نقل:
--    ولو تُركت صفوفٌ فيهما لَعُرضت بشارةٍ فارغةٍ لا لفظَ لها في المعجم.
UPDATE "TrainerApplication" SET "status" = 'under_review' WHERE "status" IN ('shortlisted', 'demo_requested');

-- ④ والافتراضُ يصير ما تكتبه اليدُ أصلا.
--    كان `email_verification_pending`، ولا موضعَ إنشاءٍ يقبله: نموذجُ
--    التقدّم يكتب `draft` صريحا، والتعيينُ الداخليُّ يكتب `active`. فكان
--    افتراضا لا يُستعمَل، وحالةً لا يكتبها مسار.
ALTER TABLE "TrainerApplication" ALTER COLUMN "status" SET DEFAULT 'draft';
