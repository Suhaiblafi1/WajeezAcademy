-- حذفُ إتاحة المدرّب: ساعاتُه الأسبوعيّة، وغيابُه، وموقفُه من كلّ فصل
--
-- قرارُ صاحب المنصّة (٢٧ سبتمبر ٢٠٢٦): «احذف ساعاتي وفصولي وفترات غيابي..
-- لأنه هو من يتحكم بكل شي.. واضح له أن اللقاءات بيده ويجب أن تكون ضمن فترة
-- الشعبة نفسها التي وضعها بنفسه ابتداءً حتى النهاية».
--
-- والجداولُ الثلاثةُ **إعلاناتٌ عن المستقبل لا خبرٌ عمّا وقع**: ساعاتٌ يقول
-- إنّه يستطيعها، ومددٌ يقول إنّه غائبٌ فيها، وموسمٌ يقول إنّه متاحٌ فيه. ولا
-- يكتبها ولا يقرؤها بعد اليوم شيء — ذهبت شاشتُها ومساراتُها وفحوصُها في
-- الإسناد معا. وجدولٌ لا يكتبه أحدٌ ولا يقرؤه يَشهد بما لم يعد صحيحا.
--
-- وما وقع فعلا باقٍ حيث يُحفظ الخبر: كلُّ إعلانٍ كُتب له سطرُه في سجلّ الأثر
-- (`trainer.availability.set` · `trainer.blackout.add` · `trainer.blackout.remove`
-- · `term.trainer_availability`)، ومعجمُ أسمائها باقٍ فيُقرأ بالعربيّة.
--
-- ومواسمُ طلب الانضمام لا تُمَسّ: `TrainerApplication.availability` عمودُ JSON
-- في الطلب نفسِه — ما قاله المتقدّمُ يومَ تقدّم، لا إعلانٌ يُدار.
--
-- ولا مفتاحَ أجنبيَّ يشير إليها من غيرها، فالحذفُ بلا `CASCADE`: لو ظهر
-- مرجعٌ لم يُحسب له لسقط الترحيلُ بصوتٍ بدل أن يأخذ معه ما لا يُعرف.

DROP TABLE IF EXISTS "TrainerTermAvailability";
DROP TABLE IF EXISTS "TrainerBlackout";
DROP TABLE IF EXISTS "TrainerAvailability";
