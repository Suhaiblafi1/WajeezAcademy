-- تطهيرُ حالةٍ قديمةٍ قبل أن يمنعها القيد — وإلّا سقط النشرُ على الإنتاج.
--
-- العطبُ الذي أُصلح في الشيفرة (`catalog-admin.service.ts`): اعتمادُ دورةٍ
-- كان يكتب **حالةَ الدورة** على وحداتها كما هي. وللدورةِ ستُّ حالات
-- (`draft | in_review | approved | published | paused | archived`) وللوحدةِ
-- ثلاثٌ (`draft | published | archived`) — فكان الاعتمادُ يكتب `approved`
-- على كلّ وحدة، والمراجعةُ `in_review`، والإيقافُ `paused`. وهي حالاتٌ لا
-- تملكها الوحدة.
--
-- ولمَ هذا الملفُّ ضروريّ: الترحيلُ التالي (`…211500_status_check_constraints`)
-- يضيف قيدا يمنع تلك القيم. والقيدُ في PostgreSQL **يُفحَص على الصفوف
-- القائمة** عند إضافته — فصفٌّ واحدٌ قديمٌ بحالة `approved` يُسقط
-- `migrate deploy`، ومعه بناءُ الإنتاج كلُّه، ويُسجَّل الترحيلُ فاشلا فتُحجَب
-- النشراتُ التالية حتّى يُحلَّ يدويّا.
--
-- وقاعدةُ التطوير المحلّيّةُ لا تكشف ذلك: بياناتُها مبذورةٌ بالشيفرة الجديدة
-- **بعد** الإصلاح، فلا صفَّ قديما فيها. والقاعدةُ الحيّةُ عمرُها أطولُ من
-- الإصلاح، فهي التي قد تحمله. (ولم يُقرأ الإنتاجُ للتحقّق — لا وصولَ إليه
-- من هنا ولا حاجة: الترحيلُ لا يفعل شيئا إن لم يوجد صفٌّ كذلك.)
--
-- ولمَ `draft` هي الوجهة: الاعتمادُ ليس نشرا. ووحدةُ دورةٍ اعتُمدت ولم تُنشر
-- حالُها الصحيحةُ `draft`، ويكتب النشرُ عليها `published` حين يقع فعلا
-- (`updateMany` بشرط `status: { not: to }`). فلا يُنشر بهذا الترحيل محتوى
-- لم يُنشَر، ولا يُخفى محتوى منشور: `published` و`archived` لا يمسّهما.

UPDATE "CourseModule"
SET "status" = 'draft'
WHERE "status" NOT IN ('draft', 'published', 'archived');
