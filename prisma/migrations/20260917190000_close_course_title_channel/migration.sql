-- ق٥: بابُ اقتراح اسم الدورة يُغلق — وما كُتب قبل إغلاقه لا يضيع.
--
-- أغلق صاحبُ المنصّة (١٧ سبتمبر ٢٠٢٦) قناةَ اقتراح اسمِ الدورة: «بابُ اسم
-- الدورة يُغلق». فخرج `course_title_edit` من `CHANGE_TYPES`، وحُذفت شاشتُه
-- ومسالكُه، وزال سطرُه من بطاقة المعتمِد.
--
-- ويبقى سؤالٌ لا تجيبه الشيفرة: **ما مصيرُ طلبٍ أرسله مدرّبٌ ولم يُبتَّ فيه
-- بعد؟** لو تُرك حيًّا لبقي في طابور الإدارة بندا لا تعرف الشاشةُ كيف تعرضه
-- ولا الخدمةُ كيف تطبّقه — فيُهمَل بلا أن يُقال لصاحبه شيء. وهذا بعينه ما
-- تعهّدنا ألّا يقع: «لا يضيع عملُ مدرّبٍ صامتا».
--
-- فيُصيَّر المعلَّقُ `superseded` — لا `withdrawn` (فلم يسحبه صاحبُه) ولا
-- `rejected` (فلم يُحكَم على مضمونه)، بل تجاوزَه قرارٌ بعده. والصفُّ يبقى
-- بنصّه وسببه واسمه المقترَح، ويُكتب في `reviewerComment` لماذا وقف.
--
-- والطلبُ الذي بُتّ فيه (معتمَدٌ أو منشورٌ أو مرفوض) لا يُمَسّ: قرارٌ وقع
-- لا يُعاد كتابتُه.

UPDATE "TrainerChangeRequest" r
SET "status" = 'superseded',
    "reviewerComment" = COALESCE(r."reviewerComment" || ' · ', '')
      || 'أُغلقت قناةُ اقتراح اسم الدورة (١٧ سبتمبر ٢٠٢٦)، فوقف هذا الطلبُ حيث هو — ولم يُحكَم على مضمونه.',
    "updatedAt" = CURRENT_TIMESTAMP
WHERE r."status" IN ('draft', 'submitted', 'under_review', 'changes_requested')
  AND EXISTS (
    SELECT 1 FROM "TrainerChangeRequestItem" i
    WHERE i."requestId" = r."id" AND i."changeType" = 'course_title_edit'
  );
