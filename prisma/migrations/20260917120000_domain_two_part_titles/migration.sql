-- ═══ عناوينُ المجالات صارت مقطعين — والصفوفُ القائمة تتبعها ═══
--
-- ── العطبُ الذي لولا هذا الترحيل لَوقع ──
--
-- `Course.domainAr` ليس زينةً في القاعدة: مخطِّطُ الفصل يقارنه **حرفا بحرف**
-- (`application/terms/planner`: `a.domainAr === b.domainAr`) ليمنع دورتين من
-- مجالٍ واحدٍ أن تتزاحما في فصلٍ واحد، ورقاقاتُ التقويم العامّ تعرضه كما هو.
--
-- والأسماءُ تغيّرت في `src/application/catalog/course-domain.ts` (قرارُ صاحب
-- المنصّة ١٧ سبتمبر ٢٠٢٦: عنوانٌ من مقطعين بلا عدد). فالدوراتُ التي وُلدت
-- قبل اليوم تحمل الاسمَ القديم، والتي تُولد بعده تحمل الجديد — فيصير
-- «التسويق» و«التسويق ورحلة العميل» مجالَين مختلفَين عند المخطِّط، ويكفّ عن
-- رؤية تزاحمٍ هو قائمٌ فعلا. ولا يحمرّ شيء: المخطَّطُ سليم، والأنواعُ تمرّ،
-- والقائمةُ تُعرض — والخللُ في صفوفٍ لا ينظر إليها أحد.
--
-- ولمَ يُعاد الاشتقاقُ من المعرّف لا تُبدَّل الأسماءُ القديمةُ واحدا واحدا:
-- العائلةُ في المعرّف هي المصدرُ الذي تقرأ منه `courseDomain` نفسُها، فالنتيجةُ
-- واحدةٌ مهما كان المكتوبُ في العمود — ويستوي فيه صفٌّ كُتب في ترحيل
-- `term_system` وصفٌّ كتبه معالجُ الدورات بعده. والجملةُ تُعاد فلا تفسد.
--
-- والعائلاتُ غيرُ المعروفة لا تُمَسّ: `catalog-admin.service` يكتب لها NULL
-- عمدا، فلا يُبدَّل صمتُها بـ«أخرى» هنا.
UPDATE "Course" SET "domainAr" = CASE split_part("id", '-', 2)
  WHEN 'AI'   THEN 'الذكاء الاصطناعي وتطبيقاته'
  WHEN 'DAT'  THEN 'تحليل البيانات ولوحات المؤشرات'
  WHEN 'AUT'  THEN 'أتمتة الأعمال والوكلاء الأذكياء'
  WHEN 'CYB'  THEN 'الأمن السيبراني وحماية البيانات'
  WHEN 'PRD'  THEN 'إدارة المنتج وإطلاقه'
  WHEN 'PM'   THEN 'إدارة المشاريع والمخاطر'
  WHEN 'MGR'  THEN 'القيادة وإدارة الفرق'
  WHEN 'OPS'  THEN 'إدارة العمليات والجودة'
  WHEN 'SCM'  THEN 'سلاسل الإمداد والمخزون'
  WHEN 'HR'   THEN 'الموارد البشرية وإدارة الأداء'
  WHEN 'FINM' THEN 'المالية والمحاسبة'
  WHEN 'MKT'  THEN 'التسويق ورحلة العميل'
  WHEN 'SAL'  THEN 'المبيعات وإغلاق الصفقات'
  WHEN 'SVC'  THEN 'خدمة العملاء وتجربة المستفيد'
  WHEN 'BIZ'  THEN 'ريادة الأعمال ونماذج العمل'
  WHEN 'NEG'  THEN 'التفاوض وإدارة الخلاف'
  WHEN 'COMX' THEN 'التواصل والإلقاء'
  WHEN 'LND'  THEN 'التصميم التعليمي وتيسير التدريب'
  WHEN 'CAR'  THEN 'المسار المهني وقرار الانتقال'
  WHEN 'JOB'  THEN 'البحث عن عمل ومهارات المقابلة'
  WHEN 'GRPH' THEN 'التصميم البصري والهوية'
  WHEN 'INTR' THEN 'التصميم الداخلي والتشطيبات'
  WHEN 'ENGR' THEN 'المخططات الهندسية وحصر الكميات'
  WHEN 'PSY'  THEN 'علم النفس والسلوك الإنساني'
  WHEN 'EDU'  THEN 'التعلّم والتربية'
  ELSE "domainAr"
END
WHERE split_part("id", '-', 2) IN (
  'AI','DAT','AUT','CYB','PRD','PM','MGR','OPS','SCM','HR','FINM','MKT','SAL',
  'SVC','BIZ','NEG','COMX','LND','CAR','JOB','GRPH','INTR','ENGR','PSY','EDU'
);
