WHERE v."courseId" = 'C-COMX-107'
  AND v."version" = (SELECT MAX(x."version") FROM "CourseVersion" x WHERE x."courseId" = 'C-COMX-107')
  AND NOT EXISTS (SELECT 1 FROM "LearningOutcome" lo WHERE lo."courseVersionId" = v."id");

