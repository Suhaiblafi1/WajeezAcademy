-- ═══ محتوى C-COMX-107 من خطّة مدرّبها المعتمَدة — بأمر صاحب المنصّة (٢٦ أكتوبر ٢٠٢٦) ═══
--
-- «دورة إعداد المعلمين، لماذا لا يوجد لها محاور وتفاصيل أخرى كباقي الدورات؟ فهي فارغةٌ من الداخل» (صاحب المنصّة).
-- وُلدت الدورةُ في اللوحة باسمها ومهاراتها ووحدةٍ واحدةٍ مؤقّتة («اعداد القادة»، بلا مخرَجٍ ولا نشاط)، ولم يُكتب لها
-- وصفٌ ولا أهدافٌ ولا مخرجات. وشعبتُها الوحيدة (صهيب احمد لافي، ٥ ديسمبر) خطّتُها معتمَدةٌ بثمانية لقاءاتٍ معنونة
-- ووصفٍ لما يخرج به المتعلّم — فمن هناك يُكتب محتواها، لا من تخمين.
--
-- ── وما يُكتب وما لا يُكتب ──
--
-- · الحقولُ الفارغةُ وحدَها في إصدارها الأحدث: الوعدُ والوصفُ والجمهورُ والمستوى. وما كتبه إنسانٌ في اللوحة لا يُمسّ.
-- · والأهدافُ والمخرجاتُ إن خلا الإصدارُ منها.
-- · والوحدةُ الأولى تُكتب عليها الأولى من الخطّة ما دامت هي المؤقّتة نفسها (عنوانُها «اعداد القادة» وبلا مخرَج).
-- · والسبعُ الباقيةُ وحداتٌ جديدةٌ منشورة — ولا تُضاف ثانيةً إن وُجدت (`ON CONFLICT`).
-- · ولا شيء إن لم تكن الدورةُ قائمة. والجملُ تُعاد فلا تفسد.
--
-- ساعاتُها ١٦ كما هي: ثماني وحداتٍ بساعتين.

-- ① الوعدُ والوصفُ والجمهورُ والمستوى — في الإصدار الأحدث، الفارغُ منها وحدَه
UPDATE "CourseVersion" AS v
SET
  "shortPromiseAr" = COALESCE(NULLIF(v."shortPromiseAr", ''), 'تدرّب طفلا بين 5 و12 سنة على الخطابة خطوة بخطوة — حتى يلقي خطابه الختامي أمام الناس.'),
  "descriptionAr" = COALESCE(NULLIF(v."descriptionAr", ''), 'تخرج منها قادرا على تدريب ابنك أو طلابك (5–12 سنة) على الخطابة والإلقاء بخطوات عملية: من كسر الخوف إلى الثقة، وتنظيم الأفكار، وقوة الصوت، ولغة الجسد. ومعك أنشطة جاهزة للتطبيق في البيت والفصل، وبطاقة تقييم تقيس بها تقدم الطفل خطوة بخطوة.'),
  "audienceAr" = COALESCE(NULLIF(v."audienceAr", ''), 'معلمون وأولياء أمور يريدون أن يبنوا ثقة الطفل في الكلام أمام الناس. وتحتاج طفلا واحدا بين 5 و12 سنة تتدرب معه طوال الدورة، من تسجيله الأول إلى خطابه الختامي.'),
  "levelAr" = COALESCE(NULLIF(v."levelAr", ''), 'تطبيقي')
WHERE v."courseId" = 'C-COMX-107'
  AND v."version" = (SELECT MAX(x."version") FROM "CourseVersion" x WHERE x."courseId" = 'C-COMX-107');

-- ② الأهدافُ — إن خلا الإصدارُ الأحدثُ منها
INSERT INTO "LearningObjective" ("id", "courseVersionId", "sequence", "textAr")
SELECT gen_random_uuid(), v."id", o.seq, o.txt
FROM "CourseVersion" v
CROSS JOIN (VALUES
  (1, 'يشخّص مستوى الطفل في الكلام أمام الناس بتسجيل أول وبطاقة تقييم.'),
  (2, 'يعلّم الطفل أن يرتب فكرته قبل أن يتكلم: بداية ووسط وخاتمة.'),
  (3, 'يدرب الطفل على نفسه وصوته ولغة جسده بأنشطة قصيرة في البيت والفصل.'),
  (4, 'يقيس تقدم الطفل بين تسجيل وآخر ويختار النشاط التالي بناء على ذلك.')
) AS o(seq, txt)
WHERE v."courseId" = 'C-COMX-107'
  AND v."version" = (SELECT MAX(x."version") FROM "CourseVersion" x WHERE x."courseId" = 'C-COMX-107')
  AND NOT EXISTS (SELECT 1 FROM "LearningObjective" lo WHERE lo."courseVersionId" = v."id");

