--
-- وُلدت دوراتُ الأسرة (٢٢ سبتمبر) وعائلتُها بلا اسمٍ في
-- `src/application/catalog/course-domain.ts`، فحمل `Course.domainAr` لها
-- فراغا: المعالجُ يكتب NULL لعائلةٍ لا يعرفها، والمستوردُ مثلُه.
--
-- ودوراتُ ملفّ الكتالوج يكتب المستوردُ مجالَها في أوّل استيرادٍ بعد هذا النشر.
-- أمّا دوراتُ اللوحة (`createdBy` غيرُ فارغ) فلا يمسّها المستورد، ولا يكتب
-- المعالجُ المجالَ إلّا يومَ الميلاد — فدورةٌ وُلدت تحت مسار الأسرة في اللوحة
-- تبقى بلا مجالٍ إلى الأبد لولا هذه الجملة.
--
-- والشرطُ على العائلة في المعرّف كترحيل `domain_two_part_titles`، والاسمُ
-- حرفيّا كما في `course-domain.ts` — فالمخطِّطُ يقارنه حرفا بحرف. والجملةُ
-- تُعاد فلا تفسد.
UPDATE "Course" SET "domainAr" = 'الحوار الأسري وتربية الأبناء'
WHERE split_part("id", '-', 2) = 'FAM';
