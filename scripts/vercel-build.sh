#!/usr/bin/env bash
# بناء Vercel: توليد Prisma + نشر الهجرات بإعادة محاولة + بناء الواجهة + تجميع API.
#
# ── الهجرات: بناءُ الإنتاج وحده يهاجر ──
#
# كان كلُّ بناءٍ يهاجر، والمعاينةُ والإنتاجُ يتشاركان قاعدة Neon نفسَها.
# فأيُّ فرعٍ يُدفع للمراجعة كان **يغيّر مخطَّط القاعدة الحيّة قبل أن يوافق
# عليه أحد** — وهجرةٌ تحذف عمودا في فرعٍ مرفوض تحذفه من الإنتاج.
#
# وإعادةُ المحاولة الأربع أدناه كانت علاجَ العَرَض لا السبب: البناءان
# يتزاحمان على القفل الاستشاري (pg_advisory_lock) فيسقط أحدهما بـP1002.
# والسببُ أنّ الثاني لا شأن له بالهجرة أصلا. وتبقى المحاولاتُ لأنّ بناءَي
# إنتاجٍ متتاليَين قد يتزاحما كذلك.
#
# والمعاينةُ تعمل على مخطَّط الإنتاج كما هو: فرعٌ يحتاج هجرةً جديدة لا
# تُختبَر معاينتُه — وهذا صحيحٌ لا نقص، فمكانُ اختبارها بيئةُ تجريبٍ
# بقاعدتها الخاصّة (خطّة النقل، المرحلة ١).
set -e

npx prisma generate

if [ "$VERCEL_ENV" = "production" ]; then
  attempt=1
  max=4
  until npx prisma migrate deploy; do
    if [ "$attempt" -ge "$max" ]; then
      echo "migrate deploy failed after $max attempts"
      exit 1
    fi
    wait_s=$((attempt * 20))
    echo "migrate deploy attempt $attempt failed — retrying in ${wait_s}s (advisory lock race)"
    sleep "$wait_s"
    attempt=$((attempt + 1))
  done
else
  echo "تخطّي نشر الهجرات — البيئة '${VERCEL_ENV:-محلية}' وليست الإنتاج."
  echo "  المعاينة تقرأ مخطَّط الإنتاج كما هو ولا تغيّره."
fi

npm run build

# ── بصمات السكربتات الداخلية في سياسة المحتوى ──
#
# سياسة المحتوى في vercel.json تسمّي سكربتَي index.html ببصمة محتواهما بدل
# 'unsafe-inline'. والبصمة تُحسب على المبنيّ لا المصدر — فلو اختلف تصغير
# الأداة هنا عمّا حُسب عليه محليّا، لخالفت البصمةُ ما يُنشَر: فيُحجَب سكربت
# المظهر (وميضٌ أبيض قبل الداكن) وشبكةُ أمان الحزمة المحذوفة (بيضُ صفحات
# سفاري) — بصمتٍ تامّ، فالمتصفّح يرفض ولا يشتكي إلى أحد.
#
# فيُسقَط البناء هنا بدل أن يُنشر موقعٌ سياستُه تكذب على نفسها.
npx tsx scripts/audit-csp.ts --check

node scripts/bundle-api.mjs

# ── استيراد الكتالوج إلى قاعدة الإنتاج ──
#
# الإنتاج وحده: نُسخ المعاينة تشترك مع الإنتاج في نفس قاعدة Neon، فلو استوردت
# لكتبت محتوى فرع قيد المراجعة في جداول الموقع الحي.
#
# ولا يُسقِط البناء عند الإخفاق: الاستيراد يمسّ الجداول فقط، والمحرك يقرأ
# اللقطة المنشورة — فإخفاقه لا يغيّر حرفا واحدا لدى المستخدم، بينما إسقاط
# البناء يمنع نشر الموقع كله. نعلنه صراحة في السجل ونكمل.
#
# والاستيراد وحده لا يصل المستخدم: المحرك يقرأ اللقطة المنشورة لا الجداول،
# فيليه النشر أدناه.
if [ "$VERCEL_ENV" = "production" ]; then
  echo "── استيراد الكتالوج إلى قاعدة الإنتاج ──"
  if CATALOG_IMPORT_SKIP_MIGRATE=1 npm run catalog:import; then
    echo "✅ الجداول محدَّثة"
    imported=1
  else
    echo "⚠️  أخفق استيراد الكتالوج — البناء يكمل، والموقع الحي لم يتأثر."
    echo "    أعده يدويا: DATABASE_URL=\"…\" npm run catalog:import"
    imported=0
  fi

  # ── نشر اللقطة ──
  #
  # اللقطة كانت الطبقة الوحيدة خارج مجرى Git: الكود والمحتوى وبنية القاعدة
  # تصل بدفعة، وهي تنتظر أربع ضغطات في اللوحة — فيتقدّم المستودع ويبقى
  # المستخدم على القديم بلا ما ينبّه.
  #
  # ما يبقى من الحوكمة: النشر ذرّي يرفض عند أي نقص، واللقطات تُحفظ فالتراجع
  # بضغطة متاح من اللوحة، وتحليل الأثر يُشغَّل ويُطبع هنا ويُخزَّن قبل النشر.
  # ولا يُنشر شيء حين تطابق بصمة الجداول اللقطة الحية.
  #
  # ولا يجري إلا بعد استيراد ناجح: النشر بعد استيراد أخفق يجمّد نصف تحديث.
  if [ "$imported" = "1" ]; then
    echo "── نشر لقطة الكتالوج ──"
    if npm run catalog:publish; then
      :
    else
      echo "⚠️  أخفق نشر اللقطة — البناء يكمل، والمحرك يبقى على اللقطة السابقة."
      echo "    انشرها يدويا من /admin/publishing."
    fi
  else
    echo "تخطّي نشر اللقطة — الاستيراد لم ينجح، فلا يُجمَّد نصف تحديث"
  fi
else
  echo "تخطّي الاستيراد والنشر — البيئة '${VERCEL_ENV:-محلية}' وليست الإنتاج"
fi
