/* انتظارُ الأثر لا انتظارُ الساعة — لنقطةٍ تردّ قبل أن تعمل.

   ═══ العطبُ الذي وُجدت له (٢٠ سبتمبر ٢٠٢٦) ═══

   نقطةُ Zoom تردّ أوّلا ثمّ تعمل، بقصدٍ مكتوبٍ في موضعه
   (`zoom-webhook.routes.ts`): «Zoom يُعطّل نقطةً تتأخّر أو تُخطئ مرارا».
   و`inject` في الاختبار يعود بمجرّد إرسال الردّ — أي **قبل** أن تبلغ
   الكتابةُ القاعدةَ. فكانت الجولاتُ تراهن على الوقت:

       await new Promise((r) => setTimeout(r, 120))

   ومئةٌ وعشرون جزءا من الألف على عدّاءٍ محمَّلٍ ليست وعدا. فسقط
   `zoom-webhook.test.ts` في CI على فرعٍ لا يمسّ Zoom بحرف (طلبُ السحب
   ٢٣٥): `expected undefined to be '2026-12-01T10:30:00.000Z'` — لا لأنّ
   الكتابةَ لم تقع، بل لأنّها لم تقع **بعدُ**.

   وأخطرُ من حمرته خضرتُه: كلُّ مرّةٍ مرّ فيها كان يمرّ لأنّ المهلةَ كفت،
   لا لأنّ الأثرَ وقع. وهو بعينه ما يحذّر منه `CLAUDE.md`: «الفحصُ على
   البنية لا على ورودِ حرفٍ في ملفّ» — وحارسٌ يقيس الساعةَ لا يقيس شيئا.

   ═══ وكيف تُصلحه ═══

   تسأل عن الأثر حتّى يقع أو تنقضي مهلةٌ سخيّة. فالخضرةُ تصير عن كتابةٍ
   وقعت، والحمرةُ عن كتابةٍ لم تقع — لا عن سرعةِ عدّاء.

   **وترجع بآخر ما قرأته عند انقضاء المهلة، ولا ترمي**: خطأٌ من هنا يقول
   «انقضت المهلة» ويُخفي ما كان في الصفّ فعلا، أمّا الرجوعُ فيترك
   `expect` يقول الفرقَ كما هو (`undefined` مقابل التاريخ المنتظَر) —
   وهو ما يُقرأ في سجلّ CI بعد أسبوع.

   ═══ وما لا تصلح له ═══

   **النفيَ.** «لم يُكتب صفٌّ ثانٍ» لا يُنتظَر: ما لم يقع بعدُ يُشبه ما لن
   يقع تماما. فمن أراد أن يثبت نفيا فليُنادِ الخدمةَ نفسَها منتظِرا
   (`await new ZoomEventService(prisma).handle(…)`) — فلا سباقَ أصلا —
   أو فليبقَ على مهلةٍ ثابتةٍ يعرف أنّها رهان. */

/** يسأل حتّى يقع الأثرُ أو تنقضي المهلة، ويرجع بآخر ما قرأ في الحالين. */
export async function untilWritten<T>(
  read: () => Promise<T>,
  done: (seen: T) => boolean,
  ms = 3_000,
): Promise<T> {
  const deadline = Date.now() + ms
  for (;;) {
    const seen = await read()
    /* المهلةُ تُقاس بعد القراءة لا قبلها: قراءةٌ أخيرةٌ تقع دائما، فلا
       تسقط جولةٌ لأنّ العدّادَ سبق الاستعلامَ بجزءٍ من الألف. */
    if (done(seen) || Date.now() >= deadline) return seen
    await new Promise((r) => setTimeout(r, 25))
  }
}
