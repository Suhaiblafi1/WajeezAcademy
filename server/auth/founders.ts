/* مؤسِّسو المنصّة — من يملك لوحةَ الإدارة، معلَنا في الشيفرة لا في أمرٍ يدويّ.
 *
 * ── العطبُ الذي يُزيله ──
 *
 * التسجيلُ يمنح `learner` وحدَه، وتعيينُ دورٍ من الشاشة محكومٌ بالرتبة: لا
 * يمنح `super_admin` إلّا `super_admin`. **فقاعدةٌ بلا مديرِ نظامٍ لا سبيلَ
 * إليها من الواجهة أصلا** — وكان السبيلُ الوحيد `npm run promote:super-admin`
 * على الخادم.
 *
 * وذلك يعني أنّ صاحبَ المنصّة لا يرى لوحتَه إلّا بيدِ من يملك SSH. وهو يملك
 * المستودَع، ويملك حساباتِ مزوّديه، ولا يملك الخادم — فبقيت شاشةُ التكاملات
 * (البريدُ والدفع) وراءَ بابٍ لا يفتحه هو.
 *
 * ── وكيف يعمل ──
 *
 * عند كلّ إقلاعٍ للخادم: من كان بريدُه هنا **وله حسابٌ على المنصّة** يُضاف
 * إليه `super_admin`، و**يُرفع عنه الإيقافُ إن كان موقوفا**. ثمّ يصير كلُّ
 * شيءٍ من المتصفّح: الأدوارُ من `/admin/users`، والبريدُ والدفعُ من
 * `/admin/integrations`.
 *
 * ── ولماذا يرفع الإيقافَ أيضا؟ ──
 *
 * للعلّةِ التي وُجد من أجلها، في صورتها الثانية. فالرتبةُ لم تكن تُنال من
 * المتصفّح وصار هذا سبيلَها؛ والإيقافُ كذلك: **رفعُه لا يقع إلّا من داخل
 * لوحةٍ لا يفتحها موقوف.** فمن أُوقف حسابُه خرج، ولا يعيده إلّا مديرُ نظامٍ
 * آخر أو من يملك SSH — وصاحبُ المنصّة قد لا يملك أيّهما.
 *
 * ووقع ذلك فعلا (٢٠ سبتمبر ٢٠٢٦): له ملفُّ مدرّبٍ كما لغيره، فرأى اسمَه في
 * قائمة المدرّبين فأوقفه — وكان إيقافُ المدرّب يوقف الحسابَ معه
 * (`trainer-review.service.ts`). فذهبت لوحتُه ورفعُ الإيقاف في نقرةٍ واحدة.
 * وقد ضُيِّق ذلك المسارُ هناك، **وهذا البابُ يبقى**: فالطرقُ إلى الخارج
 * أكثرُ من واحد، والمخرجُ يجب أن يكون واحدا لا يعتمد على أحد.
 *
 * ── وخمسةُ حدودٍ مقصودة ──
 *
 * ١) **لا يُنشئ حسابا.** لا كلمةَ مرورٍ تُخترع ولا حسابٌ يظهر لم يسجّله أحد.
 *    فمن أراد لوحتَه يسجّل من `/auth` أوّلا كأيّ أحد، ثمّ تُضاف رتبتُه.
 * ٢) **لا ينزع دورا ولا حسابا.** يُضيف ويَرفع — ولا يُسقط أحدا بتعديل قائمة.
 * ٣) **ولا يفكّ أرشفةً.** الإيقافُ حالةٌ تُرفع، والأرشفةُ قرارٌ أثقل يُخرج
 *    الحسابَ من الشاشات كلِّها — فلا يُنقض في إقلاعِ خادم. وإن كان بريدٌ هنا
 *    مؤرشَفا قيل في السجلّ ولم يُكتب شيء.
 * ٤) **يُسجَّل في الأثر** بلا فاعلٍ (النظام)، ويُطبع في السجلّ. لا ترقيةَ ولا
 *    رفعَ إيقافٍ صامتا.
 * ٥) **البريدُ يُقارَن بحروفٍ صغيرة** — كما يُخزَّن عند التسجيل.
 *
 * ── وهل هو بابٌ خلفيّ؟ ──
 *
 * من يستطيع تعديلَ هذا الملفّ يستطيع تعديلَ الشيفرة كلِّها ونشرَها. فمن ملك
 * الكتابةَ في المستودَع ملك الخادمَ فعلا، وهذه القائمةُ لا تمنحه صلاحيّةً
 * جديدة — لكنّها **تجعل ما كان يقع في الظلّ مكتوبا في سجلّ Git**: من أُضيف،
 * ومتى، وبأيّ التزام، وبمراجعةِ طلبِ سحب. وذلك أوثقُ من أمرٍ يُنفَّذ في
 * طرفيّةٍ لا يراها أحد ولا يبقى منه أثر.
 *
 * وحدُّه الحقيقيّ، ويجب أن يُقرأ صريحا: **من ملك بريدا في هذه القائمة وملك
 * حسابا به ملك المنصّة كاملةً — ولا يُوقَف.** فإيقافُه يُرفع في الإقلاع
 * التالي، وهو مقصودٌ لا عطب: مخرجٌ يمكن إغلاقُه ليس مخرجا. فلا يُضاف بريدٌ
 * إلّا بقرارِ صاحبها، ولا يُترك بريدٌ لم يعد صاحبُه من أهل المنصّة — ونزعُه
 * من هذه القائمة هو الذي يجعله يُوقَف كأيّ أحد.
 */

import type { PrismaClient } from '@prisma/client'
import { recordAudit } from '../services/audit'
import { safeNotify } from '../services/notification.service'

/** بُرُدُ المؤسِّسين — بحروفٍ صغيرة، وبقرارِ صاحب المنصّة وحدَه */
export const FOUNDER_EMAILS: readonly string[] = [
  'suhaib@wajeez.co',
]

const ROLE = 'super_admin'

export interface FounderResult {
  /** من رُقّي في هذا الإقلاع */
  promoted: string[]
  /** من كان مرقّى من قبل */
  already: string[]
  /** بريدٌ لا حسابَ له بعد — يُقال ولا يُخترع له حساب */
  missing: string[]
  /** من رُفع عنه الإيقافُ في هذا الإقلاع */
  reinstated: string[]
  /** مؤسِّسٌ حسابُه مؤرشَف — يُقال ولا تُنقَض الأرشفة */
  archived: string[]
}

/**
 * يضمن أنّ لكلّ مؤسِّسٍ له حسابٌ رتبةَ مدير النظام وحسابا غيرَ موقوف.
 * يُستدعى عند الإقلاع، وهو آمنُ الإعادة.
 */
export async function ensureFoundersPromoted(prisma: PrismaClient): Promise<FounderResult> {
  const out: FounderResult = { promoted: [], already: [], missing: [], reinstated: [], archived: [] }

  for (const raw of FOUNDER_EMAILS) {
    const email = raw.trim().toLowerCase()
    if (!email.includes('@')) continue

    const user = await prisma.user.findUnique({
      where: { email },
      select: { id: true, status: true, roles: { select: { roleId: true } } },
    })
    if (!user) { out.missing.push(email); continue }

    /* ═══ ① رفعُ الإيقاف — قبل الرتبة، وبمعزلٍ عنها ═══

       الرتبةُ لا تنفع موقوفا: `auth.service` يردّ الدخولَ على غير `active`
       قبل أن يُنظر في دورٍ أصلا. ولذلك يقع هذا **قبل** فحصِ الدور وقبل
       `continue` الذي يتخطّى المرقَّى من قبل — وإلّا لم يُرفع إيقافٌ عمّن
       رتبتُه معه، وهي حالةُ صاحب المنصّة بعينها.

       والأرشفةُ لا تُنقض: قرارٌ أثقل من أن يُلغى في إقلاعِ خادم. تُقال
       ويُترك أمرُها لإنسان. */
    if (user.status === 'archived') {
      out.archived.push(email)
    } else if (user.status === 'suspended') {
      await prisma.user.update({
        where: { id: user.id },
        data: { status: 'active', suspendedAt: null },
      })
      await recordAudit(prisma, {
        actorId: null,
        action: 'auth.founder.reinstated',
        entityType: 'user',
        entityId: user.id,
        meta: { email, source: 'FOUNDER_EMAILS' },
        reason: 'حسابُ مؤسِّسٍ موقوف — يُرفع إيقافُه عند الإقلاع',
      })
      /* وبريدٌ لا جرس: الجرسُ يُقرأ من داخل الحساب، وهو خارجُه حتّى يدخل.
         و`safeNotify` تكفي لأنّ الجرسَ يُقرأ **بعد** الدخول لا قبله — فهو
         خبرٌ يجده حين يعود، لا دعوةٌ إلى العودة. والعودةُ نفسُها صارت ممكنةً
         بالسطر فوقَه، وذلك هو المقصود. */
      await safeNotify(prisma, {
        userId: user.id, channel: 'in_app', audience: 'staff',
        templateKey: 'account.reinstated',
        title: 'رُفع الإيقافُ عن حسابك',
        body: 'كان حسابُك في أكاديمية وجيز موقوفا، ورُفع الإيقافُ عند إقلاع الخادم لأنّ بريدَك في قائمة المؤسِّسين. ودخولُك عاد كما كان.',
        data: { source: 'FOUNDER_EMAILS' },
      })
      out.reinstated.push(email)
    }

    /* ② ثمّ الرتبة */
    if (user.roles.some((r) => r.roleId === ROLE)) { out.already.push(email); continue }

    /* `skipDuplicates`: إقلاعان متزامنان لا يتنازعان على صفٍّ واحد */
    await prisma.userRole.createMany({
      data: [{ userId: user.id, roleId: ROLE }],
      skipDuplicates: true,
    })
    await recordAudit(prisma, {
      actorId: null,
      action: 'auth.founder.promoted',
      entityType: 'user',
      entityId: user.id,
      meta: { email, role: ROLE, source: 'FOUNDER_EMAILS' },
    })
    /* ═══ ويعلم صاحبُ الحساب أنّ لوحةَ الإدارة فُتحت له (ي-٤) ═══

       يقع هذا عند إقلاع الخادم بلا فاعلٍ إنسانٍ: بريدٌ في قائمة المؤسِّسين
       يُرقّى صاحبُه مديرَ نظامٍ أعلى. وكان يقع بلا خبرٍ لصاحبه — ومكانةٌ
       تُمنح في صمتٍ لا تُراجَع.

       و`audience: 'staff'` صراحةً: الافتراضُ `learner`، فصفُّ الإشعار
       ينزل في جرسِ بوّابةِ المتعلّم — وهي البوّابةُ التي لا يفتحها مديرُ
       النظام. وجرسٌ في بابٍ لا يُطرَق ليس إخبارا.

       وجرسٌ لا بريدٌ هنا بقصد: يقع في كلِّ إقلاعٍ يُرقّي، ولا يُعلَّق بدءُ
       الخادم على نداءِ شبكة. */
    await safeNotify(prisma, {
      userId: user.id, channel: 'in_app', audience: 'staff',
      templateKey: 'account.roles_changed',
      title: 'أُضيف إليك دورُ مديرِ النظام الأعلى',
      body: 'أُضيف إلى حسابك في أكاديمية وجيز دورُ مديرِ النظام الأعلى عند إقلاع الخادم، لأنّ بريدَك في قائمة المؤسِّسين. ولوحةُ الإدارة مفتوحةٌ لك الآن.',
      data: { role: ROLE, source: 'FOUNDER_EMAILS' },
    })
    out.promoted.push(email)
  }

  return out
}
