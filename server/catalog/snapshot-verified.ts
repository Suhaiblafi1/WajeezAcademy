/* «أيُّ التزامٍ آخِرُ من قارن الجداولَ باللقطة المنشورة ووجدهما سواء؟»

   ─────────── العطبُ الذي وُلد منه هذا الملفّ ───────────

   `‎/api/version` كان يحكم بالتطابق بمقارنة **بصمتَي التزام**: التزامِ الكود
   العامل، والتزامِ اسمِ اللقطة (`auto-<sha7>-<hash6>`). وهو حكمٌ سليمٌ يومَ
   كُتب، لأنّ كلَّ نشرةٍ كانت تُنشئ لقطة.

   ثمّ صار النشرُ الآليُّ **لا ينشر حين لا جديد** (`auto-publish.service.ts`):
   تطابقُ بصمةِ المحتوى يعني أنّ ما في الجداول هو ما يقرؤه المحرّك أصلا،
   فإنشاءُ إصدارٍ حينها ضجيجٌ في سجلٍّ يُقرأ عند الأعطال. **وهذا صواب.**

   وأثرُه على الحكم أنّ اسمَ اللقطة يبقى على آخر التزامٍ **غيّر المحتوى**،
   بينما الكودُ يتقدّم مع كلّ نشرة. فبعد أيّ نشرةٍ لا تمسّ الكتالوج — وهي
   أغلبُ النشرات — يفترق السهمان ويردّ المسارُ:

     «لا — الكودُ واللقطةُ من التزامين مختلفين؛ الأرجحُ أنّ نشرا جاريا لم
      يكتمل بعد»

   **ولا نشرَ جارٍ ولا شيءَ ناقص.** وقد وقع فعلا في ٨ سبتمبر ٢٠٢٦ بعد نشرة
   `2127e8b`: نصٌّ وتعليقٌ وحارس، ولا حرفَ كتالوجٍ فيها.

   ─────────── ولماذا يهمّ إنذارٌ كاذبٌ بالعطب ───────────

   هو أخو الإنذار الكاذب بالسلامة الذي في `worker/heartbeat.ts`، وضررُه من
   جنسِه: نقطةٌ تقول «لا» بعد **كلّ** نشرةٍ روتينيّة تُدرَّب على الإهمال،
   فيمرّ اليومُ الذي تقولها فيه بحقٍّ ولا يقرؤها أحد. وتعليقُ المسار نفسِه
   يحمل سابقةً لهذا: كانت العبارةُ تجزم بأنّ اللقطة «من التزامٍ أقدم» في كلّ
   اختلاف، **ورُصدت تكذب** أثناء نشرٍ متعثّر — فرُدّت إلى وصف ما ترى.

   ─────────── والعلاج: يُسجَّل من تحقَّق، لا يُخمَّن ───────────

   مقارنةُ بصمةِ المحتوى في كلّ نداءٍ هي الجوابُ الدقيق، ولكنّها تبني اللقطةَ
   المرشّحةَ من الجداول كلَّها — و`‎/api/version` هو **فحصُ صحّةِ الحاوية** في
   `Dockerfile`، يُنادى كلَّ ثلاثين ثانية. فبناءُ الكتالوج عنده ثمنٌ يُدفع
   دائما لسؤالٍ يُسأل نادرا.

   فيُكتب الجوابُ حيث حُسب أصلا: `publishSnapshotIfChanged` تقارن البصمتَين
   في كلّ نشرة — سواءٌ نشرت أم وجدتهما سواء — فتترك صفّا يقول «هذا الالتزامُ
   رأى الجداولَ واللقطةَ متطابقتَين». والقراءةُ بعدها صفٌّ واحدٌ بمفتاح.

   ─────────── وأين — ولا جدولَ جديدا ───────────

   في `SystemSetting` كالنبضة وإثباتِ الاسترجاع: مفتاحٌ وقيمةٌ JSON. وهي
   **حالةٌ راهنةٌ لا تاريخ** — صفٌّ واحدٌ يُكتب فوقه فلا ينمو شيءٌ ولا يُقلَّم. */

import type { Prisma, PrismaClient } from '@prisma/client'

/** مفتاحُ الصفّ — صفٌّ واحدٌ يُكتب فوقه لا سجلٌّ يُضاف إليه */
export const VERIFIED_KEY = 'catalog.snapshot.verifiedBy'

export interface SnapshotVerified {
  /** الالتزامُ الذي أجرى المقارنة */
  commit: string
  /** بصمةُ المحتوى وقتَها — تشخيصيّةٌ لا يُحكَم بها هنا */
  hash: string
  at: string
}

/** تكتبها `publishSnapshotIfChanged` بعد كلّ مقارنة. وإخفاقُها لا يُسقط نشرا.

    ولا يُكتب صفٌّ حين لا التزامَ معروف: صفٌّ بلا بصمةٍ لا يُجيب سؤالا،
    وغيابُه يقول «لا يمكن الحكم» وهو أصدقُ من قيمةٍ فارغةٍ تُقرأ حكما. */
export async function recordSnapshotVerified(
  prisma: PrismaClient,
  input: { commit?: string | null; hash: string; now?: Date },
): Promise<void> {
  if (!input.commit) return
  const value: SnapshotVerified = {
    commit: input.commit,
    hash: input.hash,
    at: (input.now ?? new Date()).toISOString(),
  }
  const json = value as unknown as Prisma.InputJsonObject
  await prisma.systemSetting.upsert({
    where: { key: VERIFIED_KEY },
    create: { key: VERIFIED_KEY, value: json },
    update: { value: json },
  })
}

/** آخرُ التزامٍ تحقَّق — و`null` إن لم يقع قطّ أو كان الصفُّ تالفا.

    ⚠️ **ولا يُرمى من هنا خطأٌ أبدا.** المسارُ الذي يقرؤها هو فحصُ صحّةِ
    حاويةِ الخادم، فخطأٌ يخرج منها يجعل Docker يحكم على حاويةٍ سليمةٍ
    بالسقوط ويعيد تشغيلَ الموقع لأنّ صفًّا في جدولٍ جانبيٍّ لم يُقرأ. */
export async function lastVerifiedCommit(prisma: PrismaClient): Promise<string | null> {
  try {
    const row = await prisma.systemSetting.findUnique({ where: { key: VERIFIED_KEY } })
    const v = row?.value as Partial<SnapshotVerified> | null
    return v && typeof v.commit === 'string' && v.commit.length > 0 ? v.commit : null
  } catch {
    return null
  }
}
