/* ═══ أيُّ اللقاءات يراها المتعلّم — بوّابةٌ واحدةٌ لا شرطٌ يُنسَخ ═══

   صار للّقاء منذ ١٥ سبتمبر ٢٠٢٦ موقفٌ من الإدارة (`approvalState`): يجدوله
   مدرّبُه `pending`، فلا يصير لقاءً حتّى تعتمده. وقرارُ صاحب المنصّة:
   «وبعدها الإدارةُ توافق، ويصبح هناك جلسةُ زووم لايف تُنشَر في منصّة الطلبة
   بتاريخها».

   ── ولمَ ملفٌّ لشرطٍ من سطر ──

   اللقاءاتُ تُقرأ في أكثرَ من عشرة مواضع: رحلةُ المتعلّم، وتقويمُه،
   ومواعيدُه، وتقدّمُه، وصفحةُ الشعبة العامّة. ولو كُتب الشرطُ في كلٍّ منها
   بيده لَنُسي في واحد — وذاك الواحدُ يعرض للمتعلّم موعدا لم يُعتمَد بعدُ
   ولن يُعقَد. وهو بعينه ما وقع في هذه المنصّة مع بوّابة ظهور المدرّب، حتّى
   جُمعت في `trainer-visibility.ts`.

   والأسوأُ أنّ العطبَ **صامت**: لا يسقط شيء، بل يُعرض موعدٌ زائد. فلا
   يكتشفه إلّا متعلّمٌ حضر في وقتٍ لم يأتِ فيه أحد.

   ── وما بعد الاعتماد ──

   المردودُ (`rejected`) يُكتب معه `status: 'cancelled'`، فيسقط كذلك بالشرط
   الذي تحمله المواضعُ أصلا عن الملغى. والشرطُ هنا على الاعتماد وحدَه —
   الملغى شأنُ دورةِ حياة اللقاء لا شأنُ الإذن به. */

/** ما يراه المتعلّم: المعتمَدُ وحدَه */
export const LEARNER_SESSION_WHERE = { approvalState: 'approved' } as const

/** وما ينتظر قرارا — للطابور الذي تقرّر فيه الإدارة */
export const PENDING_SESSION_WHERE = { approvalState: 'pending' } as const

/** أهذا اللقاءُ معتمَدٌ؟ — للصفوف المقروءة بلا شرطٍ في الاستعلام */
export function sessionApproved(s: { approvalState?: string | null }): boolean {
  /* والفارغُ معتمَدٌ: صفوفُ ما قبل العمود لقاءاتٌ معلَنةٌ يحضرها الناسُ فعلا،
     وحجبُها بترحيلٍ يسحبها من تقاويمهم. والترحيلُ لا يحجب. */
  return (s.approvalState ?? 'approved') === 'approved'
}
