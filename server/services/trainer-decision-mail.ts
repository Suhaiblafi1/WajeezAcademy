/* نصوصُ ما يصل المتقدّمَ عند القرار وعند التذكير — دالّاتٌ خالصةٌ لا تُرسل.

   ═══ لماذا انفصلت عن `trainer-review.service.ts` ═══

   ما يقرؤه إنسانٌ رُدَّ طلبُه أهمُّ من أن يُكتب في وسط خدمةٍ بألف سطر ولا
   يحرسه شيء. وحرسُه هناك كان يعني قاعدةَ بياناتٍ وخادما وبذرَ أدوار — أي
   حارسا لا يُشغَّل، ومكتوبٌ في `src/tests/audit-labels-coverage.test.ts`
   ماذا يجري لحارسٍ ثمنُه اثنتا عشرة دقيقة.

   فصار النصُّ دالّةً تُعطى اسما ورقما وتردّ رسالةً، ويُفحص في المسار السريع
   بلا قاعدةٍ ولا خادم: `src/tests/trainer-decision-mail.test.ts`.

   ═══ وسببُ الرفض لا يسافر في البريد — بنيةً لا اتّفاقا ═══

   قرارُ صاحب المنصّة (١٨ سبتمبر ٢٠٢٦): ما يكتبه المراجعُ عند الرفض يبقى في
   الأثر الداخليّ ولا يصل صاحبَ الطلب. وكان يصله في جدولِ حقائقَ مؤطَّرٍ
   عنوانُه «وممّا كُتب في المراجعة» — وهو أقسى ما في الرسالة: حكمٌ مكتوبٌ
   لعينِ مراجعٍ يقرؤه صاحبُه.

   ولذلك **لا تقبل `rejectionMail` ملاحظةً أصلا**: لا معامَلَ لها، فلا يمرّ
   سهوٌ في نداءٍ يوما فيُرسلها. وقائمةُ الانتظار تبقى على ملاحظتها — فتلك
   تقول «ننتظرك لأجل كذا» ولا تُقرأ حكما.

   ═══ ولا زرَّ في رسالة الرفض ═══

   القوالبُ كلُّها تحمل زرَّ دعوة، وهذا يبقى بلا زرّ بقصد: لا شاشةَ تُفتح له
   بعد القرار — و`BOOKABLE_STATUSES` تُخرج `rejected` من الحجز أصلا، فزرٌّ
   هنا يقود إلى بابٍ مغلق. */

import type { MailDoc } from './mail-template'
import { TRAINER_INTERVIEW } from '../../src/application/trainer/application-options'

/** ما يُسلَّم إلى `sendDirectEmail` — الموضوعُ ووصفُ الرسالة */
export interface DecisionMail {
  subject: string
  doc: MailDoc
}

/** الاسمُ الذي يُدعى به في كلّ ما يقرؤه المتقدّم — مصدرُه واحدٌ مع الشاشات */
export const MEETING_AR = TRAINER_INTERVIEW.labelAr

/** ردُّ الاعتذار — أربعُ حركات: شكرٌ، ثمّ مراجعةٌ متأنّية، ثمّ القرار، ثمّ بابٌ يبقى */
export function rejectionMail(input: { fullName: string; reference: string }): DecisionMail {
  return {
    subject: `بخصوص طلبك للانضمام مدرّبا — أكاديمية وجيز (${input.reference})`,
    doc: {
      greetingName: input.fullName,
      preheader: 'قرأنا طلبك كاملا، ولم نتمكّن هذه المرّة من المضيّ فيه.',
      heading: 'بخصوص طلبك للانضمام إلى فريق مدرّبي وجيز',
      blocks: [
        {
          kind: 'p',
          text: 'شكرا جزيلا لوقتك ولاهتمامك بمشاركتنا خبرتك — ونقدّر لك حقّا أنّك خصّصت من وقتك '
            + 'ما يكفي لتقديم طلبٍ كاملٍ إلينا.',
        },
        {
          kind: 'p',
          text: 'وقد قرأ فريقنا الأكاديميُّ طلبك ومستنداتِك قراءةً متأنّية، ونأسف لإبلاغك بأنّنا '
            + 'لم نتمكّن هذه المرّةَ من المضيّ قدما فيه.',
        },
        {
          kind: 'p',
          text: 'وليس في هذا حكمٌ على خبرتك ولا على ما تُتقنه: حاجاتُنا تتبدّل مع ما يُفتح من '
            + 'مساراتٍ وشعب، وما لم يوافقها اليومَ قد يوافقها غدا.',
        },
        {
          kind: 'p',
          text: 'ونشكرك مجدّدا على اهتمامك بأكاديمية وجيز، ونتمنّى لك كلَّ التوفيق في مسيرتك المهنيّة.',
        },
        /* ═══ وتنتهي عند رقم الطلب — لا سطرَ بعده (١٩ سبتمبر ٢٠٢٦) ═══

           كان تحته سطرٌ خافتٌ يدعوه إلى التقدّم من جديدٍ ويقول إنّ ردَّه
           يصلنا. وقرارُ صاحب المنصّة أن يُحذف: «لا داعي لهذه الجملة».

           ولا يضيع به شيء: **الدعوةُ إلى العودة** مقولةٌ في صفحة حالته
           (`APPLICANT_STATUS.rejected`) وهي موضعُها — يقرؤها من عاد يسأل،
           لا من فتح خبرَ الاعتذار للتوّ. **وبابُ الردّ** مقولٌ في تذييل
           القالب: «هذه رسالةٌ آليّة؛ وردُّك عليها يصل فريقَ الدعم».

           فالرسالةُ تُقال كاملةً ثمّ تسكت — والسكوتُ بعد اعتذارٍ أرفقُ من
           سطرٍ يُلحق به. */
        { kind: 'facts', rows: [{ label: 'رقم الطلب', value: input.reference }] },
      ],
    },
  }
}

/** قائمةُ الانتظار — ولا يُقال لمن ينتظر إنّه رُدّ، ولا يُترك بلا خبر */
export function waitlistMail(input: {
  fullName: string; reference: string; noteAr?: string
}): DecisionMail {
  const note = input.noteAr?.trim()
  return {
    subject: `طلبُك في قائمة الانتظار (${input.reference})`,
    doc: {
      greetingName: input.fullName,
      preheader: 'راجعنا طلبك ولم نُغلقه — وُضع في قائمة الانتظار حتّى تُفتح حاجةٌ تناسبك.',
      heading: 'طلبُك في قائمة الانتظار',
      blocks: [
        {
          kind: 'p',
          text: 'شكرا لوقتك ولما شاركتَه معنا. راجعنا طلبك ولم نُغلقه: وُضع في قائمة الانتظار '
            + 'حتّى تُفتح حاجةٌ تناسب ما تدرّسه.',
        },
        /* الملاحظةُ في إطارٍ لا في جدولِ حقائق: الجدولُ للأرقام والتواريخ،
           وجملةٌ يكتبها إنسانٌ لإنسانٍ فيه تُقرأ سجلًّا. */
        ...(note ? ([{ kind: 'h', text: 'وممّا دار في مراجعتنا' }, { kind: 'callout', text: note }] as const) : []),
        {
          kind: 'p',
          text: 'ونعود إليك على هذا العنوان حين يجدّ ما يناسبك، ولا يلزمك شيءٌ الآن.',
        },
        { kind: 'facts', rows: [{ label: 'رقم الطلب', value: input.reference }] },
      ],
    },
  }
}

/* ═══ نقضُ الاعتذار — والسببُ هنا يصل صاحبَه بقصد ═══

   قرارُ صاحب المنصّة (١٩ سبتمبر ٢٠٢٦): «عند رفض أيّ مدرّب أريد خيارَ التراجع
   عن الرفض مع ذكر السبب، والذي يصل للمتقدّم بالإيميل».

   وليس في هذا نقضٌ لقرار ١٨ سبتمبر الذي أسقط سببَ الرفض عن بريد صاحبه:
   ذاك حكمٌ على شخصٍ يُكتب لعين مراجعٍ آخر، وهذا خبرٌ **لصالح** صاحبه يفسّر
   انقلابا في قرارٍ بلغه بالأمس. ومن قرأ اعتذارا ثمّ قرأ «عاد طلبك» بلا
   كلمةٍ واحدةٍ تشرح لا يدري أخطأنا أم تبدّل شيء، فيبقى ينتظر ثالثةً تنقض
   الثانية. فالسببُ هنا **إلزاميٌّ** لا اختياريّ — يفحصه `decide` قبل أن
   ينقل حالة، ويحرسه `src/tests/trainer-decision-mail.test.ts`.

   والفرقُ بنيويّ لا اتّفاقيّ: `rejectionMail` لا معامَلَ لها للملاحظة أصلا،
   وهذه تشترطها في نوعها — فلا يمرّ سهوٌ في أيٍّ من الاتّجاهين. */
export function rejectionUndoneMail(input: {
  fullName: string; reference: string; noteAr: string
  /** صفحةُ متابعة الطلب — يقرأ فيها حالتَه الجديدة ويحجز موعدَه */
  statusUrl: string
}): DecisionMail {
  return {
    subject: `عُدنا في قرارنا — طلبُك عاد إلى المراجعة (${input.reference})`,
    doc: {
      greetingName: input.fullName,
      preheader: 'تراجعنا عن الاعتذار الذي وصلك، وطلبُك عاد إلى المراجعة.',
      heading: 'عُدنا في قرارنا — وطلبُك عاد إلى المراجعة',
      blocks: [
        {
          kind: 'p',
          text: 'وصلك منّا اعتذارٌ عن طلبك للانضمام إلى مدرّبي وجيز، ونكتب إليك اليوم لنقول إنّنا '
            + 'تراجعنا عنه: طلبُك عاد إلى المراجعة بملفّه ومستنداته كما قدّمتَها، ولا يلزمك '
            + 'أن تُعيد تقديمَ شيء.',
        },
        /* والسببُ في إطارٍ لا في جدولِ حقائق — جملةٌ يكتبها إنسانٌ لإنسان */
        { kind: 'h', text: 'ولماذا عُدنا' },
        { kind: 'callout', text: input.noteAr },
        {
          kind: 'p',
          text: 'ونأسف لما سبّبه الاعتذارُ الأوّلُ من التباس. وسنُتابع معك من هنا كما نتابع '
            + 'أيَّ طلبٍ قيدَ المراجعة.',
        },
        {
          kind: 'cta',
          label: 'تابع حالة طلبك',
          href: input.statusUrl,
          caption: 'يُفتح بحسابك — البريدُ الذي قدّمت به وكلمتُه.',
        },
        { kind: 'facts', rows: [{ label: 'رقم الطلب', value: input.reference }] },
      ],
    },
  }
}

/* ═══ تذكيرُ من لم يحجز ═══

   يُرسَل بيد الإدارة لمن وصل طلبُه ولم يحجز موعدَه — وهم موجودون: الحجزُ
   شاشةٌ تُرى مرّةً بعد الإرسال، ومن أغلقها ليعود «لاحقا» لا يعود.

   ووجهةُ الزرّ **صفحةُ طلبه** لا التقويمُ رأسا (قرارُ صاحب المنصّة، ١٨
   سبتمبر ٢٠٢٦): من يفتح صفحتَه يرى حالتَه وبريدَه موثَّقا أو غيرَ موثَّق
   ثمّ يحجز من تحتها — فيصحّح ما نقص في طريقه إلى الموعد.

   ═══ وطريقٌ واحدٌ لا ثلاثة (١٩ سبتمبر ٢٠٢٦) ═══

   كان تحت الزرّ ثلاثةُ أشياءَ أخرى: مدّةُ اللقاء ومكانُه في جدول الحقائق،
   وسطرٌ يحمل رابطَ التقويم المباشر «لمن تعذّر عليه الدخول»، وسطرٌ يدعوه إلى
   الردّ إن لم يناسبه وقت. وقرارُ صاحب المنصّة أن تُحذف: «لا داعي لهذا النصّ».

   والرسالةُ تكسب بحذفها: غرضُها نقرةٌ واحدة، وكلُّ طريقٍ ثانٍ يُعرض بجانبها
   يقسم الانتباه. والتفاصيلُ تُقرأ حيث تُحجز — بطاقةُ الحجز نفسُها تقول المدّةَ
   والمكان قبل اختيار الوقت. ومن تعذّر عليه الدخولُ ليس بلا طريق: متابعةُ
   الطلب بالبريد وحدَه مفتوحةٌ في `/join-trainer`، والحجزُ من تحتها.

   ولم يبقَ لـ`bookingUrl` مُنادٍ — فحُذف المعامَلُ ولم يُترك يُمرَّر إلى
   حيث لا يُقرأ. */
export function bookingReminderMail(input: {
  fullName: string; reference: string
  /** صفحةُ حالة الطلب — تُفتح بحسابه */
  statusUrl: string
}): DecisionMail {
  return {
    subject: `بقيت خطوةٌ واحدة — احجز موعدَ ${MEETING_AR} (${input.reference})`,
    doc: {
      greetingName: input.fullName,
      preheader: `وصل طلبك كاملا، ولم يصلنا حجزُ موعدك بعد — وهي آخرُ خطوة.`,
      heading: `بقيت خطوةٌ واحدة في طلبك: موعدُ ${MEETING_AR}`,
      blocks: [
        {
          kind: 'p',
          text: 'شكرا لتقدّمك إلى أكاديمية وجيز. طلبك وصلنا كاملا وهو بين يدي فريقنا الأكاديميّ '
            + `— ولم يصلنا حجزُ موعدِ ${MEETING_AR} بعد، وهو آخرُ ما نحتاجه منك.`,
        },
        {
          kind: 'p',
          text: 'سجّل الدخول إلى حسابك بالبريد الذي قدّمت به، وتفقّد صفحة طلبك: تجد فيها حالتَه، '
            + 'وتحتها تقويمُ المواعيد تختار منه ما يناسبك.',
        },
        {
          kind: 'cta',
          label: 'تفقّد طلبك واحجز موعدك',
          href: input.statusUrl,
          caption: 'يُفتح بحسابك — البريدُ الذي قدّمت به وكلمتُه.',
        },
        { kind: 'facts', rows: [{ label: 'رقم الطلب', value: input.reference }] },
      ],
    },
  }
}

/* ═══ وبابٌ واحدٌ للقرارَين — فيه يقع إسقاطُ الملاحظة ═══

   `decide` تملك الملاحظةَ في يدها أيًّا كان القرار. فلو تُرك لكلِّ نداءٍ أن
   يقرّر ما يمرّره لعاد سهوُ يومٍ بها إلى بريد المرفوض. وهذه تأخذها في
   الحالَين ثمّ **تُسقطها في الرفض** — والإسقاطُ في موضعٍ واحدٍ يُفحص، لا
   اتّفاقٌ متفرّقٌ على ألّا تُمرَّر. */
export function decisionMailFor(
  action: 'reject' | 'waitlist',
  input: { fullName: string; reference: string; noteAr?: string },
): DecisionMail {
  return action === 'reject'
    ? rejectionMail({ fullName: input.fullName, reference: input.reference })
    : waitlistMail(input)
}
