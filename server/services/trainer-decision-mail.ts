/* ═══ الاعتمادُ النهائيّ — آخرُ الطور ═══

   ومعه المستندُ موقَّعا من الطرفَين: بيانُ صاحب المنصّة «ويُعاد إليه العقدُ
   موقَّعا منّا عقدا نهائيّا لا عرضا مشروطا». فتوقيعُنا يقع في اللحظة التي
   يُفعَّل فيها حسابُه، لا في أوّل الطور — وما بين توقيعه واعتمادِنا لا وثيقةَ
   نافذةً على أحد، فإن لم يتحقّق الشرطُ لم يكن ثَمَّ عقدٌ يُفسَخ أصلا.
   (ونُسخ هذا في ٢٧ سبتمبر ٢٠٢٦ فصار توقيعُنا عند اعتماد توقيعه، ثمّ عاد في ١
   أكتوبر بقرار صاحب المنصّة: «لا أريد أن أتعاقد مع أحدٍ قبل أن أعتمد دوراته».)

   ولمَ تُسمّى الدوراتُ المعتمَدةُ بأسمائها: «اعتُمدت موادُّك» بلا تسميةٍ
   تُقرأ اعتمادا لكلّ ما قدّم — ومنه ما أُعيد إليه. فيُدرَّس ما لم يُعتمَد. */
/** أيُّ خَتمٍ وقع على عرضه — والرسالةُ تقوله بحرفه.

    · `now`: وقّعنا العقدَ الآن مع اعتماد دوراته — وهو الطريقُ من ١ أكتوبر ٢٠٢٦
      (قرارُ صاحب المنصّة: «سوف نقوم بتوقيع العقد وتحويله إلى عقدٍ غير مشروط
      عندما نقوم باعتماد دوراتك»).
    · `earlier`: عرضٌ خُتم يومَ اعتُمد توقيعُه (٢٧ سبتمبر — ١ أكتوبر)، فتحقّق
      شرطُه الآن ولم يُوقَّع الآن.
    · `none`: لا عرضَ مشروطَ له — عُيّن داخليّا، أو عقدُه وُثِّق وهو نشط. فلا
      يُقال له إنّ شرطَ عرضٍ تحقّق، ولا يُدعى إلى عقدٍ موقَّع. */
export type FinalApprovalSeal = 'now' | 'earlier' | 'none'

export interface FinalApprovalMailInput {
  fullName: string
  reference: string
  /** أسماءُ الدورات المعتمَدة — وبلا واحدةٍ لا يقع الاعتماد أصلا */
  approvedCoursesAr: readonly string[]
  /** مطلوبٌ لا اختياريّ: بابٌ نُسي تمريرُه يقول «وقّعنا الآن» أو يسكت عنه بلا قصد */
  sealed: FinalApprovalSeal
  /** رابطُ العقد موقَّعا من الطرفَين */
  contractUrl: string | null
  portalUrl: string
  approvedOnAr: string
}

